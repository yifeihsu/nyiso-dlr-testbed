function report=validate_cache_and_benchmark()
% Exact public-loader parity first, then a fixed 100-hour PF timing sample.
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
out=fullfile(root,'output','nygrid_2025_acpf_profile_audit','acpf');if ~isfolder(out),mkdir(out);end
t=tic;cache=load_profile_cache();load_seconds=toc(t);
q=find(cache.qualified);clock=datetime(string(cache.dispatch.timestamp_utc),'InputFormat','yyyy-MM-dd''T''HH:mm:ss''Z''','TimeZone','UTC');clock.TimeZone='America/New_York';
dst=find(cache.qualified&((month(clock)==3&day(clock)==9)|(month(clock)==11&day(clock)==2)));
pick=unique([2630;4194;523;4000;8508;8471;8472;cache.template_hours;dst([1;end]);q(1);q(end)],'stable');
rows=struct([]);
for h=pick'
    fast=profile_case_from_cache(cache,h);original=npcc_nygrid_2025_ac(h);
    assert(isequal(fast.bus,original.bus)&&isequal(fast.gen,original.gen)&&isequal(fast.branch,original.branch) ...
        &&isequal(fast.dcline,original.dcline)&&isequal(fast.gencost,original.gencost), ...
        'profileCache:NumericalParity','Cached numerical case differs at hour%d.',h);
    assert(isequal(fast.genfuel,original.genfuel)&&isequal(fast.userdata.ac_system.generator_assumed_s_cap,original.userdata.ac_system.generator_assumed_s_cap) ...
        &&isequaln(fast.userdata.ac_system.terminal_current_limits,original.userdata.ac_system.terminal_current_limits) ...
        &&isequaln(fast.userdata.ac_system.cable_section_static_current_limits,original.userdata.ac_system.cable_section_static_current_limits));
    rows=[rows struct('hour',h,'exact_bus_gen_branch_dcline_gencost',true,'maximum_numeric_difference',0)]; %#ok<AGROW>
end
sample=q(unique(round(linspace(1,numel(q),100))));
opt=mpoption('model','AC','verbose',0,'out.all',0,'pf.alg','NR','pf.nr.max_it',50, ...
    'pf.tol',1e-10,'pf.enforce_q_lims',0,'exp.use_legacy_core',1);
checks=cell(numel(sample),1);t=tic;
for k=1:numel(sample)
    m=profile_case_from_cache(cache,sample(k));[r,~]=runpf(m,opt);checks{k}=audit_profile_pf(m,r);
end
elapsed=toc(t);checks=[checks{:}];
report=struct('passed',true,'public_loader_numerical_parity_checks',rows,'template_hours',cache.template_hours, ...
    'source_qualified_hour_count',nnz(cache.qualified),'input_cache_load_seconds',load_seconds, ...
    'benchmark_hours',sample,'benchmark_count',numel(sample),'benchmark_seconds',elapsed, ...
    'seconds_per_hour_including_case_and_independent_audit',elapsed/numel(sample), ...
    'projected_annual_compute_seconds',8651*elapsed/numel(sample), ...
    'benchmark_PF_converged',sum([checks.PF_converged]),'benchmark_equation_gate',sum([checks.AC_equation_gate]), ...
    'benchmark_profile_preservation_gate',sum([checks.P_profile_preservation_gate]), ...
    'benchmark_VQ_assumption_gate',sum([checks.VQ_and_generator_assumption_gate]), ...
    'OPF_used',false,'initial_values_from_previous_PF_or_internal_P32_used',false);
fid=fopen(fullfile(out,'cache_parity_and_benchmark.json'),'w');fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
fprintf('PROFILE_CACHE parity%d benchmark%d %.2fs annualestimate%.1fs converged%d equations%d profile%d\n',numel(pick),numel(sample),elapsed,report.projected_annual_compute_seconds,report.benchmark_PF_converged,report.benchmark_equation_gate,report.benchmark_profile_preservation_gate);
end
