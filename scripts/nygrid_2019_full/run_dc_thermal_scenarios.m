function summary=run_dc_thermal_scenarios(out)
%RUN_DC_THERMAL_SCENARIOS Explicit synthetic ampacity screening of NYgrid2019.
% Fixed historical DC dispatch; nominal voltage, unity power factor. These
% limits are research MW proxies, not validated AC currents or installed DLR.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
if nargin<1,out=fullfile(root,'output','nygrid_2019_full_stage1');end
addpath(fullfile(root,'System Matpower Format','NY_Lite'));
d=load(fullfile(out,'full_year.mat'));
assert(size(d.branch_pf,1)==8760&&numel(d.hour_index)==8760 ...
    &&isequal(d.hour_index(:),(1:8760)')&&all(isfinite(d.branch_pf),'all'), ...
    'nygrid:AnnualCoverage','A complete finite2019 DC reconstruction is required.');
m=d.base_case;
m.baseMVA=double(m.baseMVA); % SciPy may serialize the integral source base as int64.
assert(size(m.bus,1)==140&&size(m.branch,1)==225&&size(m.dcline,1)==4, ...
    'nygrid:Inventory','Unexpected full final-device network.');
register=readtable(fullfile(out,'branch_register.csv'),'TextType','string');
select=register(register.structural_thermal_candidate_only==1,:);
rows=select.branch_row;
assert(~isempty(rows)&&numel(unique(rows))==numel(rows),'nygrid:Selection','No unique structural candidates.');
[~,f]=ismember(m.branch(rows,1),m.bus(:,1));[~,t]=ismember(m.branch(rows,2),m.bus(:,1));
kv=m.bus(f,10);
assert(all(kv==m.bus(t,10))&&all(kv>=69)&&all(m.branch(rows,3)>0) ...
    &&all(m.branch(rows,4)>0)&&all(m.branch(rows,11)==1) ...
    &&all(ismember(m.branch(rows,9),[0,1]))&&all(m.branch(rows,10)==0), ...
    'nygrid:NonthermalDevice','Candidates must be active equal-voltage positive-R/X AC rows without taps/shifts.');
assert(all(~logical(select.physical_verified)),'nygrid:ClaimScope','These are unverified physical assets.');
lib=dlr_conductor_library;c=lib(lib.conductor_code=="DRAKE_795_ACSR",:);
% Declared surrogate choices, made independently of flows or interface errors.
circuits=ones(numel(rows),1);bundles=ones(numel(rows),1);
bundles(kv>=345)=2;bundles(kv>=500)=4;
effective_km=m.branch(rows,3).*kv.^2/m.baseMVA.*circuits.*bundles/c.r_ref_ohm_m/1000;
selection=table(rows,select.branch_key,kv,repmat(c.conductor_code,numel(rows),1),circuits,bundles,effective_km, ...
    effective_km>=1&effective_km<=300,false(numel(rows),1),false(numel(rows),1), ...
    repmat("assumed_overhead_AC_surrogate_not_installed_asset",numel(rows),1), ...
    'VariableNames',{'branch_row','branch_key','nominal_kv','conductor_code','circuits','bundle_count', ...
    'Rmatched_effective_length_km','included_in_synthetic_screen','physical_conductor_verified', ...
    'observed_weather','asset_assumption'});
% R-derived lengths are an assumption diagnostic, never route observations.
writetable(selection,fullfile(out,'synthetic_dlr_selection.csv'));
selection=selection(selection.included_in_synthetic_screen,:);
rows=selection.branch_row;kv=selection.nominal_kv;
assert(~isempty(rows),'nygrid:LengthReview','All synthetic lengths require manual review.');
weather=table(["static_reference";"windy_mild";"hot_low_wind";"cool_windy"], ...
    [40;25;40;5],[.61;2;.2;1],[90;90;0;90],[1000;800;1000;100],repmat(101325,4,1), ...
    false(4,1),'VariableNames',{'scenario_id','ambient_c','wind_m_s','wind_angle_deg','solar_w_m2','pressure_pa','observed_weather'});
writetable(weather,fullfile(out,'synthetic_weather_scenarios.csv'));
writetable(c,fullfile(out,'synthetic_conductor.csv'));
tests=test_dlr_thermal_model;
capacity=table();summary=table();hourly=table();
flow=abs(d.branch_pf(:,rows));
hours2019=datetime(2019,1,1)+hours((0:8759)');
amps=zeros(height(weather),1);heat_error=zeros(height(weather),1);
for k=1:height(weather)
    a=dlr_steady_ampacity(c,weather(k,:),75);
    h=dlr_heat_balance(75,a.ampacity_amp,c,weather(k,:));
    assert(a.zero_current_thermally_feasible&&abs(h.net_w_m)<1e-9,'nygrid:HeatBalance','Thermal equilibrium failed.');
    amps(k)=a.ampacity_amp;heat_error(k)=abs(h.net_w_m);
    cap=sqrt(3)*kv.*selection.circuits.*selection.bundle_count*a.ampacity_amp/1000;
    inherited=m.branch(rows,6);ceiling=cap;has_ceiling=inherited>0;
    ceiling(has_ceiling)=min(cap(has_ceiling),inherited(has_ceiling));
    ceiling_label=inherited;ceiling_label(~has_ceiling)=NaN;
    thermal_excess=flow>cap'+1e-7;
    envelope_excess=flow>ceiling'+1e-7;
    capacity=[capacity;table(repmat(weather.scenario_id(k),numel(rows),1),rows,selection.branch_key, ...
        repmat(a.ampacity_amp,numel(rows),1),cap,ceiling_label,ceiling, ...
        false(numel(rows),1),repmat(abs(h.net_w_m),numel(rows),1), ...
        'VariableNames',{'scenario_id','branch_row','branch_key','subconductor_ampacity_a','thermal_dc_proxy_mw', ...
        'inherited_unverified_rate_a_mva','min_thermal_inherited_dc_proxy_mw','ac_or_installed_DLR_qualified','heat_residual_w_m'})]; %#ok<AGROW>
    summary=[summary;table(weather.scenario_id(k),numel(rows),8760, ...
        nnz(thermal_excess),nnz(any(thermal_excess,2)),max(flow./cap',[],'all'), ...
        nnz(envelope_excess),nnz(any(envelope_excess,2)),max(flow./ceiling',[],'all'), ...
        'VariableNames',{'scenario_id','screened_branches','hours','thermal_exceedance_branch_hours', ...
        'hours_any_thermal_exceedance','max_thermal_proxy_utilization','combined_exceedance_branch_hours', ...
        'hours_any_combined_exceedance','max_combined_proxy_utilization'})]; %#ok<AGROW>
    hourly=[hourly;table(hours2019,repmat(weather.scenario_id(k),8760,1), ...
        sum(thermal_excess,2),max(flow./cap',[],2),sum(envelope_excess,2), ...
        'VariableNames',{'prepared_local_hour','scenario_id','thermal_exceeded_branches', ...
        'max_thermal_proxy_utilization','combined_exceeded_branches'})]; %#ok<AGROW>
end
assert(amps(2)>amps(1)&&amps(3)<amps(1)&&amps(4)>amps(1), ...
    'nygrid:WeatherResponse','Unexpected synthetic weather ordering.');
scope=struct('stage',"synthetic_DC_thermal_exposure_screen",'year',2019, ...
    'fixed_dispatch',true,'nominal_voltage_unity_power_factor_proxy',true, ...
    'observed_weather',false,'installed_conductors_verified',false, ...
    'ac_feasibility_validated',false,'economic_redispatch_performed',false, ...
    'dynamic_temperature_time_series',false,'sag_clearance_validated',false, ...
    'zero_rate_a_policy',"unspecified equipment limit; never zero thermal capacity", ...
    'length_policy',"Rmatched at assumed75C; exclude outside1to300km; not geographic route", ...
    'conductor_policy',"2026 catalog surrogate for a2019 research scenario; not historical equipment identification", ...
    'weather_policy',"four constant conditions independently applied to the same8760 prepared hourly states", ...
    'max_heat_residual_w_m',max(heat_error),'thermal_tests_passed',all(tests.passed));
writetable(capacity,fullfile(out,'synthetic_dlr_capacities.csv'));
writetable(summary,fullfile(out,'synthetic_dlr_summary.csv'));
writetable(hourly,fullfile(out,'synthetic_dlr_hourly.csv'));
writetable(tests,fullfile(out,'synthetic_thermal_tests.csv'));
fid=fopen(fullfile(out,'synthetic_dlr_scope.json'),'w');assert(fid>=0);
clean=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(scope,PrettyPrint=true));
disp(summary);
end
