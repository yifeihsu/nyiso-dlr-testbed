function screen=screen_nygrid_2025_loss_pf_thermal(input,weather,options)
%SCREEN_NYGRID_2025_LOSS_PF_THERMAL One-way research screen of a revised PF.
% INPUT: hour index, or struct('full',full,'audit',audit,'allocation',allocation).
% WEATHER is REQUIRED: ambient_c, wind_m_s, wind_angle_deg, solar_w_m2,
% pressure_pa. Supply one declared uniform row, or key-matched candidate rows.
% Never changes electrical R or dispatch, solves temperature, runs OPF, or
% certifies historical weather, installed-asset DLR or operating feasibility.
if nargin<1||isempty(input),input=8508;end
assert(nargin>=2&&~isempty(weather),'handoff:ExplicitWeather','Supply explicit scenario weather; no observed-weather default is implied.');
if nargin<3,options=struct();end
if isstruct(weather),weather=struct2table(weather);end
required={'ambient_c','wind_m_s','wind_angle_deg','solar_w_m2','pressure_pa'};
assert(istable(weather)&&all(ismember(required,weather.Properties.VariableNames)),'handoff:WeatherSchema','Weather columns are incomplete.');
if isnumeric(input)
    options.impedance_mode='released_equivalent';options.loss_mode='boundary_consistent';options.backend='compact';
    [compact,audit,full,allocation]=run_nygrid_2025_loss_consistent_acpf(input,options); %#ok<ASGLU>
else
    assert(isstruct(input)&&all(isfield(input,{'full','audit','allocation'})),'handoff:CachedResult','Supply full, audit and allocation fields from the revised PF API.');
    full=input.full;audit=input.audit;allocation=input.allocation;
end
assert(audit.PF_converged&&audit.AC_equation_gate&&audit.loss_allocation_gate&&audit.reduction_and_equation_gate, ...
    'handoff:UnqualifiedPF','Thermal screening requires an equation- and loss-accounting-qualified revised PF; failed iterates are not predictions.');
m=allocation.final_input;
assert(full.success&&isequal(full.bus(:,1),m.bus(:,1))&&isequal(full.gen(:,1),m.gen(:,1)) ...
    &&isequal(full.branch(:,1:13),m.branch(:,1:13))&&full.baseMVA==m.baseMVA, ...
    'handoff:ResultIdentity','Solved result and final allocated input differ.');
assert(~m.userdata.ac_system.current_gamma_lift,'handoff:CurrentScale','Use the present synthetic AC current convention without gamma lifting.');
[segments,ledger,conductors]=nygrid_handoff_thermal_candidates(m);
assert(height(segments)>0,'handoff:NoThermalCandidates','No source-keyed or design-backed modeled OH segments satisfy the conservative screen.');
if height(weather)>1
    assert(height(weather)==height(segments)&&all(ismember({'branch_key','segment_id'},weather.Properties.VariableNames)), ...
        'handoff:WeatherKeys','Per-segment weather must include exact branch_key and segment_id axes.');
    assert(isequal(string(weather.branch_key),string(segments.branch_key))&&isequal(string(weather.segment_id),string(segments.segment_id)), ...
        'handoff:WeatherOrder','Weather rows do not match the returned candidate-segment order.');
end
limits=ac_dlr_limits(m,segments,conductors,weather);
thermal=ac_dlr_current_audit(full,segments,conductors,segments.reference_temperature_c,limits);
electrical=audit_ac_solution(m,full);
assert(electrical.max_nodal_P_residual_mw<1e-5&&electrical.max_nodal_Q_residual_mvar<1e-5, ...
    'handoff:KCL','Cached or solved result fails an independent electrical audit.');
p=allocation.policy_contract;[budget,budget_detail]=ac_loss_budget(m,full,p);
assert(max(abs(budget-allocation.actual_budget_MW))<1e-6 ...
    &&max(abs(full.gen(p.native,2)-allocation.baseline_PG(p.native)))<1e-7 ...
    &&abs(full.gen(p.HQ,2)-allocation.baseline_PG(p.HQ))<1e-8, ...
    'handoff:PolicyIdentity','Recomputed loss budget or fixed native/HQ profile differs.');
V=full.bus(:,8).*exp(1j*deg2rad(full.bus(:,9)));rr=limits.branch.branch_row;
[ok,f]=ismember(full.branch(rr,1),full.bus(:,1));assert(all(ok));[ok,t]=ismember(full.branch(rr,2),full.bus(:,1));assert(all(ok));
z=complex(full.branch(rr,3),full.branch(rr,4));ys=1./z;bc=1j*full.branch(rr,5)/2;
series=ys.*(V(f)-V(t));from=series+bc.*V(f);to=-series+bc.*V(t);
ibase=full.baseMVA*1000./(sqrt(3)*full.bus(f,10));is=abs(series).*ibase;iff=abs(from).*ibase;itt=abs(to).*ibase;
from_power=hypot(full.branch(rr,14),full.branch(rr,15))*1000./(sqrt(3)*full.bus(f,10).*abs(V(f)));
to_power=hypot(full.branch(rr,16),full.branch(rr,17))*1000./(sqrt(3)*full.bus(t,10).*abs(V(t)));
current_error=max(abs([iff-from_power;itt-to_power]));
branch=thermal.branch;assert(isequal(branch.branch_row,rr));
branch.original_parent_row=m.userdata.ac_system.branch_parent_row(rr);
branch.runtime_branch_key=string(m.userdata.ac_system.branch_keys(rr));
branch.series_phase_current_A=is;branch.from_terminal_current_A=iff;branch.to_terminal_current_A=itt;
branch.declared_phase_ampacity_A=limits.branch.series_phase_limit_a;
branch.from_section_end_utilization=iff./branch.declared_phase_ampacity_A;
branch.to_section_end_utilization=itt./branch.declared_phase_ampacity_A;
branch.max_section_end_utilization=max(branch.from_section_end_utilization,branch.to_section_end_utilization);
segment=thermal.segment;segment.original_parent_row=m.userdata.ac_system.branch_parent_row(segment.branch_row);
heat_at_limit=zeros(height(segments),1);
[ok,ci]=ismember(string(segments.catalog_id),string(conductors.catalog_id));assert(all(ok));
for j=1:height(segments)
    h=ac_conductor_heat(segments.temperature_max_c(j),limits.segment.ampacity_subconductor_a(j),conductors(ci(j),:),weather(min(j,height(weather)),:));
    heat_at_limit(j)=h.net_w_m;
end
assert(thermal.maximum_loss_identity_error_mw<1e-7&&current_error<1e-6&&max(abs(heat_at_limit))<1e-8, ...
    'handoff:ThermalIdentity','Joule/terminal-current/steady-ampacity identity failed.');
screen=struct('screening_completed',true,'numerical_identities_passed',true,'hour_index',audit.hour_index, ...
    'timestamp_utc',audit.timestamp_utc,'weather',weather,'weather_is_observed',false, ...
    'weather_scope','explicit_user_supplied_unverified_scenario','candidate_and_exclusion_ledger',ledger, ...
    'candidate_segments',segments,'segment_screen',segment,'branch_screen',branch,'limits',limits, ...
    'candidate_parent_count',nnz(ledger.research_screen_eligible),'excluded_parent_count',nnz(~ledger.research_screen_eligible), ...
    'candidate_runtime_branch_count',height(branch),'candidate_segment_count',height(segment), ...
    'hard_excluded_parent_rows',[224 300 309 310 386], ...
    'maximum_series_ampacity_utilization',thermal.maximum_ampacity_fraction, ...
    'maximum_section_end_ampacity_utilization',max(branch.max_section_end_utilization), ...
    'runtime_branches_above_series_ampacity',nnz(branch.max_ampacity_fraction>1+1e-6), ...
    'runtime_branches_above_section_end_ampacity',nnz(branch.max_section_end_utilization>1+1e-6), ...
    'all_candidate_current_envelopes_satisfied',thermal.maximum_ampacity_fraction<=1+1e-6&&max(branch.max_section_end_utilization)<=1+1e-6, ...
    'maximum_Joule_loss_identity_error_MW',thermal.maximum_loss_identity_error_mw, ...
    'maximum_terminal_current_crosscheck_error_A',current_error,'maximum_heat_residual_at_ampacity_W_per_m',max(abs(heat_at_limit)), ...
    'inherited_electrical_audit',audit,'fresh_KCL_audit',electrical,'fresh_loss_budget_detail',budget_detail, ...
    'inherited_VQ_operating_qualification',audit.VQ_and_generator_assumption_gate, ...
    'installed_asset_DLR_qualification',false,'whole_system_operating_qualification',false, ...
    'current_gamma_rescaling_applied',false,'OPF_run',false,'electrical_solution_changed',false, ...
    'resistance_temperature_feedback_run',false,'conductor_temperature_equilibrium_solved',false, ...
    'reference_temperature_R_is_held_fixed',true,'continuous_along_route_maximum_certified',false, ...
    'complete_IEEE738_2023_model_claimed',false, ...
    'scope','one_way_source_keyed_synthetic_OH_research_screen;not_current_loss_revision_DLR_optimizer');
end
