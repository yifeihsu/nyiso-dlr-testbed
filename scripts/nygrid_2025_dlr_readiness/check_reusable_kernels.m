function check_reusable_kernels()
% Read-only reusable-component audit; does not run a current-model DLR study.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
folder=fullfile(root,'output','nygrid_2025_dlr_readiness');if ~isfolder(folder),mkdir(folder);end
addpath(fullfile(root,'System Matpower Format'),fullfile(root,'System Matpower Format','NY_Lite'));
tests=[test_dlr_thermal_model;test_dlr_electrical_consistency;test_dlr_series_constraint];
assert(all(tests.passed));
lib=dlr_conductor_library;
m=npcc_nygrid_2025_dover_dc(8508,'bounded','x_nominal');
assert(size(m.bus,1)==148&&size(m.branch,1)==274&&size(m.gen,1)==1464&&size(m.dcline,1)==6);
assert(m.userdata.dover.DC_only&&~m.userdata.dover.physical_flowgates_certified);
gamma=m.userdata.nygrid2025.scale_factor_gamma;
assert(abs(gamma-0.30012075175285535)<1e-15);
active=m.branch(:,11)>0;
[~,f]=ismember(m.branch(:,1),m.bus(:,1));[~,t]=ismember(m.branch(:,2),m.bus(:,1));
% Dimensional identity only: this is a design-current conversion check,
% not a measured current or a reconstructed temperature on F84.
phase_a=2214;bundle=2;kv=345;
design_public_mva=sqrt(3)*kv*phase_a/1000;
model_p_unity_pf=gamma*design_public_mva;
correct_sub_amp=1000*model_p_unity_pf/(gamma*sqrt(3)*kv*bundle);
wrong_sub_amp=1000*model_p_unity_pf/(sqrt(3)*kv*bundle);
assert(abs(correct_sub_amp-1107)<1e-10&&abs(wrong_sub_amp/correct_sub_amp-gamma)<1e-15);
oldkeep={'version','baseMVA','bus','gen','branch','gencost','bus_name','success','userdata'};
removed=setdiff(fieldnames(m),oldkeep);
assert(any(strcmp(removed,'dcline'))&&any(strcmp(removed,'userfcn')));
summary=struct('audit_completed',true,'fresh_reusable_component_tests_passed',true, ...
    'component_tests',height(tests),'source_case_loader','npcc_nygrid_2025_dover_dc', ...
    'inspected_hour_index',8508,'buses',size(m.bus,1),'branch_records',size(m.branch,1), ...
    'active_branch_records',nnz(active),'generators',size(m.gen,1),'fixed_transfer_records',size(m.dcline,1), ...
    'active_zero_RATE_A_records',nnz(active&m.branch(:,6)==0), ...
    'active_voltage_changing_records',nnz(active&abs(m.bus(f,10)-m.bus(t,10))>1e-9), ...
    'generator_Q_columns_all_zero_DC_placeholders',all(m.gen(:,3:5)==0,'all'), ...
    'voltage_magnitudes_all_one_DC_placeholders',all(m.bus(:,8)==1), ...
    'legacy_thermal_catalog_codes',lib.conductor_code,'legacy_catalog_physical_NY_verified',any(lib.physical_NY_conductor_verified), ...
    'legacy_library_has_ACSS_Mallard_or_Bluebird',any(contains(lib.conductor_code,'MALLARD')|contains(lib.conductor_code,'BLUEBIRD')), ...
    'current_loader_thermal_runtime_metadata_present',isfield(m.userdata,'thermal'), ...
    'old_plain_helper_would_remove_six_transfer_records',any(strcmp(removed,'dcline')), ...
    'old_plain_helper_would_remove_control_callbacks',any(strcmp(removed,'userfcn')), ...
    'gamma',gamma,'design_F84_phase_current_A',phase_a,'design_F84_subconductor_current_A',correct_sub_amp, ...
    'design_F84_public_MVA',design_public_mva,'design_F84_model_MW_unity_PF',model_p_unity_pf, ...
    'unconverted_scaled_power_current_ratio',wrong_sub_amp/correct_sub_amp, ...
    'unconverted_scaled_power_Joule_heating_ratio',(wrong_sub_amp/correct_sub_amp)^2, ...
    'coupled_current_testbed_DLR_experiment_run',false,'current_testbed_physical_DLR_ready',false, ...
    'AC_required_for_declared_DC_proxy_research',false,'MATLAB_version',version);
names={'dlr_heat_balance','dlr_steady_ampacity','dlr_temperature_trace','dlr_conductor_library', ...
    'test_dlr_thermal_model','test_dlr_electrical_consistency','test_dlr_series_constraint', ...
    'dlr_series_current_audit','dlr_series_constraint','build_dlr_corridor_realizations', ...
    'apply_dlr_temperature_resistance','solve_dlr_steady_operating_point','npcc_nygrid_2025_dover_dc'};
paths=cellfun(@which,names,'UniformOutput',false);
paths=[paths,{fullfile(root,'System Matpower Format','NY_Lite','fixtures','dlr_nrel_reference.csv'), ...
    fullfile(root,'System Matpower Format','NY_Lite','fixtures','dlr_nrel_reference_manifest.json'), ...
    [mfilename('fullpath'),'.m']}];
dep=struct('path',{},'sha256',{});
for k=1:numel(paths),dep(end+1)=struct('path',paths{k},'sha256',file_sha256(paths{k}));end %#ok<AGROW>
summary.dependencies=dep;
writetable(tests,fullfile(folder,'fresh_reusable_component_tests.csv'));
fid=fopen(fullfile(folder,'fresh_reusable_component_audit.json'),'w');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(summary,'PrettyPrint',true));disp(summary);
end
function digest=file_sha256(path)
engine=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(path,'rb');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
while ~feof(fid),bytes=fread(fid,1048576,'*uint8');if ~isempty(bytes),engine.update(typecast(bytes,'int8'));end,end
raw=typecast(engine.digest(),'uint8');digest=lower(reshape(dec2hex(raw,2)',1,[]));
end
