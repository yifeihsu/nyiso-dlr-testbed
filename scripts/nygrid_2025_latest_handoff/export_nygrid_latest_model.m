function receipt=export_nygrid_latest_model()
%EXPORT_NYGRID_LATEST_MODEL One-time compilation of the current2025 model.
% Authoring-only: reads the existing frozen cache/constructors but does not
% ship them or their historical replay files as runtime dependencies.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
out=fullfile(root,'output','nygrid_2025_latest_handoff','model');if ~isfolder(out),mkdir(out);end
addpath(fullfile(root,'System Matpower Format'));
addpath(fullfile(root,'scripts','nygrid_2025_acpf_profile_audit','acpf'));
addpath(fullfile(root,'scripts','nygrid_2025_ac_loss_revision','core'));
addpath(fullfile(root,'scripts','nygrid_2025_compact_ac','core'));
runtime=fullfile(root,'scripts','nygrid_2025_latest_handoff','runtime');addpath(runtime);addpath(fullfile(runtime,'kernels'));
assert(strcmp(mpver,'8.1'));
[status,head]=system('git rev-parse HEAD');assert(status==0);head=strtrim(head);assert(~isempty(regexp(head,'^[0-9a-f]{40}$','once')));
cache=load_profile_cache();
anchors=readtable(fullfile(root,'output','nygrid_2025_slim','network','bus_register.csv'),'TextType','string');
model=struct('schema_version',1,'model_id','NYGRID_2025_latest_loss_consistent_RX_thermal', ...
    'source_model_commit',head,'created_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd HH:mm:ss Z')), ...
    'baseMVA',100,'frequency_Hz',60,'scale_factor_gamma',cache.dispatch.gamma, ...
    'synthetic_system_current_divided_by_gamma',false,'historical_operating_case_claimed',false);
model.axis=struct('hour_index',uint16((1:8760)'), ...
    'timestamp_utc',string(cache.dispatch.timestamp_utc(:)),'source_qualified',logical(cache.qualified(:)), ...
    'state_index',uint8(cache.state_index(:)),'state_names',string(cache.state_names(:)), ...
    'state_labels',["pre_may";"may21";"may30";"post_dover"], ...
    'template_hours',uint16(cache.template_hours(:)),'reference_bus',double(cache.dispatch.reference_bus(:)), ...
    'post_dover_full_service',logical(cache.dover.post_full_service(:)));
model.profiles=struct('bus_PD_MW',cache.dispatch.bus_pd,'bus_QD_MVAr',cache.dispatch.bus_qd, ...
    'generator_PG_MW',cache.western.gen_pg,'generator_Pmin_MW',cache.bounds.gen_pmin, ...
    'generator_Pmax_MW',cache.bounds.gen_pmax, ...
    'fixed_transfer_PF_MW',[cache.dispatch.dc_pf cache.western.P34_control_targets_model_mw], ...
    'dover_bank_phase_shift_deg',cache.dover.controls.bounded_x_nominal.bank_shift_model_deg);
model.retained_bus_ids=double(anchors.model_bus(:));assert(numel(model.retained_bus_ids)==148);
model.external=struct('generator_mask',logical(cache.external(:)),'capability_proxy_MW',cache.external_capacity(:), ...
    'capability_is_finite_model_proxy_not_observed_nameplate',true,'assumed_power_factor',.95);
model.generator_bus_ids=double(cache.templates{1}.gen(:,1));model.generator_bus_rows=cache.generator_bus_index;
model.templates=cell(4,1);model.loss_static=cell(4,1);state_records=struct([]);
for state=1:4
    hour=cache.template_hours(state);m=profile_case_from_cache(cache,hour);m=ac_loss_prepare_case(m,'released_equivalent');
    p=ac_loss_prepare_policy(m);fixed={'labels','NY','external','bus_group','parent','parent_from','parent_to', ...
        'from_runtime','to_runtime','loss_ownership','DC_external_group','native','external_gen_group', ...
        'generator_share','HQ','external_original_P_capabilities_are_proxies','policy'};
    st=pick(p,fixed);st.finite_external_generator_rows=find(p.external_gen_group>0);
    st.finite_external_Pmin_MW=p.Pmin(st.finite_external_generator_rows);st.finite_external_Pmax_MW=p.Pmax(st.finite_external_generator_rows);
    model.loss_static{state}=st;
    numeric_before={m.bus,m.gen,m.branch,m.dcline,m.gencost};m=clean_current_case(m);
    assert(isequaln(numeric_before,{m.bus,m.gen,m.branch,m.dcline,m.gencost}));
    model.templates{state}=m;
    record=struct('state_index',state,'state_name',char(model.axis.state_names(state)), ...
        'state_label',char(model.axis.state_labels(state)),'template_hour',hour, ...
        'first_hour',find(cache.state_index==state,1,'first'),'last_hour',find(cache.state_index==state,1,'last'), ...
        'source_qualified_hours',nnz(cache.qualified&cache.state_index==state), ...
        'full_bus_count',size(m.bus,1),'full_branch_rows',size(m.branch,1),'active_branch_rows',nnz(m.branch(:,11)>0), ...
        'original_parent_rows',max(m.userdata.ac_system.branch_parent_row),'generator_rows',size(m.gen,1), ...
        'retained_bus_count',148,'fixed_transfer_records',size(m.dcline,1));
    state_records=[state_records record]; %#ok<AGROW>
end
reg=readtable(fullfile(root,'output','nygrid_2025_dispatch','dispatch','model_generator_register.csv'),'TextType','string');
assert(isequal(double(reg.gen_row(:)),(1:numel(model.generator_bus_ids))'));
model.generator_registry=table(double(reg.gen_row),string(reg.device_key),model.generator_bus_ids, ...
    string(cache.templates{1}.genfuel(:)),~model.external.generator_mask, ...
    'VariableNames',{'generator_row','device_key','current_bus_id','fuel_category','native_profile_row'});
model.fixed_transfer_registry=table((1:6)',model.templates{4}.dcline(:,1),model.templates{4}.dcline(:,2), ...
    [repmat("prescribed_DC_transfer",4,1);repmat("ideal_PAR_control_equivalent",2,1)], ...
    'VariableNames',{'transfer_row','from_bus','to_bus','record_kind'});
folder=fullfile(root,'output','nygrid_2025_ac_system');
branch_registry=readtable(fullfile(folder,'branches','branch_assignments.csv'),'TextType','string');
% These are interpretation/provenance fields used by the current selector;
% actual current electrical R/X/B is always in each frozen template.branch.
columns={'branch_row','branch_key','classification','source_role','parameter_basis','original_r_pu','original_x_pu','length_min_m','length_max_m'};
model.thermal=struct('branch_registry',branch_registry(:,columns), ...
    'conductors',readtable(fullfile(folder,'engineering','thermal_conductors.csv'),'TextType','string'), ...
    'geometry',readtable(fullfile(folder,'engineering','geometry_defaults.csv'),'TextType','string'), ...
    'cable_conflicts',readtable(fullfile(root,'output','nygrid_2025_acpf_profile_audit','structure','overhead_cable_classification_conflicts.csv'),'TextType','string'));
model.policy=struct('solver','compact_coupled_voltage_and_boundary_loss_Newton','retained_bus_count',148, ...
    'native_and_HQ_active_profiles_fixed',true,'NY_P58_demand_is_served_load_plus_allocated_loss',true, ...
    'external_losses_balanced_with_frozen_shares_and_finite_proxies',true, ...
    'four_DC_and_two_ideal_PAR_control_records',true,'R_X_B_and_control_policies_changed',false, ...
    'thermal_scope','one_way_RX_conditioned_synthetic_screen_with_explicit_weather', ...
    'installed_conductor_identity_required',false,'geographic_chord_required',false, ...
    'OPF_supported',false,'annual_replay_included',false,'whole_system_operating_qualification_claimed',false);
assert(isequaln(model.profiles.bus_PD_MW,cache.dispatch.bus_pd)&&isequaln(model.profiles.bus_QD_MVAr,cache.dispatch.bus_qd) ...
    &&isequaln(model.profiles.generator_PG_MW,cache.western.gen_pg)&&isequaln(model.profiles.generator_Pmin_MW,cache.bounds.gen_pmin) ...
    &&isequaln(model.profiles.generator_Pmax_MW,cache.bounds.gen_pmax)&&isequaln(model.axis.source_qualified,cache.qualified));
annual=model.profiles;model=rmfield(model,'profiles');model.profile_shards=struct('name',{},'first_hour',{},'last_hour',{},'bytes',{},'sha256',{});
fields=fieldnames(annual);
for shard=1:2
    first=(shard-1)*4380+1;last=shard*4380;profiles=struct();
    for k=1:numel(fields),name=fields{k};profiles.(name)=annual.(name)(first:last,:);end
    name=sprintf('profiles_h%04d_%04d.mat',first,last);save(fullfile(out,name),'profiles','-v7');item=dir(fullfile(out,name));
    assert(item.bytes<95000000,'nylatest:ShardSize','A profile shard exceeds the portable per-file size target.');
    model.profile_shards(end+1)=struct('name',name,'first_hour',first,'last_hour',last,'bytes',item.bytes,'sha256',nylatest_file_sha256(fullfile(out,name))); %#ok<AGROW>
end
file=fullfile(out,'latest_model.mat');save(file,'model','-v7');
fi=dir(file);receipt=struct('schema_version',1,'passed',true,'source_model_commit',head, ...
    'model_file',struct('name','latest_model.mat','bytes',fi.bytes,'sha256',nylatest_file_sha256(file)), ...
    'model_files',[struct('name','latest_model.mat','bytes',fi.bytes,'sha256',nylatest_file_sha256(file)), ...
        rmfield(model.profile_shards,{'first_hour','last_hour'})], ...
    'profile_shards',model.profile_shards, ...
    'hours',8760,'source_qualified_hours',8651,'first_timestamp_utc',char(model.axis.timestamp_utc(1)), ...
    'last_timestamp_utc',char(model.axis.timestamp_utc(end)),'state_records',state_records, ...
    'all_annual_profile_arrays_copied_without_numeric_conversion',true, ...
    'historical_loader_metadata_removed',true,'serialized_function_handles_included',false, ...
    'already_released_equivalent_templates',true,'loss_policy_static_vectors_embedded',true, ...
    'historical_replay_files_required_at_runtime',false,'physical_arrays_changed',false, ...
    'fresh_PF_solve_run',false,'annual_replay_run',false,'OPF_run',false, ...
    'package_runtime_dependencies',{{'model/latest_model.mat','model/profiles_h0001_4380.mat','model/profiles_h4381_8760.mat', ...
        'model/model_receipt.json','runtime/*.m','runtime/kernels/*.m','vendor/matpower8.1 code','MATLAB with JVM'}}, ...
    'public_API',{{'setup_nygrid_latest','load_nygrid_latest','run_nygrid_latest_acpf','screen_nygrid_latest_dlr'}});
write_json(fullfile(out,'model_receipt.json'),receipt);
fprintf('LATEST_MODEL_EXPORT static_bytes%d profile_bytes%d source_hours%d states%d\n',fi.bytes,sum([model.profile_shards.bytes]),8651,4);disp(struct2table(state_records));
end

function m=clean_current_case(m)
if isfield(m,'userfcn'),m=rmfield(m,'userfcn');end
u=m.userdata.ac_system;
keep={'version','modeltype','hour_index','timestamp_utc','gamma','baseMVA','power_scale','current_gamma_lift', ...
    'power_and_impedance_rescaling_applied','as_built_equivalence_claimed','branch_keys','branch_parent_row', ...
    'generator_q_policy','generator_reactive_policy_version','external_reactive_policy', ...
    'external_Q_uses_complete_fixed_P_apparent_power_circle_slice','external_capacity_is_engineering_model_proxy_not_observed_nameplate', ...
    'offline_reactive_support_allowed','assumed_power_factor','GEN_STATUS_is_DC_availability_admission_not_observed_commitment', ...
    'physical_unit_commitment_and_generator_D_curves_validated','generator_p_reference','generator_capability_reference', ...
    'generator_q_cap','generator_assumed_s_cap','p_objective_weight','q_objective_weight','economic_dispatch_claimed', ...
    'external_generator_mask','voltage_limits_pu','fixed_six_transfers_preserved','thermal_constraints_applied', ...
    'thermal_segments','cable_segments','terminal_current_constraints_applied','terminal_current_limits','cable_section_static_current_limits'};
u=pick(u,keep);u.current_loss_policy='NY_boundary_load_partition_and_external_area_loss_balance_at_NY_terminals';
u.native_and_HQ_generation_profiles_fixed=true;u.external_loss_balancing_uses_finite_proxies=true;
sections=pick(m.userdata.ac_sections,{'branch_keys','branch_parent_row','branch_map','added_bus_map', ...
    'thermal_segments','cable_segments','terminal_current_limit_A','static_cable_current_limit_A','reactor_ledger', ...
    'original_bus_count','original_branch_count','added_bus_count','added_branch_count','reactor_BS_delta','current_gamma_lift'});
revision=pick(m.userdata.ac_loss_revision,{'version','impedance_mode','parent224_after_R_X_B','parent224_runtime_rows', ...
    'parent224_is_released_network_equivalent','parent224_physical_impedance_validated','parent224_conductor_DLR_eligible', ...
    'parent224_temperature_resistance_update_allowed','topology_bus_and_branch_axes_preserved','OPF_supported'});
m.userdata=struct('ac_system',u,'ac_sections',sections,'ac_loss_revision',revision);
end

function target=pick(source,names)
target=struct();for k=1:numel(names),name=names{k};assert(isfield(source,name),'nylatest:ExportField','Required current field is missing.');target.(name)=source.(name);end
end

function write_json(path,value)
fid=fopen(path,'w');assert(fid>=0);clean=onCleanup(@()fclose(fid));fprintf(fid,'%s\n',jsonencode(value,'PrettyPrint',true));
end
