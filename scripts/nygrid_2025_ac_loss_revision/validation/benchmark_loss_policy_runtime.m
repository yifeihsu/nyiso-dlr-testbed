function report=benchmark_loss_policy_runtime()
% Warmed fixed100-hour performance/coverage snapshot, never annual evidence.
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
addpath(fullfile(root,'System Matpower Format'));
addpath(fullfile(root,'scripts','nygrid_2025_acpf_profile_audit','acpf'));
out=fullfile(root,'output','nygrid_2025_ac_loss_revision','validation','benchmark');if ~isfolder(out),mkdir(out);end
source_records=loss_validation_source_records(root);cache=load_profile_cache();
old=jsondecode(fileread(fullfile(root,'output','nygrid_2025_acpf_profile_audit','acpf','cache_parity_and_benchmark.json')));
hours=old.benchmark_hours(:);assert(numel(hours)==100&&all(cache.qualified(hours)));
options=struct('impedance_mode','released_equivalent','loss_mode','boundary_consistent','backend','compact');
for h=[2630 8508],base=profile_case_from_cache(cache,h);run_nygrid_2025_loss_consistent_acpf(base,options);end
ws=warning;cleanup=onCleanup(@()warning(ws));warning('off','MATLAB:nearlySingularMatrix');warning('off','MATLAB:singularMatrix');
rows=struct([]);started=tic;
for h=hours'
    t=tic;base=profile_case_from_cache(cache,h);input_seconds=toc(t);
    t=tic;[result,audit]=run_nygrid_2025_loss_consistent_acpf(base,options);call_seconds=toc(t);
    row=struct('hour_index',h,'input_seconds',input_seconds,'call_seconds',call_seconds, ...
        'solver_with_context_seconds',audit.elapsed_seconds,'public_wrapper_overhead_seconds',max(0,call_seconds-audit.elapsed_seconds), ...
        'NR_updates',audit.total_NR_iterations,'PF_converged',audit.PF_converged, ...
        'policy_qualified',audit.loss_allocation_gate&&audit.AC_equation_gate&&audit.reduction_and_equation_gate, ...
        'physical_VQ_qualified',audit.VQ_and_generator_assumption_gate,'status',audit.loss_status);
    rows=[rows row]; %#ok<AGROW>
end
elapsed=toc(started);after=loss_validation_source_records(root);
assert(isequal(source_records,after),'acLossBenchmark:SourceChanged','Frozen numerical/input files changed during benchmark.');
report=struct('completed',true,'benchmark_hours',hours,'warmup_hours',[2630 8508],'count',100,'elapsed_seconds',elapsed, ...
    'projected_8651_hours_seconds',elapsed/100*8651,'PF_converged',sum([rows.PF_converged]), ...
    'policy_qualified',sum([rows.policy_qualified]),'physical_VQ_qualified',sum([rows.physical_VQ_qualified]), ...
    'mean_call_seconds',mean([rows.call_seconds]),'mean_solver_with_context_seconds',mean([rows.solver_with_context_seconds]), ...
    'mean_public_wrapper_overhead_seconds',mean([rows.public_wrapper_overhead_seconds]),'mean_NR_updates',mean([rows.NR_updates]), ...
    'source_records',source_records,'source_files_unchanged',true,'MATLAB_profiler_enabled',false, ...
    'benchmark_is_not_annual_coverage_evidence',true,'rows',rows);
writetable(struct2table(rows),fullfile(out,'runtime_by_hour.csv'));
fid=fopen(fullfile(out,'benchmark_receipt.json'),'w');fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
fprintf('LOSS_BENCHMARK100 %.2fs annualprojection%.1fs policy%d PF%d VQ%d meanCall%.4f contextSolve%.4f wrapper%.4f\n', ...
    elapsed,report.projected_8651_hours_seconds,report.policy_qualified,report.PF_converged,report.physical_VQ_qualified, ...
    report.mean_call_seconds,report.mean_solver_with_context_seconds,report.mean_public_wrapper_overhead_seconds);
end
