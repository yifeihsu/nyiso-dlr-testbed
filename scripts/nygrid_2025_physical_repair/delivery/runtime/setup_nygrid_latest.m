function info=setup_nygrid_latest(package_root,matpower_root)
%SETUP_NYGRID_LATEST Session-only setup for the single current model.
% Package layout: runtime/, model/, vendor/matpower8.1/. MATLAB is external.
p=nylatest_paths();if nargin<1||isempty(package_root),package_root=p.root;end
assert(usejava('jvm'),'nylatest:JVM','MATLAB with JVM is required for model SHA-256 checks.');
package_root=char(java.io.File(char(package_root)).getCanonicalPath());
assert(strcmpi(package_root,char(java.io.File(p.root).getCanonicalPath())), ...
    'nylatest:Root','Call the setup helper belonging to the selected package.');
if nargin<2||isempty(matpower_root),matpower_root=fullfile(package_root,'vendor','matpower8.1');end
matpower_root=char(java.io.File(char(matpower_root)).getCanonicalPath());
dirs={fullfile(matpower_root,'lib'),fullfile(matpower_root,'mips','lib'), ...
    fullfile(matpower_root,'mp-opt-model','lib'),fullfile(matpower_root,'mptest','lib'),p.kernels,p.runtime};
for j=1:numel(dirs),assert(isfolder(dirs{j}),'nylatest:Dependency','Missing required current runtime or vendor folder.');addpath(dirs{j},'-begin');end
assert(strcmp(mpver,'8.1'),'nylatest:MATPOWERVersion','This current model is validated with MATPOWER8.1.');
assert(strcmpi(char(java.io.File(which('runpf')).getCanonicalPath()),fullfile(matpower_root,'lib','runpf.m')), ...
    'nylatest:ShadowedVendor','MATPOWER resolves outside the selected vendor root.');
[model,receipt]=nylatest_data();
names={'setup_nygrid_latest','load_nygrid_latest','run_nygrid_latest_acpf','screen_nygrid_latest_dlr', ...
    'nylatest_coupled_solve','nylatest_compact_build','nylatest_thermal_candidates','runpf','makeYbus','pfsoln'};
resolution=struct('function',{},'path',{});
for j=1:numel(names),resolution(end+1)=struct('function',names{j},'path',which(names{j}));end %#ok<AGROW>
info=struct('package_root',package_root,'runtime_root',p.runtime,'model_file',p.model_file, ...
    'model_sha256',receipt.model_file.sha256,'matpower_root',matpower_root,'MATLAB_version',version, ...
    'MATPOWER_version',mpver,'source_model_commit',model.source_model_commit, ...
    'hours',numel(model.axis.hour_index),'source_qualified_hours',nnz(model.axis.source_qualified), ...
    'topology_states',numel(model.templates),'retained_bus_count',numel(model.retained_bus_ids), ...
    'generator_count',numel(model.generator_bus_ids),'fixed_transfer_records',6, ...
    'historical_model_loader_required',false,'persistent_user_path_changed',false,'function_resolution',resolution);
end
