function report=run_Q_limit_pairs()
% Separate diagnostic: identical standard Q-limit policy on seven fixed inputs.
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
addpath(fullfile(root,'System Matpower Format'));
addpath(fullfile(root,'scripts','nygrid_2025_compact_ac','core'));
addpath(fullfile(root,'scripts','nygrid_2025_acpf_profile_audit','acpf'));
out=fullfile(root,'output','nygrid_2025_compact_ac','validation','Q_limit_pairs');if ~isfolder(out),mkdir(out);end
hours=[2630 4194 523 4000 8508 8471 8472];checks=struct([]);
opt=mpoption('model','AC','verbose',0,'out.all',0,'pf.alg','NR','pf.nr.max_it',50, ...
    'pf.tol',1e-10,'pf.enforce_q_lims',1,'exp.use_legacy_core',1);
ws=warning;cleanup=onCleanup(@()warning(ws));warning('off','MATLAB:nearlySingularMatrix');warning('off','MATLAB:singularMatrix');
for h=hours
    m=npcc_nygrid_2025_ac(h);c=compact_ac_build(m);
    [detailed,~]=runpf(m,opt);[da,dd]=audit_profile_pf(m,detailed);
    [compact,ca,recovered]=compact_ac_solve(c,opt);
    both=logical(detailed.success&&compact.success);refs_equal=isequal(detailed.bus(detailed.bus(:,2)==3,1),recovered.bus(recovered.bus(:,2)==3,1));
    a=struct('hour_index',h,'detailed_PF_converged',logical(detailed.success),'compact_PF_converged',logical(compact.success), ...
        'both_converged',both,'detailed_equation_gate',da.AC_equation_gate,'compact_equation_gate',ca.AC_equation_gate, ...
        'detailed_P_profile_gate',da.P_profile_preservation_gate,'compact_P_profile_gate',ca.P_profile_preservation_gate, ...
        'same_final_reference',refs_equal,'compact_final_reference',recovered.bus(recovered.bus(:,2)==3,1), ...
        'compact_reference_changed',~isequal(m.bus(m.bus(:,2)==3,1),recovered.bus(recovered.bus(:,2)==3,1)), ...
        'compact_PV_to_PQ_bus_count',nnz(m.bus(:,2)~=1&recovered.bus(:,2)==1), ...
        'compact_PG_changed_generators',nnz(abs(m.gen(:,2)-recovered.gen(:,2))>1e-7), ...
        'compact_max_non_slack_PG_change_MW',ca.maximum_non_slack_PG_change_MW, ...
        'compact_max_Q_bound_violation_MVAr',ca.max_Q_bound_violation_mvar, ...
        'compact_max_DC_Q_bound_violation_MVAr',ca.max_transfer_Q_bound_violation_mvar, ...
        'compact_normal_voltage_gate',ca.normal_voltage_gate,'compact_generator_P_gate',ca.generator_active_bound_gate, ...
        'compact_VQ_assumption_gate',ca.VQ_and_generator_assumption_gate, ...
        'detailed_NR_iterations',detailed.iterations,'compact_NR_iterations',compact.iterations, ...
        'maximum_complex_voltage_difference_pu',NaN,'maximum_original_branch_PQ_difference_MVA',NaN, ...
        'maximum_original_branch_current_difference_A',NaN,'maximum_generator_PQ_difference_MVA',NaN, ...
        'maximum_DC_PQ_difference_MVA',NaN,'qualified_pair_equivalent',false,'outcome_consistent',false, ...
        'failed_iterates_are_not_compared_as_solutions',true);
    if both
        vd=detailed.bus(:,8).*exp(1j*deg2rad(detailed.bus(:,9)));vc=compact.recovered_full_voltage;
        a.maximum_complex_voltage_difference_pu=max(abs(vd-vc));
        a.maximum_original_branch_PQ_difference_MVA=max(abs(detailed.branch(:,14:17)-recovered.branch(:,14:17)),[],'all');
        a.maximum_original_branch_current_difference_A=max(abs(compact.recovered_line_current_A- ...
            [dd.from_terminal_current_amp dd.to_terminal_current_amp dd.series_current_amp]),[],'all');
        a.maximum_generator_PQ_difference_MVA=max(abs(detailed.gen(:,2:3)-recovered.gen(:,2:3)),[],'all');
        a.maximum_DC_PQ_difference_MVA=max(abs(detailed.dcline(:,4:7)-recovered.dcline(:,4:7)),[],'all');
        a.qualified_pair_equivalent=da.AC_equation_gate&&ca.AC_equation_gate&&refs_equal ...
            &&a.maximum_complex_voltage_difference_pu<1e-7&&a.maximum_original_branch_PQ_difference_MVA<1e-4 ...
            &&a.maximum_original_branch_current_difference_A<1e-3&&a.maximum_generator_PQ_difference_MVA<1e-4 ...
            &&a.maximum_DC_PQ_difference_MVA<1e-4;
    end
    a.outcome_consistent=a.qualified_pair_equivalent||(~detailed.success&&~compact.success);
    save(fullfile(out,sprintf('h%04d.mat',h)),'m','c','detailed','da','compact','ca','recovered','a','opt');
    fid=fopen(fullfile(out,sprintf('h%04d.json',h)),'w');fprintf(fid,'%s\n',jsonencode(a,'PrettyPrint',true));fclose(fid);
    checks=[checks a]; %#ok<AGROW>
    fprintf('COMPACT_Q1_PAIR h%d full%d compact%d paired%d consistent%d V%.3g PQ%.3g I%.3g\n',h,detailed.success,compact.success,a.qualified_pair_equivalent,a.outcome_consistent,a.maximum_complex_voltage_difference_pu,a.maximum_original_branch_PQ_difference_MVA,a.maximum_original_branch_current_difference_A);
end
report=struct('completed',true,'outcomes_consistent',all([checks.outcome_consistent]),'Q_limit_mode',1,'diagnostic_only',true, ...
    'same_seven_hours',hours,'both_converged_hours',[checks([checks.both_converged]).hour_index], ...
    'qualified_pairs',[checks([checks.qualified_pair_equivalent]).hour_index], ...
    'detailed_failed_hours',[checks(~[checks.detailed_PF_converged]).hour_index], ...
    'compact_failed_hours',[checks(~[checks.compact_PF_converged]).hour_index], ...
    'OPF_or_parameter_fitting_used',false,'primary_q0_annual_results_replaced',false, ...
    'global_infeasibility_claimed_from_failed_PF',false,'checks',checks);
writetable(struct2table(checks),fullfile(out,'Q_limit_pair_checks.csv'));
fid=fopen(fullfile(out,'Q_limit_pair_receipt.json'),'w');fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
end
