function report=run_representative_pairs()
% Fresh paired native148/detailed PF on unchanged source profiles.
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
addpath(fullfile(root,'System Matpower Format'));
addpath(fullfile(root,'scripts','nygrid_2025_compact_ac','core'));
addpath(fullfile(root,'scripts','nygrid_2025_acpf_profile_audit','acpf'));
out=fullfile(root,'output','nygrid_2025_compact_ac','validation','representative_pairs');if ~isfolder(out),mkdir(out);end
hours=[2630 4194 523 4000 8508 8471 8472 3360];checks=struct([]);
opt=mpoption('model','AC','verbose',0,'out.all',0,'pf.alg','NR','pf.nr.max_it',50, ...
    'pf.tol',1e-10,'pf.enforce_q_lims',0,'exp.use_legacy_core',1);
for h=hours
    m=npcc_nygrid_2025_ac(h);
    t=tic;c=compact_ac_build(m);build_seconds=toc(t);
    assert(numel(c.retained_bus_ids)==148&&isempty(c.promoted_bus_ids));
    ref=compact_reference_operators(m,c.retained_bus_ids);
    matrix_error=norm(c.Yred-ref.Yred,inf)/max(1,norm(ref.Yred,inf));
    lift_error=max(abs(full(c.voltage_lift)-ref.voltage_lift),[],'all');
    assert(matrix_error<1e-10&&lift_error<1e-9);
    t=tic;[detailed,detailed_ok]=runpf(m,opt);detailed_seconds=toc(t);
    [detailed_audit,detailed_detail]=audit_profile_pf(m,detailed);
    t=tic;[compact,compact_audit,recovered]=run_nygrid_2025_compact_acpf(c,opt);compact_seconds=toc(t);
    [independent_audit,independent_detail]=audit_profile_pf(m,recovered);
    % Independent effective-control reconstruction, including converted DC VG.
    mi=ext2int(m,opt);[refi,pvi,pqi]=bustypes(mi.bus,mi.gen); %#ok<ASGLU>
    on=find(mi.gen(:,8)>0);gb=mi.gen(on,1);voltage=mi.bus(:,8).*exp(1j*deg2rad(mi.bus(:,9)));
    controlled=ones(size(mi.bus,1),1);controlled(pqi)=0;use=find(controlled(gb));
    voltage(gb(use))=mi.gen(on(use),6)./abs(voltage(gb(use))).*voltage(gb(use));
    [ok,retained_internal]=ismember(c.retained_bus_ids,mi.order.bus.i2e);assert(all(ok));
    controls_exact=isequal(compact.initial_control.generator_PG,mi.gen(:,2)) ...
        &&isequal(compact.initial_control.generator_QG,mi.gen(:,3)) ...
        &&isequal(compact.initial_control.generator_VG,mi.gen(:,6)) ...
        &&max(abs(compact.initial_control.retained_initial_voltage-voltage(retained_internal)))<1e-14;
    assert(controls_exact);
    VD=detailed.bus(:,8).*exp(1j*deg2rad(detailed.bus(:,9)));
    VC=recovered.bus(:,8).*exp(1j*deg2rad(recovered.bus(:,9)));
    direct_from=ref.Yfrom*VC;direct_to=ref.Yto*VC;direct_series=ref.Yseries*VC;
    If=abs(direct_from)*m.baseMVA*1000./(sqrt(3)*m.bus(ref.from_bus_rows,10));
    It=abs(direct_to)*m.baseMVA*1000./(sqrt(3)*m.bus(ref.to_bus_rows,10));
    Is=abs(direct_series)*m.baseMVA*1000./(sqrt(3)*m.bus(ref.to_bus_rows,10));
    direct_current_error=max(abs(compact.recovered_line_current_A-[If It Is]),[],'all');
    a=struct('hour_index',h,'in_original_seven_hour_cohort',h~=3360,'retained_buses',148,'full_buses',size(m.bus,1), ...
        'eliminated_buses',numel(c.eliminated_full_rows),'matrix_relative_error',matrix_error,'lift_matrix_max_error',lift_error, ...
        'effective_initial_PQ_VG_DC_controls_exact',controls_exact,'build_seconds',build_seconds, ...
        'detailed_PF_seconds',detailed_seconds,'compact_PF_seconds_including_full_recovery_audit',compact_seconds, ...
        'detailed_PF_converged',logical(detailed_ok),'compact_PF_converged',compact.success, ...
        'detailed_equation_gate',detailed_audit.AC_equation_gate,'compact_full_equation_gate',independent_audit.AC_equation_gate, ...
        'profile_P_preserved',independent_audit.P_profile_preservation_gate, ...
        'detailed_iterations',detailed.iterations,'compact_iterations',compact.iterations, ...
        'maximum_full_complex_voltage_difference_pu',max(abs(VD-VC)), ...
        'maximum_original_branch_PQ_difference_MVA',max(abs(detailed.branch(:,14:17)-recovered.branch(:,14:17)),[],'all'), ...
        'maximum_original_branch_current_difference_A',max(abs(compact.recovered_line_current_A- ...
            [detailed_detail.from_terminal_current_amp detailed_detail.to_terminal_current_amp detailed_detail.series_current_amp]),[],'all'), ...
        'maximum_generator_PQ_difference_MVA',max(abs(detailed.gen(:,2:3)-recovered.gen(:,2:3)),[],'all'), ...
        'maximum_DC_PQ_difference_MVA',max(abs(detailed.dcline(:,4:7)-recovered.dcline(:,4:7)),[],'all'), ...
        'maximum_independent_current_operator_error_A',direct_current_error, ...
        'compact_VQ_assumption_gate',independent_audit.VQ_and_generator_assumption_gate, ...
        'no_full_network_Newton_solve_inside_compact',compact_audit.no_full_network_Newton_solve,'passed',false);
    a.passed=a.detailed_PF_converged&&a.compact_PF_converged&&a.detailed_equation_gate&&a.compact_full_equation_gate ...
        &&a.profile_P_preserved&&a.maximum_full_complex_voltage_difference_pu<1e-7 ...
        &&a.maximum_original_branch_PQ_difference_MVA<1e-4&&a.maximum_original_branch_current_difference_A<1e-3 ...
        &&a.maximum_generator_PQ_difference_MVA<1e-4&&a.maximum_DC_PQ_difference_MVA<1e-4&&direct_current_error<1e-5;
    save(fullfile(out,sprintf('h%04d.mat',h)),'m','c','compact','compact_audit','recovered','detailed','detailed_audit','independent_audit','a','opt');
    fid=fopen(fullfile(out,sprintf('h%04d.json',h)),'w');fprintf(fid,'%s\n',jsonencode(a,'PrettyPrint',true));fclose(fid);
    checks=[checks a]; %#ok<AGROW>
    fprintf('COMPACT_PAIR h%d full%d compact%d pass%d V%.3g PQ%.3g I%.3g build%.3fs full%.3fs compact%.3fs\n', ...
        h,detailed_ok,compact.success,a.passed,a.maximum_full_complex_voltage_difference_pu,a.maximum_original_branch_PQ_difference_MVA, ...
        a.maximum_original_branch_current_difference_A,build_seconds,detailed_seconds,compact_seconds);
end
report=struct('completed',true,'passed',all([checks.passed]),'checks',checks, ...
    'primary_seven_hours_preserved',true,'additional_May21_topology_case',3360,'OPF_used',false, ...
    'new_internal_interface_observations_read',false,'reduction_does_not_upgrade_parent_physical_flags',true, ...
    'median_build_seconds',median([checks.build_seconds]),'median_compact_solve_recovery_audit_seconds',median([checks.compact_PF_seconds_including_full_recovery_audit]));
writetable(struct2table(checks),fullfile(out,'representative_pair_checks.csv'));
fid=fopen(fullfile(out,'representative_pair_receipt.json'),'w');fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
end
