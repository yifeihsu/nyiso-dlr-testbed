function receipt=export_models()
%EXPORT_MODELS Save inspectable 148-bus matrix models and recovery operators.
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
addpath(fullfile(root,'System Matpower Format'));
addpath(fullfile(root,'scripts','nygrid_2025_compact_ac','core'));
addpath(fullfile(root,'scripts','nygrid_2025_acpf_profile_audit','acpf'));
out=fullfile(root,'output','nygrid_2025_compact_ac','models');
if ~exist(out,'dir'),mkdir(out);end
cache=load_profile_cache();hours=[cache.template_hours(:);8508];items=struct([]);
for n=1:numel(hours)
    h=hours(n);m=profile_case_from_cache(cache,h);model=compact_ac_build(m);
    filename=sprintf('compact_ac_h%04d.mat',h);save(fullfile(out,filename),'model','-v7');
    item=struct('hour_index',h,'timestamp_utc',string(m.userdata.ac_system.timestamp_utc), ...
        'dated_state',cache.state_names(cache.state_index(h)), 'filename',filename, ...
        'baseMVA',model.baseMVA,'retained_bus_count',size(model.bus,1), ...
        'eliminated_bus_count',numel(model.eliminated_full_rows), ...
        'promoted_necessary_bus_count',numel(model.promoted_bus_ids), ...
        'detailed_branch_rows',size(m.branch,1),'Yred_nonzero_entries',nnz(model.Yred), ...
        'source_fingerprint',model.source_fingerprint,'operator_fingerprint',model.operator_fingerprint, ...
        'validation',model.validation);
    items=[items;item]; %#ok<AGROW>
end
receipt=struct('passed',true,'OPF_used',false,'fixed_hour_examples',true, ...
    'live_hourly_constructor','npcc_nygrid_2025_compact_ac', ...
    'solver','run_nygrid_2025_compact_acpf','models',items);
fid=fopen(fullfile(out,'model_exports.json'),'w');assert(fid>0);
fprintf(fid,'%s\n',jsonencode(receipt,PrettyPrint=true));fclose(fid);
end
