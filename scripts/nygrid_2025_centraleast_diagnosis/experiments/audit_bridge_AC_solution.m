function a=audit_bridge_AC_solution(m,r)
% Physics/profile audit for diagnostic AC cases without inherited asset labels.
nb=size(m.bus,1);nl=size(m.branch,1);V=r.bus(:,8).*exp(1j*deg2rad(r.bus(:,9)));
[ok,f]=ismember(m.branch(:,1),m.bus(:,1));assert(all(ok));[ok,t]=ismember(m.branch(:,2),m.bus(:,1));assert(all(ok));
[ok,g]=ismember(m.gen(:,1),m.bus(:,1));assert(all(ok));
tap=m.branch(:,9);tap(tap==0)=1;tap=tap.*exp(1j*deg2rad(m.branch(:,10)));on=m.branch(:,11)>0;
y=zeros(nl,1);y(on)=1./complex(m.branch(on,3),m.branch(on,4));bc=1j*m.branch(:,5)/2;bc(~on)=0;
Is=y.*(V(f)./tap-V(t));If=Is./conj(tap)+bc.*V(f)./abs(tap).^2;It=-Is+bc.*V(t);
Sf=m.baseMVA*V(f).*conj(If);St=m.baseMVA*V(t).*conj(It);
Sgen=accumarray(g,complex(r.gen(:,2),r.gen(:,3)).*(m.gen(:,8)>0),[nb 1]);Sdc=zeros(nb,1);
for k=find(r.dcline(:,3)>0)'
    df=find(m.bus(:,1)==r.dcline(k,1));dt=find(m.bus(:,1)==r.dcline(k,2));
    Sdc(df)=Sdc(df)+complex(-r.dcline(k,4),r.dcline(k,6));Sdc(dt)=Sdc(dt)+complex(r.dcline(k,5),r.dcline(k,7));
end
kcl=Sgen+Sdc-complex(m.bus(:,3),m.bus(:,4))-abs(V).^2.*complex(m.bus(:,5),-m.bus(:,6)) ...
    -accumarray(f,Sf,[nb 1])-accumarray(t,St,[nb 1]);
ref=m.bus(m.bus(:,2)==3,1);slack=find(m.gen(:,1)==ref&m.gen(:,8)>0,1);other=true(size(m.gen,1),1);other(slack)=false;
delta=r.gen(:,2)-m.gen(:,2);expected=sum(real(Sf+St))+sum(r.dcline(:,4)-r.dcline(:,5))+sum(m.bus(:,5).*abs(V).^2)+sum(m.bus(:,3))-sum(m.gen(:,2));
a=struct('converged',logical(r.success),'max_P_residual_MW',max(abs(real(kcl))),'max_Q_residual_MVAr',max(abs(imag(kcl))), ...
    'max_branch_complex_error_MVA',max(abs([Sf-complex(r.branch(:,14),r.branch(:,15));St-complex(r.branch(:,16),r.branch(:,17))])), ...
    'PD_QD_preserved',isequal(m.bus(:,[1 3 4]),r.bus(:,[1 3 4])),'max_non_slack_PG_change_MW',max(abs(delta(other))), ...
    'max_DC_P_change_MW',max(abs(r.dcline(:,4:5)-m.dcline(:,4:5)),[],'all'),'AC_loss_MW',sum(real(Sf+St)), ...
    'slack_increment_MW',delta(slack),'slack_balance_error_MW',delta(slack)-expected, ...
    'min_VM_pu',min(abs(V)),'max_VM_pu',max(abs(V)), ...
    'max_P_bound_violation_MW',max([0;m.gen(:,10)-r.gen(:,2);r.gen(:,2)-m.gen(:,9)]), ...
    'max_Q_bound_violation_MVAr',max([0;m.gen(:,5)-r.gen(:,3);r.gen(:,3)-m.gen(:,4)]), ...
    'equation_and_profile_qualified',false,'physical_or_asset_qualification_claimed',false);
a.equation_and_profile_qualified=a.converged&&a.PD_QD_preserved ...
    &&max([a.max_P_residual_MW,a.max_Q_residual_MVAr,a.max_branch_complex_error_MVA, ...
    a.max_non_slack_PG_change_MW,a.max_DC_P_change_MW,abs(a.slack_balance_error_MW)])<1e-5;
end
