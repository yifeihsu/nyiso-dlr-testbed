function report=run_loss_and_parent_diagnostics()
% Representative R0, half-loss-loadedDCF, and coherent old-parentAC diagnostics.
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
base=fullfile(root,'output','nygrid_2025_centraleast_diagnosis','experiments');
proof=jsondecode(fileread(fullfile(base,'representative_bridge','bridge_receipt.json')));assert(proof.passed);
out=fullfile(base,'loss_and_parent_diagnostics');if ~isfolder(out),mkdir(out);end
checks=struct([]);started=tic;ws=warning;cleanup=onCleanup(@()warning(ws));warning('off','MATLAB:nearlySingularMatrix');warning('off','MATLAB:singularMatrix');
for h=proof.hours(:)'
    b=load(fullfile(base,'representative_bridge',sprintf('bridge_h%04d.mat',h)));gamma=b.a.gamma;parents=b.detailed.userdata.ac_system.branch_parent_row;
    % R0 changes series resistance only. It changes voltages and angles too,
    % so its difference is a broad conductance intervention, not pure losses.
    zeroR=b.detailed;zeroR.branch(:,3)=0;
    assert(isequal(zeroR.branch(:,[1:2 4:end]),b.detailed.branch(:,[1:2 4:end])));
    t=tic;result_R0=runpf(zeroR,b.acopt);R0_seconds=toc(t);audit_R0=audit_bridge_AC_solution(zeroR,result_R0);
    if_R0=physical_interface_flows(result_R0,parents,b.full);
    % Add the solved baseline real losses as half-demand at each branch end.
    loss_by_branch=b.detailed_ac.branch(:,14)+b.detailed_ac.branch(:,16);assert(min(loss_by_branch)>-1e-6);
    [ok,f]=ismember(b.detailed.branch(:,1),b.detailed.bus(:,1));assert(all(ok));[ok,t]=ismember(b.detailed.branch(:,2),b.detailed.bus(:,1));assert(all(ok));
    loss_PD=accumarray(f,loss_by_branch/2,[size(b.detailed.bus,1) 1])+accumarray(t,loss_by_branch/2,[size(b.detailed.bus,1) 1]);
    loaded=b.detailed;loaded.bus(:,3)=loaded.bus(:,3)+loss_PD;
    assert(abs(sum(loss_PD)-b.ac_audit.AC_real_losses_mw)<1e-7&&isequal(loaded.gen,b.detailed.gen)&&isequal(loaded.dcline,b.detailed.dcline));
    t=tic;result_loss_DCF=rundcpf(loaded,b.dcopt);loss_DCF_seconds=toc(t);audit_loss_DCF=audit_diagnostic_DCPF(loaded,result_loss_DCF);
    if_loss_DCF=physical_interface_flows(result_loss_DCF,parents,b.full);
    % Coherent old-parent R/X/B/GS/BS; copy the same detailedAC real generator
    % and converter control fields plus bus classifications/initial voltages.
    parent_AC=b.full;parent_AC.gen=b.detailed.gen;parent_AC.dcline=b.detailed.dcline;
    [ok,ix]=ismember(parent_AC.bus(:,1),b.detailed.bus(:,1));assert(all(ok));
    parent_AC.bus(:,[2 8 9])=b.detailed.bus(ix,[2 8 9]);
    assert(isequal(parent_AC.branch,b.full.branch)&&isequal(parent_AC.bus(:,3:6),b.full.bus(:,3:6)));
    assert(isequal(parent_AC.gen(:,[1 2 6 8]),b.detailed.gen(:,[1 2 6 8]))&&isequal(parent_AC.dcline,b.detailed.dcline));
    t=tic;result_parent_AC=runpf(parent_AC,b.acopt);parent_AC_seconds=toc(t);audit_parent_AC=audit_bridge_AC_solution(parent_AC,result_parent_AC);
    if_parent_AC=physical_interface_flows(result_parent_AC,(1:size(parent_AC.branch,1))',b.full);
    a=struct('hour_index',h,'R0_AC_equation_profile_qualified',audit_R0.equation_and_profile_qualified, ...
        'R0_AC_seconds',R0_seconds,'R0_CE_public_MW',if_R0(5,1)/gamma, ...
        'R0_CE_delta_from_baseline_AC_public_MW',(if_R0(5,1)-b.detailed_ac_if(5,1))/gamma, ...
        'R0_AC_losses_model_MW',audit_R0.AC_loss_MW,'R0_min_VM',audit_R0.min_VM_pu,'R0_max_VM',audit_R0.max_VM_pu, ...
        'loss_loaded_DCF_audit_passed',audit_loss_DCF.passed,'loss_loaded_DCF_seconds',loss_DCF_seconds, ...
        'half_loss_PD_total_model_MW',sum(loss_PD),'loss_loaded_DCF_slack_increment_model_MW',audit_loss_DCF.slack_PG_change_MW, ...
        'loss_loaded_DCF_CE_public_MW',if_loss_DCF(5,1)/gamma, ...
        'CE_loss_allocation_delta_public_MW',(if_loss_DCF(5,1)-b.detailed_dc_if(5,1))/gamma, ...
        'CE_remaining_AC_minus_loss_loaded_DCF_public_MW',(b.detailed_ac_if(5,1)-if_loss_DCF(5,1))/gamma, ...
        'parent_AC_equation_profile_qualified',audit_parent_AC.equation_and_profile_qualified,'parent_AC_seconds',parent_AC_seconds, ...
        'parent_AC_CE_public_MW',if_parent_AC(5,1)/gamma,'parent_AC_CE_minus_archived_DC_public_MW',(if_parent_AC(5,1)-b.archived_if(5))/gamma, ...
        'parent_AC_losses_model_MW',audit_parent_AC.AC_loss_MW,'parent_AC_min_VM',audit_parent_AC.min_VM_pu,'parent_AC_max_VM',audit_parent_AC.max_VM_pu, ...
        'diagnostic_only_no_production_profile_or_model_change',true);
    save(fullfile(out,sprintf('h%04d.mat',h)),'zeroR','result_R0','audit_R0','if_R0','loaded','loss_by_branch','loss_PD', ...
        'result_loss_DCF','audit_loss_DCF','if_loss_DCF','parent_AC','result_parent_AC','audit_parent_AC','if_parent_AC','a');
    checks=[checks a]; %#ok<AGROW>
    fprintf('CE_LOSS_PARENT h%d R0ok%d delta%+.3f lossDCFok%d lossdelta%+.3f remainder%+.3f parentACok%d parentdelta%+.3f publicMW\n', ...
        h,a.R0_AC_equation_profile_qualified,a.R0_CE_delta_from_baseline_AC_public_MW,a.loss_loaded_DCF_audit_passed, ...
        a.CE_loss_allocation_delta_public_MW,a.CE_remaining_AC_minus_loss_loaded_DCF_public_MW,a.parent_AC_equation_profile_qualified,a.parent_AC_CE_minus_archived_DC_public_MW);
end
report=struct('completed',true,'hours',proof.hours,'checks',checks,'elapsed_seconds',toc(started), ...
    'R0_qualified',sum([checks.R0_AC_equation_profile_qualified]),'loss_loaded_DCF_qualified',sum([checks.loss_loaded_DCF_audit_passed]), ...
    'parent_AC_qualified',sum([checks.parent_AC_equation_profile_qualified]),'OPF_or_fitting_used',false, ...
    'R0_is_conductance_intervention_not_pure_loss_attribution',true,'half_loss_allocation_is_nonunique_diagnostic',true, ...
    'parent_AC_uses_original_R_X_B_GS_BS_and_same_controlled_VG_reference',true, ...
    'production_profiles_models_and_results_unchanged',true,'failed_iterates_retained_not_valid_predictions',true);
writetable(struct2table(checks),fullfile(out,'diagnostic_checks.csv'));
fid=fopen(fullfile(out,'diagnostic_receipt.json'),'w');fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
end
