function a=audit_diagnostic_DCPF(input,result)
% Independent lossless DC branch law and nodalP check; AC gate is inapplicable.
[ok,f]=ismember(result.branch(:,1),result.bus(:,1));assert(all(ok));
[ok,t]=ismember(result.branch(:,2),result.bus(:,1));assert(all(ok));
[ok,g]=ismember(result.gen(:,1),result.bus(:,1));assert(all(ok));
[ok,df]=ismember(result.dcline(:,1),result.bus(:,1));assert(all(ok));
[ok,dt]=ismember(result.dcline(:,2),result.bus(:,1));assert(all(ok));
nb=size(result.bus,1);tau=result.branch(:,9);tau(tau==0)=1;
theta=deg2rad(result.bus(:,9));expected=result.baseMVA*result.branch(:,11)./(result.branch(:,4).*tau).*(theta(f)-theta(t)-deg2rad(result.branch(:,10)));
P=accumarray(g,result.gen(:,2).*(result.gen(:,8)>0),[nb 1])-result.bus(:,3)-result.bus(:,5) ...
    -accumarray(df,result.dcline(:,4),[nb 1])+accumarray(dt,result.dcline(:,5),[nb 1]);
out=accumarray(f,result.branch(:,14),[nb 1])+accumarray(t,result.branch(:,16),[nb 1]);
ref=input.bus(input.bus(:,2)==3,1);slack=find(input.gen(:,1)==ref&input.gen(:,8)>0,1);other=true(size(input.gen,1),1);other(slack)=false;
a=struct('converged',logical(result.success),'max_branch_law_error_MW',max(abs(expected-result.branch(:,14))), ...
    'max_nodal_P_residual_MW',max(abs(P-out)),'max_lossless_terminal_identity_MW',max(abs(result.branch(:,14)+result.branch(:,16))), ...
    'PD_QD_exact',isequal(input.bus(:,[1 3 4]),result.bus(:,[1 3 4])), ...
    'max_non_slack_PG_change_MW',max(abs(result.gen(other,2)-input.gen(other,2))), ...
    'slack_PG_change_MW',result.gen(slack,2)-input.gen(slack,2), ...
    'max_six_DC_P_change_MW',max(abs(result.dcline(:,4:5)-input.dcline(:,4:5)),[],'all'),'passed',false);
a.passed=a.converged&&a.PD_QD_exact&&max([a.max_branch_law_error_MW,a.max_nodal_P_residual_MW, ...
    a.max_lossless_terminal_identity_MW,a.max_non_slack_PG_change_MW,a.max_six_DC_P_change_MW])<1e-7;
end
