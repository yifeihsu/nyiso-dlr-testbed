function report=run_X_only_ablations()
% Independent X-only counterfactuals after a qualified originalDC bridge.
root=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
addpath(fullfile(root,'scripts','nygrid_2025_acpf_profile_audit','acpf'));
addpath(fullfile(root,'scripts','nygrid_2025_ac_system','thermal'));
addpath(fullfile(root,'System Matpower Format','NY_Lite'));
base=fullfile(root,'output','nygrid_2025_centraleast_diagnosis','experiments');
proof=jsondecode(fileread(fullfile(base,'representative_bridge','bridge_receipt.json')));assert(proof.passed);
out=fullfile(base,'X_only_ablations');if ~isfolder(out),mkdir(out);end
labels={'restore_parent224_X','restore_parent41_X','restore_all33_X'};selections={224,41,'all_changed'};checks=struct([]);start=tic;
ws=warning;cleanup=onCleanup(@()warning(ws));warning('off','MATLAB:nearlySingularMatrix');warning('off','MATLAB:singularMatrix');
for h=proof.hours(:)'
    b=load(fullfile(base,'representative_bridge',sprintf('bridge_h%04d.mat',h)));
    for k=1:3
        [m,ledger]=restore_parent_X_only(b.detailed,b.full,selections{k});
        t=tic;rdc=rundcpf(m,b.dcopt);dc_seconds=toc(t);da=audit_diagnostic_DCPF(m,rdc);
        fdc=physical_interface_flows(rdc,m.userdata.ac_system.branch_parent_row,b.full);
        t=tic;rac=runpf(m,b.acopt);ac_seconds=toc(t);[aa,detail]=audit_profile_pf(m,rac);
        fac=physical_interface_flows(rac,m.userdata.ac_system.branch_parent_row,b.full);gamma=b.a.gamma;
        a=struct('hour_index',h,'variant',labels{k},'changed_parent_count',size(ledger,1), ...
            'DCPF_seconds',dc_seconds,'ACPF_seconds',ac_seconds,'DCPF_audit_passed',da.passed, ...
            'ACPF_converged',logical(rac.success),'AC_equation_gate',aa.AC_equation_gate,'P_profile_gate',aa.P_profile_preservation_gate, ...
            'VQ_assumption_gate',aa.VQ_and_generator_assumption_gate,'AC_comparison_qualified',aa.AC_equation_gate&&aa.P_profile_preservation_gate, ...
            'CE_DCPF_public_MW',fdc(5,1)/gamma,'CE_ACPF_public_MW',fac(5,1)/gamma, ...
            'CE_DCPF_delta_from_detailed_baseline_public_MW',(fdc(5,1)-b.detailed_dc_if(5,1))/gamma, ...
            'CE_ACPF_delta_from_detailed_baseline_public_MW',(fac(5,1)-b.detailed_ac_if(5,1))/gamma, ...
            'CE_DCPF_minus_archived_DC_public_MW',(fdc(5,1)-b.archived_if(5))/gamma, ...
            'CE_ACPF_minus_archived_DC_public_MW',(fac(5,1)-b.archived_if(5))/gamma, ...
            'AC_loss_model_MW',aa.AC_real_losses_mw,'slack_P_increment_model_MW',aa.reference_PG_change_MW, ...
            'max_non_slack_PG_change_MW',aa.maximum_non_slack_PG_change_MW,'min_VM_pu',aa.min_voltage_pu,'max_VM_pu',aa.max_voltage_pu, ...
            'diagnostic_intervention_not_repair_or_physical_requalification',true);
        save(fullfile(out,sprintf('%s_h%04d.mat',labels{k},h)),'m','ledger','rdc','rac','da','aa','detail','fdc','fac','a');
        checks=[checks a]; %#ok<AGROW>
        fprintf('CE_X_ONLY h%d %s DCpass%d ACeq%d CE_DCdelta%+.3f ACdelta%+.3f remainingDC%+.3g publicMW\n', ...
            h,labels{k},da.passed,a.AC_comparison_qualified,a.CE_DCPF_delta_from_detailed_baseline_public_MW, ...
            a.CE_ACPF_delta_from_detailed_baseline_public_MW,a.CE_DCPF_minus_archived_DC_public_MW);
    end
end
report=struct('completed',true,'all_DCPF_audits_passed',all([checks.DCPF_audit_passed]), ...
    'AC_equation_and_profile_qualified',sum([checks.AC_comparison_qualified]),'attempts',numel(checks), ...
    'variants',{labels},'hours',proof.hours,'checks',checks,'elapsed_seconds',toc(start), ...
    'only_selected_parent_X_changed',true,'R_B_taps_phase_shunts_status_and_profiles_unchanged',true, ...
    'OPF_or_fitting_used',false,'diagnostic_only_not_model_repair',true,'failed_iterates_not_valid_predictions',true);
writetable(struct2table(checks),fullfile(out,'X_only_checks.csv'));
fid=fopen(fullfile(out,'X_only_receipt.json'),'w');fprintf(fid,'%s\n',jsonencode(report,'PrettyPrint',true));fclose(fid);
end
