function assert_unique_policy_row(policy, category, setting, expected_value)
scope = policy.category == string(category) & ...
    policy.setting == string(setting);
matches = scope & policy.value == string(expected_value);
if nnz(scope) ~= 1 || nnz(matches) ~= 1
    error('run_handoff_reproduction:HierarchyPolicyMismatch', ...
        'Expected exactly one %s/%s row with value %s.', ...
        category, setting, expected_value);
end
end
