function outputs = run_handoff_reproduction(options)
%RUN_HANDOFF_REPRODUCTION Rebuild and verify the NPCC/NYISO hierarchy.
%   Run from the package root:
%       outputs = run_handoff_reproduction;
%
%   The default path regenerates public targets from the included cache,
%   reruns the legacy S6/S7 regressions, applies ratings-only Phase 0 to the
%   full S7 provenance case, and validates the cumulative Phase 1B S13-FULL
%   construction parent's structural provenance. S14-NYISO is the pending
%   promoted DLR operating model and is not built by this runner. Set
%   run_s8_operational_closure=true to
%   rerun the iterative AC dispatch diagnostic. The S8.1 capability certificate
%   S9a reactive-control diagnostic, S9b feasibility restoration, and the
%   S10a control-preserving PERFORM benchmark can be enabled independently.
%   S8.1/S9a/S9b refresh their S8 prerequisite. Set
%   run_full_calibration=true to
%   rerun the broad 226-candidate S7 parameter sweep (several minutes).
%   S12 remains a reference oracle and is not promoted by this runner.

if nargin < 1, options = struct(); end
if ~isfield(options, 'rebuild_public_targets'), options.rebuild_public_targets = true; end
if ~isfield(options, 'run_full_calibration'), options.run_full_calibration = false; end
if ~isfield(options, 'run_s8_operational_closure')
    options.run_s8_operational_closure = false;
end
if ~isfield(options, 'run_s8_1_capability_certificate')
    options.run_s8_1_capability_certificate = false;
end
if ~isfield(options, 'run_s9a_q_support_diagnostic')
    options.run_s9a_q_support_diagnostic = false;
end
if ~isfield(options, 'run_s9b_feasibility_restoration')
    options.run_s9b_feasibility_restoration = false;
end
if ~isfield(options, 'run_s9b_reference_audit')
    options.run_s9b_reference_audit = false;
end
if ~isfield(options, 'run_s10a_control_benchmark')
    options.run_s10a_control_benchmark = false;
end
if ~isfield(options, 'run_s13_phase1a_smoke')
    options.run_s13_phase1a_smoke = true;
end
if ~isfield(options, 'run_s13_phase1a_oracle_preflight')
    options.run_s13_phase1a_oracle_preflight = true;
end
if ~isfield(options, 'run_s13_phase1b_validation')
    options.run_s13_phase1b_validation = true;
end
if ~isfield(options, 'run_s12_reference_comparison')
    options.run_s12_reference_comparison = false;
end
if options.run_s12_reference_comparison
    error('run_handoff_reproduction:S12PairedComparisonNotImplemented', ...
        ['The requested paired S12/S13-FULL diagnostic is not executable ' ...
        'because the common full-NPCC operating baseline remains fail-closed. ' ...
        'Use the default S13.1 preflight for the exact local identity and ' ...
        'readiness evidence.']);
end

root = fileparts(mfilename('fullpath'));
case_dir = fullfile(root, 'System Matpower Format');
helper_dir = fullfile(case_dir, 'NY_Lite');
addpath(root); addpath(case_dir); addpath(helper_dir);
hierarchy_policy = readtable(fullfile(root, 'LATEST_MODEL_CONFIGURATION.csv'), ...
    'TextType', 'string', 'VariableNamingRule', 'preserve');
assert_unique_policy_row(hierarchy_policy, "model", ...
    "structural_provenance_case", ...
    "npcc_ny_lite_s7_seven_interface_perform_direct_candidate");
assert_unique_policy_row(hierarchy_policy, "model", ...
    "construction_validation_parent", ...
    "npcc_ny_lite_s13_npcc_augmented_2019");
assert_unique_policy_row(hierarchy_policy, "model", ...
    "promoted_operating_case", ...
    "pending_npcc_ny_lite_s14_nyiso_dlr_operating_model");
assert_unique_policy_row(hierarchy_policy, "model", "reference_oracle", ...
    "npcc_ny_lite_s12_perform_retention_core");
assert_unique_policy_row(hierarchy_policy, "s14_nyiso", ...
    "promotion_eligible", "false");

if options.rebuild_public_targets
    public = build_nyiso_public_targets;
    scales = build_s4_interface_objective_scales;
else
    public = struct();
    scales = struct();
end

targets = readtable(fullfile(helper_dir, 'nyiso_public_interface_targets.csv'), ...
    'TextType', 'string', 'VariableNamingRule', 'preserve');
assert(height(targets) == 42, 'Expected 42 public target rows (7 interfaces x 6 scenarios).');
assert(numel(unique(targets.interface_name)) == 7, 'Expected seven public interfaces.');

s6 = run_s6_nyiso_net_injection_pf_benchmark;
assert(s6.scenario_count == 6 && s6.pf_success_count == 6, ...
    'S6 standard PF must converge for all six scenarios.');

direct = struct('gl_scales', 1, 'pv_wood_scales', 1, ...
    'wood_millwood_scales', 1, 'b_fractions', 1, ...
    'grid_file', fullfile(helper_dir, 's7_perform_direct_grid.csv'), ...
    'run_file', fullfile(helper_dir, 's7_perform_direct_pf_runs.csv'), ...
    'residual_file', fullfile(helper_dir, 's7_perform_direct_all_residuals.csv'), ...
    'summary_file', fullfile(helper_dir, 's7_perform_direct_comparison_summary.csv'), ...
    'selected_run_file', fullfile(helper_dir, 's7_perform_direct_pf_results.csv'), ...
    'selected_residual_file', fullfile(helper_dir, 's7_perform_direct_interface_residuals.csv'), ...
    'selected_parameter_file', fullfile(helper_dir, 's7_perform_direct_parameters.csv'), ...
    'selected_tie_file', fullfile(helper_dir, 's7_perform_direct_branch_parameters.csv'), ...
    'q_diagnostic_file', fullfile(helper_dir, 's7_perform_direct_q_diagnostics.csv'));
s7 = run_s7_seven_interface_perform_tieline_calibration(direct);
assert(s7.pf_run_count == 12 && s7.pf_success_count == 12, ...
    'Current and direct-PERFORM standard PF runs must all converge.');

mpc = loadcase('npcc_ny_lite_s7_seven_interface_perform_direct_candidate');
assert(size(mpc.bus, 1) == 143 && size(mpc.branch, 1) == 246 && ...
    size(mpc.gen, 1) == 62, 'Unexpected recommended S7 case dimensions.');
assert(~mpc.userdata.ny_lite.s7_seven_interface_calibration.promotion_eligible, ...
    'S7 must remain ineligible for DLR-model promotion.');
s12_role_check = loadcase('npcc_ny_lite_s12_perform_retention_core');
assert(~s12_role_check.userdata.promotion_eligible, ...
    'S12 must remain an oracle-only case.');

% Phase 0 must be topology-neutral and ratings-only by default.
[phase0_parent, phase0_report] = apply_ny_core_phase0_corrections(mpc, ...
    struct('fit_reactance', false, 'verbose', false));
assert(isequal(size(phase0_parent.bus), size(mpc.bus)) && ...
    isequal(size(phase0_parent.branch), size(mpc.branch)) && ...
    isequal(phase0_parent.bus(:, 1), mpc.bus(:, 1)) && ...
    isequal(phase0_parent.branch(:, 1:2), mpc.branch(:, 1:2)), ...
    'Ratings-only Phase 0 changed S7 topology or row identity.');
assert(max(abs(phase0_parent.branch(:, 3:5) - mpc.branch(:, 3:5)), [], 'all') == 0, ...
    'Ratings-only Phase 0 changed branch R/X/B.');

s13_candidate = loadcase('npcc_ny_lite_s13_npcc_augmented_2019');
s13_validation = validate_s13_structural_preservation(struct( ...
    'candidate_case', s13_candidate, ...
    'candidate_name', 'npcc_ny_lite_s13_npcc_augmented_2019', ...
    'write_outputs', false, 'fail_on_structural', true));
assert(s13_validation.all_structural_gates_pass, ...
    'The S13-FULL construction parent failed a structural preservation gate.');
assert(~s13_validation.promotion_eligible, ...
    'S13-FULL must remain permanently ineligible for DLR-model promotion.');

s13_artifact_consistency = validate_s13_artifact_consistency(struct( ...
    'candidate_case', s13_candidate, 'artifact_dir', helper_dir, ...
    'fail_on_mismatch', true));
assert(s13_artifact_consistency.all_artifacts_match, ...
    'A committed S13 register or structural ledger differs from rebuilt evidence.');
s13_adversarial_validation = test_s13_structural_validator_adversarial(struct( ...
    'write_outputs', false, ...
    'output_file', fullfile(helper_dir, ...
    's13_structural_adversarial_results.csv')));
assert(s13_adversarial_validation.all_expected_gates_observed, ...
    'The S13 adversarial harness did not observe every expected hard-gate failure.');
s12_interface_snapshot_test = test_s12_interface_snapshot_sums(struct( ...
    'verbose', false));
assert(s12_interface_snapshot_test.pass && ...
    s12_interface_snapshot_test.total_east_circuit_count == 8, ...
    'The S12 oracle sidecar is stale or Total East no longer has eight circuits.');

s13_phase1b_local = struct();
s13_phase1b_operator = struct();
s13_phase1b_artifacts = struct();
s13_phase1b_adversarial = struct();
s13_phase1b_smoke = struct();
if options.run_s13_phase1b_validation
    s13_phase1b_local = run_s13_phase1b_local_identity(struct( ...
        's13_case', s13_candidate, 'write_outputs', false, ...
        'fail_on_gate', true, 'verbose', false));
    assert(s13_phase1b_local.pass && ...
        s13_phase1b_local.phase1a_report_exact_match && ...
        s13_phase1b_local.phase1a_physical_rows_bit_identical && ...
        ~s13_phase1b_local.residual_fit_performed && ...
        ~s13_phase1b_local.promotion_performed, ...
        'Phase 1B local identity or Phase 1A immutability failed.');
    s13_phase1b_operator = validate_s13_phase1b_upny_operator(struct( ...
        'candidate_case', s13_candidate, 'write_outputs', false, ...
        'fail_on_gate', true, 'verbose', false));
    assert(s13_phase1b_operator.pass && ...
        ~s13_phase1b_operator.exact_public_operator && ...
        ~s13_phase1b_operator.promotion_eligible, ...
        'The Phase 1B UPNY-ConEd proxy gate or fail-closed role changed.');
    s13_phase1b_artifacts = ...
        validate_s13_phase1b_artifact_consistency(struct( ...
        'candidate_case', s13_candidate, 'artifact_dir', helper_dir, ...
        'write_outputs', false, 'fail_on_mismatch', true, ...
        'verbose', false));
    assert(s13_phase1b_artifacts.all_artifacts_match, ...
        'One or more committed Phase 1B artifacts are stale.');
    s13_phase1b_adversarial = ...
        test_s13_phase1b_validator_adversarial(struct( ...
        'write_outputs', false, 'verbose', false));
    assert(s13_phase1b_adversarial.all_expected_gates_observed, ...
        'A Phase 1B adversarial mutation escaped its expected gate.');
    s13_phase1b_smoke = validate_s13_phase1b_smoke(struct( ...
        'write_outputs', false, 'verbose', false));
    assert(s13_phase1b_smoke.standard_pf_all_pass, ...
        'The inherited-snapshot standard PF must pass through Phase 1B.');
end

s13_oracle_preflight = struct();
s13_oracle_artifacts = struct();
if options.run_s13_phase1a_oracle_preflight
    s13_oracle_preflight = run_s13_phase1a_oracle_comparison(struct( ...
        'write_outputs', false, 'verbose', false, ...
        'fail_on_incomplete', false));
    assert(s13_oracle_preflight.stage_a_pass && ...
        ~s13_oracle_preflight.promotion_eligible && ...
        ~s13_oracle_preflight.electrically_validated, ...
        ['The S13.1 local identity must pass while the unavailable common ' ...
        'system diagnostic remains fail-closed.']);
    s13_oracle_artifacts = ...
        validate_s13_phase1a_oracle_artifact_consistency(struct( ...
        'oracle_result', s13_oracle_preflight, ...
        'artifact_dir', helper_dir, 'fail_on_mismatch', true, ...
        'verbose', false));
    assert(s13_oracle_artifacts.all_artifacts_match, ...
        'One or more committed S13.1 oracle/preflight artifacts are stale.');
end

