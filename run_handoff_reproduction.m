    s8 = run_s8_iterative_ac_injection_closure;
    assert(s8.scenario_count == 6 && s8.standard_pf_success_count == 6, ...
        'S8 standard PF must converge for all six scenarios.');
end

voltage_references = struct();
if options.run_s9b_feasibility_restoration || options.run_s9b_reference_audit
    voltage_references = build_ny_voltage_reference_sets;
    provenance = voltage_references.s1_provenance;
    refs = voltage_references.references;
    perform_controls = voltage_references.perform_controls;
    ce_s1 = refs(refs.reference_set == "S1_OPF_SOLVED_REFERENCE" & ...
        refs.model_bus == 78, :);
    ce_original = refs(refs.reference_set == "ORIGINAL_NPCC_VG_REFERENCE" & ...
        refs.model_bus == 78, :);
    assert(height(provenance) == 48 && all(provenance.changed), ...
        'All 48 S1 VG fields should be identified as OPF-solved changes.');
    assert(height(ce_s1) == 1 && height(ce_original) == 1 && ...
        abs(ce_s1.voltage_reference_pu - 0.974721326) < 1e-8 && ...
        abs(ce_original.voltage_reference_pu - 1.02) < 1e-8, ...
        'CE UG voltage-reference provenance changed unexpectedly.');
    online_internal_controls = perform_controls.status > 0 & ...
        perform_controls.mapped_to_nyiso_zone;
    assert(height(perform_controls) == 649 && ...
        sum(online_internal_controls) == 417 && ...
        numel(unique(perform_controls.source_bus(online_internal_controls))) == 179 && ...
        sum(online_internal_controls & perform_controls.reactive_only_QS) == 34 && ...
        sum(online_internal_controls & ...
            perform_controls.positive_active_capability) == 381 && ...
        sum(online_internal_controls & perform_controls.fixed_negative_active) == 2 && ...
        sum(online_internal_controls & perform_controls.remote_regulation) == 1 && ...
        sum(isfinite(perform_controls.converted_gen_index)) == 615 && ...
        all(perform_controls.regulated_bus_found(online_internal_controls)), ...
        'PERFORM RAW control extraction or device classification changed unexpectedly.');
    assert(~any(contains(perform_controls.source_file, ":")), ...
        'Packaged voltage-control provenance must use relative paths.');
end

s9b = struct();
if options.run_s9b_feasibility_restoration
    s9b = run_s9b_ac_feasibility_restoration;
    restoration = s9b.summary;
    at_080 = restoration(abs(restoration.reference_weight - 0.80) < 1e-9, :);
    at_100 = restoration(abs(restoration.reference_weight - 1.00) < 1e-9, :);
    assert(height(restoration) == 27 && all(restoration.opf_success), ...
        'S9b must return 27 successfully solved restoration cases.');
    assert(all(string(at_080.termination_class) == "hard_feasible_zero_slack"), ...
        'S9b should find hard feasibility at S1 reference weight 0.80.');
    assert(all(string(at_100.termination_class) == "restored_nonzero_slack"), ...
        'S9b should quantify nonzero restoration slack at S1 reference weight 1.00.');
    assert(all(restoration.branch_slack_mva < 1e-6), ...
        'S9b should not require branch-flow restoration slack.');
    assert(all(restoration.requested_reference_bus_count == ...
        restoration.applied_reference_bus_count + ...
        restoration.skipped_pq_reference_bus_count), ...
        'Every requested S9b reference must be applied or identified as PQ-skipped.');
    assert(max(restoration.max_ac_balance_component_residual_mw_or_mvar) < 0.01 && ...
        max(restoration.max_complex_power_mismatch_mva) < 0.01, ...
        'S9b AC balance residuals exceed the numerical acceptance threshold.');
end

