    'mandatory_structural_total', nnz(structural_mask), ...
    'mandatory_structural_passed', ...
        nnz(structural_mask & s13_validation.gates.pass), ...
    'construction_validation_total', nnz(construction_validation_mask), ...
    'construction_validation_fail_closed', ...
        nnz(construction_validation_mask & ~s13_validation.gates.pass), ...
    'promotion_only_total', 0, ... % deprecated: S13 has no promotion gates
    'promotion_only_fail_closed', 0);
assert(s13_gate_counts.mandatory_structural_passed == ...
    s13_gate_counts.mandatory_structural_total, ...
    'Not all mandatory S13 structural gates passed.');

