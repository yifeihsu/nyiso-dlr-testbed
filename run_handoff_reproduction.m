if options.run_s13_phase1a_smoke
    s13_smoke = validate_s13_phase1a_smoke(struct('write_outputs', false));
    assert(s13_smoke.standard_pf_both_pass, ...
        'The inherited-snapshot standard PF smoke test must pass for S7 and S13.');
end

