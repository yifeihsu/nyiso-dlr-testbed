function [targets, diagnostics] = derive_nyiso_zonal_net_injections_ac_iterative( ...
        mpc, scenario_id, gsk, external_gen_idx, options)
%DERIVE_NYISO_ZONAL_NET_INJECTIONS_AC_ITERATIVE Close the DC-to-AC loop.
%   Starts from the constrained DC estimate, allocates measured AC losses
%   across zones by available headroom, and iteratively updates zonal
%   generation using finite-difference AC interface-flow sensitivities.
%   Sensitivity transfers use a distributed participation vector rather
%   than balancing every perturbation at the reference generator.

if nargin < 5, options = struct(); end
helper_dir = fileparts(mfilename('fullpath'));
options = defaults(options, helper_dir);
define_constants;

zones = string(('A':'K')');
scenario_id = string(scenario_id);
mpc = attach_nyiso_zone_metadata(mpc);
external_gen_idx = unique(external_gen_idx(:));
external_gen_idx = external_gen_idx(external_gen_idx >= 1 & ...
    external_gen_idx <= size(mpc.gen, 1));

dc_options = struct('interface_target_file', options.interface_target_file, ...
    'interface_scale_file', options.interface_scale_file, ...
    'prior_weight', options.dc_prior_weight, ...
    'balance_zone', options.dc_balance_zone, ...
    'sensitivity_step_mw', options.dc_sensitivity_step_mw);
[initial_targets, dc_diagnostics] = derive_nyiso_zonal_net_injections( ...
    mpc, scenario_id, gsk, external_gen_idx, dc_options);

generation = initial_targets.target_generation_mw;
prior = initial_targets.generation_prior_mw;
pmin = initial_targets.pmin_mw;
pmax = initial_targets.pmax_mw;
load_mw = initial_targets.target_load_mw;
external_import_mw = initial_targets.external_import_mw;
adjustable = pmax - pmin > options.bound_tolerance_mw;
if sum(adjustable) < 2
    error('derive_nyiso_zonal_net_injections_ac_iterative:Participation', ...
        'At least two adjustable zones are required.');
end

public_targets = read_public_interface_targets(scenario_id, ...
    options.interface_target_file);
target_names = string(public_targets.interface_name);
target_flow = public_targets.target_flow_mw;
accuracy_scale = interface_accuracy_scales(target_names, options);
reference_gen = choose_reference_generator(mpc, external_gen_idx, ...
    options.reference_zone);
pfopt = mpoption('verbose', 0, 'out.all', 0, 'pf.enforce_q_lims', 0);

history = table();
sensitivity_history = table();
participation_history = table();
last_step_norm = NaN;
last_exitflag = NaN;
converged = false;

for iteration = 1:options.max_iterations
    [pre_result, ~] = run_generation(mpc, zones, generation, gsk, ...
        reference_gen, pfopt, [], external_gen_idx);
    require_success(pre_result, scenario_id, iteration, 'pre-loss AC PF');

    pre_metrics = physical_metrics(pre_result, external_gen_idx, generation);
    required_internal = sum(load_mw) + pre_metrics.losses_mw - ...
        sum(external_import_mw);
    total_adjustment = required_internal - sum(generation);
    alpha_loss = loss_participation(generation, pmin, pmax, ...
        total_adjustment, adjustable);
    loss_seed = generation + alpha_loss * total_adjustment;
    balanced_generation = project_generation_total(loss_seed, pmin, pmax, ...
        required_internal);

    [base_result, ~] = run_generation(mpc, zones, ...
        balanced_generation, gsk, reference_gen, pfopt, pre_result, ...
        external_gen_idx);
    require_success(base_result, scenario_id, iteration, 'loss-balanced AC PF');
    base_flow = interface_vector(base_result, public_targets);
    residual = base_flow - target_flow;
    base_metrics = physical_metrics(base_result, external_gen_idx, ...
        balanced_generation);
    alpha_sensitivity = sensitivity_participation( ...
        balanced_generation, pmin, pmax, adjustable);

    [response, finite_steps, sensitivity_rows] = ac_response_matrix( ...
        mpc, zones, balanced_generation, pmin, pmax, gsk, ...
        reference_gen, pfopt, base_result, base_flow, target_names, ...
        alpha_sensitivity, adjustable, options, scenario_id, iteration, ...
        external_gen_idx);
    sensitivity_history = append_table(sensitivity_history, sensitivity_rows);

    participation_rows = participation_table(scenario_id, iteration, zones, ...
        balanced_generation, pmin, pmax, alpha_loss, alpha_sensitivity, ...
        finite_steps);
    participation_history = append_table(participation_history, ...
        participation_rows);

    [delta_generation, exitflag] = solve_ac_redispatch(response, residual, ...
        balanced_generation, prior, pmin, pmax, accuracy_scale, adjustable, ...
        options);
    applied_step = options.damping * delta_generation;
    next_generation = balanced_generation + applied_step;
    next_generation = project_generation_total(next_generation, pmin, pmax, ...
        sum(balanced_generation));
    last_step_norm = norm(applied_step, inf);
    last_exitflag = exitflag;

    [limit_objective, ~] = interface_target_objective_balanced( ...
        ny_lite_interface_flows(base_result, ...
        ny_lite_interface_definitions(base_result)), public_targets, ...
        struct('scale_file', options.interface_scale_file, ...
        'min_scale_mw', 500));
    calibration_objective = huber_objective(residual, accuracy_scale, ...
        options.huber_delta);
    hrow = history_row(scenario_id, iteration, "iterate", base_metrics, ...
        limit_objective, calibration_objective, residual, ...
        required_internal, total_adjustment, last_step_norm, exitflag);
    history = append_table(history, hrow);

    if max(abs(residual)) <= options.flow_tolerance_mw && ...
            abs(base_metrics.reference_adjustment_mw) <= ...
            options.loss_balance_tolerance_mw
        generation = balanced_generation;
        converged = true;
        break;
    end
    if last_step_norm <= options.generation_step_tolerance_mw && ...
            abs(base_metrics.reference_adjustment_mw) <= ...
            options.loss_balance_tolerance_mw
        generation = balanced_generation;
        converged = true;
        break;
    end
    generation = next_generation;
end

% Finish with a short loss-only closure so the remaining reference pickup
% is numerical rather than the full AC-loss requirement.
for k = 1:options.final_loss_iterations
    [probe, ~] = run_generation(mpc, zones, generation, gsk, ...
        reference_gen, pfopt, [], external_gen_idx);
    require_success(probe, scenario_id, options.max_iterations + k, ...
        'final loss-closure PF');
    metrics = physical_metrics(probe, external_gen_idx, generation);
    required_internal = sum(load_mw) + metrics.losses_mw - ...
        sum(external_import_mw);
    delta_total = required_internal - sum(generation);
    if abs(delta_total) <= options.loss_balance_tolerance_mw, break; end
    alpha_loss = loss_participation(generation, pmin, pmax, ...
        delta_total, adjustable);
    generation = project_generation_total(generation + ...
        alpha_loss * delta_total, pmin, pmax, required_internal);
end

[final_result, final_allocation, final_case] = run_generation(mpc, zones, generation, ...
    gsk, reference_gen, pfopt, [], external_gen_idx);
require_success(final_result, scenario_id, options.max_iterations + 1, ...
    'final AC PF');
[final_flow, interface_names] = interface_vector(final_result, public_targets);
final_residual = final_flow - target_flow;
final_metrics = physical_metrics(final_result, external_gen_idx, generation);
[final_limit_objective, limit_detail] = interface_target_objective_balanced( ...
    ny_lite_interface_flows(final_result, ...
    ny_lite_interface_definitions(final_result)), public_targets, ...
    struct('scale_file', options.interface_scale_file, 'min_scale_mw', 500));
final_calibration_objective = huber_objective(final_residual, ...
    accuracy_scale, options.huber_delta);
final_required_internal = sum(load_mw) + final_metrics.losses_mw - ...
    sum(external_import_mw);
history = append_table(history, history_row(scenario_id, height(history) + 1, ...
    "final", final_metrics, final_limit_objective, ...
    final_calibration_objective, final_residual, final_required_internal, ...
    final_required_internal - sum(generation), 0, last_exitflag));

actual_generation = zonal_actual_generation(final_result, zones, ...
    external_gen_idx);
final_loss_alpha = loss_participation(generation, pmin, pmax, 1, adjustable);
targets = initial_targets;
targets.initial_dc_generation_mw = initial_targets.target_generation_mw;
targets.target_generation_mw = generation;
targets.final_actual_generation_mw = actual_generation;
targets.dc_to_ac_generation_change_mw = generation - ...
    initial_targets.target_generation_mw;
targets.final_generation_error_mw = actual_generation - generation;
targets.loss_participation_factor = final_loss_alpha;
targets.target_native_net_injection_mw = generation - load_mw;
targets.target_effective_net_injection_mw = ...
    targets.target_native_net_injection_mw + external_import_mw;

interface_table = table(interface_names, target_flow, final_flow, ...
    final_residual, accuracy_scale, final_residual ./ accuracy_scale, ...
    'VariableNames', {'interface_name','target_flow_mw','final_ac_flow_mw', ...
    'final_ac_residual_mw','accuracy_scale_mw','normalized_residual'});
if ismember('scale_mw', limit_detail.Properties.VariableNames)
    interface_table.reporting_scale_mw = limit_detail.scale_mw;
    interface_table.reporting_objective_term = limit_detail.objective_term;
end

diagnostics = struct('scenario_id', scenario_id, ...
    'converged', converged, 'iteration_count', ...
    sum(history.row_type == "iterate"), ...
    'dc_diagnostics', dc_diagnostics, ...
    'initial_dc_interface_objective', dc_diagnostics.predicted_objective, ...
    'operational_score_reoptimized_dispatch', final_limit_objective, ...
    'calibration_huber_objective', final_calibration_objective, ...
    'reference_gen_index', reference_gen, ...
    'history', history, 'sensitivity_history', sensitivity_history, ...
    'participation_history', participation_history, ...
    'interface_table', interface_table, ...
    'final_metrics', final_metrics, ...
    'final_result', final_result, 'final_case', final_case, ...
    'initial_targets', initial_targets, ...
    'initial_dc_interface_table', dc_diagnostics.interface_table, ...
    'final_allocation', final_allocation, ...
    'last_step_norm_mw', last_step_norm, ...
    'last_solver_exitflag', last_exitflag);
end

