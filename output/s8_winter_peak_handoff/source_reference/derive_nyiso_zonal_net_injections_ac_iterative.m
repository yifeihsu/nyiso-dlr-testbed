items = { ...
    'interface_target_file', fullfile(helper_dir, 'nyiso_public_interface_targets.csv'); ...
    'interface_scale_file', fullfile(helper_dir, 'nyiso_interface_objective_scales.csv'); ...
    'accuracy_scale_file', fullfile(helper_dir, 'nyiso_interface_accuracy_scales.csv'); ...
    'dc_prior_weight', 0.05; ...
    'dc_balance_zone', "J"; ...
    'dc_sensitivity_step_mw', 1; ...
    'reference_zone', "J"; ...
    'max_iterations', 6; ...
    'final_loss_iterations', 4; ...
    'damping', 0.4; ...
    'ac_sensitivity_step_mw', 25; ...
    'min_sensitivity_step_mw', 0.25; ...
    'max_redispatch_step_mw', 1000; ...
    'prior_weight', 0.002; ...
    'update_weight', 0.0005; ...
    'default_accuracy_mw', 100; ...
    'huber_delta', 1.5; ...
    'flow_tolerance_mw', 25; ...
    'loss_balance_tolerance_mw', 0.1; ...
    'generation_step_tolerance_mw', 0.25; ...
    'bound_tolerance_mw', 1e-6};
for k = 1:size(items, 1)
    if ~isfield(options, items{k, 1})
        options.(items{k, 1}) = items{k, 2};
    end
end
end

function [result, allocation, case_mpc] = run_generation(template, zones, generation, ...
        gsk, reference_gen, pfopt, warm_result, external_idx)
define_constants;
target = table(zones, generation, ...
    'VariableNames', {'zone','target_generation_mw'});
[case_mpc, allocation] = apply_perform_generation_allocation( ...
    template, target, gsk, struct('exclude_gen_idx', external_idx));
if nargin >= 7 && ~isempty(warm_result) && ...
        size(warm_result.bus, 1) == size(case_mpc.bus, 1)
    case_mpc.bus(:, [VM VA]) = warm_result.bus(:, [VM VA]);
end
case_mpc = set_scenario_reference_bus(case_mpc, reference_gen, ...
    struct('require_external', false));
result = runpf(case_mpc, pfopt);
end

function require_success(result, scenario_id, iteration, label)
if ~isfield(result, 'success') || ~logical(result.success)
    error('derive_nyiso_zonal_net_injections_ac_iterative:PowerFlow', ...
        '%s failed for %s at iteration %d.', label, scenario_id, iteration);
end
end

function gi = choose_reference_generator(mpc, external_idx, preferred_zone)
define_constants;
mpc = attach_nyiso_zone_metadata(mpc);
[mapped, bi] = ismember(mpc.gen(:, GEN_BUS), mpc.bus(:, BUS_I));
zone = strings(size(mpc.gen, 1), 1);
zone(mapped) = string(mpc.userdata.nyiso_physical_zone(bi(mapped)));
mask = mpc.gen(:, GEN_STATUS) > 0 & zone ~= "";
mask(external_idx) = false;
preferred = mask & zone == upper(string(preferred_zone));
if any(preferred), mask = preferred; end
idx = find(mask);
qrange = max(0, mpc.gen(idx, QMAX) - mpc.gen(idx, QMIN));
prange = max(0, mpc.gen(idx, PMAX) - mpc.gen(idx, PMIN));
score = prange + 0.1 * qrange;
score(qrange <= 1e-6) = -Inf;
[~, k] = max(score);
if isempty(k) || ~isfinite(score(k))
    [~, k] = max(prange);
end
gi = idx(k);
end

function alpha = loss_participation(generation, pmin, pmax, delta, adjustable)
if delta >= 0
    reserve = max(0, pmax - generation);
else
    reserve = max(0, generation - pmin);
end
reserve(~adjustable) = 0;
if sum(reserve) <= 1e-9
    reserve = max(0, pmax - pmin);
    reserve(~adjustable) = 0;
end
alpha = reserve / sum(reserve);
end

function alpha = sensitivity_participation(generation, pmin, pmax, adjustable)
reserve = min(max(0, pmax - generation), max(0, generation - pmin));
reserve(~adjustable) = 0;
if sum(reserve) <= 1e-9
    reserve = max(0, generation - pmin);
    reserve(~adjustable) = 0;
end
if sum(reserve) <= 1e-9
    reserve = max(0, pmax - pmin);
    reserve(~adjustable) = 0;
end
alpha = reserve / sum(reserve);
end

function projected = project_generation_total(seed, lower, upper, total)
if total < sum(lower) - 1e-6 || total > sum(upper) + 1e-6
    error('derive_nyiso_zonal_net_injections_ac_iterative:GenerationBounds', ...
        'Required internal generation %.3f MW is outside [%.3f, %.3f] MW.', ...
        total, sum(lower), sum(upper));
end
scale = max(100, upper - lower);
C = diag(1 ./ scale);
d = C * seed;
opts = optimoptions('lsqlin', 'Display', 'off', 'Algorithm', 'interior-point');
[projected, ~, ~, exitflag, output] = lsqlin(C, d, [], [], ...
    ones(1, numel(seed)), total, lower, upper, ...
    min(max(seed, lower), upper), opts);
if exitflag <= 0
    error('derive_nyiso_zonal_net_injections_ac_iterative:Projection', ...
        'Generation projection failed: %s', output.message);
end
end

function [response, steps, rows] = ac_response_matrix(template, zones, ...
        generation, pmin, pmax, gsk, reference_gen, pfopt, base_result, ...
        base_flow, interface_names, alpha, adjustable, options, ...
        scenario_id, iteration, external_idx)
nz = numel(zones);
nm = numel(base_flow);
response = zeros(nm, nz);
steps = zeros(nz, 1);
rows = table();
for z = find(adjustable(:))'
    direction = -alpha;
    direction(z) = direction(z) + 1;
    if norm(direction, inf) <= 1e-12, continue; end
    positive_margin = feasible_margin(generation, direction, pmin, pmax);
    negative_margin = feasible_margin(generation, -direction, pmin, pmax);
    if positive_margin >= negative_margin
        signed_margin = positive_margin;
        direction_sign = 1;
    else
        signed_margin = negative_margin;
        direction_sign = -1;
    end
    magnitude = min(options.ac_sensitivity_step_mw, 0.8 * signed_margin);
    if ~isfinite(magnitude)
        magnitude = options.ac_sensitivity_step_mw;
    end
    if magnitude < options.min_sensitivity_step_mw
        continue;
    end
    h = direction_sign * magnitude;
    trial_generation = generation + h * direction;
    [trial_result, ~] = run_generation(template, zones, trial_generation, ...
        gsk, reference_gen, pfopt, base_result, external_idx);
    require_success(trial_result, scenario_id, iteration, ...
        "AC sensitivity for zone " + zones(z));
    trial_flow = interface_vector(trial_result, ...
        table(interface_names, base_flow, ...
        'VariableNames', {'interface_name','target_flow_mw'}));
    response(:, z) = (trial_flow - base_flow) / h;
    steps(z) = h;
    for m = 1:nm
        row = table(scenario_id, iteration, interface_names(m), zones(z), ...
            response(m, z), h, direction(z), alpha(z), ...
            'VariableNames', {'scenario_id','iteration','interface_name', ...
            'perturbed_zone','sensitivity_mw_per_mw','finite_difference_step_mw', ...
            'direction_zone_component','distributed_participation_factor'});
        rows = append_table(rows, row);
    end
end
end

function margin = feasible_margin(generation, direction, lower, upper)
limits = [];
positive = direction > 1e-12;
negative = direction < -1e-12;
if any(positive)
    limits = [limits; (upper(positive) - generation(positive)) ./ ...
        direction(positive)];
end
if any(negative)
    limits = [limits; (generation(negative) - lower(negative)) ./ ...
        (-direction(negative))];
end
if isempty(limits), margin = Inf; else, margin = max(0, min(limits)); end
end

function [delta, exitflag] = solve_ac_redispatch(response, residual, ...
        generation, prior, pmin, pmax, accuracy, adjustable, options)
nz = numel(generation);
normalized = residual ./ accuracy;
irls = ones(size(normalized));
large = abs(normalized) > options.huber_delta;
irls(large) = options.huber_delta ./ abs(normalized(large));
W = diag(sqrt(irls) ./ accuracy);
C_flow = W * response;
d_flow = W * (-residual);

prior_scale = max(500, pmax);
C_prior = diag(sqrt(options.prior_weight) ./ prior_scale);
d_prior = C_prior * (prior - generation);
C_update = diag(repmat(sqrt(options.update_weight) / 500, nz, 1));
d_update = zeros(nz, 1);
C = [C_flow; C_prior; C_update];
d = [d_flow; d_prior; d_update];

lower = max(pmin - generation, -options.max_redispatch_step_mw);
upper = min(pmax - generation, options.max_redispatch_step_mw);
lower(~adjustable) = 0;
upper(~adjustable) = 0;
opts = optimoptions('lsqlin', 'Display', 'off', 'Algorithm', 'interior-point');
[delta, ~, ~, exitflag, output] = lsqlin(C, d, [], [], ...
    ones(1, nz), 0, lower, upper, zeros(nz, 1), opts);
if exitflag <= 0
    error('derive_nyiso_zonal_net_injections_ac_iterative:Redispatch', ...
        'AC redispatch solve failed: %s', output.message);
end
end

function [vector, names] = interface_vector(results, targets)
flows = ny_lite_interface_flows(results, ny_lite_interface_definitions(results));
names = string(targets.interface_name);
vector = nan(height(targets), 1);
for k = 1:height(targets)
    idx = find(strcmp({flows.interface_name}, char(names(k))), 1);
    if isempty(idx)
        error('Interface %s is not defined in the reduced case.', names(k));
    end
    vector(k) = flows(idx).flow_mw;
end
end

function scales = interface_accuracy_scales(names, options)
scales = repmat(options.default_accuracy_mw, numel(names), 1);
if exist(options.accuracy_scale_file, 'file') ~= 2, return; end
tbl = readtable(options.accuracy_scale_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
if ~all(ismember({'interface_name','accuracy_scale_mw'}, ...
        tbl.Properties.VariableNames))
    return;
end
for k = 1:numel(names)
    idx = find(string(tbl.interface_name) == names(k), 1);
    if ~isempty(idx) && isfinite(tbl.accuracy_scale_mw(idx)) && ...
            tbl.accuracy_scale_mw(idx) > 0
        scales(k) = tbl.accuracy_scale_mw(idx);
    end
end
end

function value = huber_objective(residual, scale, delta)
u = abs(residual ./ scale);
term = 0.5 * u.^2;
large = u > delta;
term(large) = delta * (u(large) - 0.5 * delta);
value = sum(term);
end

function metrics = physical_metrics(results, external_idx, scheduled_generation)
define_constants;
online = results.gen(:, GEN_STATUS) > 0;
total_generation = sum(results.gen(online, PG));
total_load = sum(results.bus(:, PD));
losses = total_generation - total_load;
[mapped, bi] = ismember(results.gen(:, GEN_BUS), results.bus(:, BUS_I));
results = attach_nyiso_zone_metadata(results);
gen_zone = strings(size(results.gen, 1), 1);
gen_zone(mapped) = string(results.userdata.nyiso_physical_zone(bi(mapped)));
internal = online & gen_zone ~= "";
internal(external_idx) = false;
actual_internal = sum(results.gen(internal, PG));
sf = hypot(results.branch(:, PF), results.branch(:, QF));
st = hypot(results.branch(:, PT), results.branch(:, QT));
smax = max(sf, st);
rated = results.branch(:, RATE_A) > 0 & results.branch(:, BR_STATUS) > 0;
over = max(0, smax - results.branch(:, RATE_A));
vviol = results.bus(:, VM) < results.bus(:, VMIN) - 1e-6 | ...
    results.bus(:, VM) > results.bus(:, VMAX) + 1e-6;
pviol = max(max(0, results.gen(:, PMIN) - results.gen(:, PG)), ...
    max(0, results.gen(:, PG) - results.gen(:, PMAX)));
qviol = max(max(0, results.gen(:, QMIN) - results.gen(:, QG)), ...
    max(0, results.gen(:, QG) - results.gen(:, QMAX)));
metrics = struct('total_load_mw', total_load, ...
    'total_generation_mw', total_generation, 'losses_mw', losses, ...
    'scheduled_internal_generation_mw', sum(scheduled_generation), ...
    'actual_internal_generation_mw', actual_internal, ...
    'reference_adjustment_mw', actual_internal - sum(scheduled_generation), ...
    'min_voltage_pu', min(results.bus(:, VM)), ...
    'max_voltage_pu', max(results.bus(:, VM)), ...
    'voltage_violation_count', sum(vviol), ...
    'branch_overload_count', sum(rated & over > 1e-6), ...
    'max_branch_overload_mva', max([0; over(rated)]), ...
    'generator_p_violation_count', sum(pviol > 1e-6), ...
    'max_generator_p_violation_mw', max([0; pviol]), ...
    'generator_q_violation_count', sum(qviol > 1e-6), ...
    'max_generator_q_violation_mvar', max([0; qviol]));
end

function row = history_row(scenario_id, iteration, row_type, metrics, ...
        reporting_objective, calibration_objective, residual, ...
        required_internal, loss_adjustment, step_norm, exitflag)
row = table(scenario_id, iteration, row_type, true, reporting_objective, ...
    calibration_objective, max(abs(residual)), mean(abs(residual)), ...
    mean(residual), metrics.total_load_mw, metrics.total_generation_mw, ...
    metrics.losses_mw, required_internal, ...
    metrics.scheduled_internal_generation_mw, ...
    metrics.actual_internal_generation_mw, ...
    metrics.reference_adjustment_mw, loss_adjustment, step_norm, exitflag, ...
    metrics.min_voltage_pu, metrics.max_voltage_pu, ...
    metrics.voltage_violation_count, metrics.branch_overload_count, ...
    metrics.max_branch_overload_mva, metrics.generator_p_violation_count, ...
    metrics.max_generator_p_violation_mw, ...
    metrics.generator_q_violation_count, ...
    metrics.max_generator_q_violation_mvar, ...
    'VariableNames', {'scenario_id','iteration','row_type','pf_success', ...
    'reporting_interface_objective','calibration_huber_objective', ...
    'max_abs_interface_residual_mw','mean_abs_interface_residual_mw', ...
    'mean_signed_interface_residual_mw','total_load_mw', ...
    'total_generation_mw','losses_mw','required_internal_generation_mw', ...
    'scheduled_internal_generation_mw','actual_internal_generation_mw', ...
    'reference_adjustment_mw','loss_total_adjustment_mw', ...
    'redispatch_step_inf_norm_mw','redispatch_solver_exitflag', ...
    'min_voltage_pu','max_voltage_pu','voltage_violation_count', ...
    'branch_overload_count','max_branch_overload_mva', ...
    'generator_p_violation_count','max_generator_p_violation_mw', ...
    'generator_q_violation_count','max_generator_q_violation_mvar'});
end

function rows = participation_table(scenario_id, iteration, zones, ...
        generation, pmin, pmax, alpha_loss, alpha_sensitivity, steps)
rows = table(repmat(scenario_id, numel(zones), 1), ...
    repmat(iteration, numel(zones), 1), zones, generation, pmin, pmax, ...
    pmax - generation, generation - pmin, alpha_loss, alpha_sensitivity, ...
    steps, 'VariableNames', {'scenario_id','iteration','zone', ...
    'scheduled_generation_mw','pmin_mw','pmax_mw','upward_headroom_mw', ...
    'downward_headroom_mw','loss_participation_factor', ...
    'sensitivity_participation_factor','finite_difference_step_mw'});
end

function generation = zonal_actual_generation(results, zones, external_idx)
define_constants;
results = attach_nyiso_zone_metadata(results);
[mapped, bi] = ismember(results.gen(:, GEN_BUS), results.bus(:, BUS_I));
gen_zone = strings(size(results.gen, 1), 1);
gen_zone(mapped) = string(results.userdata.nyiso_physical_zone(bi(mapped)));
internal = results.gen(:, GEN_STATUS) > 0 & gen_zone ~= "";
internal(external_idx) = false;
generation = zeros(numel(zones), 1);
for z = 1:numel(zones)
    generation(z) = sum(results.gen(internal & gen_zone == zones(z), PG));
end
end

function out = append_table(out, row)
if isempty(row), return; end
if isempty(out), out = row; else, out = [out; row]; end
end
