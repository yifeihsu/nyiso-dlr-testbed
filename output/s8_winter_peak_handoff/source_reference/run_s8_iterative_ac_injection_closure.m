function [J, detail] = score_interfaces(results, targets, options)
flows = ny_lite_interface_flows(results, ny_lite_interface_definitions(results));
[J, detail] = interface_target_objective_balanced(flows, targets, ...
    struct('scale_file', options.interface_scale_file, 'min_scale_mw', 500));
end

function combined = combine_interface_detail(scenario_id, targets, dc, ...
        structural, operational)
names = string(targets.interface_name);
n = numel(names);
combined = table(repmat(scenario_id, n, 1), names, ...
    targets.target_flow_mw, nan(n, 1), nan(n, 1), nan(n, 1), nan(n, 1), ...
    nan(n, 1), nan(n, 1), nan(n, 1), nan(n, 1), ...
    'VariableNames', {'scenario_id','interface_name','target_flow_mw', ...
    'initial_dc_flow_mw','initial_dc_residual_mw','structural_ac_flow_mw', ...
    'structural_ac_residual_mw','operational_ac_flow_mw', ...
    'operational_ac_residual_mw','reporting_scale_mw','accuracy_scale_mw'});
for k = 1:n
    di = find(string(dc.interface_name) == names(k), 1);
    si = find(string(structural.interface_name) == names(k), 1);
    oi = find(string(operational.interface_name) == names(k), 1);
    combined.initial_dc_flow_mw(k) = dc.predicted_dc_flow_mw(di);
    combined.initial_dc_residual_mw(k) = dc.predicted_dc_residual_mw(di);
    combined.structural_ac_flow_mw(k) = structural.lite_flow_mw(si);
    combined.structural_ac_residual_mw(k) = structural.residual_mw(si);
    combined.operational_ac_flow_mw(k) = operational.final_ac_flow_mw(oi);
    combined.operational_ac_residual_mw(k) = ...
        operational.final_ac_residual_mw(oi);
    combined.reporting_scale_mw(k) = structural.scale_mw(si);
    combined.accuracy_scale_mw(k) = operational.accuracy_scale_mw(oi);
end
combined.dc_to_structural_shift_mw = combined.structural_ac_flow_mw - ...
    combined.initial_dc_flow_mw;
combined.operational_correction_mw = combined.operational_ac_flow_mw - ...
    combined.structural_ac_flow_mw;
end

function summary = summarize_scores(detail)
modes = ["initial_dc"; "structural_frozen_s6_ac"; ...
    "operational_reoptimized_ac"];
columns = {'initial_dc_residual_mw','structural_ac_residual_mw', ...
    'operational_ac_residual_mw'};
summary = table();
for k = 1:numel(modes)
    residual = detail.(columns{k});
    objective = sum((residual ./ detail.reporting_scale_mw).^2);
    row = table(modes(k), objective, mean(abs(residual)), ...
        max(abs(residual)), mean(residual), sum(residual < 0), ...
        sum(residual > 0), numel(unique(detail.scenario_id)), ...
        'VariableNames', {'score_type','sum_reporting_interface_objective', ...
        'mean_abs_residual_mw','max_abs_residual_mw', ...
        'mean_signed_residual_mw','negative_residual_count', ...
        'positive_residual_count','scenario_count'});
    summary = append_table(summary, row);
end
end

function summary = summarize_interfaces(detail)
names = unique(detail.interface_name, 'stable');
summary = table();
modes = ["initial_dc"; "structural_frozen_s6_ac"; ...
    "operational_reoptimized_ac"];
columns = {'initial_dc_residual_mw','structural_ac_residual_mw', ...
    'operational_ac_residual_mw'};
for n = 1:numel(names)
    rows = detail(detail.interface_name == names(n), :);
    for k = 1:numel(modes)
        residual = rows.(columns{k});
        row = table(names(n), modes(k), mean(abs(residual)), ...
            max(abs(residual)), mean(residual), ...
            'VariableNames', {'interface_name','score_type', ...
            'mean_abs_residual_mw','max_abs_residual_mw', ...
            'mean_signed_residual_mw'});
        summary = append_table(summary, row);
    end
end
end

function metrics = result_metrics(results, external_idx, scheduled_internal)
define_constants;
results = attach_nyiso_zone_metadata(results);
online = results.gen(:, GEN_STATUS) > 0;
[mapped, bi] = ismember(results.gen(:, GEN_BUS), results.bus(:, BUS_I));
zone = strings(size(results.gen, 1), 1);
zone(mapped) = string(results.userdata.nyiso_physical_zone(bi(mapped)));
internal = online & zone ~= "";
internal(external_idx) = false;
metrics = struct('losses_mw', sum(results.gen(online, PG)) - ...
    sum(results.bus(:, PD)), 'reference_adjustment_mw', ...
    sum(results.gen(internal, PG)) - scheduled_internal);
end

function [success, note, metrics] = q_diagnostic(mpc, qpfopt, scenario_id, ...
        targets, ext, options)
metrics = struct('interface_objective', NaN, ...
    'max_abs_interface_residual_mw', NaN, 'min_voltage_pu', NaN, ...
    'max_voltage_pu', NaN, 'voltage_violation_count', NaN, ...
    'branch_overload_count', NaN);
success = false;
note = "";
try
    result = runpf(mpc, qpfopt);
    success = isfield(result, 'success') && logical(result.success);
    if ~success
        note = "Q-limit-enforced PF returned success = 0";
        return;
    end
    [metrics.interface_objective, detail] = score_interfaces( ...
        result, targets, options);
    metrics.max_abs_interface_residual_mw = max(abs(detail.residual_mw));
    define_constants;
    metrics.min_voltage_pu = min(result.bus(:, VM));
    metrics.max_voltage_pu = max(result.bus(:, VM));
    metrics.voltage_violation_count = sum(result.bus(:, VM) < ...
        result.bus(:, VMIN) - 1e-6 | result.bus(:, VM) > ...
        result.bus(:, VMAX) + 1e-6);
    sf = hypot(result.branch(:, PF), result.branch(:, QF));
    st = hypot(result.branch(:, PT), result.branch(:, QT));
    metrics.branch_overload_count = sum(result.branch(:, RATE_A) > 0 & ...
        max(sf, st) > result.branch(:, RATE_A) + 1e-6);
    if max(abs(result.gen(ext.added_gen_index, PG) - ext.target_flow_mw)) > 1e-6
        note = "External schedule changed in Q-limit diagnostic";
    end
catch ME
    note = string(regexprep(ME.message, '\s+', ' '));
end
if ~success && strlength(note) == 0
    note = "Q-limit-enforced PF failed for " + scenario_id;
end
end

function mpc = set_zone_reference(mpc, external_idx, zone_name)
define_constants;
mpc = attach_nyiso_zone_metadata(mpc);
[mapped, bi] = ismember(mpc.gen(:, GEN_BUS), mpc.bus(:, BUS_I));
zone = strings(size(mpc.gen, 1), 1);
zone(mapped) = string(mpc.userdata.nyiso_physical_zone(bi(mapped)));
mask = mpc.gen(:, GEN_STATUS) > 0 & zone == upper(string(zone_name));
mask(external_idx) = false;
idx = find(mask);
qrange = mpc.gen(idx, QMAX) - mpc.gen(idx, QMIN);
if any(qrange > 1e-6), idx = idx(qrange > 1e-6); end
[~, k] = max(mpc.gen(idx, PMAX) - mpc.gen(idx, PG));
mpc = set_scenario_reference_bus(mpc, idx(k), ...
    struct('require_external', false));
end

function rows = collect_violations(results, scenario_id, external_idx)
define_constants;
rows = table();
names = string(results.bus_name(:));
sf = hypot(results.branch(:, PF), results.branch(:, QF));
st = hypot(results.branch(:, PT), results.branch(:, QT));
smax = max(sf, st);
for b = find(results.branch(:, RATE_A) > 0 & ...
        smax > results.branch(:, RATE_A) + 1e-6)'
    fi = find(results.bus(:, BUS_I) == results.branch(b, F_BUS), 1);
    ti = find(results.bus(:, BUS_I) == results.branch(b, T_BUS), 1);
    row = table(scenario_id, "BRANCH_OVERLOAD", b, ...
        results.branch(b, F_BUS), names(fi), results.branch(b, T_BUS), ...
        names(ti), smax(b), results.branch(b, RATE_A), ...
        smax(b) - results.branch(b, RATE_A), "MVA", ...
        'VariableNames', violation_names());
    rows = append_table(rows, row);
end
for b = find(results.bus(:, VM) < results.bus(:, VMIN) - 1e-6 | ...
        results.bus(:, VM) > results.bus(:, VMAX) + 1e-6)'
    if results.bus(b, VM) < results.bus(b, VMIN)
        kind = "LOW_VOLTAGE";
        limit = results.bus(b, VMIN);
    else
        kind = "HIGH_VOLTAGE";
        limit = results.bus(b, VMAX);
    end
    row = table(scenario_id, kind, b, results.bus(b, BUS_I), names(b), ...
        NaN, "", results.bus(b, VM), limit, abs(results.bus(b, VM) - limit), ...
        "pu", 'VariableNames', violation_names());
    rows = append_table(rows, row);
end
pviol = max(max(0, results.gen(:, PMIN) - results.gen(:, PG)), ...
    max(0, results.gen(:, PG) - results.gen(:, PMAX)));
qviol = max(max(0, results.gen(:, QMIN) - results.gen(:, QG)), ...
    max(0, results.gen(:, QG) - results.gen(:, QMAX)));
for g = find(pviol > 1e-6)'
    bi = find(results.bus(:, BUS_I) == results.gen(g, GEN_BUS), 1);
    kind = "GEN_P_LIMIT";
    if ismember(g, external_idx), kind = "EXTERNAL_GEN_P_LIMIT"; end
    row = table(scenario_id, kind, g, results.gen(g, GEN_BUS), names(bi), ...
        NaN, "", results.gen(g, PG), ...
        max(results.gen(g, PMIN), min(results.gen(g, PG), results.gen(g, PMAX))), ...
        pviol(g), "MW", 'VariableNames', violation_names());
    rows = append_table(rows, row);
end
for g = find(qviol > 1e-6)'
    bi = find(results.bus(:, BUS_I) == results.gen(g, GEN_BUS), 1);
    kind = "GEN_Q_LIMIT";
    if ismember(g, external_idx), kind = "EXTERNAL_GEN_Q_LIMIT"; end
    row = table(scenario_id, kind, g, results.gen(g, GEN_BUS), names(bi), ...
        NaN, "", results.gen(g, QG), ...
        max(results.gen(g, QMIN), min(results.gen(g, QG), results.gen(g, QMAX))), ...
        qviol(g), "MVAr", 'VariableNames', violation_names());
    rows = append_table(rows, row);
end
end

