function outputs = run_s8_iterative_ac_injection_closure(options)
%RUN_S8_ITERATIVE_AC_INJECTION_CLOSURE Benchmark AC dispatch re-estimation.
%   Preserves direct-PERFORM S7 as the structural network. For each public
%   scenario it compares the frozen S6 dispatch against an iterative,
%   loss-adjusted AC zonal dispatch inferred from the same seven public
%   interface targets. The operational score is explicitly in-sample and
%   must not be interpreted as independent validation of interface physics.

if nargin < 1, options = struct(); end
helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
addpath(case_dir); addpath(helper_dir);
options = defaults(options, helper_dir);
define_constants;

scenarios = readtable(options.scenario_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
frozen = readtable(options.frozen_zonal_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
base_full = loadcase(options.structural_case);
[gsk, ~] = build_perform_npcc_generation_shift_keys(base_full);
[core_template, ~] = build_ny_only_equivalent_case(base_full);
[core_template, ~] = align_npcc_generation_capacity_to_perform_gsk( ...
    core_template, gsk);

pfopt = mpoption('verbose', 0, 'out.all', 0, 'pf.enforce_q_lims', 0);
qpfopt = mpoption('verbose', 0, 'out.all', 0, 'pf.enforce_q_lims', 1);
result_rows = table();
interface_rows = table();
history_rows = table();
sensitivity_rows = table();
participation_rows = table();
zonal_rows = table();
allocation_rows = table();
violation_rows = table();
q_rows = table();

for s = 1:height(scenarios)
    scenario_id = string(scenarios.scenario_id(s));
    loaded_core = core_template;
    [loaded_core, ~] = apply_nyiso_zonal_loads(loaded_core, ...
        scenario_id, 1.0, struct('preserve_total_ny_load', true));

    frozen_target = frozen(string(frozen.scenario_id) == scenario_id, :);
    if height(frozen_target) ~= 11
        error('Expected 11 frozen S6 zonal rows for %s.', scenario_id);
    end
    [structural_case, ~] = apply_perform_generation_allocation( ...
        loaded_core, frozen_target(:, {'zone','target_generation_mw'}), gsk);
    [structural_case, structural_ext] = ...
        apply_nyiso_external_interface_injections(structural_case, ...
        scenario_id, struct('target_file', options.external_target_file));
    structural_case = set_zone_reference(structural_case, ...
        structural_ext.added_gen_index, options.structural_balance_zone);
    structural_result = runpf(structural_case, pfopt);
    if ~structural_result.success
        error('Frozen-S6 structural PF failed for %s.', scenario_id);
    end

    public_targets = read_public_interface_targets(scenario_id, ...
        options.interface_target_file);
    [structural_objective, structural_detail] = score_interfaces( ...
        structural_result, public_targets, options);

    [estimator_case, ext] = apply_nyiso_external_interface_injections( ...
        loaded_core, scenario_id, ...
        struct('target_file', options.external_target_file));
    estimator_options = options.estimator_options;
    estimator_options.interface_target_file = options.interface_target_file;
    estimator_options.interface_scale_file = options.interface_scale_file;
    estimator_options.accuracy_scale_file = options.accuracy_scale_file;
    [final_targets, iterative] = ...
        derive_nyiso_zonal_net_injections_ac_iterative(estimator_case, ...
        scenario_id, gsk, ext.added_gen_index, estimator_options);
    operational_result = iterative.final_result;
    operational_detail = iterative.interface_table;
    operational_objective = iterative.operational_score_reoptimized_dispatch;

    dc_detail = iterative.initial_dc_interface_table;
    combined = combine_interface_detail(scenario_id, public_targets, ...
        dc_detail, structural_detail, operational_detail);
    interface_rows = append_table(interface_rows, combined);
    history_rows = append_table(history_rows, iterative.history);
    sensitivity_rows = append_table(sensitivity_rows, ...
        iterative.sensitivity_history);
    participation_rows = append_table(participation_rows, ...
        iterative.participation_history);
    zonal_rows = append_table(zonal_rows, add_scenario(final_targets, scenario_id));
    allocation_rows = append_table(allocation_rows, ...
        add_scenario(iterative.final_allocation, scenario_id));

    structural_metrics = result_metrics(structural_result, ...
        structural_ext.added_gen_index, sum(frozen_target.target_generation_mw));
    operational_metrics = iterative.final_metrics;
    violations = collect_violations(operational_result, scenario_id, ...
        ext.added_gen_index);
    violation_rows = append_table(violation_rows, violations);
    [q_success, q_note, q_metrics] = q_diagnostic(iterative.final_case, ...
        qpfopt, scenario_id, public_targets, ext, options);
    qrow = table(scenario_id, q_success, q_metrics.interface_objective, ...
        q_metrics.max_abs_interface_residual_mw, q_metrics.min_voltage_pu, ...
        q_metrics.max_voltage_pu, q_metrics.voltage_violation_count, ...
        q_metrics.branch_overload_count, q_note, ...
        'VariableNames', {'scenario_id','q_enforced_pf_success', ...
        'interface_objective','max_abs_interface_residual_mw', ...
        'min_voltage_pu','max_voltage_pu','voltage_violation_count', ...
        'branch_overload_count','diagnostic'});
    q_rows = append_table(q_rows, qrow);

    improvement = 100 * (structural_objective - operational_objective) / ...
        max(structural_objective, eps);
    row = table(scenario_id, true, true, ...
        iterative.initial_dc_interface_objective, structural_objective, ...
        operational_objective, improvement, ...
        max(abs(structural_detail.residual_mw)), ...
        max(abs(operational_detail.final_ac_residual_mw)), ...
        mean(abs(structural_detail.residual_mw)), ...
        mean(abs(operational_detail.final_ac_residual_mw)), ...
        mean(structural_detail.residual_mw), ...
        mean(operational_detail.final_ac_residual_mw), ...
        iterative.calibration_huber_objective, iterative.iteration_count, ...
        iterative.converged, structural_metrics.losses_mw, ...
        operational_metrics.losses_mw, ...
        structural_metrics.reference_adjustment_mw, ...
        operational_metrics.reference_adjustment_mw, ...
        operational_metrics.min_voltage_pu, operational_metrics.max_voltage_pu, ...
        operational_metrics.voltage_violation_count, ...
        operational_metrics.branch_overload_count, ...
        operational_metrics.max_branch_overload_mva, ...
        operational_metrics.generator_p_violation_count, ...
        operational_metrics.max_generator_p_violation_mw, ...
        operational_metrics.generator_q_violation_count, ...
        operational_metrics.max_generator_q_violation_mvar, q_success, ...
        'VariableNames', result_names());
    result_rows = append_table(result_rows, row);
end

score_summary = summarize_scores(interface_rows);
interface_summary = summarize_interfaces(interface_rows);
writetable(result_rows, options.result_file);
writetable(interface_rows, options.interface_file);
writetable(score_summary, options.summary_file);
writetable(interface_summary, options.interface_summary_file);
writetable(history_rows, options.history_file);
writetable(sensitivity_rows, options.sensitivity_file);
writetable(participation_rows, options.participation_file);
writetable(zonal_rows, options.zonal_file);
writetable(allocation_rows, options.allocation_file);
writetable(violation_rows, options.violation_file);
writetable(q_rows, options.q_diagnostic_file);

outputs = struct('result_file', options.result_file, ...
    'interface_file', options.interface_file, ...
    'summary_file', options.summary_file, ...
    'interface_summary_file', options.interface_summary_file, ...
    'history_file', options.history_file, ...
    'sensitivity_file', options.sensitivity_file, ...
    'participation_file', options.participation_file, ...
    'zonal_file', options.zonal_file, ...
    'allocation_file', options.allocation_file, ...
    'violation_file', options.violation_file, ...
    'q_diagnostic_file', options.q_diagnostic_file, ...
    'scenario_count', height(result_rows), ...
    'standard_pf_success_count', sum(result_rows.operational_pf_success), ...
    'q_enforced_pf_success_count', sum(result_rows.q_enforced_pf_success), ...
    'score_summary', score_summary, ...
    'interface_summary', interface_summary);
end

