function outputs = export_s8_winter_peak_handoff(options)
%EXPORT_S8_WINTER_PEAK_HANDOFF Export runnable S7/S8 winter PF artifacts.
%   Produces flattened MATPOWER cases and compact scenario reports. The S8
%   interface fit is in-sample because the same seven targets are used by
%   the iterative AC zonal-injection estimator.

if nargin < 1, options = struct(); end
helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
workspace_dir = fileparts(case_dir);
addpath(case_dir); addpath(helper_dir);
options = defaults(options, helper_dir, workspace_dir);
define_constants;

case_output = fullfile(options.output_dir, 'cases');
data_output = fullfile(options.output_dir, 'data');
result_output = fullfile(options.output_dir, 'results');
ensure_dir(options.output_dir);
ensure_dir(case_output);
ensure_dir(data_output);
ensure_dir(result_output);

structural = loadcase(options.structural_case);
[gsk, ~] = build_perform_npcc_generation_shift_keys(structural);
[core, ~] = build_ny_only_equivalent_case(structural);
[core, ~] = align_npcc_generation_capacity_to_perform_gsk(core, gsk);
[core, ~] = apply_nyiso_zonal_loads(core, options.scenario_id, 1.0, ...
    struct('preserve_total_ny_load', true));
[estimator_case, external] = apply_nyiso_external_interface_injections( ...
    core, options.scenario_id, struct('target_file', options.external_target_file));

estimator_options = struct( ...
    'interface_target_file', options.interface_target_file, ...
    'interface_scale_file', options.interface_scale_file, ...
    'accuracy_scale_file', options.accuracy_scale_file);
[zonal_targets, iterative] = derive_nyiso_zonal_net_injections_ac_iterative( ...
    estimator_case, options.scenario_id, gsk, external.added_gen_index, ...
    estimator_options);

operating_case = iterative.final_case;
operating_case.userdata.handoff = struct( ...
    'scenario_id', char(options.scenario_id), ...
    'structural_source', options.structural_case, ...
    'operational_stage', 'S8 iterative AC zonal-injection closure', ...
    'interface_fit_status', 'in-sample seven-interface fit', ...
    'standard_pf_success', logical(iterative.final_result.success), ...
    'estimator_iteration_count', iterative.iteration_count);
solution = iterative.final_result;

structural_m = fullfile(case_output, 'npcc_ny_lite_s7_perform_direct_flat.m');
structural_mat = fullfile(case_output, 'npcc_ny_lite_s7_perform_direct_flat.mat');
operating_m = fullfile(case_output, 'npcc_ny_lite_s8_winter_peak_operating_case.m');
operating_mat = fullfile(case_output, 'npcc_ny_lite_s8_winter_peak_operating_case.mat');
solution_m = fullfile(case_output, 'npcc_ny_lite_s8_winter_peak_pf_solution.m');
solution_mat = fullfile(case_output, 'npcc_ny_lite_s8_winter_peak_pf_solution.mat');

savecase(structural_m, structural);
mpc = structural;
save(structural_mat, 'mpc');
savecase(operating_m, operating_case);
mpc = operating_case;
save(operating_mat, 'mpc');
savecase(solution_m, solution);
results = solution;
save(solution_mat, 'results');

public_targets = readtable(options.interface_target_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
public_targets = public_targets(public_targets.scenario_id == options.scenario_id & ...
    ismember(public_targets.interface_name, iterative.interface_table.interface_name), :);
load_targets = readtable(options.load_target_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
load_targets = load_targets(load_targets.scenario_id == options.scenario_id, :);
external_targets = readtable(options.external_target_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
external_targets = external_targets(external_targets.scenario_id == options.scenario_id, :);

comparison = iterative.interface_table;
comparison.Properties.VariableNames{'final_ac_flow_mw'} = 'calculated_pf_flow_mw';
comparison.Properties.VariableNames{'final_ac_residual_mw'} = 'residual_mw';
comparison.absolute_error_mw = abs(comparison.residual_mw);
comparison.signed_percentage_error_pct = 100 * comparison.residual_mw ./ ...
    abs(comparison.target_flow_mw);
comparison.absolute_percentage_error_pct = ...
    abs(comparison.signed_percentage_error_pct);
comparison.target_source = repmat("scaled NYISO P-32", height(comparison), 1);
wape_pct = 100 * sum(comparison.absolute_error_mw) / ...
    sum(abs(comparison.target_flow_mw));
mape_pct = mean(comparison.absolute_percentage_error_pct);

defs = ny_lite_interface_definitions(solution);
interface_map = struct2table(defs);
interface_map.interface_name = string(interface_map.interface_name);
interface_map = interface_map(ismember(interface_map.interface_name, ...
    comparison.interface_name), :);

external_dispatch = external;
external_dispatch.actual_pg_mw = solution.gen(external.added_gen_index, PG);
external_dispatch.actual_qg_mvar = solution.gen(external.added_gen_index, QG);
external_dispatch.pg_error_mw = external_dispatch.actual_pg_mw - ...
    external_dispatch.target_flow_mw;

dispatch = generator_dispatch_table(solution, external.added_gen_index);
case_metadata = case_metadata_table(structural, operating_case, solution, ...
    structural_m, structural_mat, operating_m, operating_mat, solution_m, ...
    solution_mat, options);
provenance = provenance_table(options);

all_results = readtable(options.s8_result_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
summary = all_results(all_results.scenario_id == options.scenario_id, :);
if height(summary) ~= 1
    error('Expected one S8 result row for %s.', options.scenario_id);
end
summary.wape_pct = wape_pct;
summary.mape_pct = mape_pct;
summary.all_interfaces_within_25_mw = ...
    all(comparison.absolute_error_mw <= 25);
summary.all_interfaces_within_50_mw = ...
    all(comparison.absolute_error_mw <= 50);

writetable(public_targets, fullfile(data_output, ...
    'winter_peak_nyiso_interface_targets.csv'));
writetable(load_targets, fullfile(data_output, ...
    'winter_peak_nyiso_zonal_load_targets.csv'));
writetable(external_targets, fullfile(data_output, ...
    'winter_peak_nyiso_external_targets.csv'));
writetable(interface_map, fullfile(data_output, ...
    'winter_peak_interface_branch_map.csv'));
writetable(gsk, fullfile(data_output, 'perform_generation_shift_keys.csv'));
copyfile(options.tie_parameter_file, fullfile(data_output, ...
    'perform_supported_tie_parameters.csv'));

writetable(comparison, fullfile(result_output, ...
    'winter_peak_interface_comparison.csv'));
writetable(summary, fullfile(result_output, 'winter_peak_pf_summary.csv'));
writetable(zonal_targets, fullfile(result_output, ...
    'winter_peak_zonal_generation.csv'));
writetable(iterative.final_allocation, fullfile(result_output, ...
    'winter_peak_bus_generation_allocation.csv'));
writetable(dispatch, fullfile(result_output, ...
    'winter_peak_generator_dispatch.csv'));
writetable(external_dispatch, fullfile(result_output, ...
    'winter_peak_external_dispatch.csv'));
writetable(case_metadata, fullfile(options.output_dir, 'CASE_INVENTORY.csv'));
writetable(provenance, fullfile(options.output_dir, 'SOURCE_PROVENANCE.csv'));

outputs = struct('output_dir', options.output_dir, ...
    'scenario_id', options.scenario_id, 'structural_case', structural, ...
    'operating_case', operating_case, 'solution', solution, ...
    'interface_comparison', comparison, 'summary', summary, ...
    'zonal_targets', zonal_targets, 'external_dispatch', external_dispatch, ...
    'wape_pct', wape_pct, 'mape_pct', mape_pct, ...
    'iteration_count', iterative.iteration_count);
end

function options = defaults(options, helper_dir, workspace_dir)
items = { ...
    'scenario_id', "S2_2025_WINTER_PEAK_PUBLIC"; ...
    'structural_case', 'npcc_ny_lite_s7_seven_interface_perform_direct_candidate'; ...
    'interface_target_file', fullfile(helper_dir, 'nyiso_public_interface_targets.csv'); ...
    'interface_scale_file', fullfile(helper_dir, 'nyiso_interface_objective_scales.csv'); ...
    'accuracy_scale_file', fullfile(helper_dir, 'nyiso_interface_accuracy_scales.csv'); ...
    'load_target_file', fullfile(helper_dir, 'ny_zonal_load_targets.csv'); ...
    'external_target_file', fullfile(helper_dir, 'ny_external_interface_targets.csv'); ...
    'tie_parameter_file', fullfile(helper_dir, 's7_perform_direct_branch_parameters.csv'); ...
    's8_result_file', fullfile(helper_dir, 's8_ac_iterative_pf_results.csv'); ...
    'output_dir', fullfile(workspace_dir, 'output', 's8_winter_peak_handoff')};
for k = 1:size(items, 1)
    if ~isfield(options, items{k, 1}), options.(items{k, 1}) = items{k, 2}; end
end
options.scenario_id = string(options.scenario_id);
end

function dispatch = generator_dispatch_table(results, external_idx)
define_constants;
results = attach_nyiso_zone_metadata(results);
n = size(results.gen, 1);
[mapped, bi] = ismember(results.gen(:, GEN_BUS), results.bus(:, BUS_I));
bus_name = strings(n, 1);
zone = strings(n, 1);
bus_name(mapped) = string(results.bus_name(bi(mapped)));
zone(mapped) = string(results.userdata.nyiso_physical_zone(bi(mapped)));
is_external = ismember((1:n)', external_idx);
dispatch = table((1:n)', results.gen(:, GEN_BUS), bus_name, zone, ...
    is_external, results.gen(:, GEN_STATUS), results.gen(:, PG), ...
    results.gen(:, QG), results.gen(:, PMIN), results.gen(:, PMAX), ...
    results.gen(:, QMIN), results.gen(:, QMAX), results.gen(:, VG), ...
    'VariableNames', {'gen_index','bus_id','bus_name','zone', ...
    'is_external_boundary_equivalent','status','pg_mw','qg_mvar', ...
    'pmin_mw','pmax_mw','qmin_mvar','qmax_mvar','vg_pu'});
end

function inventory = case_metadata_table(structural, operating, solution, ...
        structural_m, structural_mat, operating_m, operating_mat, solution_m, ...
        solution_mat, options)
stage = ["S7_STRUCTURAL"; "S7_STRUCTURAL"; "S8_WINTER_OPERATING"; ...
    "S8_WINTER_OPERATING"; "S8_WINTER_PF_SOLUTION"; "S8_WINTER_PF_SOLUTION"];
file_type = ["MATPOWER_M"; "MAT_FULL_METADATA"; "MATPOWER_M"; ...
    "MAT_FULL_METADATA"; "MATPOWER_M"; "MAT_FULL_RESULTS"];
file = string({structural_m; structural_mat; operating_m; operating_mat; ...
    solution_m; solution_mat});
file = "cases/" + string(cellfun(@file_name, cellstr(file), ...
    'UniformOutput', false));
bus_count = [size(structural.bus, 1); size(structural.bus, 1); ...
    size(operating.bus, 1); size(operating.bus, 1); ...
    size(solution.bus, 1); size(solution.bus, 1)];
branch_count = [size(structural.branch, 1); size(structural.branch, 1); ...
    size(operating.branch, 1); size(operating.branch, 1); ...
    size(solution.branch, 1); size(solution.branch, 1)];
generator_count = [size(structural.gen, 1); size(structural.gen, 1); ...
    size(operating.gen, 1); size(operating.gen, 1); ...
    size(solution.gen, 1); size(solution.gen, 1)];
scenario_id = [""; ""; options.scenario_id; options.scenario_id; ...
    options.scenario_id; options.scenario_id];
authoritative_for_rerun = [false; false; false; true; false; false];
inventory = table(stage, file_type, file, scenario_id, bus_count, ...
    branch_count, generator_count, authoritative_for_rerun);
end

function name = file_name(path)
[~, base, ext] = fileparts(path);
name = [base ext];
end

function provenance = provenance_table(options)
asset = ["structural_network"; "zonal_load"; "internal_interface_targets"; ...
    "external_interchange"; "within_zone_generation_allocation"; ...
    "zonal_generation_totals"; "supported_tie_parameters"];
source = ["S7 direct-PERFORM structural candidate"; "NYISO P-58C scaled"; ...
    "NYISO P-32 scaled"; "NYISO P-32 scaled"; "PERFORM 2019 GSK"; ...
    "S8 iterative AC inverse"; "PERFORM direct circuits"];
application = ["flattened 143-bus structural source"; ...
    "preserve 10902.22 MW NPCC NY total"; "seven in-sample PF targets"; ...
    "fixed boundary-equivalent schedules"; "allocate zonal generation to buses"; ...
    "loss-adjusted AC interface closure"; "three supported added corridors"];
caveat = ["structural candidate, not certified operating case"; ...
    "scaled public snapshot"; "used to infer dispatch, so not holdout validation"; ...
    "fixed P schedules with simplified Q behavior"; "single 2019 on-peak prior"; ...
    "operational diagnostic, not observed generation"; ...
    "remaining added proxy ties are engineering equivalents"];
scenario_id = repmat(options.scenario_id, numel(asset), 1);
provenance = table(asset, source, application, caveat, scenario_id);
end

function ensure_dir(path)
if exist(path, 'dir') ~= 7, mkdir(path); end
end
