function out=compact_nyiso_interface_operator_variant(mpc,branch_keys,options)
%COMPACT_NYISO_INTERFACE_OPERATOR_VARIANT Source-informed research cuts.
% Separate from the frozen compact_nyiso_interface_operators baseline.
% Definitions depend only on topology, zone metadata and stable circuit keys.
% No snapshot targets, generation dispatch or interface residuals are inputs.
% NYgrid Table I and NYISO interface definitions justify A/all, AB/all, and
% western A-E/eastern F-K partitions, rather than adjacent-zone-only cuts.
% Uniform upstream-terminal AC metering is a declared research convention;
% official mixed metering locations and missing circuits remain unresolved.
if nargin<3,options=struct();end
if ~isfield(options,'variant'),options.variant="nygrid_informed_partition_v1";end
assert(string(options.variant)=="nygrid_informed_partition_v1", ...
    'compact_operator_variant:Variant','Unknown operator variant.');
define_constants;keys=string(branch_keys(:));n=size(mpc.branch,1);nb=size(mpc.bus,1);
assert(numel(keys)==n&&numel(unique(keys))==n&&all(strlength(keys)>0), ...
    'compact_operator_variant:Keys','One unique stable key is required per branch.');
assert(isfield(mpc,'userdata')&&isfield(mpc.userdata,'nyiso_physical_zone'), ...
    'compact_operator_variant:Zones','Explicit bus-aligned physical zones required.');
z=string(mpc.userdata.nyiso_physical_zone(:));ids=mpc.bus(:,BUS_I);
assert(numel(z)==nb&&all(ismember(z,string(('A':'K')')))&&numel(unique(ids))==nb, ...
    'compact_operator_variant:Zones','Only uniquely identified NY buses and A-K zones are accepted.');
[ok,f]=ismember(mpc.branch(:,F_BUS),ids);assert(all(ok),'compact_operator_variant:Endpoint','Unknown from bus.');
[ok,t]=ismember(mpc.branch(:,T_BUS),ids);assert(all(ok),'compact_operator_variant:Endpoint','Unknown to bus.');
names=["Dysinger_East";"West_Central";"Moses_South";"Central_East"; ...
    "Total_East_proxy";"UPNY_ConEd";"Dunwoodie_South"];
up=false(nb,7);down=false(nb,7);
up(:,1)=z=="A";down(:,1)=~up(:,1);
up(:,2)=ismember(z,["A","B"]);down(:,2)=~up(:,2);
up(:,3)=z=="D";down(:,3)=~up(:,3);
up(:,4)=z=="E";down(:,4)=z=="F";
up(:,5)=ismember(z,["A","B","C","D","E"]);down(:,5)=~up(:,5);
up(:,6)=ismember(z,["A","B","C","D","E","F","G"])&~ismember(ids,[858;9002]);
down(:,6)=~up(:,6); % East Fishkill and Wood Street lie beyond this local cut.
up(:,7)=z=="I";down(:,7)=z=="J";
% These inherited identities are the documented non-adjacent paths that
% motivated the correction. Resolve by key and validate endpoints, not row.
anchor(keys,mpc,"NPCC_S7:BRANCH_ROW:73",[62 63]);
anchor(keys,mpc,"NPCC_S7:BRANCH_ROW:37",[38 69]);
upny=["PERFORM2019:AC:651:858:1";"PERFORM2019:AC:651:858:2"; ...
    "PERFORM2019:AC:651:902:1";"PERFORM2019:AC:651:902:2"; ...
    "PERFORM2019:AC:774:900:1";"PERFORM2019:AC:900:1519:1"];
ends=[73 858;73 858;73 9002;73 9002;774 77;76 77];
for j=1:6,anchor(keys,mpc,upny(j),ends(j,:));end
Cf=sparse(7,n);Ct=sparse(7,n);members=table();
for k=1:7
    a=up(f,k)&down(t,k)&mpc.branch(:,BR_STATUS)>0;
    b=up(t,k)&down(f,k)&mpc.branch(:,BR_STATUS)>0;
    ix=find(a|b);assert(~isempty(ix),'compact_operator_variant:Empty','Empty active operator.');
    if k==6
        assert(isequal(sort(keys(ix)),sort(upny)), ...
            'compact_operator_variant:UPNYCut','UPNY partition no longer equals its six registered source circuits.');
    end
    Cf(k,a)=1;Ct(k,b)=1;meter=mpc.branch(ix,F_BUS);meter(b(ix))=mpc.branch(ix(b(ix)),T_BUS);
    col=repmat("PF",numel(ix),1);col(b(ix))="PT";
    members=[members;table(repmat(names(k),numel(ix),1),keys(ix),ix, ...
        mpc.branch(ix,F_BUS),mpc.branch(ix,T_BUS),meter,col,ones(numel(ix),1), ...
        'VariableNames',{'interface_name','branch_key','model_branch_row','from_bus', ...
        'to_bus','metered_bus','meter_column','sign'})]; %#ok<AGROW>
end
complete_partition=all(up|down,1)';
kind=["full_A_export_partition";"full_AB_export_partition";"full_D_export_partition"; ...
    "partial_E_to_F_corridor_proxy";"full_A_to_E_export_partition"; ...
    "source_six_circuit_local_partition";"partial_I_to_J_corridor_proxy"];
registry=table(names,kind,complete_partition,false(7,1), ...
    repmat("uniform_upstream_terminal_AC_proxy",7,1), ...
    'VariableNames',{'interface_name','operator_kind','complete_NY_partition', ...
    'exact_public_operator','metering_convention'});
gaps=table(names,[ ...
    "Western transfer aggregation lacks individual115kV paths and later Dysinger physical devices"; ...
    "Stolle-Meyer bypass restored; individual115kV and low-voltage members remain aggregated"; ...
    "Explicit Massena-Marcy765kV path absent;230kV and lower-voltage paths are aggregated"; ...
    "Marcy-NewScotland and115kV members absent; Plattsburgh-SandBar boundary not separately observed; two inherited230kV proxies remain"; ...
    "No explicit Coopers-Middletown MarcySouth paths; Binghamton-Gilboa is a coarse substitute; selected PJM and Plattsburgh boundary contributions unresolved"; ...
    "RFK305 and lower-voltage EastFishkill members absent; six-circuit source proxy only"; ...
    "Receiving network aggregates monitored circuits; I-J excludes K-J and differs from closed Dunwoodie definitions"], ...
    'VariableNames',{'interface_name','unresolved_public_coverage'});
sources=table(["NYgrid_TableI_and_flow4Plot";"NYISO_DE_WC_2014";"NYISO_CEVC_2024"; ...
    "NYISO_TE_2023";"NYISO_MS_2024";"NYISO_Appendix5_1"], ...
    ["https://github.com/AndersonEnergyLab-Cornell/NYgrid/blob/47698b6c7823ae7b1bc6935e5601d5b64b8f918e/Utility/flow4Plot.m"; ...
    "https://www.nyiso.com/documents/20142/1394656/DE_WC_Stability_Limit_Report_final-3.pdf/b461b192-f51d-7bf7-340e-d424b60c84fa"; ...
    "https://www.nyiso.com/documents/20142/3692791/Central-East-Voltage-Limit-Study-2024-FINAL.pdf"; ...
    "https://www.nyiso.com/documents/20142/3692388/TE-23-StabReport-OC-09-15-2023-Approved.pdf/b03ef116-aa5a-616d-9a5a-86f091e8e53d"; ...
    "https://www.nyiso.com/documents/20142/1411640/MS-24-StabReport-OC-07-18-2024-Approved.pdf/1c512118-6ef0-2092-5653-2f2807d3e380"; ...
    "https://www.nyiso.com/documents/20142/1410707/CRPP_Appendix_5.1_Interface_Definitions.pdf/6bd50d60-bfd2-4572-31bf-634fbb6c8ddf"], ...
    'VariableNames',{'source_id','source_uri'});
out=struct('variant',string(options.variant),'names',names,'from_coefficients',Cf, ...
    'to_coefficients',Ct,'members',members,'registry',registry,'coverage_gaps',gaps, ...
    'definition_sources',sources,'upstream_bus_mask',up,'downstream_bus_mask',down, ...
    'public_operator_complete',false,'targets_used_to_construct',false, ...
    'boundary_offset_mw',zeros(7,1),'boundary_offsets_inferred',false, ...
    'qualification_scope',"source_informed_research_partition_operators_only");
end

function anchor(keys,m,key,ends)
ix=find(keys==key);assert(isscalar(ix),'compact_operator_variant:AnchorKey','Missing or duplicate critical stable key %s.',key);
assert(isequal(sort(m.branch(ix,1:2)),sort(ends)), ...
    'compact_operator_variant:AnchorEndpoint','Critical key %s has different endpoints.',key);
assert(m.branch(ix,11)>0,'compact_operator_variant:InactiveAnchor','Critical member %s is inactive.',key);
end
