    ["replaced_existing_added_zero_injection230_proxy";repmat("new_zero_injection_station_section",5,1)], ...
    repmat("declared_compact_zone_allocation_not_verified_NYISO_station_zone",6,1), ...
    'VariableNames',{'model_bus','model_bus_name','base_kv','physical_zone','initial_voltage_anchor', ...
