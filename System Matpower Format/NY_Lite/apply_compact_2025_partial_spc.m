    md=struct('bus_id',ids(k),'physical_zone',char(zones(k)), ...
        'load_allocation_group',char(zones(k)),'nyiso_zone_name',char(zones(k)), ...
        'nyiso_zone_id',zid,'perform_zone_code',64+zid);
    c.userdata.ny_lite.transit_zone_metadata(end+1)=md;
end
