        "DRAKE_795_ACSR",bundles(k),lengths(k),src.source_key,true);
    spec.template_base_kv(end)=src.from_base_kv;spec.template_length_miles(end)=src.estimated_length_miles;
    spec.template_x_pu(end)=src.x_pu;spec.template_b_pu(end)=src.b_pu;
    spec.x_ohm_per_mile(end)=x_ohm_per_mile;spec.b_siemens_per_mile(end)=b_si_per_mile;
