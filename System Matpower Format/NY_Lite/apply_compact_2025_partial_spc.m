spec.parameter_ground_truth_verified=false(height(spec),1);spec.physical_conductor_verified=false(height(spec),1);
spec.thermal_surrogate_qualified=false(height(spec),1);spec.circuits=ones(height(spec),1);
spec.conductor_choice_basis=repmat("none_nonthermal",height(spec),1);
spec.conductor_choice_basis(1:3)="planning_Drake_size_motivates_ACSR_surrogate_installed_conductor_unverified";
spec.conductor_choice_basis(4:6)="planning_ACSS_is_not_ACSR_library_uses_declared_Drake_ACSR_surrogate";
spec.resistance_reference_c=nan(height(spec),1);spec.resistance_reference_c(1:6)=75;
spec.effective_thermal_length_miles=nan(height(spec),1);
spec.effective_thermal_length_miles(1:6)=spec.length_miles(1:6)*options.impedance_scale;
br=[spec.from_bus spec.to_bus spec.r_pu spec.x_pu spec.b_pu ...
    repmat(spec.rate_a_mva,1,3) spec.tap spec.shift_degree spec.status repmat([-360 360],height(spec),1)];
if size(p.branch,2)>13,br(:,14:size(p.branch,2))=0;end
