spec=add(spec,"PLATTS_REGIONAL_EQ",[49 9124],r(3:5),r(6),r(9), ...
    "inherited_regional_voltage_transforming_equivalent", ...
    "NPCC_S7:BRANCH_ROW:220;SPC_WRY1;SPC_WPN1;SPC_WPN2;SPC_W1", ...
    "relocate230kV_end_to_Willis_keep115_230_base_and_parent_R_X_B_whole_function_retired_once", ...
    "",0,nan,"NPCC_S7:BRANCH_ROW:220",false);
