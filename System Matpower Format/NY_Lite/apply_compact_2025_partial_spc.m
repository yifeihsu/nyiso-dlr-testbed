function t=manifest(root,a,b)
files={a;b;mfilename('fullpath');which('dlr_conductor_library')};
if ~endsWith(files{3},'.m'),files{3}=[files{3} '.m'];end
artifact=strings(4,1);relative_path=artifact;sha256=artifact;
for k=1:4
    [~,name,ext]=fileparts(files{k});artifact(k)=string([name ext]);
    relative_path(k)=replace(string(files{k}),string(root)+filesep,"");
    relative_path(k)=replace(relative_path(k),"\","/");sha256(k)=hash_file(files{k});
end
t=table(["commissioning_status";"commissioning_sources";"partial_spc_builder";"conductor_surrogate"], ...
    artifact,relative_path,sha256,repmat("pinned_local_source_input_no_ignored_cache_dependency",4,1), ...
    'VariableNames',{'source_id','artifact','relative_path','sha256','use_policy'});
t.source_path=t.relative_path;t.sha256_lf_normalized=t.sha256;
t.hash_policy=repmat("SHA256_UTF8_source_bytes_with_CRLF_normalized_to_LF",height(t),1);
end

function h=hash_file(path)
fid=fopen(path,'rb');assert(fid>=0,'partial_spc:SourceFile','Cannot read source file.');
cleaner=onCleanup(@()fclose(fid)); %#ok<NASGU>
raw=fread(fid,Inf,'*uint8');raw=uint8(strrep(char(raw'),sprintf('\r\n'),sprintf('\n')));
md=java.security.MessageDigest.getInstance('SHA-256');
md.update(raw);h=lower(string(reshape(dec2hex(typecast(md.digest(),'uint8'),2).',1,[])));
end

