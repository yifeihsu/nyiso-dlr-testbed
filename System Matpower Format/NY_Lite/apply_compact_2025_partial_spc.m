[~,oldf]=ismember(p.branch(retired,1),p.bus(:,1));[~,oldt]=ismember(p.branch(retired,2),p.bus(:,1));
disposition=table(retired_keys,retired,p.branch(retired,1),p.branch(retired,2), ...
    p.bus(oldf,10),p.bus(oldt,10),ones(5,1),zeros(5,1), ...
    [repmat("whole_functional_replacement_not_individual_circuit_retirement_crosswalk",4,1); ...
    "relocated_regional_equivalent_whole_parent_row_retired"], ...
    [repmat(strjoin(spec.branch_key([1:3 5:9]),';'),4,1);strjoin(spec.branch_key([4 9 10]),';')], ...
    'VariableNames',{'parent_branch_key','parent_branch_row','historical_from_bus','historical_to_bus', ...
