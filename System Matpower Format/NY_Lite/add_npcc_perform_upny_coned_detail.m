    error('add_npcc_perform_upny_coned_detail:AlreadyPresent', ...
        'One or more Phase 1B PERFORM bus IDs already exist in the case.');
end

% Preserve source within-path phasor differences while aligning each new
% terminal to its existing NPCC attachment reference. These are initial
% values only; no operating-state or source-dispatch claim is made.
reference_model = [73; 76];
reference_source = [651; 1519];
first_bus_row = size(mpc.bus, 1) + 1;
for k = 1:numel(added_source_buses)
    si = find(src.bus(:, BUS_I) == added_source_buses(k), 1);
    mi = find(mpc.bus(:, BUS_I) == reference_model(k), 1);
    ri = find(src.bus(:, BUS_I) == reference_source(k), 1);
    if isempty(si) || isempty(mi) || isempty(ri)
        error('add_npcc_perform_upny_coned_detail:MissingSourceBus', ...
            'Missing Phase 1B source/reference bus for source bus %d.', ...
            added_source_buses(k));
    end
    if any(abs(src.bus(si, [PD QD GS BS])) > 1e-12)
        error('add_npcc_perform_upny_coned_detail:SourceInjection', ...
            'Source bus %d is not a zero-injection physical terminal.', ...
            added_source_buses(k));
    end
    new_bus = zeros(1, size(mpc.bus, 2));
    ncopy = min([13, size(src.bus, 2), size(mpc.bus, 2)]);
    new_bus(1:ncopy) = src.bus(si, 1:ncopy);
    new_bus([PD QD GS BS]) = 0;
    new_bus(BUS_TYPE) = PQ;
    new_bus(BUS_AREA) = mpc.bus(mi, BUS_AREA);
    new_bus(VA) = src.bus(si, VA) + ...
        (mpc.bus(mi, VA) - src.bus(ri, VA));
    new_bus(VM) = src.bus(si, VM) * ...
        (mpc.bus(mi, VM) / src.bus(ri, VM));
    mpc.bus = [mpc.bus; new_bus];
    mpc = append_bus_name(mpc, strtrim(src.bus_name{si}));
end

% Stable source order: Pleasant Valley/East Fishkill/Wood Street mesh,
% followed by the Ramapo/Ladentown/Buchanan path.
