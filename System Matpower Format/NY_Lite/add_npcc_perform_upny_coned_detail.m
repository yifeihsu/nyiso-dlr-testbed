mpc.userdata.ny_lite.transit_zone_metadata = existing;
end

function values = append_unique(values, additions)
values = values(:);
for k = 1:numel(additions)
    if ~ismember(additions(k), values)
        values(end + 1, 1) = additions(k); %#ok<AGROW>
    end
end
end

function out = append_struct(out, entry)
if isempty(out), out = entry; else, out(end + 1) = entry; end
end

