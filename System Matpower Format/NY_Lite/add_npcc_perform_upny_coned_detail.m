function validate_parent(mpc)
define_constants;
if size(mpc.bus, 1) ~= 147 || size(mpc.branch, 1) ~= 253 || ...
        size(mpc.gen, 1) ~= 62
    error('add_npcc_perform_upny_coned_detail:ParentDimensions', ...
        'Phase 1B requires the 147-bus/253-branch/62-generator Phase 1A case.');
end
required = [(1:140)'; 9001; 9002; 9003; 1228; 1222; 1567; 772];
if ~all(ismember(required, mpc.bus(:, BUS_I)))
    error('add_npcc_perform_upny_coned_detail:ParentIdentity', ...
        'The complete S7 parent and Phase 1A terminal identities are required.');
end
if ~isfield(mpc, 'userdata') || ...
        ~isfield(mpc.userdata, 'npcc_perform_overlay')
    error('add_npcc_perform_upny_coned_detail:ParentMetadata', ...
        'The Phase 1A cumulative overlay metadata is missing.');
end
overlay = mpc.userdata.npcc_perform_overlay;
if ~isfield(overlay, 'current_phase') || ...
        string(overlay.current_phase) ~= "phase1a"
    error('add_npcc_perform_upny_coned_detail:ParentPhase', ...
        'The input must be the Phase 1A candidate.');
end
expected_source_rows = [2137; 2131; 2154; 2133; 1567; 1568; 1571];
expected_model_rows = (247:253)';
if ~isfield(overlay, 'source_branch_rows') || ...
        ~isequal(overlay.source_branch_rows(:), expected_source_rows) || ...
        ~isfield(overlay, 'physical_branch_rows') || ...
        ~isequal(overlay.physical_branch_rows(:), expected_model_rows)
    error('add_npcc_perform_upny_coned_detail:ParentPhase1AIdentity', ...
        'The Phase 1A physical/source branch register changed.');
end
if isfield(overlay, 'promotion_eligible') && ...
        (~isscalar(overlay.promotion_eligible) || ...
        logical(overlay.promotion_eligible))
    error('add_npcc_perform_upny_coned_detail:ParentPromotion', ...
        'The Phase 1A parent must remain explicitly unpromoted.');
end
end

function validate_attachments(mpc, src, model_bus, source_bus, expected_zone)
define_constants;
for k = 1:numel(model_bus)
    mi = find(mpc.bus(:, BUS_I) == model_bus(k), 1);
    si = find(src.bus(:, BUS_I) == source_bus(k), 1);
    if isempty(mi) || isempty(si)
        error('add_npcc_perform_upny_coned_detail:MissingAttachment', ...
            'Missing model/source attachment %d/%d.', model_bus(k), ...
            source_bus(k));
    end
    model_name = normalize_attachment_name(mpc.bus_name{mi});
    source_name = normalize_attachment_name(src.bus_name{si});
    if model_name ~= source_name
        error('add_npcc_perform_upny_coned_detail:AttachmentName', ...
            'Attachment %d/%d does not satisfy the registered name alias.', ...
            model_bus(k), source_bus(k));
    end
    if abs(mpc.bus(mi, BASE_KV) - src.bus(si, BASE_KV)) > 1e-12 || ...
            abs(src.bus(si, BASE_KV) - 345) > 1e-12
        error('add_npcc_perform_upny_coned_detail:AttachmentVoltage', ...
            'Attachment %d/%d is not a matching 345-kV terminal.', ...
            model_bus(k), source_bus(k));
    end
    if model_physical_zone(mpc, mi) ~= expected_zone(k) || ...
            source_zone(src.bus(si, BUS_AREA)) ~= expected_zone(k)
        error('add_npcc_perform_upny_coned_detail:AttachmentZone', ...
            'Attachment %d/%d does not have the expected physical zone.', ...
            model_bus(k), source_bus(k));
    end
    if mpc.bus(mi, BUS_TYPE) ~= PQ || ...
            ~any(mpc.branch(:, F_BUS) == model_bus(k) | ...
            mpc.branch(:, T_BUS) == model_bus(k))
        error('add_npcc_perform_upny_coned_detail:AttachmentRole', ...
            'Attachment bus %d is not the expected connected PQ terminal.', ...
            model_bus(k));
    end
    if any(abs(src.bus(si, [PD QD GS BS])) > 1e-12)
        error('add_npcc_perform_upny_coned_detail:SourceTerminalRole', ...
            'Source bus %d is not the audited zero-bus-injection terminal.', ...
            source_bus(k));
    end
end

% The retained full-NPCC Pleasant Valley terminal must still connect to the
% external network. This distinguishes it from the PERFORM boundary proxy.
pv = find(mpc.bus(:, BUS_I) == 73, 1);
incident = find(mpc.branch(:, F_BUS) == 73 | mpc.branch(:, T_BUS) == 73);
neighbor = zeros(numel(incident), 1);
for k = 1:numel(incident)
    row = incident(k);
    neighbor(k) = mpc.branch(row, F_BUS);
    if neighbor(k) == 73, neighbor(k) = mpc.branch(row, T_BUS); end
end
neighbor_names = strings(numel(neighbor), 1);
for k = 1:numel(neighbor)
    ni = find(mpc.bus(:, BUS_I) == neighbor(k), 1);
    neighbor_names(k) = normalize_attachment_name(mpc.bus_name{ni});
end
if isempty(pv) || ~any(neighbor_names == "SOUTHINGTEN")
    error('add_npcc_perform_upny_coned_detail:PleasantValleyRole', ...
        'Pleasant Valley no longer has its retained full-NPCC external tie.');
end
end

