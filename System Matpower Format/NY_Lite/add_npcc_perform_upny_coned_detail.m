    ncopy = min([13, size(src.branch, 2), size(mpc.branch, 2)]);
    new_branch(1:ncopy) = src.branch(sr, 1:ncopy);
    new_branch(F_BUS) = model_from(k);
    new_branch(T_BUS) = model_to(k);
