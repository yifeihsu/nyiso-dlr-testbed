function [mpc, report] = add_npcc_perform_upny_coned_detail(mpc, options)
%ADD_NPCC_PERFORM_UPNY_CONED_DETAIL Append the source-backed Phase 1B overlay.
%   This function requires the 147-bus/253-branch S13 Phase 1A candidate.
%   It appends two zero-injection 345-kV terminals and nine direct PERFORM
%   physical branches. Existing NPCC/S7/S13 rows are not modified.
%
%   The resulting physical proxy is deliberately unpromoted. It excludes
%   unresolved public UPNY-ConEd elements and leaves overlapping aggregate
%   NPCC branches unchanged pending the Phase 1D passive residual fit.

if nargin < 2, options = struct(); end
if ~isfield(options, 'verbose'), options.verbose = true; end
if ~isfield(options, 'neutral_angle_bounds')
    options.neutral_angle_bounds = true;
end

helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
root = fileparts(case_dir);
perform_dir = fullfile(root, 'PERFORM', ...
    'On Peak 2019 v23_Perform_NY', 'On Peak 2019 v23');
addpath(case_dir); addpath(helper_dir); addpath(perform_dir);
define_constants;

validate_parent(mpc);
src = nyiso_On_Peak_v23_shunts_as_z_load;

source_case = "PERFORM/On Peak 2019 v23_Perform_NY/On Peak 2019 v23/" + ...
    "nyiso_On_Peak_v23_shunts_as_z_load.m";
source_name = "full_PERFORM_2019_case";

% Existing physical-terminal mappings. Pleasant Valley uses the explicit
% NPCC abbreviation alias; all other names must match exactly.
attachment_model = [73; 9002; 77; 74; 76];
attachment_source = [651; 902; 900; 897; 1519];
attachment_zone = ["G"; "G"; "H"; "H"; "G"];
validate_attachments(mpc, src, attachment_model, attachment_source, ...
    attachment_zone);

