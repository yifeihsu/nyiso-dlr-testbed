function row = gated_metric_row(type, name, circuit_id, source_branch, ...
        reduced_branch, source_value, reduced_value, unit, options, note)
[absolute_error, percent_error] = comparison_error( ...
    source_value, reduced_value, options.zero_reference_tolerance);
assessment = pass_fail(percent_error <= options.gate_percent);
row = table(string(type), string(name), string(circuit_id), ...
    double(source_branch), double(reduced_branch), double(source_value), ...
    double(reduced_value), string(unit), double(absolute_error), ...
    double(percent_error), options.gate_percent, assessment, string(note), ...
    'VariableNames', metric_variable_names());
end

function row = diagnostic_metric_row(type, name, source_value, ...
        reduced_value, unit, note)
row = table(string(type), string(name), "", NaN, NaN, ...
    double(source_value), double(reduced_value), string(unit), NaN, NaN, ...
    NaN, "diagnostic", string(note), ...
    'VariableNames', metric_variable_names());
end

function names = metric_variable_names()
names = {'metric_type','metric_name','physical_circuit_id', ...
    'source_branch_index','reduced_branch_index','source_value', ...
    'reduced_value','unit','absolute_error','absolute_percent_error', ...
    'gate_percent','assessment','note'};
end

function [absolute_error, percent_error] = comparison_error( ...
        source_value, reduced_value, zero_tolerance)
if ~isfinite(source_value) || ~isfinite(reduced_value)
    absolute_error = NaN;
    percent_error = Inf;
    return;
end
absolute_error = abs(reduced_value-source_value);
if abs(source_value) > zero_tolerance
    percent_error = 100 * absolute_error / abs(source_value);
elseif absolute_error <= zero_tolerance
    percent_error = 0;
else
    percent_error = Inf;
end
end

function value = max_or_zero(values)
if isempty(values), value = 0; else, value = max(values); end
end

function value = pass_fail(condition)
if condition, value = "pass"; else, value = "fail"; end
end

function out = append_table(out, row)
if isempty(out), out = row; else, out = [out; row]; end
end
