    'structural_case', "npcc_ny_lite_s7_seven_interface_perform_direct_candidate"; ...
    'perform_case_dir', string(fullfile(workspace_dir, 'PERFORM', ...
        'On Peak 2019 v23_Perform_NY', 'On Peak 2019 v23')); ...
    'perform_case_function', "nyiso_On_Peak_v23_shunts_as_z_load"; ...
    'perform_zone_file', string(fullfile(workspace_dir, 'PERFORM', ...
        'Auxilliary_Perform_NY', 'internal_NYISO_MOD2MAP.xlsx')); ...
    'control_map_file', string(fullfile(helper_dir, ...
        'perform_source_to_reduced_control_mapping.csv')); ...
    'output_file', string(fullfile(helper_dir, ...
        's11_2019_same_snapshot_benchmark.csv')); ...
    'write_output', true; ...
    'gate_percent', 15; ...
    'expected_boundary_group_count', 7; ...
    'load_tolerance_mva', 1e-7; ...
    'q_saturation_tolerance_mvar', 1e-3; ...
    'control_tolerance_mva', 1e-5; ...
    'zero_reference_tolerance', 1e-9; ...
    'enable_hard_feasibility_projection', true; ...
    'opf_solver', "IPOPT"; ...
    'opf_max_iterations', 1000; ...
    'non_dlr_correction', []};
for k = 1:size(items, 1)
    if ~isfield(options, items{k, 1})
        options.(items{k, 1}) = items{k, 2};
    end
end

string_fields = {'structural_case','perform_case_dir', ...
    'perform_case_function','perform_zone_file','control_map_file','output_file', ...
    'opf_solver'};
for k = 1:numel(string_fields)
    options.(string_fields{k}) = string(options.(string_fields{k}));
    if ~isscalar(options.(string_fields{k}))
        error('run_s11_2019_same_snapshot_benchmark:BadTextOption', ...
            '%s must be scalar text.', string_fields{k});
    end
end
validateattributes(options.write_output, {'logical','numeric'}, {'scalar'});
validateattributes(options.gate_percent, {'numeric'}, ...
    {'scalar','positive','finite'});
validateattributes(options.expected_boundary_group_count, {'numeric'}, ...
    {'scalar','integer','nonnegative','finite'});
validateattributes(options.load_tolerance_mva, {'numeric'}, ...
    {'scalar','positive','finite'});
validateattributes(options.q_saturation_tolerance_mvar, {'numeric'}, ...
    {'scalar','positive','finite'});
validateattributes(options.control_tolerance_mva, {'numeric'}, ...
    {'scalar','positive','finite'});
validateattributes(options.zero_reference_tolerance, {'numeric'}, ...
    {'scalar','nonnegative','finite'});
validateattributes(options.enable_hard_feasibility_projection, ...
    {'logical','numeric'}, {'scalar'});
validateattributes(options.opf_max_iterations, {'numeric'}, ...
    {'scalar','integer','positive','finite'});
options.write_output = logical(options.write_output);
options.enable_hard_feasibility_projection = ...
    logical(options.enable_hard_feasibility_projection);

required_files = [options.perform_zone_file; options.control_map_file];
for k = 1:numel(required_files)
    if exist(char(required_files(k)), 'file') ~= 2
        error('run_s11_2019_same_snapshot_benchmark:MissingInput', ...
            'Required benchmark input is missing: %s', required_files(k));
    end
end
if ~isfolder(options.perform_case_dir)
    error('run_s11_2019_same_snapshot_benchmark:MissingSourceDirectory', ...
        'PERFORM source-case directory is missing: %s', ...
        options.perform_case_dir);
end
end

function source = load_source_case(options)
if isfield(options, 'source_case') && ~isempty(options.source_case)
    source = options.source_case;
    if ischar(source) || isstring(source)
        source = loadcase(char(source));
    end
else
    function_name = char(options.perform_case_function);
    if exist(function_name, 'file') ~= 2
        error('run_s11_2019_same_snapshot_benchmark:MissingSourceCase', ...
            'Cannot resolve PERFORM source-case function %s.', function_name);
    end
    source = feval(function_name);
end
if ~isstruct(source) || ~isfield(source, 'bus') || ...
        ~isfield(source, 'branch') || ~isfield(source, 'gen')
    error('run_s11_2019_same_snapshot_benchmark:BadSourceCase', ...
        'The PERFORM source case is not a valid MATPOWER case struct.');
end
end

function [zone_pd, zone_qd, bus_zones] = perform_zonal_loads(source, ~)
define_constants;
bus_zones = perform_nyiso_zone_letters(source, source.bus(:, BUS_I));

letters = string(('A':'K')');
zone_pd = zeros(numel(letters), 1);
zone_qd = zeros(numel(letters), 1);
for k = 1:numel(letters)
    in_zone = bus_zones == letters(k);
    zone_pd(k) = sum(source.bus(in_zone, PD));
    zone_qd(k) = sum(source.bus(in_zone, QD));
end
if any(~isfinite(zone_pd)) || any(zone_pd < 0) || any(~isfinite(zone_qd))
    error('run_s11_2019_same_snapshot_benchmark:BadSourceLoads', ...
        'Mapped 2019 A-K source loads are invalid.');
end
end

function [mpc, report] = apply_exact_zonal_q(mpc, target_pd, target_qd, tol)
define_constants;
letters = string(('A':'K')');
if ~isfield(mpc, 'userdata') || ...
        ~isfield(mpc.userdata, 'nyiso_physical_zone')
    error('run_s11_2019_same_snapshot_benchmark:MissingReducedZones', ...
        'Reduced-case NYISO physical-zone metadata is missing.');
end
zones = upper(strtrim(string(mpc.userdata.nyiso_physical_zone(:))));
before_pd = zeros(numel(letters), 1);
before_qd = zeros(numel(letters), 1);
applied_pd = zeros(numel(letters), 1);
applied_qd = zeros(numel(letters), 1);

for k = 1:numel(letters)
    zone_idx = find(zones == letters(k));
    if isempty(zone_idx)
        error('run_s11_2019_same_snapshot_benchmark:MissingReducedZone', ...
            'No reduced bus is assigned to NYISO zone %s.', letters(k));
    end
    before_pd(k) = sum(mpc.bus(zone_idx, PD));
    before_qd(k) = sum(mpc.bus(zone_idx, QD));
    if abs(before_pd(k) - target_pd(k)) > tol
        error('run_s11_2019_same_snapshot_benchmark:ZonalPAllocation', ...
            ['apply_nyiso_zonal_loads did not reproduce exact source P in ' ...
            'zone %s (target %.12g, applied %.12g MW).'], ...
            letters(k), target_pd(k), before_pd(k));
    end

    weights = max(mpc.bus(zone_idx, PD), 0);
    if sum(weights) <= tol
        weights = abs(mpc.bus(zone_idx, QD));
    end
    if sum(weights) <= tol
        weights = ones(numel(zone_idx), 1);
    end
    weights = weights / sum(weights);
    q_allocation = target_qd(k) * weights;
    [~, correction_idx] = max(weights);
    q_allocation(correction_idx) = q_allocation(correction_idx) + ...
        target_qd(k) - sum(q_allocation);
    mpc.bus(zone_idx, QD) = q_allocation;
    applied_pd(k) = sum(mpc.bus(zone_idx, PD));
    applied_qd(k) = sum(mpc.bus(zone_idx, QD));
end

if max(abs(applied_pd-target_pd)) > tol || ...
        max(abs(applied_qd-target_qd)) > tol
    error('run_s11_2019_same_snapshot_benchmark:ZonalPQMismatch', ...
        'The reduced case does not contain the exact 2019 A-K P/Q loads.');
end
report = table(letters, target_pd(:), target_qd(:), before_pd, before_qd, ...
    applied_pd, applied_qd, applied_pd-target_pd(:), ...
    applied_qd-target_qd(:), ...
    'VariableNames', {'zone','source_pd_mw','source_qd_mvar', ...
    'pre_exact_q_pd_mw','pre_exact_q_qd_mvar','applied_pd_mw', ...
    'applied_qd_mvar','pd_error_mw','qd_error_mvar'});
end

function validation = validate_benchmark_controls(mpc, report, options)
define_constants;
rows = report.generator_report;
finite_row = isfinite(rows.reduced_gen_index);
boundary = finite_row & rows.is_external_boundary_equivalent;
boundary_idx = rows.reduced_gen_index(boundary);
tol = options.control_tolerance_mva;

validation = struct();
validation.boundary_group_count = nnz(boundary);
validation.public_external_gen_count = numel(report.external_gen_idx);
validation.max_boundary_fixed_p_error_mw = max_or_zero(abs([ ...
    mpc.gen(boundary_idx, PMIN)-mpc.gen(boundary_idx, PG); ...
    mpc.gen(boundary_idx, PMAX)-mpc.gen(boundary_idx, PG)]));
validation.max_boundary_fixed_q_error_mvar = max_or_zero(abs([ ...
    mpc.gen(boundary_idx, QMIN)-mpc.gen(boundary_idx, QG); ...
    mpc.gen(boundary_idx, QMAX)-mpc.gen(boundary_idx, QG)]));
validation.boundary_placeholder_capability_count = nnz( ...
    mpc.gen(boundary_idx, QMIN) <= -9899 & ...
    mpc.gen(boundary_idx, QMAX) >= 9899);

pg_prior_rows = finite_row & rows.is_native_active_control & ...
    ismember(rows.injection_role, ["combined_pq_control","remote_p_injection"]);
q_prior_rows = finite_row & ismember(rows.injection_role, ...
    ["combined_pq_control","remote_q_control", ...
    "reactive_only_q_control","benchmark_boundary_fixed_pq", ...
    "benchmark_reference_boundary_fixed_pq"]);
validation.max_native_pg_prior_error_mw = max_or_zero(abs( ...
    rows.initial_pg_mw(pg_prior_rows)-rows.source_pg_mw(pg_prior_rows)));
validation.max_q_prior_error_mvar = max_or_zero(abs( ...
    rows.initial_qg_mvar(q_prior_rows)-rows.source_qg_mvar(q_prior_rows)));
validation.source_group_prior_zone_count = nnz( ...
    report.zone_dispatch.target_policy == "source_group_priors");
validation.expected_zone_count = 11;
validation.no_control_scaling = ...
    validation.max_native_pg_prior_error_mw <= tol && ...
    validation.max_q_prior_error_mvar <= tol;
validation.fixed_boundary_pass = ...
    validation.boundary_group_count == options.expected_boundary_group_count && ...
    validation.public_external_gen_count == 0 && ...
    validation.max_boundary_fixed_p_error_mw <= tol && ...
    validation.max_boundary_fixed_q_error_mvar <= tol && ...
    validation.boundary_placeholder_capability_count == 0;
validation.source_prior_policy_pass = ...
    validation.source_group_prior_zone_count == validation.expected_zone_count;
validation.all_pass = validation.no_control_scaling && ...
    validation.fixed_boundary_pass && validation.source_prior_policy_pass && ...
    report.invariance.all_pass && report.alignment.all_pass;

if ~validation.all_pass
    error('run_s11_2019_same_snapshot_benchmark:ControlValidation', ...
        ['Benchmark control validation failed: boundary=%d, public=%d, ' ...
        'PG prior error=%.6g MW, Q prior error=%.6g MVAr, placeholders=%d.'], ...
        validation.boundary_group_count, validation.public_external_gen_count, ...
        validation.max_native_pg_prior_error_mw, ...
        validation.max_q_prior_error_mvar, ...
        validation.boundary_placeholder_capability_count);
end
end

function [rows, aggregate] = compare_physical_currents(physical_map, ...
        source_currents, reduced_currents, reduced_success, options)
physical = physical_map.branch_classification == "physical_circuit";
map = sortrows(physical_map(physical, :), ...
    {'corridor_name','source_circuit_id'});
if height(map) ~= 5 || numel(unique(map.source_branch_index)) ~= 5
    error('run_s11_2019_same_snapshot_benchmark:PhysicalMap', ...
        'Exactly five unique mapped physical circuits are required.');
end

n = height(map);
source_value = nan(n, 1);
reduced_value = nan(n, 1);
absolute_error = nan(n, 1);
absolute_percent_error = inf(n, 1);
assessment = repmat("fail", n, 1);
for k = 1:n
    source_branch = map.source_branch_index(k);
    reduced_branch = map.branch_index(k);
    if source_branch < 1 || source_branch > height(source_currents)
        error('run_s11_2019_same_snapshot_benchmark:SourceBranchIndex', ...
            'Mapped source branch index %d is invalid.', source_branch);
    end
    source_value(k) = source_currents.series_current_kA(source_branch);
    if reduced_success
        reduced_value(k) = reduced_currents.series_current_kA(reduced_branch);
        [absolute_error(k), absolute_percent_error(k)] = comparison_error( ...
            source_value(k), reduced_value(k), ...
            options.zero_reference_tolerance);
        assessment(k) = pass_fail( ...
            absolute_percent_error(k) <= options.gate_percent);
    end
end

rows = table(map.physical_circuit_id, map.corridor_name, ...
    map.source_circuit_id, map.source_branch_index, map.branch_index, ...
    source_value, reduced_value, absolute_error, absolute_percent_error, ...
    repmat(options.gate_percent, n, 1), assessment, ...
    'VariableNames', {'physical_circuit_id','corridor_name', ...
    'source_circuit_id','source_branch_index','reduced_branch_index', ...
    'source_series_current_kA','reduced_series_current_kA', ...
    'absolute_error_kA','absolute_percent_error','gate_percent','assessment'});
aggregate = struct( ...
    'physical_circuit_count', n, ...
    'maximum_absolute_percent_error', max(absolute_percent_error), ...
    'passing_circuit_count', nnz(assessment == "pass"), ...
    'all_circuit_gates_pass', all(assessment == "pass"));
end

function metrics = network_metrics(result)
define_constants;
[loss, fchg, tchg] = get_losses(result);
online = result.gen(:, GEN_STATUS) > 0;
metrics = struct();
metrics.series_active_loss_mw = sum(real(loss));
metrics.bus_shunt_active_loss_mw = sum( ...
    result.bus(:, GS) .* result.bus(:, VM).^2);
metrics.active_network_loss_mw = metrics.series_active_loss_mw + ...
    metrics.bus_shunt_active_loss_mw;
metrics.active_balance_loss_mw = sum(result.gen(online, PG)) - ...
    sum(result.bus(:, PD));
metrics.active_identity_residual_mw = metrics.active_balance_loss_mw - ...
    metrics.active_network_loss_mw;
metrics.series_reactive_loss_mvar = sum(imag(loss));
metrics.line_charging_injection_mvar = sum(real(fchg + tchg));
metrics.bus_shunt_injection_mvar = sum( ...
    result.bus(:, BS) .* result.bus(:, VM).^2);
metrics.net_network_q_mvar = metrics.series_reactive_loss_mvar - ...
    metrics.line_charging_injection_mvar - ...
    metrics.bus_shunt_injection_mvar;
metrics.qg_minus_qd_mvar = sum(result.gen(online, QG)) - ...
    sum(result.bus(:, QD));
metrics.reactive_identity_residual_mvar = metrics.qg_minus_qd_mvar - ...
    metrics.net_network_q_mvar;
end

function metrics = empty_network_metrics()
names = {'series_active_loss_mw','bus_shunt_active_loss_mw', ...
    'active_network_loss_mw','active_balance_loss_mw', ...
    'active_identity_residual_mw','series_reactive_loss_mvar', ...
    'line_charging_injection_mvar','bus_shunt_injection_mvar', ...
    'net_network_q_mvar','qg_minus_qd_mvar', ...
    'reactive_identity_residual_mvar'};
metrics = struct();
for k = 1:numel(names), metrics.(names{k}) = NaN; end
end

function status = q_limit_status(input_case, result, tolerance)
define_constants;
online = result.gen(:, GEN_STATUS) > 0;
variable_q = online & result.gen(:, QMAX)-result.gen(:, QMIN) > tolerance;
at_min = abs(result.gen(:, QG)-result.gen(:, QMIN)) <= tolerance;
at_max = abs(result.gen(:, QG)-result.gen(:, QMAX)) <= tolerance;
status = struct();
status.variable_q_generator_count = nnz(variable_q);
status.q_saturation_count = nnz(variable_q & (at_min | at_max));
if status.variable_q_generator_count > 0
    status.q_saturation_fraction = status.q_saturation_count / ...
        status.variable_q_generator_count;
else
    status.q_saturation_fraction = 0;
end
initial_regulating_ids = input_case.bus( ...
    ismember(input_case.bus(:, BUS_TYPE), [PV REF]), BUS_I);
[found, result_idx] = ismember(initial_regulating_ids, result.bus(:, BUS_I));
status.initial_regulating_bus_count = numel(initial_regulating_ids);
became_pq = false(size(found));
