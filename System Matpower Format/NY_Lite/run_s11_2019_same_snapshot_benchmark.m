function outputs = run_s11_2019_same_snapshot_benchmark(options)
%RUN_S11_2019_SAME_SNAPSHOT_BENCHMARK Validate S11 against 2019 PERFORM.
%   OUTPUTS = RUN_S11_2019_SAME_SNAPSHOT_BENCHMARK(OPTIONS) builds the
%   49-bus NY-only S11 structure, restores the five individual PERFORM
%   circuits, applies exact 2019 PERFORM A-K P/Q loads, and replaces the
%   internal controls with solved-source PERFORM control-group priors.
%
%   This is a diagnostic same-snapshot benchmark. Map-derived boundary
%   groups are fixed at solved-source P/Q only in this runner, and no public
%   external schedule is added. The function does not fit or alter branch
%   admittances.
%
%   The default CSV is s11_2019_same_snapshot_benchmark.csv. Set
%   OPTIONS.write_output=false for an in-memory run.

if nargin < 1, options = struct(); end
helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
workspace_dir = fileparts(case_dir);
options = defaults(options, helper_dir, workspace_dir);

addpath(case_dir);
addpath(helper_dir);
addpath(char(options.perform_case_dir));
define_constants;

structural = loadcase(char(options.structural_case));
[core, reduction_report] = build_ny_only_equivalent_case(structural);
[core, physical_map] = split_perform_parallel_corridors(core);
structure_validation = validate_s11_structure(core, physical_map);

source_case = load_source_case(options);
pf_options = mpoption('verbose', 0, 'out.all', 0, ...
    'pf.enforce_q_lims', 1);
[source_pf, source_success] = runpf(source_case, pf_options);
if ~source_success
    error('run_s11_2019_same_snapshot_benchmark:SourcePFFailed', ...
        'The unmodified 2019 PERFORM source case did not converge.');
end

[source_zone_pd, source_zone_qd, source_bus_zones] = ...
    perform_zonal_loads(source_case, options.perform_zone_file);
[prepared, load_report] = apply_nyiso_zonal_loads(core, source_zone_pd, 1.0, ...
    struct('preserve_total_ny_load', false, 'default_power_factor', 1.0));
[prepared, exact_load_report] = apply_exact_zonal_q( ...
    prepared, source_zone_pd, source_zone_qd, options.load_tolerance_mva);

control_options = struct( ...
    'control_map_file', char(options.control_map_file), ...
    'source_operating_case', source_pf, ...
    'boundary_p_policy', "fixed_source_when_no_public_external", ...
    'internal_pg_policy', "source_group_priors");
[reduced_input, control_report] = ...
    apply_perform_controls_to_operating_case(prepared, control_options);
control_validation = validate_benchmark_controls( ...
    reduced_input, control_report, options);
correction_application = struct('status', 'not_applied', ...
    'dlr_frozen_exact', true, 'changed_branch_count', 0, ...
    'changed_bus_shunt_count', 0);
if ~isempty(options.non_dlr_correction)
    [reduced_input, correction_application] = ...
        apply_s11_non_dlr_equivalent_correction( ...
        reduced_input, physical_map, options.non_dlr_correction);
end

reduced_pf_error = "";
reduced_preprojection_input = reduced_input;
reduced_projection = struct('attempted', false, 'success', false, ...
    'reason', "direct Q-limit PF accepted", 'result', struct(), ...
    'input_case', reduced_input, 'total_absolute_pg_movement_mw', 0, ...
    'maximum_pg_movement_mw', 0);
try
    [reduced_pf, reduced_success] = runpf(reduced_input, pf_options);
catch err
    % MATPOWER can throw when every regulating bus is converted to PQ during
    % Q-limit enforcement. Treat that as a failed mandatory benchmark gate,
    % not as an unreported validation crash.
    reduced_pf = reduced_input;
    reduced_success = false;
    reduced_pf_error = string(err.message);
end
if ~reduced_success && options.enable_hard_feasibility_projection
    physical = physical_map.branch_classification == "physical_circuit";
    trusted = false(size(reduced_input.branch, 1), 1);
    trusted(double(physical_map.branch_index(physical))) = true;
    reduced_projection = project_s11_hard_ac_feasibility( ...
        reduced_input, struct('opf_solver', options.opf_solver, ...
        'max_iterations', options.opf_max_iterations), trusted);
    if reduced_projection.success
        reduced_input = reduced_projection.input_case;
        try
            [reduced_pf, reduced_success] = runpf(reduced_input, pf_options);
            reduced_pf_error = "";
        catch err
            reduced_pf = reduced_input;
            reduced_success = false;
            reduced_pf_error = string(err.message);
        end
    end
end

source_current_report = compute_branch_currents_kA(source_pf);
if reduced_success
    reduced_current_report = compute_branch_currents_kA( ...
        reduced_pf, physical_map);
else
    reduced_current_report = table();
end
[circuit_comparison, circuit_summary] = compare_physical_currents( ...
    physical_map, source_current_report, reduced_current_report, ...
    logical(reduced_success), options);

source_metrics = network_metrics(source_pf);
if reduced_success
    reduced_metrics = network_metrics(reduced_pf);
else
    reduced_metrics = empty_network_metrics();
end
source_q_status = q_limit_status(source_case, source_pf, ...
    options.q_saturation_tolerance_mvar);
reduced_q_status = q_limit_status(reduced_input, reduced_pf, ...
    options.q_saturation_tolerance_mvar);

zonal_load_comparison = build_zonal_load_comparison( ...
    source_zone_pd, source_zone_qd, exact_load_report);
summary = build_summary(circuit_comparison, source_metrics, ...
    reduced_metrics, source_q_status, reduced_q_status, ...
    source_success, reduced_success, control_validation, options);

if options.write_output
    output_dir = fileparts(char(options.output_file));
    if ~isempty(output_dir) && ~isfolder(output_dir)
        error('run_s11_2019_same_snapshot_benchmark:MissingOutputDirectory', ...
            'Output directory does not exist: %s', output_dir);
    end
    writetable(summary, char(options.output_file));
end

outputs = struct();
outputs.summary = summary;
outputs.circuit_comparison = circuit_comparison;
outputs.circuit_summary = circuit_summary;
outputs.zonal_load_comparison = zonal_load_comparison;
outputs.source_case = source_case;
outputs.source_pf = source_pf;
outputs.reduced_input = reduced_input;
outputs.reduced_preprojection_input = reduced_preprojection_input;
outputs.reduced_projection = reduced_projection;
outputs.reduced_pf = reduced_pf;
outputs.physical_map = physical_map;
outputs.source_current_report = source_current_report;
outputs.reduced_current_report = reduced_current_report;
outputs.source_bus_zones = source_bus_zones;
outputs.source_metrics = source_metrics;
outputs.reduced_metrics = reduced_metrics;
outputs.source_q_status = source_q_status;
outputs.reduced_q_status = reduced_q_status;
outputs.reduction_report = reduction_report;
outputs.structure_validation = structure_validation;
outputs.load_report = load_report;
outputs.exact_load_report = exact_load_report;
outputs.control_report = control_report;
outputs.control_validation = control_validation;
outputs.correction_application = correction_application;
outputs.source_pf_success = logical(source_success);
outputs.reduced_pf_success = logical(reduced_success);
outputs.reduced_pf_error = reduced_pf_error;
outputs.all_mandatory_gates_pass = ...
    all(summary.assessment(summary.gate_percent == options.gate_percent) == "pass") && ...
    logical(source_success) && logical(reduced_success);
outputs.output_file = options.output_file;
outputs.output_written = options.write_output;
end

function validation = validate_s11_structure(mpc, branch_map)
validation = struct( ...
    'bus_count', size(mpc.bus, 1), ...
    'branch_count', size(mpc.branch, 1), ...
    'physical_circuit_count', nnz( ...
        branch_map.branch_classification == "physical_circuit"), ...
    'aggregate_equivalent_count', nnz( ...
        branch_map.branch_classification == "aggregate_equivalent"), ...
    'transformer_or_boundary_equivalent_count', nnz( ...
        branch_map.branch_classification == ...
        "transformer_or_boundary_equivalent"));
validation.all_pass = validation.bus_count == 49 && ...
    validation.branch_count == 83 && validation.physical_circuit_count == 5;
if ~validation.all_pass
    error('run_s11_2019_same_snapshot_benchmark:S11Structure', ...
        'Expected a 49-bus, 83-branch S11 case with five physical circuits.');
end
end

