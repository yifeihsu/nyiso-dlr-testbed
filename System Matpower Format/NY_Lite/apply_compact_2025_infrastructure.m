function out=apply_compact_2025_infrastructure(base,options)
%APPLY_COMPACT_2025_INFRASTRUCTURE Dated, explicitly approximate NY expansion.
% This is a 2025-12-31 research scenario, not an as-built network. The compact
% 51-NY-bus parent is preserved apart from eight registered branch retirements.
% New buses have no imported source load, generation or shunt. Historical
% PERFORM parameters are templates; commissioned-project R/X/B remain assumed.
% No thermal qualification follows from project names, voltage or public MW.
if nargin<1||isempty(base),base=build_compact_npcc_corridors();end
if nargin<2,options=struct();end
options=defaults(options);
assert(~isfield(base.candidate.userdata,'compact_2025'), ...
    'compact_2025:AlreadyApplied','The infrastructure overlay may be applied only once.');
p=base.candidate;
assert(size(p.bus,1)==145&&size(p.branch,1)==257&&sum(base.ny_bus_mask)==51 ...
    && p.baseMVA==100&&all(ismember((37:82)',p.bus(:,1))), ...
    'compact_2025:Parent','Expected the unchanged 100 MVA compact 51-NY-bus construction.');
assert(isequal(p,base.full_candidate),'compact_2025:Parent','Full and candidate construction must agree.');
retired=[36;40;47;95;97;239;240;246];
expected_endpoints=[37 43;40 44;44 48;78 79;78 81;78 81;78 79;9001 73];
assert(isequal(p.branch(retired,1:2),expected_endpoints)&&all(p.branch(retired,11)==1), ...
    'compact_2025:RetirementIdentity','Exact predecessor rows/endpoints/status changed.');
root=fileparts(fileparts(fileparts(mfilename('fullpath'))));
workbook=fullfile(root,'PERFORM','Auxilliary_Perform_NY','Branch_changes_2019_to_2030.xlsx');
raw=readcell(workbook,'Sheet','2019 On Peak','Range','A1:U2373');
template_keys=["800_1233_1";"1220_1230_1";"1220_1230_2";"1220_1232_1"; ...
    "1220_1232_2";"1130_1529_1";"1493_601_1"];
template=table();
for k=1:numel(template_keys)
    j=find(strcmp(string(raw(:,1)),template_keys(k)));
    assert(numel(j)==1,'compact_2025:TemplateIdentity','Expected one workbook circuit %s.',template_keys(k));
    r=raw(j,:);vals=cell2mat(r([2 6 7 9 12:19 21]));
    template=[template;table(template_keys(k),j,vals(1),vals(3),vals(2),vals(4), ...
        vals(5),vals(6),vals(7),vals(8),vals(9),vals(10),vals(11),vals(12),vals(13), ...
        'VariableNames',{'source_key','xlsx_row','source_from_bus','source_to_bus', ...
        'from_base_kv','to_base_kv','r_pu','x_pu','b_pu','tap','shift_degree', ...
        'rate_a_mva','rate_b_mva','rate_c_mva','estimated_length_miles'})]; %#ok<AGROW>
end
assert(isequal(template.r_pu,[.00293;.0136;.01361;.00815;.00815;.00124;.0008]) ...
    && isequal(template.x_pu,[.04468;.10931;.10934;.0655;.0655;.065;.00401]), ...
    'compact_2025:TemplateIdentity','Historical workbook template R/X changed.');

ids=[9101;9102;9103;9104;1220;1130;557;1529;1493;601;1129;9111;9112;9113;9114];
names=["PRINCETOWN 345";"GORDON ROAD 345";"GORDON ROAD 230 PROXY"; ...
    "CHURCHTOWN 345";"ADIRONDACK 230";"RAINEY 345";"EAST ASTORIA 345"; ...
    "RAINEY 138";"EAST ASTORIA 138";"CORONA 138";"GOWANUS 345"; ...
    "GREENWOOD 138 PROXY";"GOWANUS PAR 138 PROXY";"GOETHALS PAR 138 PROXY";"FOX HILLS 138 PROXY"];
kv=[345;345;230;345;230;345;345;138;138;138;345;138;138;138;138];
zones=["F";"F";"F";"G";"E";repmat("J",10,1)];
anchors=[37;37;40;9001;44;78;78;79;79;79;81;81;81;81;81];
sourcebus=[nan(4,1);1220;1130;557;1529;1493;601;1129;nan(4,1)];
assert(~any(ismember(ids,p.bus(:,1))),'compact_2025:BusIdentity','New station IDs collide with the parent.');
c=p;
for k=1:numel(ids)
    j=find(p.bus(:,1)==anchors(k));r=p.bus(j,1:13);r(1)=ids(k);r(2)=1;r(3:6)=0;r(10)=kv(k);
    c.bus(end+1,:)=r;c.bus_name{end+1,1}=char(names(k));
    zid=double(char(zones(k)))-double('A')+1;
    metadata=struct('bus_id',ids(k),'physical_zone',char(zones(k)), ...
        'load_allocation_group',char(zones(k)),'nyiso_zone_name',char(zones(k)), ...
        'nyiso_zone_id',zid,'perform_zone_code',64+zid);
    c.userdata.ny_lite.transit_zone_metadata(end+1)=metadata;
end
c=attach_nyiso_zone_metadata(c);c.branch(retired,11)=0;
busmap=table(ids,names,kv,zones,anchors,sourcebus, ...
    repmat("zero_injection_PQ_station_or_receiving_network_proxy",numel(ids),1), ...
    'VariableNames',{'model_bus','model_bus_name','base_kv','physical_zone','initial_voltage_anchor', ...
    'source_bus_name_voltage_identity','injection_policy'});
busmap.physical_station_equivalence_assumed=true(height(busmap),1);

% Record order is fixed; keys are the durable identity, not these row numbers.
spec=table();
o=template(1,:);ohl=[o.r_pu o.x_pu o.b_pu]/o.estimated_length_miles;
ceec_ends=[43 9101;43 9101;9101 37;9101 37;43 9102;9101 9102];
lengths=[67;67;26;26;72;5];
circuits=["351";"352";"361";"362";"14";"371"];
for k=1:6
    spec=add(spec,"CEEC:"+circuits(k),"CEEC",ceec_ends(k,:),ohl*lengths(k),2000,0,1, ...
        "assumed_345kV_overhead_circuit",36,"800_1233_1",lengths(k), ...
        "2019_345kV_template_per_estimated_mile_project_segment_lengths_and_2000MVA_assumed");
end
% A registered split of the old 230 kV backbone supplies the new station's
% lower-voltage port. Its identity remains an equivalent, not an as-built line.
for k=1:2
    ends=[40 9103;9103 44];spec=add(spec,"CEEC:LEGACY230:"+k,"CEEC",ends(k,:), ...
        p.branch(40,3:5)/2,p.branch(40,6),0,1,"inherited_equivalent_resegmented",40, ...
        "NPCC_S7:BRANCH_ROW:40",nan,"half_R_X_B_split_of_retired_230kV_equivalent_response_approximate");
end
spec=add(spec,"CEEC:GORDON_XFMR","CEEC",[9102 9103],[.0006 .025 0],1200,1,1, ...
    "assumed_station_transformer",36,"assumption",0,"Gordon_345_230_connection_proxy_fixed_nominal_tap");
for k=1:2
    ends=[9001 9104;9104 73];len=[22;32];
    spec=add(spec,"NYES:"+k,"NYES",ends(k,:),ohl*len(k),1800,0,1, ...
        "assumed_345kV_overhead_circuit",246,"800_1233_1",len(k), ...
        "historical_345kV_template_54mile_public_corridor_1800MVA_assumed_no_series_compensation_copy");
end
for k=1:4
    t=template(k+1,:);if k<=2,ends=[1220 48];else,ends=[1220 44];end
    rxb=[t.r_pu t.x_pu t.b_pu];if k<=2,rxb(1)=.85*rxb(1);end
    spec=add(spec,"SMART_PATH:"+k,"SMART_PATH",ends,rxb,t.rate_a_mva,0,1, ...
        "230kV_historical_template_rebuild_equivalent",47,t.source_key,t.estimated_length_miles, ...
        "230kV_through_cutoff_Moses_leg_R_times085_assumed_X_B_and_rating_historical_Porter_leg_unchanged");
end
% Split the two existing generator-delivery paths through distinct receiving
% stations. Their total series R/X and static limits are retained; new loops
% intentionally change the network response and are not claimed equivalent.
old=[95;240;97;239];mid=[1130;557;1129;1129];
for k=1:4
    r=p.branch(old(k),:);ends=[r(1) mid(k);mid(k) r(2)];
    for j=1:2
        [~,fb]=ismember(ends(j,1),c.bus(:,1));[~,tb]=ismember(ends(j,2),c.bus(:,1));
        tap=double(c.bus(fb,10)~=c.bus(tb,10));
        spec=add(spec,"NYC:DELIVERY:"+old(k)+":"+j,"NYC_BACKBONE",ends(j,:),r(3:5)/2,r(6),tap,1, ...
            "inherited_equivalent_resegmented",old(k),"NPCC_S7:BRANCH_ROW:"+old(k),nan, ...
            "half_series_budget_split_existing_delivery_equivalent_not_physical_conductor");
    end
end
t=template(6,:);
spec=add(spec,"NYC:RAINEY_XFMR","NYC_BACKBONE",[1130 1529],[t.r_pu t.x_pu 0]/2,1500,1,1, ...
    "assumed_parallel_transformer_equivalent",0,t.source_key,0,"two_parallel_historical_Rainey_transformers_equivalent_fixed_tap");
spec=add(spec,"NYC:ASTORIA_XFMR","NYC_BACKBONE",[557 1493],[.0006 .025 0],1500,1,1, ...
    "assumed_station_transformer",0,t.source_key,0,"Rainey_template_orders_of_magnitude_Assumed_Astoria_equivalent");
t=template(7,:);cable=[t.r_pu t.x_pu t.b_pu]/t.estimated_length_miles;
spec=add(spec,"NYC:CORONA_BASELINE","NYC_BACKBONE",[1493 601],[t.r_pu/4 t.x_pu/4 t.b_pu*4],2248,0,1, ...
    "historical_parallel_cable_equivalent",0,t.source_key,5.5,"four_historical_EastAstoria_Corona_circuits_aggregated");
spec=add(spec,"RCC_QUEENS:CABLE","RCC_QUEENS",[1529 601],cable*6,300,0,1, ...
    "assumed_138kV_underground_cable",0,t.source_key,6,"6mile_Rainey_Corona_300MW_public_capacity_used_as_assumed300MVA_apparent_power_limit");
status=double(options.include_announced_2025_rcc);
spec=add(spec,"RCC_BROOKLYN:PAR","RCC_BROOKLYN",[1129 9112],[.002 .03 0],300,1,status, ...
    "assumed_fixed_PAR_transformer",0,"assumption",0,"fixed_tap1_shift0_no_automatic_phase_control_public345_138_feeder");
spec=add(spec,"RCC_BROOKLYN:CABLE","RCC_BROOKLYN",[9112 9111],cable,300,0,status, ...
    "assumed_138kV_underground_cable",0,t.source_key,1,"1mile_300MW_project_rating_used_as_assumed300MVA");
spec=add(spec,"RCC_STATEN:PAR","RCC_STATEN",[81 9113],[.002 .03 0],300,1,status, ...
    "assumed_fixed_PAR_transformer",0,"assumption",0,"fixed_tap1_shift0_no_automatic_phase_control_public345_138_feeder");
spec=add(spec,"RCC_STATEN:CABLE","RCC_STATEN",[9113 9114],cable*9.2,300,0,status, ...
    "assumed_138kV_underground_cable",0,t.source_key,9.2,"approximately9mile_300MW_project_rating_used_as_assumed300MVA");
spec=add(spec,"NYC:GREENWOOD_CORONA","NYC_BACKBONE",[9111 601],cable*8,600,0,1, ...
    "assumed_regional_138kV_network_equivalent",0,"assumption",8,"aggregate_omitted_NYC_receiving_network_connection_not_named_physical_circuit");
spec=add(spec,"NYC:FOX_GREENWOOD","NYC_BACKBONE",[9114 9111],cable*10,600,0,1, ...
    "assumed_regional_138kV_network_equivalent",0,"assumption",10,"aggregate_omitted_NYC_receiving_network_connection_not_named_physical_circuit");

% The optional-off project transformer nodes still need an electrical
% attachment. Leave their fixed nominal transformer on while cable is off;
% they carry no load and create no additional through path in that scenario.
if ~options.include_announced_2025_rcc
    spec.status(ismember(spec.branch_key,["NY2025:RCC_BROOKLYN:PAR","NY2025:RCC_STATEN:PAR"]))=1;
end
spec.nominal_r_pu=spec.r_pu;spec.nominal_x_pu=spec.x_pu;spec.nominal_b_pu=spec.b_pu;
spec.nominal_rate_a_mva=spec.rate_a_mva;
adjust=spec.electrical_role~="inherited_equivalent_resegmented";
spec.r_pu(adjust)=spec.r_pu(adjust)*options.impedance_scale;
spec.x_pu(adjust)=spec.x_pu(adjust)*options.impedance_scale;
spec.b_pu(adjust)=spec.b_pu(adjust)*options.charging_scale;
spec.rate_a_mva(adjust)=spec.rate_a_mva(adjust)*options.rating_scale;
nr=height(spec);spec.model_branch_row=(258:257+nr)';
br=[spec.from_bus spec.to_bus spec.r_pu spec.x_pu spec.b_pu ...
    repmat(spec.rate_a_mva,1,3) spec.tap zeros(nr,1) spec.status repmat([-360 360],nr,1)];
c.branch=[c.branch;br];
spec.base_mva=repmat(100,nr,1);spec.shift_degree=zeros(nr,1);
spec.rate_b_mva=spec.rate_a_mva;spec.rate_c_mva=spec.rate_a_mva;
[~,f]=ismember(br(:,1),c.bus(:,1));[~,t]=ismember(br(:,2),c.bus(:,1));
spec.from_base_kv=c.bus(f,10);spec.to_base_kv=c.bus(t,10);
spec.sensitivity_required=adjust;spec.parameter_ground_truth_verified=false(nr,1);
spec.thermal_eligible=false(nr,1);spec.dlr_eligible=false(nr,1);
spec.rating_basis=repmat("declared_static_MVA_assumption_not_conductor_ampacity_or_interface_limit",nr,1);

dispositions=table(retired,base.branch_keys(retired),p.branch(retired,1),p.branch(retired,2), ...
    ones(numel(retired),1),zeros(numel(retired),1),repmat("",numel(retired),1), ...
    repmat("entire_predecessor_row_retired_once_response_change_declared_no_fitted_residual",numel(retired),1), ...
    'VariableNames',{'parent_branch_row','parent_branch_key','from_bus','to_bus', ...
    'old_status','new_status','replacement_branch_keys','disposition'});
for k=1:height(dispositions)
    dispositions.replacement_branch_keys(k)=strjoin(spec.branch_key(spec.parent_row==retired(k)),';');
end
projects=project_register(options.include_announced_2025_rcc);
source=table("Branch_changes_2019_to_2030.xlsx","PERFORM/Auxilliary_Perform_NY/Branch_changes_2019_to_2030.xlsx", ...
    file_hash(workbook),"2019 On Peak", ...
    "historical_electrical_templates_2030_planning_sheet_not_commissioning_evidence", ...
    'VariableNames',{'artifact','relative_path','sha256','selected_sheet','use_policy'});
assumptions=table(["cutoff";"parameter_source";"ratings";"NYC_receiving_network";"injections"; ...
    "controls";"project_status";"excluded_future";"impedance_sensitivity";"charging_sensitivity";"rating_sensitivity"], ...
    ["2025-12-31";"public project endpoints plus historical PERFORM templates and declared equivalent parameters"; ...
    "MVA limits are finite research assumptions; public MW project benefit is not a circuit MVA rating"; ...
    "station and 138kV connections approximate omitted local network; no device-level fidelity claim"; ...
    "all parent PD QD GS BS generators and capabilities preserved; all added nodes zero injection"; ...
    "fixed nominal transformer/PAR taps and zero phase shifts; no new unlimited Q or voltage support"; ...
    "RCC Queens confirmed2023; Brooklyn/Staten assumed2025 from owner announced May2025 energization"; ...
    "CHPE SmartPathConnect RCC_LongIslandCity2026 and Propel2030 excluded from default"; ...
    string(options.impedance_scale)+" applied to non-split R and X; allowed0.75to1.25"; ...
    string(options.charging_scale)+" applied to non-split B; allowed0to1.5"; ...
    string(options.rating_scale)+" applied to non-split static MVA; allowed0.8to1.2"], ...
    'VariableNames',{'assumption','declaration'});
z=string(c.userdata.nyiso_physical_zone);ny=ismember(z,string(('A':'K')'));nyids=c.bus(ny,1);
nybr=ismember(c.branch(:,1),nyids)&ismember(c.branch(:,2),nyids);
unchanged=p.branch;unchanged(retired,11)=0;
active=c.branch(:,11)>0;[~,f]=ismember(c.branch(active,1),c.bus(:,1));[~,t]=ismember(c.branch(active,2),c.bus(:,1));
components=conncomp(graph(f,t,[],size(c.bus,1)));
keys=[base.branch_keys;spec.branch_key];
gates=table(["all_original_NPCC_NY_IDs_preserved";"parent_bus_devices_preserved"; ...
    "parent_generator_capability_and_cost_preserved";"eight_predecessor_rows_retired_once"; ...
    "all_added_nodes_zero_PQ_GS_BS";"within_NY_bus_cap";"all_new_nodes_zoned"; ...
    "unique_branch_keys";"finite_positive_branch_impedances_and_ratings"; ...
    "voltage_transition_has_explicit_transformer";"connected_full_network"; ...
    "original_source_UPNY_circuits_unchanged";"no_new_generator_or_import"], ...
    [all(ismember((37:82)',nyids));isequal(c.bus(1:145,:),p.bus); ...
    isequal(c.gen,p.gen)&&isequal(c.gencost,p.gencost);isequal(c.branch(1:257,:),unchanged); ...
    all(c.bus(146:end,3:6)==0,'all');sum(ny)==66&&sum(ny)<=200;all(strlength(z(146:end))>0); ...
    numel(unique(keys))==numel(keys);all(isfinite(br),'all')&&all(spec.r_pu>=0&spec.x_pu>0&spec.rate_a_mva>0); ...
    all(spec.tap(spec.from_base_kv~=spec.to_base_kv)==1);numel(unique(components))==1; ...
    isequal(c.branch(247:257,:),p.branch(247:257,:));size(c.gen,1)==size(p.gen,1)], ...
    'VariableNames',{'metric','passed'});
assert(all(gates.passed),'compact_2025:Validation','Infrastructure topology/accounting validation failed.');
c.userdata.compact_2025=struct('cutoff','2025-12-31','new_bus_ids',ids,'retired_parent_rows',retired, ...
    'new_branch_keys',spec.branch_key,'declared_approximation',true,'options',options, ...
    'project_status_ground_truth_complete',false,'electrical_baseline_qualified',false,'dlr_ready',false);
c.userdata.compact_npcc.ny_bus_count=sum(ny);
out=base;out.infrastructure_parent=base.candidate;out.candidate=c;out.full_candidate=c;
out.branch_keys=keys;out.ny_bus_mask=ny;out.ny_bus_ids=nyids;out.ny_branch_mask=nybr;
out.ny_generator_mask=ismember(c.gen(:,1),nyids);out.infrastructure_branch_register=spec;
out.branch_dispositions=dispositions;out.bus_map_2025=busmap;out.project_register=projects;
out.assumption_register=assumptions;out.infrastructure_source_manifest=source;
out.historical_template_register=template;out.infrastructure_validation=struct('pass',all(gates.passed),'gates',gates);
out.infrastructure_model_notes=table(["NYgrid_baseline";"workbook_2030_sheet";"CEEC_topology";"NYES_series_compensation"; ...
    "retained_NPCC_230kV_backbone";"project_status_sensitivity"], ...
    ["2019_validation_supports_baseline_methodology_not_2025_as_built_parameters"; ...
    "New2030_and_rerated2030_sheets_have_no_CEEC_NYES_named_station_records_SmartPath_230kV_rows_unchanged"; ...
    "owner_named_stations_and_NYISO_six_circuit_connections_segment_lengths_and_Gordon230_attachment_assumed"; ...
    "Van_Wagner_series_capacitor_exists_publicly_but_is_not_copied_default_uncompensated_equivalent_sensitivity_required"; ...
    "row40_split_retains_separate_lower_voltage_equivalent_role_while_row36_full_retirement_replaces_345kV_function"; ...
    "include_announced_2025_rcc_false_opens_two_cable_through_paths_only_zero_injection_PAR_station_stubs_remain_energized"], ...
    ["https://github.com/AndersonEnergyLab-Cornell/NYgrid"; ...
    "PERFORM/Auxilliary_Perform_NY/Branch_changes_2019_to_2030.xlsx"; ...
    "https://www.nyiso.com/documents/20142/23262467/07%20AC%20Transmission%20Segment%20A%20PPTN%20Project%20Update.pdf/191cfafa-f1ab-b91d-0bc0-085be4e56d57"; ...
    "https://www.ny-es.com/project-overview";"declared_research_equivalent";"declared_scenario_policy"], ...
    'VariableNames',{'topic','declaration','source'});
out.validation=out.infrastructure_validation;out.electrical_baseline_qualified=false;out.dlr_ready=false;
end

function o=defaults(o)
d=struct('cutoff','2025-12-31','impedance_scale',1,'charging_scale',1, ...
    'rating_scale',1,'include_announced_2025_rcc',true);
names=fieldnames(d);
assert(all(ismember(fieldnames(o),names)),'compact_2025:Options','Unknown infrastructure option.');
for k=1:numel(names),if ~isfield(o,names{k}),o.(names{k})=d.(names{k});end,end
assert(strcmp(string(o.cutoff),"2025-12-31"),'compact_2025:Cutoff','This overlay is dated only2025-12-31.');
assert(isscalar(o.impedance_scale)&&isfinite(o.impedance_scale)&&o.impedance_scale>=.75&&o.impedance_scale<=1.25 ...
    && isscalar(o.charging_scale)&&isfinite(o.charging_scale)&&o.charging_scale>=0&&o.charging_scale<=1.5 ...
    && isscalar(o.rating_scale)&&isfinite(o.rating_scale)&&o.rating_scale>=.8&&o.rating_scale<=1.2 ...
    && islogical(o.include_announced_2025_rcc)&&isscalar(o.include_announced_2025_rcc), ...
    'compact_2025:SensitivityBounds','Sensitivity multipliers must remain inside their declared bounds.');
end

function s=add(s,key,project,ends,rxb,rate,tap,status,role,parent,source,len,policy)
r=table("NY2025:"+key,project,ends(1),ends(2),rxb(1),rxb(2),rxb(3),rate,tap,status, ...
    role,parent,source,len,policy,'VariableNames',{'branch_key','project_id','from_bus','to_bus', ...
    'r_pu','x_pu','b_pu','rate_a_mva','tap','status','electrical_role','parent_row', ...
    'parameter_template_key','length_miles','parameter_policy'});s=[s;r];
end

