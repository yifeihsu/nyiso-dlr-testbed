function [q_saturation_count, pv_to_pq_conversion_count] = ...
        q_transition_counts(input_case, result)
define_constants;
online = result.gen(:,GEN_STATUS)>0;
variable_q = online & result.gen(:,QMAX)-result.gen(:,QMIN)>1e-6;
at_limit = abs(result.gen(:,QG)-result.gen(:,QMIN))<=1e-4 | ...
    abs(result.gen(:,QG)-result.gen(:,QMAX))<=1e-4;
q_saturation_count = sum(variable_q & at_limit);
was_regulating = ismember(input_case.bus(:,BUS_TYPE),[PV REF]);
pv_to_pq_conversion_count = sum(was_regulating & result.bus(:,BUS_TYPE)==PQ);
end

function count = branch_overload_count(results)
