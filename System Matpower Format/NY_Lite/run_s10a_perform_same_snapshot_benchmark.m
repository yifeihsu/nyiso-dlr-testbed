function rows = append_branch_rows(rows, results, zones, model, scale, top_n)
define_constants;
sf = hypot(results.branch(:,PF), results.branch(:,QF));
st = hypot(results.branch(:,PT), results.branch(:,QT));
smax = max(sf,st);
rate = results.branch(:,RATE_A);
loading = 100 * smax ./ max(rate, eps);
loading(rate <= 0 | results.branch(:,BR_STATUS)<=0) = NaN;
[~, order] = sort(loading, 'descend', 'MissingPlacement', 'last');
order = order(1:min(top_n, nnz(isfinite(loading))));
if model == "REDUCED_S10A" && size(results.branch,1) >= 29
    order = unique([order(:);29], 'stable');
end
for br = order(:)'
    fi = find(results.bus(:,BUS_I)==results.branch(br,F_BUS),1);
    ti = find(results.bus(:,BUS_I)==results.branch(br,T_BUS),1);
    row = table(string(model), br, results.branch(br,F_BUS), ...
        bus_name(results,fi), zones(fi), results.branch(br,T_BUS), ...
        bus_name(results,ti), zones(ti), scale*smax(br), scale*rate(br), ...
        loading(br), scale*max(0,smax(br)-rate(br)), ...
        'VariableNames', {'model','branch_index','from_bus','from_bus_name', ...
        'from_zone','to_bus','to_bus_name','to_zone','flow_mva','rate_a_mva', ...
        'loading_pct','overload_mva'});
    rows = append_table(rows,row);
end
end

function rows = control_action_report(discrete, source, reduced, control_map, ...
        gen_report, gamma)
define_constants;
rows = table();
for k = 1:height(discrete)
    kind = discrete.control_type(k);
    source_output = NaN; reduced_output = NaN;
    if kind == "switched_shunt_snapshot"
        bi = discrete.source_element_index(k);
        source_output = gamma * source.bus(bi,BS) * source.bus(bi,VM)^2;
        source_bus = discrete.source_from_bus(k);
        map_idx = control_map.device_class == "reactive_only_QS" & ...
            control_map.source_bus == source_bus;
        reduced_output = 0;
        for group_id = unique(control_map.reduced_control_group_id(map_idx))'
            gri = gen_report.reduced_control_group_id == group_id;
            group_q = sum(reduced.gen(gen_report.reduced_gen_index(gri),QG));
            participation = sum(control_map.q_participation_factor( ...
                map_idx & control_map.reduced_control_group_id == group_id));
            reduced_output = reduced_output + participation * group_q;
        end
    end
    row = addvars(discrete(k,:), source_output, reduced_output, ...
        'NewVariableNames', {'scaled_source_control_output','reduced_control_output'});
    rows = append_table(rows,row);
end
end

