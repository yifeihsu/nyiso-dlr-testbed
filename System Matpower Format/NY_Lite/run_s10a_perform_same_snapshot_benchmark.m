function write_assessment(path, summary, report)
value = @(metric) summary.value(summary.metric==metric);
text = sprintf([ ...
    '# S10a Control-Preserving PERFORM Benchmark\n\n' ...
    '## Status\n\n' ...
    'S10a is a diagnostic same-snapshot benchmark. S7 remains the structural baseline.\n\n' ...
    'The 2019 PERFORM source is similarity-scaled by `gamma = %.9f` so its ' ...
    'per-unit operating point is preserved at the %.3f-MW NPCC-NY load scale.\n\n' ...
    '## Results\n\n' ...
    '| Metric | Result | Initial target |\n|---|---:|---:|\n' ...
    '| Reduced Q-limit PF | %d | 1 |\n' ...
    '| Retained/pilot voltage RMSE | %.6f pu | < 0.01 pu |\n' ...
    '| Maximum retained/pilot voltage error | %.6f pu | < 0.03 pu |\n' ...
    '| Seven-interface MAE | %.3f MW | < 100 MW |\n' ...
    '| Mean normalized control-group Q error | %.6f | < 0.10 |\n' ...
    '| Scaled source active loss | %.3f MW | diagnostic |\n' ...
    '| Reduced active loss | %.3f MW | diagnostic |\n\n' ...
    '## Interpretation\n\n' ...
    'The benchmark isolates control/reduction error from the 2025 public scenarios. ' ...
    'The first five interface rows use matched zone-pair cut proxies. UPNY-ConEd ' ...
    'and Dunwoodie South remain conceptual source-to-reduced mappings because ' ...
    'exact monitored-element operators are not yet available.\n\n' ...
    'All ten previously PQ-skipped S7 generator/proxy locations have source ' ...
    'control evidence, but broad Q limits or low-confidence aggregation remain ' ...
    'at some locations. PV treatment in S10a is therefore diagnostic and does ' ...
    'not promote those buses in S7.\n\n' ...
    'Transformer control modes, switched-shunt block optimization, exact interface ' ...
    'operators, and a full Ward/Kron network equivalent remain pending.\n'], ...
    report.gamma, report.target_ny_load_mw, round(value("reduced_pf_success")), ...
    value("voltage_rmse_pu"), value("voltage_max_error_pu"), ...
    value("interface_mae_mw"), value("mean_normalized_control_group_q_error"), ...
    value("source_scaled_active_loss_mw"), value("reduced_active_loss_mw"));
fid = fopen(path,'w'); if fid<0, error('Cannot write %s.',path); end
cleanup = onCleanup(@() fclose(fid));
fprintf(fid,'%s',text);
end

function out = append_table(out,row)
