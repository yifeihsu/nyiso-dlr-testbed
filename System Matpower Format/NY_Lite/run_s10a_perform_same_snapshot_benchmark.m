function outputs = run_s10a_perform_same_snapshot_benchmark(options)
%RUN_S10A_PERFORM_SAME_SNAPSHOT_BENCHMARK Compare detailed and reduced 2019 PF.
%   S10a is diagnostic. It validates the device-classified control mapping
%   on a similarity-scaled 2019 PERFORM snapshot without replacing S7.

if nargin < 1, options = struct(); end
helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
options = defaults(options, helper_dir, case_dir);
addpath(case_dir); addpath(helper_dir);
define_constants;

[input_case, build_report] = build_s10a_perform_control_mapped_case;
source = build_report.mapping_outputs.source_pf;
control_map = build_report.mapping_outputs.control_mapping;
groups = build_report.mapping_outputs.control_groups;
gamma = build_report.gamma;
pfopt = mpoption('verbose', 0, 'out.all', 0, 'pf.enforce_q_lims', 1);
reduced = runpf(input_case, pfopt);

voltage = voltage_comparison(source, reduced, control_map, input_case);
qgroups = q_group_comparison(reduced, groups, ...
    build_report.generator_report, gamma);
interfaces = interface_comparison(source, reduced, gamma, helper_dir);
losses = loss_comparison(source, reduced, gamma);
external_q = external_q_comparison(qgroups);
branch_loading = branch_loading_report(source, reduced, gamma, helper_dir);
control_actions = control_action_report( ...
    build_report.mapping_outputs.discrete_detail, source, reduced, ...
    control_map, build_report.generator_report, gamma);
summary = benchmark_summary(source, reduced, voltage, qgroups, interfaces, ...
    losses, external_q, build_report, gamma, ...
    build_report.mapping_outputs.source_case, input_case);
boundary_q_sensitivity = run_boundary_q_sensitivity(helper_dir);

writetable(summary, options.summary_file);
writetable(voltage, options.voltage_file);
writetable(qgroups, options.q_file);
writetable(interfaces, options.interface_file);
writetable(losses, options.loss_file);
writetable(external_q, options.external_q_file);
writetable(branch_loading, options.branch_file);
writetable(control_actions, options.control_action_file);
writetable(build_report.generator_report, options.generator_file);
writetable(boundary_q_sensitivity, options.boundary_q_sensitivity_file);
savecase(options.solved_case_file, reduced);
write_assessment(options.assessment_file, summary, build_report);

outputs = struct('summary', summary, 'voltage_comparison', voltage, ...
    'q_group_comparison', qgroups, 'interface_comparison', interfaces, ...
    'loss_comparison', losses, 'external_q_comparison', external_q, ...
    'branch_loading', branch_loading, 'control_actions', control_actions, ...
    'boundary_q_sensitivity', boundary_q_sensitivity, ...
    'input_case', input_case, 'reduced_pf', reduced, 'source_pf', source, ...
    'build_report', build_report, 'summary_file', options.summary_file, ...
    'solved_case_file', options.solved_case_file, ...
    'assessment_file', options.assessment_file);
end

