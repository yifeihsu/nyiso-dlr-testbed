function rows = run_boundary_q_sensitivity(helper_dir)
define_constants;
modes = ["fixed_source_q","limited_source_q","no_discretionary_q"];
rows = table();
for k = 1:numel(modes)
    [input_case, report] = build_s10a_perform_control_mapped_case( ...
        struct('boundary_q_mode', modes(k)));
    opt = mpoption('verbose',0,'out.all',0,'pf.enforce_q_lims',1);
    result = runpf(input_case,opt);
    boundary = report.generator_report.reduced_device_type == ...
        "boundary_import_equivalent";
    gi = report.generator_report.reduced_gen_index(boundary);
    source_q = report.generator_report.initial_qg_mvar(boundary);
    external_q_error = sum(abs(result.gen(gi,QG) - source_q));
    ref_gen = find(result.gen(:,GEN_BUS)==report.reference_bus);
    initial_ref = sum(input_case.gen(ref_gen,PG));
    ref_delta = sum(result.gen(ref_gen,PG)) - initial_ref;
    source = report.mapping_outputs.source_pf;
    v = voltage_comparison(source,result,report.mapping_outputs.control_mapping,input_case);
    i = interface_comparison(source,result,report.gamma,helper_dir);
    q = q_group_comparison(result,report.mapping_outputs.control_groups, ...
        report.generator_report,report.gamma);
    [q_saturation_count, pv_to_pq_conversion_count] = ...
        q_transition_counts(input_case, result);
    row = table(modes(k), double(result.success), min(result.bus(:,VM)), ...
        max(result.bus(:,VM)), sqrt(mean(v.voltage_error_pu.^2)), ...
        mean(i.absolute_residual_mw), mean(q.normalized_q_error), ...
        external_q_error, ref_delta, ...
        nnz(result.gen(:,QG)<result.gen(:,QMIN)-1e-6 | ...
            result.gen(:,QG)>result.gen(:,QMAX)+1e-6), ...
        branch_overload_count(result), q_saturation_count, ...
        pv_to_pq_conversion_count, ...
        'VariableNames', {'boundary_q_mode','pf_success','min_voltage_pu', ...
        'max_voltage_pu','voltage_rmse_pu','interface_mae_mw', ...
        'mean_normalized_control_group_q_error', ...
        'external_q_total_abs_error_mvar','reference_generation_adjustment_mw', ...
        'q_violation_count','branch_overload_count','q_saturation_count', ...
        'pv_to_pq_conversion_count'});
    rows = append_table(rows,row);
end
end

function rows = voltage_comparison(source, reduced, control_map, input_case)
define_constants;
online = control_map.snapshot_effective_status > 0 & ...
    isfinite(control_map.retained_pilot_bus) & ...
    isfinite(control_map.source_regulated_bus);
source_fuel = lower(strtrim(string(control_map.source_fuel)));
device_class = lower(strtrim(string(control_map.device_class)));
device_type = lower(strtrim(string(control_map.reduced_device_type)));
source_id = upper(strtrim(string(control_map.source_generator_id)));
boundary = ismember(source_fuel, ["import","reference"]) | ...
    device_class == "fixed_import_or_boundary_equivalent" | ...
    device_type == "boundary_import_equivalent" | source_id == "RF";
placeholder = generic_q_placeholder( ...
    control_map.source_QMIN, control_map.source_QMAX);
physical_reference = online & ~boundary & ~placeholder;
pilots = unique(control_map.retained_pilot_bus(physical_reference), 'stable');
rows = table();
for pilot = pilots(:)'
    idx = physical_reference & control_map.retained_pilot_bus == pilot;
    [found, source_bi] = ismember(control_map.source_regulated_bus(idx), ...
        source.bus(:, BUS_I));
    source_vm = source.bus(source_bi(found), VM);
    source_vs = control_map.source_VS(idx); source_vs = source_vs(found);
    weights = max(control_map.source_QMAX(idx) - control_map.source_QMIN(idx), 0);
    weights = weights(found);
    if sum(weights) <= 0, weights = ones(numel(source_vm), 1); end
    weights = weights / sum(weights);
    target_vm = sum(weights .* source_vm);
    target_vs = sum(weights .* source_vs);
    rbi = find(reduced.bus(:, BUS_I) == pilot, 1);
    ibi = find(input_case.bus(:, BUS_I) == pilot, 1);
    if isempty(rbi), continue; end
    name = bus_name(reduced, rbi);
    zone = string(reduced.userdata.nyiso_physical_zone{rbi});
    reduced_vm = reduced.bus(rbi, VM);
    error_pu = reduced_vm - target_vm;
    row = table(pilot, name, zone, sum(idx), numel(unique( ...
        control_map.source_regulated_bus(idx))), target_vm, target_vs, ...
        input_case.bus(ibi, VM), reduced_vm, error_pu, abs(error_pu), ...
        aggregate_confidence(control_map.mapping_confidence(idx)), ...
        join(string(unique(control_map.source_regulated_bus(idx)))', '|'), ...
        'VariableNames', {'retained_pilot_bus','retained_bus_name','zone', ...
        'source_control_record_count','source_regulated_bus_count', ...
        'source_pf_weighted_vm_pu','source_weighted_vs_pu', ...
        'reduced_initial_vm_pu','reduced_pf_vm_pu','voltage_error_pu', ...
        'absolute_voltage_error_pu','mapping_confidence','source_regulated_bus_ids'});
    rows = append_table(rows, row);
end
end

function flag = generic_q_placeholder(qmin, qmax)
qmin = double(qmin);
qmax = double(qmax);
flag = false(size(qmin));
for value = [999 9999 9900]
    flag = flag | (abs(qmin+value)<=1e-6 & abs(qmax-value)<=1e-6);
end
end

function rows = q_group_comparison(reduced, groups, gen_report, gamma)
define_constants;
rows = table();
for k = 1:height(groups)
    id = groups.reduced_control_group_id(k);
    report_rows = gen_report.reduced_control_group_id == id;
    gen_idx = gen_report.reduced_gen_index(report_rows);
    source_q = gamma * groups.source_qg_mvar(k);
    reduced_q = sum(reduced.gen(gen_idx, QG));
    qrange = gamma * (groups.source_qmax_mvar(k) - groups.source_qmin_mvar(k));
    error = reduced_q - source_q;
    normalized = abs(error) / max(qrange, 1);
    source_sat = source_q <= gamma * groups.source_qmin_mvar(k) + 1e-3 | ...
        source_q >= gamma * groups.source_qmax_mvar(k) - 1e-3;
    reduced_qmin = sum(reduced.gen(gen_idx, QMIN));
    reduced_qmax = sum(reduced.gen(gen_idx, QMAX));
    reduced_sat = reduced_q <= reduced_qmin + 1e-3 | reduced_q >= reduced_qmax - 1e-3;
    row = table(id, groups.retained_device_bus(k), groups.retained_pilot_bus(k), ...
        groups.reduced_device_type(k), groups.source_record_count(k), source_q, ...
        reduced_q, error, abs(error), qrange, normalized, source_sat, ...
        reduced_sat, groups.mapping_confidence(k), groups.source_bus_ids(k), ...
        'VariableNames', {'reduced_control_group_id','retained_device_bus', ...
        'retained_pilot_bus','reduced_device_type','source_record_count', ...
        'scaled_source_q_mvar','reduced_pf_q_mvar','q_error_mvar', ...
        'absolute_q_error_mvar','scaled_usable_q_range_mvar', ...
        'normalized_q_error','source_q_limit_saturated', ...
        'reduced_q_limit_saturated','mapping_confidence','source_bus_ids'});
    rows = append_table(rows, row);
end
end

function rows = interface_comparison(source, reduced, gamma, helper_dir)
source_zone = perform_bus_zones(source, helper_dir);
reduced_zone = string(reduced.userdata.nyiso_physical_zone);
specs = { ...
    'Dysinger_East','A','B','A','B','same zone-pair proxy'; ...
    'West_Central','B','C','B','C','same zone-pair proxy'; ...
    'Moses_South','D','E','D','E','same zone-pair proxy'; ...
    'Central_East','E','F','E','F','same zone-pair proxy'; ...
    'Total_East_proxy','F','G','F','G','same zone-pair proxy'; ...
    'UPNY_ConEd','G','I','G','H','conceptual mapping; exact monitored elements unresolved'; ...
    'Dunwoodie_South','H','J','I','J','conceptual mapping; exact monitored elements unresolved'};
rows = table();
for k = 1:size(specs,1)
    [sf, sb] = zone_cut_flow(source, source_zone, specs{k,2}, specs{k,3});
    [rf, rb] = zone_cut_flow(reduced, reduced_zone, specs{k,4}, specs{k,5});
    sf = gamma * sf;
    residual = rf - sf;
    if abs(sf) > 1e-9, pct = 100 * residual / abs(sf); else, pct = NaN; end
    floored_pct = 100 * residual / max(abs(sf), 100);
    row = table(string(specs{k,1}), string(specs{k,2})+"-"+string(specs{k,3}), ...
        string(specs{k,4})+"-"+string(specs{k,5}), sf, rf, residual, ...
        abs(residual), pct, floored_pct, sb, rb, string(specs{k,6}), ...
        'VariableNames', {'interface_name','source_zone_cut', ...
        'reduced_zone_cut','scaled_source_flow_mw','reduced_pf_flow_mw', ...
        'residual_mw','absolute_residual_mw','relative_percentage_error', ...
        'normalized_percentage_error_100mw_floor', ...
        'source_branch_count','reduced_branch_count','operator_status'});
    rows = append_table(rows, row);
end
end

function [flow, count] = zone_cut_flow(results, zones, from_zone, to_zone)
define_constants;
flow = 0; count = 0;
for br = find(results.branch(:, BR_STATUS) > 0)'
    fi = find(results.bus(:, BUS_I) == results.branch(br, F_BUS), 1);
    ti = find(results.bus(:, BUS_I) == results.branch(br, T_BUS), 1);
    if zones(fi) == string(from_zone) && zones(ti) == string(to_zone)
        flow = flow + results.branch(br, PF); count = count + 1;
    elseif zones(fi) == string(to_zone) && zones(ti) == string(from_zone)
        flow = flow + results.branch(br, PT); count = count + 1;
    end
end
end

function rows = loss_comparison(source, reduced, gamma)
define_constants;
[source_loss, source_fchg, source_tchg] = get_losses(source);
[reduced_loss, reduced_fchg, reduced_tchg] = get_losses(reduced);
source_balance_p = gamma * (sum(source.gen(source.gen(:,GEN_STATUS)>0,PG)) - ...
    sum(source.bus(:,PD)));
reduced_balance_p = sum(reduced.gen(reduced.gen(:,GEN_STATUS)>0,PG)) - ...
    sum(reduced.bus(:,PD));
source_shunt_q = sum(source.bus(:,BS) .* source.bus(:,VM).^2);
reduced_shunt_q = sum(reduced.bus(:,BS) .* reduced.bus(:,VM).^2);
source_balance_q = gamma * (sum(source.gen(source.gen(:,GEN_STATUS)>0,QG)) - ...
    sum(source.bus(:,QD)));
reduced_balance_q = sum(reduced.gen(reduced.gen(:,GEN_STATUS)>0,QG)) - ...
    sum(reduced.bus(:,QD));
rows = table(["active_balance_loss";"series_active_loss"; ...
    "series_reactive_loss";"line_charging_injection"; ...
    "bus_shunt_injection";"net_network_q_balance"], ...
    [source_balance_p;gamma*sum(real(source_loss));gamma*sum(imag(source_loss)); ...
    gamma*sum(source_fchg+source_tchg);gamma*source_shunt_q;source_balance_q], ...
    [reduced_balance_p;sum(real(reduced_loss));sum(imag(reduced_loss)); ...
    sum(reduced_fchg+reduced_tchg);reduced_shunt_q;reduced_balance_q], ...
    ["MW";"MW";"MVAr";"MVAr";"MVAr";"MVAr"], ...
    'VariableNames', {'quantity','scaled_source_value','reduced_value','unit'});
rows.residual = rows.reduced_value - rows.scaled_source_value;
end

