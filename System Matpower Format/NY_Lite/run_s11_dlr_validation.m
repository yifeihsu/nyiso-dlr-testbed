function outputs = run_s11_dlr_validation(options)
%RUN_S11_DLR_VALIDATION Build and gate the S11 DLR power-flow case set.
%   OUTPUTS = RUN_S11_DLR_VALIDATION(OPTIONS) validates the central-Q,
%   0.90-Q, and 1.10-Q variants of the S1, S2, and S5 public snapshots. It
%   also runs the 2019 PERFORM same-snapshot structural benchmark.
%
%   A scenario is included in the preliminary model set only when every
%   operating-point gate and the shared 2019 structural benchmark pass.
%   Failures are retained in the validation tables but are never relabeled
%   as accepted. No tolerance is relaxed in response to a failed case.
%
%   Common options:
%       build_cases        call BUILD_S11_DLR_PF_CASE (default true)
%       write_outputs      write the validation CSVs (default true)
%       fail_on_nominal    error after writing if nominal is not promoted
%                          (default true)
%       write_case_files   save only cases that pass every gate (default true)
%       build_options      options forwarded to BUILD_S11_DLR_PF_CASE
%       benchmark_options  options forwarded to the 2019 benchmark
%
%   With build_cases=false, existing case files are rechecked. Saved cases
%   that lack build-time dispatch provenance cannot pass the promotion gate.

if nargin < 1, options = struct(); end
helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
options = defaults(options, helper_dir, case_dir);
validate_options(options);

addpath(case_dir);
addpath(helper_dir);
define_constants;

variants = build_variant_table(options);
[benchmark, benchmark_pass, benchmark_error] = run_benchmark(options);

records = repmat(summary_template(), height(variants), 1);
interface_validation = table();
gate_validation = table();
branch_report = table();
build_outputs = cell(height(variants), 1);

for k = 1:height(variants)
    scenario_id = variants.scenario_id(k);
    role = variants.role(k);
    q_multiplier = variants.q_multiplier(k);
    built = [];
    record = summary_template();
    record.scenario_id = scenario_id;
    record.role = role;
    record.q_multiplier = q_multiplier;
    record.is_central_q = abs(q_multiplier - 1) <= 1e-12;
    record.is_nominal = record.is_central_q && ...
        scenario_id == options.nominal_scenario_id;
    try
        if options.build_cases
            build_options = options.build_options;
            build_options.q_multiplier = q_multiplier;
            % The validation runner owns final exclusion and case writing.
            % Keep failed solved cases in memory for complete diagnostics.
            build_options.write_cases = false;
            build_options.require_operating_gates = false;
            if ~isfield(build_options, 'write_intermediate_maps')
                % A diagnostic/no-write validation must not mutate shared
                % provenance CSVs. In a publishing run, write the invariant
                % physical/interface maps once on the first variant only.
                build_options.write_intermediate_maps = ...
                    logical(options.write_outputs && k == 1);
            end
            if ~isfield(build_options, 'non_dlr_correction')
                build_options.non_dlr_correction = ...
                    options.non_dlr_correction_file;
            end
            built = build_s11_dlr_pf_case(scenario_id, build_options);
            provenance_complete = true;
            record.case_status = "built_and_validated";
        else
            built = load_existing_variant(scenario_id, role, q_multiplier, ...
                options);
            provenance_complete = built.provenance_complete;
            record.case_status = "loaded_and_rechecked";
        end
        record = assess_variant(record, built, provenance_complete, options);
        interface_rows = make_interface_rows(record, built, options);
        branch_rows = make_branch_rows(record, built, benchmark);
    catch ex
        record.build_success = false;
        record.case_status = "excluded_after_validation_failure";
        record.exception_identifier = string(ex.identifier);
        record.exception_message = string(ex.message);
        record.operating_gate_pass = false;
        record.included_in_preliminary_model_set = false;
        interface_rows = failed_interface_row(record);
        branch_rows = table();
    end

    record.structural_2019_pass = benchmark_pass;
    record.included_in_preliminary_model_set = ...
        record.operating_gate_pass && benchmark_pass;
    record.nominal_promotion_pass = false;
    if record.included_in_preliminary_model_set
        if record.is_nominal
            record.case_status = "promoted_preliminary_operating_case";
        elseif record.is_central_q
            record.case_status = "accepted_validation_case";
        else
            record.case_status = "accepted_reactive_load_sensitivity_case";
        end
        if options.build_cases && options.write_case_files
            try
                [built, case_files] = write_validated_case_files( ...
                    built, role, q_multiplier, options.case_dir);
                record.case_files_written = true;
                record.input_case_file = case_files.input_file;
                record.solution_case_file = case_files.solution_file;
            catch ex
                record.case_status = "excluded_after_case_write_failure";
                record.exception_identifier = string(ex.identifier);
                record.exception_message = string(ex.message);
                record.included_in_preliminary_model_set = false;
            end
        end
    elseif record.build_success
        record.case_status = "excluded_by_mandatory_gate";
    end
    if options.build_cases && options.write_case_files && ...
            ~record.case_files_written
        try
            invalidate_managed_case_files(role, q_multiplier, options.case_dir);
        catch ex
            record.case_status = "excluded_after_stale_case_invalidation_failure";
            record.exception_identifier = string(ex.identifier);
            record.exception_message = string(ex.message);
            record.included_in_preliminary_model_set = false;
        end
    end
    if exist('built', 'var') && isstruct(built)
        build_outputs{k} = built;
    end
    record.nominal_promotion_pass = record.is_nominal && ...
        record.included_in_preliminary_model_set && ...
        record.case_files_written;
    records(k) = record;

    interface_rows.structural_2019_pass(:) = benchmark_pass;
    interface_rows.included_in_preliminary_model_set(:) = ...
        record.included_in_preliminary_model_set;
    if ~isempty(branch_rows)
        branch_rows.structural_2019_pass(:) = benchmark_pass;
        branch_rows.included_in_preliminary_model_set(:) = ...
            record.included_in_preliminary_model_set;
    end
    interface_validation = append_table(interface_validation, interface_rows);
    branch_report = append_table(branch_report, branch_rows);
    gate_validation = append_table(gate_validation, ...
        make_variant_gate_rows(record, options));
end

% Keep the complete reduced 2019 branch solution in the current report as
% a diagnostic benchmark block. It is never an operating scenario and is
% therefore never marked as included in the preliminary model set.
benchmark_branch_rows = make_benchmark_branch_rows(benchmark, benchmark_pass);
branch_report = append_table(branch_report, benchmark_branch_rows);

summary = struct2table(records);
[benchmark_gate_rows, benchmark_summary_rows] = ...
    benchmark_validation_rows(benchmark, benchmark_pass, benchmark_error);
gate_validation = append_table(gate_validation, benchmark_gate_rows);
summary = [summary; benchmark_summary_rows];

% Add the shared structural gate and final inclusion status after all rows
% are available. This keeps operating and structural failures distinct.
for k = 1:height(variants)
    record = records(k);
    row = gate_row(record, "structural_benchmark", ...
        "2019_same_snapshot_all_gates", double(benchmark_pass), "flag", ...
        "==", 1, benchmark_pass, true, ...
        "Shared current, active-loss, and corrected net-network-Q gate.");
    gate_validation = append_table(gate_validation, row);
    row = gate_row(record, "overall", ...
        "included_in_preliminary_model_set", ...
        double(record.included_in_preliminary_model_set), "flag", "==", 1, ...
        record.included_in_preliminary_model_set, true, ...
        "Requires every operating gate and the shared 2019 benchmark.");
    gate_validation = append_table(gate_validation, row);
end

if isempty(branch_report)
    branch_report = empty_branch_report();
end

files = output_files(options.output_dir);
if options.write_outputs
    require_output_directory(options.output_dir);
    writetable(interface_validation, files.interface_validation);
    writetable(gate_validation, files.voltage_q_branch_validation);
    writetable(branch_report, files.branch_current_report);
    writetable(summary, files.dispatch_and_loss_summary);
end

nominal_idx = find(summary.scenario_id == options.nominal_scenario_id & ...
    summary.is_central_q, 1);
nominal_pass = ~isempty(nominal_idx) && ...
    summary.nominal_promotion_pass(nominal_idx);
outputs = struct( ...
    'variants', variants, ...
    'scenario_summary', summary, ...
    'interface_validation', interface_validation, ...
    'voltage_q_branch_validation', gate_validation, ...
    'branch_current_report', branch_report, ...
    'build_outputs', {build_outputs}, ...
    'benchmark', benchmark, ...
    'benchmark_pass', benchmark_pass, ...
    'benchmark_error', benchmark_error, ...
    'nominal_promotion_pass', nominal_pass, ...
    'included_scenario_count', nnz([records.included_in_preliminary_model_set]), ...
    'output_files', files, ...
    'outputs_written', logical(options.write_outputs));

if options.fail_on_nominal && ~nominal_pass
    error('run_s11_dlr_validation:NominalNotPromoted', ...
        ['The S1 central-Q case did not pass every mandatory operating and ' ...
        '2019 structural gate. Validation outputs were retained.']);
end
end

