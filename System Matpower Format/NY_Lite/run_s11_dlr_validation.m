function rows = reconstruct_interfaces(result, scenario_id, options)
defs = ny_lite_interface_definitions(result, ...
    struct('map_file', options.interface_map_file));
flow_records = ny_lite_interface_flows(result, defs);
flows = struct2table(flow_records);
flows = flows(string(flows.result_type) == "subpath", :);
targets = readtable(options.interface_target_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
targets = targets(string(targets.scenario_id) == scenario_id, :);
names = string(flows.interface_name);
[found, idx] = ismember(names, string(targets.interface_name));
if ~all(found)
    error('run_s11_dlr_validation:InterfaceTarget', ...
        'One or more explicit S11 interfaces have no public target.');
end
if options.use_raw_public_targets
    target_value = double(targets.nyiso_flow_mw(idx));
    source = repmat("raw_NYISO_public", height(flows), 1);
else
    target_value = double(targets.target_flow_mw(idx));
    source = repmat("S7_similarity_scaled", height(flows), 1);
end
calibration = false(height(flows), 1);
for k = 1:height(flows)
    calibration(k) = any(strcmp({defs.interface_name}, char(names(k))) & ...
        [defs.calibration_eligible]);
end
rows = table(names, calibration, source, target_value, double(flows.flow_mw), ...
    double(flows.flow_mw)-target_value, ...
    'VariableNames', {'interface_name','calibration_eligible','target_source', ...
    'target_flow_mw','final_ac_flow_mw','final_ac_residual_mw'});
end

function [mae, maximum, bias] = interface_aggregate(built, scenario_id, options)
mae = NaN; maximum = NaN; bias = NaN;
if ~isfield(built, 'solution') || ~isstruct(built.solution)
    return;
end
rows = reconstruct_interfaces(built.solution, scenario_id, options);
if isempty(rows), return; end
mask = logical(rows.calibration_eligible);
residual = double(rows.final_ac_residual_mw(mask));
if isempty(residual), return; end
mae = mean(abs(residual));
maximum = max(abs(residual));
bias = mean(residual);
end

function [original, seed, source, source_balanced, scenario_balanced] = ...
        dispatch_movement(built)
original = NaN; seed = NaN; source = NaN;
source_balanced = NaN; scenario_balanced = NaN;
if isfield(built, 'dispatch_targets') && ~isempty(built.dispatch_targets)
    targets = built.dispatch_targets;
    if ismember('original_to_final_redispatch_mw', ...
            targets.Properties.VariableNames)
        original = sum(abs(targets.original_to_final_redispatch_mw));
    end
    if ismember('seed_to_final_redispatch_mw', ...
            targets.Properties.VariableNames)
        seed = sum(abs(targets.seed_to_final_redispatch_mw));
    end
    if ismember('source_prior_to_final_redispatch_mw', ...
            targets.Properties.VariableNames)
        source = sum(abs(targets.source_prior_to_final_redispatch_mw));
    end
    if ismember('source_balanced_prior_to_final_redispatch_mw', ...
            targets.Properties.VariableNames)
        source_balanced = sum(abs( ...
            targets.source_balanced_prior_to_final_redispatch_mw));
    end
    if ismember('scenario_balanced_prior_to_final_redispatch_mw', ...
            targets.Properties.VariableNames)
        scenario_balanced = sum(abs( ...
            targets.scenario_balanced_prior_to_final_redispatch_mw));
    end
end
end

function [trusted_rated, legacy_diagnostic_rated] = ...
        branch_limit_masks(branch_count, branch_map, rated)
trusted = false(branch_count, 1);
if isempty(branch_map) || ~istable(branch_map) || ...
        ~ismember('branch_index', branch_map.Properties.VariableNames) || ...
        ~ismember('branch_classification', branch_map.Properties.VariableNames)
    error('run_s11_dlr_validation:BranchMapSchema', ...
        'The physical-circuit map lacks branch indices or classifications.');
end
idx = double(branch_map.branch_index(:));
if any(~isfinite(idx) | idx<1 | idx>branch_count | idx~=fix(idx)) || ...
        numel(unique(idx))~=numel(idx)
    error('run_s11_dlr_validation:BranchMapIndex', ...
        'The physical-circuit map has invalid or duplicate branch indices.');
end
map_trusted = string(branch_map.branch_classification) == "physical_circuit";
if ismember('trusted_static_limit', branch_map.Properties.VariableNames)
    map_trusted = map_trusted | ...
        logical_map_values(branch_map.trusted_static_limit);
end
trusted(idx(map_trusted)) = true;
trusted_rated = trusted & rated(:);
legacy_diagnostic_rated = ~trusted & rated(:);
end

function values = logical_map_values(raw)
if islogical(raw)
    values = raw(:);
elseif isnumeric(raw)
    values = isfinite(raw(:)) & raw(:)~=0;
else
    text = lower(strtrim(string(raw(:))));
    values = ismember(text, ["true","1","yes","y"]);
end
end

function count = placeholder_internal_q_count(mpc, external_idx, tolerance)
define_constants;
internal = mpc.gen(:, GEN_STATUS)>0;
external_idx = external_idx(external_idx>=1 & external_idx<=numel(internal));
internal(external_idx) = false;
qmin = mpc.gen(:, QMIN); qmax = mpc.gen(:, QMAX);
placeholder = (abs(qmin+999)<=tolerance & abs(qmax-999)<=tolerance) | ...
    (abs(qmin+9999)<=tolerance & abs(qmax-9999)<=tolerance);
count = nnz(internal & placeholder);
end

