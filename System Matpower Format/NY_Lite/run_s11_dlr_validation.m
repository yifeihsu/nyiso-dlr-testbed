function role = scenario_role(scenario_id)
switch string(scenario_id)
    case "S1_2025_SUMMER_PEAK_PUBLIC"
        role = "summer_peak";
    case "S2_2025_WINTER_PEAK_PUBLIC"
        role = "winter_peak";
    case "S5_2025_HIGH_TOTAL_EAST_PUBLIC"
        role = "high_total_east";
    otherwise
        role = lower(regexprep(string(scenario_id), '[^A-Za-z0-9]+', '_'));
end
end

function value = success_flag(result)
value = isstruct(result) && isfield(result, 'success') && ...
    logical(result.success);
end

function out = append_table(out, rows)
if isempty(rows), return; end
if isempty(out), out = rows; else, out = [out; rows]; end
end

function value = ternary(condition, yes, no)
if condition, value = yes; else, value = no; end
end
