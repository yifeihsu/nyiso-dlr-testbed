if ~success_flag(q_pf)
    error('run_s11_dlr_validation:ExistingCaseQPF', ...
        'Q-limit PF failed for existing case %s.', file);
end
if exist(options.physical_map_file, 'file') ~= 2
    error('run_s11_dlr_validation:MissingPhysicalMap', ...
        'The S11 physical-circuit map is missing.');
end
map = readtable(options.physical_map_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
interface_table = reconstruct_interfaces(q_pf, scenario_id, options);
built = struct( ...
    'scenario_id', scenario_id, ...
    'input_case', mpc, ...
    'solution', q_pf, ...
    'standard_pf', standard_pf, ...
    'physical_circuit_map', map, ...
    'interface_branch_map', table(), ...
    'control_report', struct('external_gen_idx', []), ...
    'dispatch_targets', table(), ...
    'closure', struct('converged', false, ...
        'stop_reason', "saved_case_lacks_build_time_closure_provenance", ...
        'iteration_count', NaN, 'accepted_step_count', NaN, ...
        'interface_table', interface_table), ...
    'projection', struct('attempted', false, 'success', false), ...
    'metrics', struct('reference_pickup_mw', NaN), ...
    'case_files', struct('input_file', string(file), 'solution_file', ""), ...
    'provenance_complete', false);
end

function [standard_pf, q_pf] = run_pf_pair(mpc)
