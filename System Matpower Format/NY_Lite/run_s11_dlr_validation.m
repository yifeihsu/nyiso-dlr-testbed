function metrics = network_metrics(result)
define_constants;
[loss, fchg, tchg] = get_losses(result);
online = result.gen(:, GEN_STATUS)>0;
series_p = sum(real(loss));
bus_p = sum(result.bus(:, GS).*result.bus(:, VM).^2);
active_network = series_p + bus_p;
active_balance = sum(result.gen(online, PG))-sum(result.bus(:, PD));
series_q = sum(imag(loss));
charging_q = sum(real(fchg+tchg));
bus_q = sum(result.bus(:, BS).*result.bus(:, VM).^2);
net_q = series_q-charging_q-bus_q;
q_balance = sum(result.gen(online, QG))-sum(result.bus(:, QD));
metrics = struct('active_network_loss_mw', active_network, ...
    'active_identity_residual_mw', active_balance-active_network, ...
    'net_network_q_mvar', net_q, ...
    'reactive_identity_residual_mvar', q_balance-net_q);
end

