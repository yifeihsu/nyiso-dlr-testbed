function validate_options(options)
validateattributes(options.q_multipliers, {'numeric'}, ...
    {'vector','finite','positive'});
validateattributes(options.interface_mae_gate_mw, {'numeric'}, ...
    {'scalar','finite','positive'});
validateattributes(options.interface_max_residual_gate_mw, {'numeric'}, ...
    {'scalar','finite','positive'});
validateattributes(options.interface_signed_bias_gate_mw, {'numeric'}, ...
    {'scalar','finite','positive'});
validateattributes(options.reference_pickup_gate_mw, {'numeric'}, ...
    {'scalar','finite','positive','<=',1});
validateattributes(options.redispatch_gate_percent_of_load, {'numeric'}, ...
    {'scalar','finite','positive'});
validateattributes(options.redispatch_hard_limit_mw, {'numeric'}, ...
    {'scalar','finite','positive'});
validateattributes(options.maximum_external_q_range_mvar, {'numeric'}, ...
    {'scalar','finite','nonnegative'});
if ~isscalar(options.nominal_scenario_id)
    error('run_s11_dlr_validation:NominalScenario', ...
        'nominal_scenario_id must be scalar text.');
end
if ~isscalar(options.redispatch_justification)
    error('run_s11_dlr_validation:RedispatchJustification', ...
        'redispatch_justification must be scalar text.');
end
if ~ismember(options.nominal_scenario_id, options.scenario_ids)
    error('run_s11_dlr_validation:NominalScenario', ...
        'The nominal scenario must be in scenario_ids.');
end
if ~isstruct(options.build_options) || ~isstruct(options.benchmark_options)
    error('run_s11_dlr_validation:Options', ...
        'build_options and benchmark_options must be structs.');
end
end

function variants = build_variant_table(options)
n = numel(options.scenario_ids) * numel(options.q_multipliers);
scenario_id = strings(n, 1);
role = strings(n, 1);
q_multiplier = zeros(n, 1);
is_central_q = false(n, 1);
row = 0;
for s = 1:numel(options.scenario_ids)
    for q = 1:numel(options.q_multipliers)
        row = row + 1;
        scenario_id(row) = options.scenario_ids(s);
        role(row) = scenario_role(options.scenario_ids(s));
        q_multiplier(row) = options.q_multipliers(q);
        is_central_q(row) = abs(q_multiplier(row)-1) <= 1e-12;
    end
end
variants = table(scenario_id, role, q_multiplier, is_central_q);
end

function [benchmark, passed, error_text] = run_benchmark(options)
benchmark = struct();
passed = false;
error_text = "";
if ~options.run_2019_benchmark
    error_text = "2019 benchmark disabled; structural gate is unverified.";
    return;
end
benchmark_options = options.benchmark_options;
benchmark_options.write_output = options.write_outputs;
benchmark_options.output_file = fullfile(options.output_dir, ...
    's11_2019_same_snapshot_benchmark.csv');
if ~isfield(benchmark_options, 'non_dlr_correction')
    benchmark_options.non_dlr_correction = ...
        options.non_dlr_correction_file;
end
try
    benchmark = run_s11_2019_same_snapshot_benchmark(benchmark_options);
    correction_ward_audit = correction_ward_gate( ...
        benchmark_options.non_dlr_correction);
    benchmark.correction_ward_audit = correction_ward_audit;
    passed = isfield(benchmark, 'all_mandatory_gates_pass') && ...
        logical(benchmark.all_mandatory_gates_pass);
catch ex
    error_text = string(ex.identifier) + ": " + string(ex.message);
    benchmark = struct('exception_identifier', string(ex.identifier), ...
        'exception_message', string(ex.message));
end
end

function audit = correction_ward_gate(input)
audit = struct('required', false, 'metadata_present', false, ...
    'ward_nonworsening', true, 'pass', true, ...
    'baseline_complex_relative_frobenius_error', NaN, ...
    'corrected_complex_relative_frobenius_error', NaN, ...
    'note', "No non-DLR correction supplied; Ward correction gate not applicable.");
if isempty(input), return; end
audit.required = true;
if ischar(input) || isstring(input)
    data = load(char(input));
    if ~isfield(data, 'correction')
        audit.ward_nonworsening = false;
        audit.note = "Diagnostic unavailable: correction MAT-file lacks the correction variable.";
        return;
    end
    correction = data.correction;
else
    correction = input;
end
if ~isstruct(correction) || ~isfield(correction, 'ward_nonworsening')
    audit.ward_nonworsening = false;
    audit.note = "Diagnostic unavailable: correction lacks ward_nonworsening metadata.";
    return;
end
audit.metadata_present = true;
audit.ward_nonworsening = logical(correction.ward_nonworsening);
if isfield(correction, 'ward_summary') && istable(correction.ward_summary)
    rows = correction.ward_summary;
    quantity = string(rows.quantity);
    idx = find(quantity == "complex_relative_frobenius", 1);
    if ~isempty(idx)
        audit.baseline_complex_relative_frobenius_error = ...
            double(rows.baseline_value(idx));
        audit.corrected_complex_relative_frobenius_error = ...
            double(rows.fitted_value(idx));
    end
end
if audit.pass
    if audit.ward_nonworsening
        audit.note = "Diagnostic: local Ward-anchor relative Frobenius error is nonworsening.";
    else
        audit.note = "Diagnostic: empirical correction worsens the local Ward-anchor " + ...
            "relative Frobenius error; the plan's mandatory 2019 gates remain " + ...
            "circuit current, active loss, and net network Q.";
    end
else
    audit.note = "Diagnostic unavailable.";
end
end

function record = assess_variant(record, built, provenance_complete, options)
define_constants;
record.build_success = true;
record.dispatch_justification = options.redispatch_justification;
record.non_dlr_correction_file = string(options.non_dlr_correction_file);
if isfield(built, 'correction_report') && ...
        isfield(built.correction_report, 'correction')
    ward = correction_ward_gate(built.correction_report.correction);
    record.ward_nonworsening = ward.ward_nonworsening;
    record.baseline_ward_relative_frobenius_error = ...
        ward.baseline_complex_relative_frobenius_error;
    record.corrected_ward_relative_frobenius_error = ...
        ward.corrected_complex_relative_frobenius_error;
end
record.provenance_complete = logical(provenance_complete);
record.standard_pf_success = success_flag(built.standard_pf);
record.q_limit_pf_success = success_flag(built.solution);
if ~record.q_limit_pf_success
    error('run_s11_dlr_validation:QPF', ...
        'The Q-limit-enforced power flow did not converge.');
end
result = built.solution;
input_case = built.input_case;
allowed_reference_buses = [37 38 39 41 73 76 81];
regulating_bus_ids = input_case.bus( ...
    ismember(input_case.bus(:, BUS_TYPE), [PV REF]), BUS_I);
reference_bus_ids = input_case.bus( ...
    input_case.bus(:, BUS_TYPE) == REF, BUS_I);
record.regulating_bus_count = numel(regulating_bus_ids);
record.unexpected_regulating_bus_count = nnz( ...
    ~ismember(regulating_bus_ids, allowed_reference_buses));
record.operational_reference_bus = NaN;
if isscalar(reference_bus_ids)
    record.operational_reference_bus = reference_bus_ids(1);
end
record.mapped_operational_reference_bus = NaN;
if isfield(built, 'control_report') && ...
        isfield(built.control_report, 'generator_report') && ...
        istable(built.control_report.generator_report)
    control_rows = built.control_report.generator_report;
    required_reference_columns = {'retained_device_bus', ...
        'is_native_active_control','is_operational_reference'};
    if all(ismember(required_reference_columns, ...
            control_rows.Properties.VariableNames))
        mapped = logical(control_rows.is_native_active_control) & ...
            logical(control_rows.is_operational_reference);
        mapped_buses = unique(double( ...
            control_rows.retained_device_bus(mapped)));
        if isscalar(mapped_buses)
            record.mapped_operational_reference_bus = mapped_buses(1);
        end
    end
end
record.mapped_reference_control_match = ...
    isfinite(record.operational_reference_bus) && ...
    isfinite(record.mapped_operational_reference_bus) && ...
    record.operational_reference_bus == ...
    record.mapped_operational_reference_bus;
record.bus_count = size(result.bus, 1);
record.branch_count = size(result.branch, 1);
record.total_load_mw = sum(result.bus(:, PD));
record.total_generation_mw = sum(result.gen(result.gen(:, GEN_STATUS)>0, PG));
record.active_loss_mw = record.total_generation_mw-record.total_load_mw;
network = network_metrics(result);
record.net_network_q_mvar = network.net_network_q_mvar;
record.active_balance_identity_residual_mw = ...
    network.active_identity_residual_mw;
record.reactive_balance_identity_residual_mvar = ...
    network.reactive_identity_residual_mvar;

external = [];
if isfield(built, 'control_report') && ...
        isfield(built.control_report, 'external_gen_idx')
    external = built.control_report.external_gen_idx(:);
end
external = external(external >= 1 & external <= size(result.gen, 1));
online = result.gen(:, GEN_STATUS) > 0;
internal = online;
internal(external) = false;
record.internal_generation_mw = sum(result.gen(internal, PG));
record.external_schedule_mw = sum(result.gen(external, PG));

vviol = result.bus(:, VM) < result.bus(:, VMIN)-options.numeric_tolerance | ...
    result.bus(:, VM) > result.bus(:, VMAX)+options.numeric_tolerance;
qviol = online & (result.gen(:, QG) < ...
    result.gen(:, QMIN)-options.hard_limit_tolerance_mva | ...
    result.gen(:, QG) > result.gen(:, QMAX)+options.hard_limit_tolerance_mva);
pviol = online & (result.gen(:, PG) < ...
    result.gen(:, PMIN)-options.hard_limit_tolerance_mva | ...
    result.gen(:, PG) > result.gen(:, PMAX)+options.hard_limit_tolerance_mva);
smax = max(hypot(result.branch(:, PF), result.branch(:, QF)), ...
    hypot(result.branch(:, PT), result.branch(:, QT)));
rated = result.branch(:, RATE_A) > 0 & ...
    result.branch(:, BR_STATUS) > 0;
[trusted_rated, legacy_diagnostic_rated] = branch_limit_masks( ...
    size(result.branch, 1), built.physical_circuit_map, rated);
all_rated_over = rated & ...
    smax > result.branch(:, RATE_A)+options.numeric_tolerance;
trusted_over = trusted_rated & all_rated_over;
legacy_diagnostic_over = legacy_diagnostic_rated & all_rated_over;
loading_ratio = nan(size(smax));
loading_ratio(rated) = smax(rated)./result.branch(rated, RATE_A);
record.min_voltage_pu = min(result.bus(:, VM));
record.max_voltage_pu = max(result.bus(:, VM));
record.voltage_violation_count = nnz(vviol);
record.generator_p_violation_count = nnz(pviol);
record.generator_q_violation_count = nnz(qviol);
record.branch_overload_count = nnz(trusted_over);
record.max_branch_overload_mva = max([0; ...
    smax(trusted_over)-result.branch(trusted_over, RATE_A)]);
record.trusted_static_branch_count = nnz(trusted_rated);
record.trusted_static_branch_overload_count = nnz(trusted_over);
record.trusted_static_max_loading_ratio = max([0; ...
    loading_ratio(trusted_rated)]);
record.legacy_rated_diagnostic_branch_count = nnz(legacy_diagnostic_rated);
record.legacy_rated_diagnostic_overload_count = ...
    nnz(legacy_diagnostic_over);
record.legacy_rated_diagnostic_max_loading_ratio = max([0; ...
    loading_ratio(legacy_diagnostic_rated)]);
record.legacy_rated_diagnostic_max_overload_mva = max([0; ...
    smax(legacy_diagnostic_over)- ...
    result.branch(legacy_diagnostic_over, RATE_A)]);
record.all_rated_branch_count = nnz(rated);
record.all_rated_branch_overload_count = nnz(all_rated_over);
record.all_rated_max_loading_ratio = max([0; loading_ratio(rated)]);

variable_q = online & result.gen(:, QMAX)-result.gen(:, QMIN) > ...
    options.numeric_tolerance;
at_q_limit = abs(result.gen(:, QG)-result.gen(:, QMIN)) <= 1e-3 | ...
    abs(result.gen(:, QG)-result.gen(:, QMAX)) <= 1e-3;
record.regulating_generator_count = nnz(variable_q);
record.q_saturation_count = nnz(variable_q & at_q_limit);
if record.regulating_generator_count > 0
    record.q_saturation_percent = 100 * record.q_saturation_count / ...
        record.regulating_generator_count;
else
    record.q_saturation_percent = 0;
end
initial_reg_ids = input_case.bus( ...
    ismember(input_case.bus(:, BUS_TYPE), [PV REF]), BUS_I);
[found, result_idx] = ismember(initial_reg_ids, result.bus(:, BUS_I));
became_pq = false(size(found));
became_pq(found) = result.bus(result_idx(found), BUS_TYPE) == PQ;
record.pv_to_pq_conversion_count = nnz(became_pq);
record.placeholder_internal_q_limit_count = ...
    placeholder_internal_q_count(input_case, external, options.numeric_tolerance);
external_q_width = input_case.gen(external, QMAX)-input_case.gen(external, QMIN);
record.unrestricted_external_q_count = ...
    nnz(external_q_width > options.maximum_external_q_range_mvar + ...
    options.numeric_tolerance);
record.maximum_external_q_range_mvar = max([0; external_q_width]);

record.restoration_slack_mw = 0;
record.restoration_slack_mvar = 0;
if isfield(built, 'metrics')
    record.reference_pickup_mw = built.metrics.reference_pickup_mw;
else
    record.reference_pickup_mw = NaN;
end
if isfield(built, 'closure')
    closure = built.closure;
    if isfield(closure, 'converged'), record.closure_converged = closure.converged; end
    if isfield(closure, 'stop_reason'), record.closure_stop_reason = string(closure.stop_reason); end
    if isfield(closure, 'iteration_count'), record.closure_iteration_count = closure.iteration_count; end
    if isfield(closure, 'accepted_step_count'), record.accepted_step_count = closure.accepted_step_count; end
end
if isfield(built, 'projection')
    record.projection_attempted = logical(built.projection.attempted);
    record.projection_success = logical(built.projection.success);
end

[record.interface_mae_mw, record.interface_max_residual_mw, ...
    record.interface_signed_bias_mw] = interface_aggregate( ...
    built, record.scenario_id, options);
[record.original_dispatch_movement_mw, ...
    record.seed_dispatch_movement_mw, ...
    record.source_prior_dispatch_movement_mw, ...
    record.source_balanced_prior_dispatch_movement_mw, ...
    record.scenario_balanced_prior_dispatch_movement_mw] = ...
    dispatch_movement(built);
if record.total_load_mw > 0
    record.dispatch_movement_percent_of_load = ...
        100 * record.source_balanced_prior_dispatch_movement_mw / ...
        record.total_load_mw;
end

map = built.physical_circuit_map;
physical = string(map.branch_classification) == "physical_circuit";
ids = string(map.physical_circuit_id(physical));
record.physical_circuit_row_count = nnz(physical);
record.unique_physical_circuit_count = numel(unique(ids(strlength(ids)>0)));
record.one_branch_per_physical_circuit = ...
    record.physical_circuit_row_count == record.unique_physical_circuit_count && ...
    numel(unique(map.branch_index(physical))) == nnz(physical);

mandatory = [ ...
    record.provenance_complete; ...
    record.closure_converged; ...
    record.standard_pf_success; ...
    record.q_limit_pf_success; ...
    abs(record.restoration_slack_mw) <= options.numeric_tolerance; ...
    abs(record.restoration_slack_mvar) <= options.numeric_tolerance; ...
    record.voltage_violation_count == 0; ...
    record.generator_p_violation_count == 0; ...
    record.generator_q_violation_count == 0; ...
    record.trusted_static_branch_overload_count == 0; ...
    isfinite(record.reference_pickup_mw) && ...
        abs(record.reference_pickup_mw) < options.reference_pickup_gate_mw; ...
    isfinite(record.interface_mae_mw) && ...
        record.interface_mae_mw <= options.interface_mae_gate_mw; ...
    isfinite(record.interface_max_residual_mw) && ...
        record.interface_max_residual_mw <= ...
        options.interface_max_residual_gate_mw; ...
    isfinite(record.interface_signed_bias_mw) && ...
        abs(record.interface_signed_bias_mw) <= ...
        options.interface_signed_bias_gate_mw; ...
    record.placeholder_internal_q_limit_count == 0; ...
    record.unrestricted_external_q_count == 0; ...
    record.unexpected_regulating_bus_count == 0; ...
    record.mapped_reference_control_match; ...
    record.bus_count == options.expected_bus_count; ...
    record.branch_count == options.expected_branch_count; ...
    record.one_branch_per_physical_circuit && ...
        record.unique_physical_circuit_count == options.physical_circuit_count; ...
    isfinite(record.source_balanced_prior_dispatch_movement_mw) && ...
        record.source_balanced_prior_dispatch_movement_mw <= ...
        options.redispatch_hard_limit_mw; ...
    isfinite(record.dispatch_movement_percent_of_load) && ...
        (record.dispatch_movement_percent_of_load <= ...
        options.redispatch_gate_percent_of_load || ...
        strlength(strtrim(record.dispatch_justification)) > 0)];
record.operating_gate_pass = all(mandatory);
end

function built = load_existing_variant(scenario_id, role, q_multiplier, options)
