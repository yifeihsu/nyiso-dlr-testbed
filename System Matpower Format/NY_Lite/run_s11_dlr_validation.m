    standard_pf = runpf(mpc, mpoption('verbose',0,'out.all',0, ...
        'pf.enforce_q_lims',0));
catch
end
try
    q_pf = runpf(mpc, mpoption('verbose',0,'out.all',0, ...
        'pf.enforce_q_lims',1));
catch
end
end

function file = existing_case_file(role, q_multiplier, case_dir)
central = abs(q_multiplier-1) <= 1e-12;
if central && role == "summer_peak"
    file = fullfile(case_dir, 'npcc_ny_lite_s11_dlr_pf_base.m');
elseif central && role == "winter_peak"
    file = fullfile(case_dir, 'npcc_ny_lite_s11_dlr_winter_validation.m');
elseif central && role == "high_total_east"
    file = fullfile(case_dir, ...
        'npcc_ny_lite_s11_dlr_high_total_east_validation.m');
else
    qtag = sprintf('q%03d', round(100*q_multiplier));
    file = fullfile(case_dir, sprintf( ...
        'npcc_ny_lite_s11_dlr_%s_%s_sensitivity.m', role, qtag));
end
end

function invalidate_managed_case_files(role, q_multiplier, case_dir)
% Remove only exact validator-owned S11 filenames for a variant that is not
% accepted in the current publishing run. This prevents a previously passing
% artifact from surviving a later failed gate and appearing current.
central = abs(q_multiplier-1) <= 1e-12;
if central && role == "summer_peak"
    paths = [string(fullfile(case_dir, ...
        'npcc_ny_lite_s11_dlr_pf_base.m')); ...
        string(fullfile(case_dir, ...
        'npcc_ny_lite_s11_dlr_pf_solution.m'))];
else
    paths = string(existing_case_file(role, q_multiplier, case_dir));
end
for k = 1:numel(paths)
    if exist(char(paths(k)), 'file') == 2
        delete(char(paths(k)));
    end
    if exist(char(paths(k)), 'file') == 2
        error('run_s11_dlr_validation:StaleCaseInvalidation', ...
            'Could not invalidate stale managed S11 case: %s', paths(k));
    end
end
end

