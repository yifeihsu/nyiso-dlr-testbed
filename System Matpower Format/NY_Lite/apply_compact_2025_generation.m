function out=apply_compact_2025_generation(base,options)
%APPLY_COMPACT_2025_GENERATION Identified 2020-25 events within NPCC aggregates.
% Public plant MW are scaled by one fixed nominal system-scale factor. New
% plant proxies are carved out of existing regional slots, not superimposed.
% These are P-only research proxies. No source-native reactive capability or
% plant dispatch observation is asserted. Remaining aggregates are unverified.
if nargin<1||isempty(base),base=apply_compact_2025_infrastructure();end
if nargin<2,options=struct();end
d=struct('include_assumed_astoria_retirement',true,'south_fork_available_fraction',1);
fn=fieldnames(d);assert(all(ismember(fieldnames(options),fn)), ...
    'compact_2025_gen:Options','Unknown generation scenario option.');
for k=1:numel(fn),if ~isfield(options,fn{k}),options.(fn{k})=d.(fn{k});end,end
assert(islogical(options.include_assumed_astoria_retirement)&&isscalar(options.include_assumed_astoria_retirement) ...
    && isscalar(options.south_fork_available_fraction)&&isfinite(options.south_fork_available_fraction) ...
    && options.south_fork_available_fraction>=0&&options.south_fork_available_fraction<=1, ...
    'compact_2025_gen:Bounds','Retirement must be logical and assumed wind availability must lie in[0,1].');
p=base.candidate;
assert(~isfield(p.userdata,'compact_2025_generation'), ...
    'compact_2025_gen:AlreadyApplied','Generation events may be applied only once.');
assert(isfield(p.userdata,'compact_2025')&&size(p.gen,1)==62&&p.baseMVA==100 ...
    && isequal(p,base.full_candidate), ...
    'compact_2025_gen:Parent','Expected the original62-generator compact2025 infrastructure construction.');
slots=[58;62;49];buses=[73;9003;79];slotp=[900;600;1200];
assert(isequal(p.gen(slots,1),buses)&&isequal(p.gen(slots,9),slotp) ...
    && all(p.gen(slots,[2:5 10])==0,'all')&&all(p.gen(slots,8)==1) ...
    && all(base.generator_keys(slots)=="NPCC_S7:GEN_ROW:"+slots+":BUS:"+buses), ...
    'compact_2025_gen:SlotIdentity','Expected unchanged P-only regional substitute slots.');
gamma=.355758660106238;public_mw=[1100;132;528];mapped=gamma*public_mw;
c=p;c.gen(58,9)=c.gen(58,9)-mapped(1);c.gen(62,9)=c.gen(62,9)-mapped(2);
removed=double(options.include_assumed_astoria_retirement)*mapped(3);
c.gen(49,9)=c.gen(49,9)-removed;
newkeys=["NY2025:GEN:CRICKET_VALLEY:PV73";"NY2025:GEN:SOUTH_FORK:K9003"];
for k=1:2
    row=p.gen(slots(k),:);row(2:5)=0;row(9)=mapped(k);row(10)=0;
    if k==2,row(9)=row(9)*options.south_fork_available_fraction;end
    c.gen(end+1,:)=row;c.gencost(end+1,:)=p.gencost(slots(k),:);
end
if isfield(c,'genfuel'),c.genfuel(end+1:end+2,1)={'ng';'wind'};end
if isfield(c,'gentype'),c.gentype(end+1:end+2,1)={'CC';'WT'};end
keys=[base.generator_keys;newkeys];
change=table(["CRICKET_VALLEY";"SOUTH_FORK";"ASTORIA_2023"],slots,buses,base.generator_keys(slots), ...
    public_mw,repmat(gamma,3,1),mapped,[mapped(1);mapped(2);removed], ...
    p.gen(slots,9),c.gen(slots,9),[63;64;nan],[mapped(1);c.gen(64,9);0], ...
    ["carve_identified_proxy_out_of_existing_G_equivalent"; ...
    "carve_identified_proxy_out_of_existing_K_equivalent_then_apply_assumed_wind_availability"; ...
    "assumed_retired_Astoria_share_deducted_from_generic_J_slot_not_identified_original_machine"], ...
    'VariableNames',{'event_id','parent_generator_row','model_bus','parent_generator_key', ...
    'public_plant_mw','public_to_benchmark_scale','nominal_modeled_event_mw','removed_from_parent_slot_mw', ...
    'parent_slot_pmax_mw','residual_slot_pmax_mw','new_generator_row','new_available_pmax_mw','accounting_policy'});
change.public_capacity_is_coincident_observation=false(3,1);
change.site_mapping_assumed=true(3,1);
change.cutoff=repmat("2025-12-31",3,1);
change.source_url=["https://www.jera.co.jp/en/news/information/20200420_488"; ...
    "https://www.governor.ny.gov/news/governor-hochul-announces-completion-south-fork-wind-first-utility-scale-offshore-wind-farm"; ...
    "https://www.governor.ny.gov/news/governor-hochul-announces-new-transmission-line-deliver-clean-energy-queens"];
change.event_date=["2020-04-17";"2024-03-14";"2023-05-01"];
ip=table(["INDIAN_POINT_2";"INDIAN_POINT_3"],["2020-04-30";"2021-04-30"], ...
    repmat(77,2,1),zeros(2,1),zeros(2,1), ...
    repmat("no_explicit_Buchanan_generator_in_compact_parent_aggregate_composition_unknown_no_second_retirement_deduction",2,1), ...
    ["https://www.nrc.gov/info-finder/reactors/ip2";"https://www.nrc.gov/info-finder/reactors/ip3"], ...
    'VariableNames',{'event_id','permanent_shutdown_date','Buchanan_model_bus','explicit_parent_generator_count', ...
    'additional_retirement_deduction_mw','accounting_policy','source_url'});
assert(~any(p.gen(:,1)==77),'compact_2025_gen:IndianPointIdentity','Unexpected explicit Buchanan generator needs separate disposition.');
prior=table((1:64)',keys,c.gen(:,1),c.gen(:,2),c.gen(:,9),c.gen(:,10),c.gen(:,4),c.gen(:,5), ...
    repmat("inherited_regional_aggregate_composition_and_machine_capability_unverified",64,1), ...
    false(64,1),'VariableNames',{'model_generator_row','generator_key','model_bus','initial_pg_mw', ...
    'pmax_mw','pmin_mw','qmax_mvar','qmin_mvar','representation','dispatch_observed'});
prior.representation(63:64)="identified_plant_P_only_proxy_in_benchmark_scale_not_native_machine_model";
prior.prior_policy=repmat("initial_case_value_not_observation_snapshot_dispatch_fit_is_separate",64,1);
prior.prior_policy(63)="zero_initial_dispatch_no_coincident_Cricket_observation_bounded_snapshot_fit_required";
prior.prior_policy(64)="zero_initial_dispatch_wind_upper_bound_is_assumed_availability_not_observed_output";
prior.thermal_eligible=false(64,1);
remaining=table(["other_2020_to_2025_generator_additions_retirements";"Indian_Point_aggregate_embedding"; ...
    "site_specific_reactive_capability";"wind_hourly_availability";"Empire_Wind_Sunrise_Wind"], ...
    ["not_exhaustively_reconciled_remaining_NPCC_regional_aggregates_unverified"; ...
    "no_explicit_Buchanan_unit_does_not_prove_all_legacy_aggregate_Indian_Point_supply_removed"; ...
    "new_identified_proxies_Qmin_Qmax0_inherited_aggregate_Q_support_retained"; ...
    "available_fraction_is_declared_assumption_no_hourly_plant_telemetry_input"; ...
    "future_or_not_confirmed_operational_by2025_cutoff_not_added"], ...
    'VariableNames',{'scope','disposition'});
ny=base.ny_bus_ids;nygen=ismember(c.gen(:,1),ny);
oldP=sum(p.gen(ismember(p.gen(:,1),ny)&p.gen(:,8)>0,9));newP=sum(c.gen(nygen&c.gen(:,8)>0,9));
expected_delta=-removed-mapped(2)*(1-options.south_fork_available_fraction);
gates=table(["unchanged_topology_load_shunt_and_bus_types";"all_original_generator_keys_preserved"; ...
    "only_three_registered_parent_Pmax_changes";"identified_G_and_K_capacity_not_double_counted"; ...
    "scaled_retirement_and_availability_accounting";"new_proxies_have_no_reactive_or_slack_control"; ...
    "finite_nonnegative_generation_bounds";"no_extra_Indian_Point_retirement_deduction"], ...
    [isequal(c.bus,p.bus)&&isequal(c.branch,p.branch);isequal(keys(1:62),base.generator_keys); ...
    unchanged_except(c.gen(1:62,:),p.gen,slots,9); ...
    abs(c.gen(58,9)+c.gen(63,9)-p.gen(58,9))<1e-10&& ...
    abs(c.gen(62,9)+mapped(2)-p.gen(62,9))<1e-10; ...
    abs(newP-oldP-expected_delta)<1e-8;all(c.gen(63:64,[4 5])==0,'all'); ...
    all(isfinite(c.gen(:,[4 5 9 10])),'all')&&all(c.gen(:,9)>=c.gen(:,10)); ...
    all(ip.additional_retirement_deduction_mw==0)],'VariableNames',{'metric','passed'});
assert(all(gates.passed),'compact_2025_gen:Validation','Generation accounting failed.');
c.userdata.compact_2025_generation=struct('cutoff','2025-12-31', ...
    'public_to_benchmark_scale',gamma,'options',options,'new_generator_keys',newkeys, ...
    'site_calibrated',false,'capability_observed',false,'remaining_aggregate_composition_unverified',true);
c.userdata.compact_npcc.parent_devices_preserved=false;
c.userdata.compact_npcc.model_role='NPCC_benchmark_2025_infrastructure_and_registered_generation_event_proxies';
out=base;out.generation_parent=base.candidate;out.candidate=c;out.full_candidate=c;
out.generator_keys=keys;out.ny_generator_mask=nygen;out.generation_change_register=change;
out.generation_retirement_register=ip;out.generation_prior_register=prior;
out.generation_scope_register=remaining;out.generation_validation=struct('pass',all(gates.passed),'gates',gates);
out.validation=out.generation_validation;
out.generation_scale_policy="fixed_nominal_2025_summer_peak_to_NPCC_benchmark_scale_not_snapshot_or_site_calibration";
out.electrical_baseline_qualified=false;out.dlr_ready=false;
end

function yes=unchanged_except(actual,original,rows,col)
actual(rows,col)=original(rows,col);yes=isequal(actual,original);
end
