end
end

function zonal_rows = summarize_zonal_dispatch(scenario_id, spec, status, results, generation_targets)
zonal_rows = table();
if strcmp(status, "error") || ~isfield(results, 'bus'), return; end
define_constants;
results = attach_nyiso_zone_metadata(results);
zones = ["A","B","C","D","E","F","G","H","I","J","K"];
boundary_idx = excluded_boundary_generator_indices(results);
s4_idx = s4_generator_indices(results);
zj_idx = zone_j_generator_indices(results);
for z = zones
    bus_ids = zone_bus_ids(results, z);
    gen_idx = find(ismember(results.gen(:, GEN_BUS), bus_ids) & results.gen(:, GEN_STATUS) > 0);
    local_idx = setdiff(gen_idx, boundary_idx);
    load_mw = sum(results.bus(ismember(results.bus(:, BUS_I), bus_ids), PD));
    qload_mvar = sum(results.bus(ismember(results.bus(:, BUS_I), bus_ids), QD));
    all_pg = sum(results.gen(gen_idx, PG));
    local_pg = sum(results.gen(local_idx, PG));
    pmax = sum(results.gen(local_idx, PMAX));
    boundary_pg = sum(results.gen(intersect(gen_idx, boundary_idx), PG));
    s4_pg = sum(results.gen(intersect(gen_idx, s4_idx), PG));
    zj_pg = sum(results.gen(intersect(gen_idx, zj_idx), PG));
    target = generation_targets(generation_targets.scenario_id == string(scenario_id) & ...
        generation_targets.zone == z, :);
    if height(target) == 0
        target_load = NaN; target_export = NaN; target_gen = NaN; prior = NaN;
    else
        target_load = target.target_load_mw(1);
        target_export = target.target_net_export_mw(1);
        target_gen = target.target_generation_mw(1);
        prior = target.generation_prior_mw(1);
    end
    row = table(spec.case_id, spec.case_group, string(scenario_id), ...
        spec.include_s4, spec.apply_abc_caps, spec.x_spine_multiplier, z, ...
        load_mw, qload_mvar, all_pg, local_pg, boundary_pg, s4_pg, zj_pg, ...
        pmax, local_pg - load_mw, target_load, target_export, target_gen, ...
        prior, local_pg - target_gen, ...
        'VariableNames', {'case_id','case_group','scenario_id','include_s4', ...
        'apply_abc_caps','x_spine_multiplier','zone','load_mw','qload_mvar', ...
        'total_pg_mw','local_pg_excluding_boundary_mw','boundary_equiv_pg_mw', ...
        's4_equiv_pg_mw','zone_j_equiv_pg_mw','local_pmax_excluding_boundary_mw', ...
        'local_net_injection_mw','target_load_mw','target_net_export_mw', ...
        'target_generation_mw','generation_prior_mw','local_generation_residual_mw'});
    zonal_rows = append_table(zonal_rows, row);
end
end

function device_rows = summarize_device_dispatch(scenario_id, spec, status, results)
device_rows = table();
if strcmp(status, "error") || ~isfield(results, 'gen'), return; end
define_constants;
zone_j_devices = device_structs(results, 'zone_j');
s4_devices = device_structs(results, 's4');
devices = [zone_j_devices(:); s4_devices(:)];
for k = 1:numel(devices)
    gi = devices(k).gen_index;
    if gi < 1 || gi > size(results.gen, 1), continue; end
    row = table(spec.case_id, spec.case_group, string(scenario_id), ...
        spec.include_s4, spec.apply_abc_caps, spec.x_spine_multiplier, ...
        string(devices(k).device_group), string(devices(k).name), ...
        string(devices(k).zone), devices(k).bus_id, string(devices(k).bus_name), ...
        gi, results.gen(gi, PG), results.gen(gi, QG), results.gen(gi, PMAX), ...
        results.gen(gi, PMIN), results.gen(gi, QMAX), results.gen(gi, QMIN), ...
        safe_div(results.gen(gi, PG), results.gen(gi, PMAX)), ...
        'VariableNames', {'case_id','case_group','scenario_id','include_s4', ...
        'apply_abc_caps','x_spine_multiplier','device_group','device_name', ...
        'zone','bus_id','bus_name','gen_index','pg_mw','qg_mvar','pmax_mw', ...
        'pmin_mw','qmax_mvar','qmin_mvar','fraction_pmax_used'});
    device_rows = append_table(device_rows, row);
end
end

function summary = summarize_cases(rows, zonal_rows)
keys = unique(rows(:, {'case_id','case_group','include_s4','apply_abc_caps', ...
    'x_spine_multiplier','zone_j_total_pmax_mw','zone_j_cost_c1', ...
    'zone_j_cost_c2','s4_equiv_cost_c1','s4_equiv_cost_c2'}), 'rows');
summary = table();
for k = 1:height(keys)
    mask = rows.case_id == keys.case_id(k);
    subset = rows(mask, :);
    zmask = zonal_rows.case_id == keys.case_id(k);
    zsub = zonal_rows(zmask, :);
    downstate = ismember(zsub.zone, ["G", "J", "K"]);
    row = table(keys.case_id(k), keys.case_group(k), keys.include_s4(k), ...
        keys.apply_abc_caps(k), keys.x_spine_multiplier(k), ...
        height(subset), sum(subset.opf_success == 1), ...
        sum(subset.interface_objective, 'omitnan'), ...
        mean(subset.interface_objective, 'omitnan'), ...
        max(subset.max_abs_interface_residual_mw, [], 'omitnan'), ...
        mean(subset.zone_j_equiv_pg_mw, 'omitnan'), ...
        max(subset.zone_j_equiv_pg_mw, [], 'omitnan'), ...
        mean(subset.s4_equiv_pg_mw, 'omitnan'), ...
        max(subset.s4_equiv_pg_mw, [], 'omitnan'), ...
        mean(abs(zsub.local_generation_residual_mw), 'omitnan'), ...
        mean(abs(zsub.local_generation_residual_mw(downstate)), 'omitnan'), ...
        max(subset.branch_overload_count, [], 'omitnan'), ...
        max(subset.voltage_bound_count_high + subset.voltage_bound_count_low, [], 'omitnan'), ...
        'VariableNames', {'case_id','case_group','include_s4','apply_abc_caps', ...
        'x_spine_multiplier','scenario_count','success_count', ...
        'sum_interface_objective','mean_interface_objective', ...
        'max_abs_interface_residual_mw','mean_zone_j_equiv_pg_mw', ...
        'max_zone_j_equiv_pg_mw','mean_s4_equiv_pg_mw', ...
        'max_s4_equiv_pg_mw','mean_abs_zonal_generation_residual_mw', ...
        'mean_abs_downstate_generation_residual_mw','max_branch_overload_count', ...
        'max_voltage_bound_count'});
    summary = append_table(summary, row);
end
end

function [J, detail] = interface_objective_detail(scenario_id, results, options)
targets = read_public_interface_targets(scenario_id, options.interface_target_file);
flows = ny_lite_interface_flows(results, ny_lite_interface_definitions(results));
[J, detail] = interface_target_objective(flows, targets);
end

function out = residual_map(detail)
out = struct('central_east', NaN, 'total_east', NaN, 'upny_coned', NaN, ...
    'dunwoodie_south', NaN, 'moses_south', NaN);
for k = 1:height(detail)
    name = string(detail.interface_name(k));
    switch name
        case "Central_East"
            out.central_east = detail.residual_mw(k);
        case "Total_East_proxy"
            out.total_east = detail.residual_mw(k);
        case "UPNY_ConEd"
            out.upny_coned = detail.residual_mw(k);
        case "Dunwoodie_South"
            out.dunwoodie_south = detail.residual_mw(k);
        case "Moses_South"
            out.moses_south = detail.residual_mw(k);
    end
end
end

function devices = device_structs(results, group)
devices = struct('device_group', {}, 'name', {}, 'zone', {}, 'bus_id', {}, ...
    'bus_name', {}, 'gen_index', {});
if ~isfield(results, 'userdata') || ~isfield(results.userdata, 'ny_lite'), return; end
if strcmp(group, 'zone_j')
    field = 'zone_j_equivalent_supply';
    device_group = 'zone_j_equivalent';
else
    field = 's4_zonal_capability_equivalents';
    device_group = 's4_zonal_capability_equivalent';
end
if ~isfield(results.userdata.ny_lite, field), return; end
src = results.userdata.ny_lite.(field);
for k = 1:numel(src)
    devices(end + 1) = struct('device_group', device_group, ...
        'name', src(k).name, 'zone', src(k).zone, 'bus_id', src(k).bus_id, ...
        'bus_name', src(k).bus_name, 'gen_index', src(k).gen_index); %#ok<AGROW>
end
end

function idx = zone_j_generator_indices(results)
idx = [];
if isfield(results, 'userdata') && isfield(results.userdata, 'ny_lite') && ...
        isfield(results.userdata.ny_lite, 'zone_j_equivalent_supply')
    d = results.userdata.ny_lite.zone_j_equivalent_supply;
    if ~isempty(d), idx = [d.gen_index]; end
end
idx = idx(:);
end

