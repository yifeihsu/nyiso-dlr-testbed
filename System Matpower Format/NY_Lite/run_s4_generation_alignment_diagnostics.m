function spec = make_case(case_id, case_group, include_s4, apply_abc_caps, x_mult, ...
    zone_j_pmax, zone_j_c1, zone_j_c2, s4_c1, s4_c2)
spec = struct('case_id', string(case_id), 'case_group', string(case_group), ...
    'include_s4', include_s4, 'apply_abc_caps', apply_abc_caps, ...
    'x_spine_multiplier', x_mult, 'zone_j_pmax_mw', zone_j_pmax, ...
    'zone_j_cost_c1', zone_j_c1, 'zone_j_cost_c2', zone_j_c2, ...
    's4_cost_c1', s4_c1, 's4_cost_c2', s4_c2);
end

function [row, residual_rows, zonal_rows, device_rows] = run_one(scenario_id, spec, mpopt, generation_targets, options)
define_constants;
status = "ok";
note = "";
try
    base = loadcase('npcc_ny_lite_s1_acopf_feasible_uncalibrated');
    [mpc, ~] = build_ny_only_equivalent_case(base);
    [mpc, ~] = add_ny_downstate_delivery_spine(mpc, 'full');
    [mpc, scale_report] = scale_ny_downstate_delivery_spine_impedance(mpc, ...
        spec.x_spine_multiplier, struct('include_gilboa_leeds', false));
    [mpc, ~] = apply_nyiso_zonal_loads(mpc, scenario_id, 1.0, ...
        struct('preserve_total_ny_load', true));
    [mpc, ext_report] = apply_nyiso_external_interface_injections(mpc, ...
        scenario_id, struct('target_file', options.target_file));
    if spec.include_s4
        [mpc, add_report] = add_s4_zonal_capability_equivalents(mpc, ...
            struct('include_zone_j', true, ...
            'zone_j_total_pmax_mw', spec.zone_j_pmax_mw, ...
            'zone_j_cost_c1', spec.zone_j_cost_c1, ...
            'zone_j_cost_c2', spec.zone_j_cost_c2, ...
            'equiv_cost_c1', spec.s4_cost_c1, ...
            'equiv_cost_c2', spec.s4_cost_c2, ...
            'q_abs_ratio', 0, ...
            'apply_upstate_participation_caps', spec.apply_abc_caps, ...
            'reclassify_ce_ug', true));
    else
        [mpc, add_report] = add_zone_j_equivalent_supply(mpc, ...
            struct('total_pmax_mw', spec.zone_j_pmax_mw, ...
            'q_abs_ratio', 0, ...
            'cost_c1', spec.zone_j_cost_c1, ...
            'cost_c2', spec.zone_j_cost_c2));
    end
    results = runopf(mpc, mpopt);
catch ME
    results = struct();
    scale_report = table();
    ext_report = table();
    add_report = table();
    status = "error";
    note = string(regexprep(ME.message, '\s+', ' '));
end

row = summarize_result(scenario_id, spec, status, note, results, scale_report, ...
    ext_report, add_report, options);
residual_rows = summarize_residuals(scenario_id, spec, status, results, options);
zonal_rows = summarize_zonal_dispatch(scenario_id, spec, status, results, generation_targets);
device_rows = summarize_device_dispatch(scenario_id, spec, status, results);
end

function row = summarize_result(scenario_id, spec, status, note, results, scale_report, ext_report, add_report, options)
define_constants;
names = result_columns();
if strcmp(status, "error") || ~isfield(results, 'bus')
    values = num2cell(NaN(1, numel(names) - 18));
    row = table(spec.case_id, spec.case_group, string(scenario_id), ...
        spec.include_s4, spec.apply_abc_caps, spec.x_spine_multiplier, ...
        spec.zone_j_pmax_mw, spec.zone_j_cost_c1, spec.zone_j_cost_c2, ...
        spec.s4_cost_c1, spec.s4_cost_c2, string(status), string(note), ...
        height(scale_report), height(add_report), ext_sum(ext_report, 'target_flow_mw'), ...
        ext_sum(ext_report, 'target_q_mvar'), values{:}, ...
        'VariableNames', names);
    return;
end
online = results.gen(:, GEN_STATUS) > 0;
sf = sqrt(results.branch(:, PF).^2 + results.branch(:, QF).^2);
st = sqrt(results.branch(:, PT).^2 + results.branch(:, QT).^2);
smax = max(sf, st);
rate = results.branch(:, RATE_A);
rated = rate > 0;
flows = ny_lite_interface_flows(results, ny_lite_interface_definitions(results));
[J, detail] = interface_objective_detail(scenario_id, results, options);
res = residual_map(detail);
[zj_pg, zj_pmax] = named_device_sums(results, 'zone_j');
[s4_pg, s4_pmax] = named_device_sums(results, 's4');
row = table(spec.case_id, spec.case_group, string(scenario_id), ...
    spec.include_s4, spec.apply_abc_caps, spec.x_spine_multiplier, ...
    spec.zone_j_pmax_mw, spec.zone_j_cost_c1, spec.zone_j_cost_c2, ...
    spec.s4_cost_c1, spec.s4_cost_c2, string(status), string(note), ...
    height(scale_report), height(add_report), ext_sum(ext_report, 'target_flow_mw'), ...
    ext_sum(ext_report, 'target_q_mvar'), double(results.success), raw_info(results), ...
    results.f, J, max(abs(detail.residual_mw), [], 'omitnan'), ...
    mean(abs(detail.residual_mw), 'omitnan'), size(results.bus, 1), ...
    size(results.branch, 1), size(results.gen, 1), sum(results.bus(:, PD)), ...
    sum(results.bus(:, QD)), sum(results.gen(online, PG)), sum(results.gen(online, QG)), ...
    zj_pg, zj_pmax, safe_div(zj_pg, zj_pmax), s4_pg, s4_pmax, safe_div(s4_pg, s4_pmax), ...
    min(results.bus(:, VM)), max(results.bus(:, VM)), ...
    sum(results.bus(:, VM) >= results.bus(:, VMAX) - 1e-5), ...
    sum(results.bus(:, VM) <= results.bus(:, VMIN) + 1e-5), ...
    sum(rated & smax > rate + 1e-6), max([0; smax(rated) - rate(rated)]), ...
    res.central_east, res.total_east, res.upny_coned, res.dunwoodie_south, ...
    res.moses_south, interface_flow(flows, 'Total_East_proxy'), ...
    interface_flow(flows, 'UPNY_ConEd'), interface_flow(flows, 'Dunwoodie_South'), ...
    'VariableNames', names);
end

