function outputs = run_s4_generation_alignment_diagnostics(options)
%RUN_S4_GENERATION_ALIGNMENT_DIAGNOSTICS Test S4 zonal generation alignment.
%
%   This runner compares S3 and first-pass S4 variants on the public
%   P+Q/public-external scenarios. It is diagnostic, not a final optimizer.

if nargin < 1, options = struct(); end
helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
addpath(case_dir); addpath(helper_dir);

if ~isfield(options, 'target_file')
    options.target_file = fullfile(helper_dir, 'ny_external_interface_targets.csv');
end
if ~isfield(options, 'interface_target_file')
    options.interface_target_file = fullfile(helper_dir, 'nyiso_public_interface_targets.csv');
end
if ~isfield(options, 'capability_file')
    options.capability_file = fullfile(helper_dir, 'nyiso_generator_capability_targets.csv');
end
if ~isfield(options, 'generation_target_file')
    options.generation_target_file = fullfile(helper_dir, 'nyiso_zonal_generation_targets.csv');
end
if ~isfield(options, 'result_file')
    options.result_file = fullfile(helper_dir, 's4_generation_alignment_results.csv');
end
if ~isfield(options, 'residual_file')
    options.residual_file = fullfile(helper_dir, 's4_generation_alignment_interface_residuals.csv');
end
if ~isfield(options, 'zonal_dispatch_file')
    options.zonal_dispatch_file = fullfile(helper_dir, 's4_zonal_generation_dispatch.csv');
end
if ~isfield(options, 'device_dispatch_file')
    options.device_dispatch_file = fullfile(helper_dir, 's4_equivalent_device_dispatch.csv');
end
if ~isfield(options, 'summary_file')
    options.summary_file = fullfile(helper_dir, 's4_generation_alignment_summary.csv');
end
if ~isfield(options, 'archive_dir')
    options.archive_dir = fullfile(helper_dir, 'archives');
end
if ~isfield(options, 'make_archive'), options.make_archive = true; end

build_s4_generation_alignment_targets(struct( ...
    'capability_file', options.capability_file, ...
    'generation_target_file', options.generation_target_file, ...
    'zone_j_total_pmax_mw', 3000));

public_scenarios = readtable(fullfile(helper_dir, 'nyiso_public_scenarios.csv'), ...
    'TextType', 'string', 'VariableNamingRule', 'preserve');
generation_targets = readtable(options.generation_target_file, ...
    'TextType', 'string', 'VariableNamingRule', 'preserve');
cases = diagnostic_cases();

mpopt = mpoption( ...
    'verbose', 0, ...
    'out.all', 0, ...
    'opf.ac.solver', 'IPOPT', ...
    'opf.flow_lim', 'S', ...
    'opf.violation', 1e-6, ...
    'opf.use_vg', 0, ...
    'opf.ignore_angle_lim', 0);

result_rows = table();
residual_rows = table();
zonal_rows = table();
device_rows = table();

for c = 1:numel(cases)
    spec = cases(c);
    for s = 1:height(public_scenarios)
        scenario_id = string(public_scenarios.scenario_id(s));
        [row, residuals, zonal, devices] = run_one(scenario_id, spec, mpopt, ...
            generation_targets, options);
        result_rows = append_table(result_rows, row);
        residual_rows = append_table(residual_rows, residuals);
        zonal_rows = append_table(zonal_rows, zonal);
        device_rows = append_table(device_rows, devices);
    end
end

summary_rows = summarize_cases(result_rows, zonal_rows);
writetable(result_rows, options.result_file);
writetable(residual_rows, options.residual_file);
writetable(zonal_rows, options.zonal_dispatch_file);
writetable(device_rows, options.device_dispatch_file);
writetable(summary_rows, options.summary_file);

archive_file = "";
if options.make_archive
    if exist(options.archive_dir, 'dir') ~= 7, mkdir(options.archive_dir); end
    stamp = string(datetime('now', 'Format', 'yyyyMMdd_HHmmss'));
    archive_file = fullfile(options.archive_dir, ...
        "s4_generation_alignment_results_" + stamp + ".zip");
    files = {options.result_file, options.residual_file, ...
        options.zonal_dispatch_file, options.device_dispatch_file, ...
        options.summary_file, options.capability_file, ...
        options.generation_target_file, ...
        fullfile(helper_dir, 'run_s4_generation_alignment_diagnostics.m'), ...
        fullfile(helper_dir, 'build_s4_generation_alignment_targets.m'), ...
        fullfile(helper_dir, 'add_s4_zonal_capability_equivalents.m'), ...
        fullfile(helper_dir, 'add_zone_j_equivalent_supply.m'), ...
        fullfile(helper_dir, 'add_ny_downstate_delivery_spine.m'), ...
        fullfile(helper_dir, 'scale_ny_downstate_delivery_spine_impedance.m'), ...
        fullfile(helper_dir, 'nyiso_public_scenarios.csv'), ...
        fullfile(helper_dir, 'ny_zonal_load_targets.csv'), ...
        fullfile(helper_dir, 'ny_external_interface_targets.csv'), ...
        fullfile(helper_dir, 'nyiso_public_interface_targets.csv'), ...
        fullfile(case_dir, 'npcc_ny_lite_s4_generation_capability_aligned_uncalibrated.m')};
    files = files(cellfun(@(f) exist(f, 'file') == 2, files));
    zip(archive_file, files);
end

outputs = struct('result_file', options.result_file, ...
    'residual_file', options.residual_file, ...
    'zonal_dispatch_file', options.zonal_dispatch_file, ...
    'device_dispatch_file', options.device_dispatch_file, ...
    'summary_file', options.summary_file, ...
    'capability_file', options.capability_file, ...
    'generation_target_file', options.generation_target_file, ...
    'archive_file', archive_file, ...
    'result_row_count', height(result_rows), ...
    'residual_row_count', height(residual_rows), ...
    'zonal_row_count', height(zonal_rows), ...
    'device_row_count', height(device_rows));
end

