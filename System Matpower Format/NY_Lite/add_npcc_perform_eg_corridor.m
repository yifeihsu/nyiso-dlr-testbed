physical = branch_map(:, {'model_branch_row','model_from_bus','model_to_bus', ...
    'overlay_path_id','npcc_attachment_from_bus','npcc_attachment_to_bus', ...
    'source_model','source_case','source_branch_row','source_from_bus','source_to_bus', ...
    'source_circuit_id','source_r_pu','source_x_pu','source_b_pu', ...
    'source_rate_a_mva','source_rate_b_mva','source_rate_c_mva', ...
    'branch_classification','construction_method','residual_overlap_status', ...
