function out = validate_s13_structural_preservation(options)
%VALIDATE_S13_STRUCTURAL_PRESERVATION Gate S13-FULL identity and provenance.
%   The default candidate is the cumulative full-NPCC construction parent.
%   Structural preservation can pass while qualification as the S14 reduction
%   source remains false. S13-FULL is never promotion-eligible itself.

if nargin < 1, options = struct(); end
if ~isfield(options, 'candidate_case')
    options.candidate_case = 'npcc_ny_lite_s13_npcc_augmented_2019';
end
if ~isfield(options, 'candidate_name')
    if isstruct(options.candidate_case)
        options.candidate_name = 'provided_s13_candidate';
    else
        options.candidate_name = char(options.candidate_case);
    end
end
if ~isfield(options, 'write_outputs'), options.write_outputs = true; end
if ~isfield(options, 'fail_on_structural'), options.fail_on_structural = true; end
if ~isfield(options, 'output_file')
    options.output_file = fullfile(fileparts(mfilename('fullpath')), ...
        's13_structural_preservation.csv');
end

helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
addpath(case_dir); addpath(helper_dir);
define_constants;

original = loadcase('npcc_original');
s7 = loadcase('npcc_ny_lite_s7_seven_interface_perform_direct_candidate');
phase0_parent = apply_ny_core_phase0_corrections(s7, struct( ...
    'fit_reactance', false, 'verbose', false));
if isstruct(options.candidate_case)
    candidate = options.candidate_case;
else
    candidate = loadcase(options.candidate_case);
end

model_name = string(options.candidate_name);
[s13_metadata, s13_metadata_ok, s13_metadata_detail] = ...
    validate_s13_metadata(candidate);
model_role = "<missing>";
if isfield(s13_metadata, 'model_role')
    [candidate_role, candidate_role_ok] = scalar_text_value( ...
        s13_metadata.model_role);
    if candidate_role_ok
        model_role = candidate_role;
    else
        model_role = "<invalid>";
    end
end

rows = empty_gate_table();
rows = add_gate(rows, model_name, model_role, "provenance", ...
    "s13_metadata_coherence", ...
    "S13-FULL construction role, supported phase, cumulative and per-phase reports agree", ...
    s13_metadata_detail, s13_metadata_ok, true, true, ...
    "overlay_report is the cumulative source of truth; phase_reports stores " + ...
    "per-phase evidence; phase1a_report is a compatibility alias.");
rows = add_gate(rows, model_name, model_role, "source_baseline", ...
    "original_npcc_dimensions", "140 buses / 233 branches", ...
    sprintf('%d buses / %d branches', size(original.bus, 1), ...
    size(original.branch, 1)), ...
    size(original.bus, 1) == 140 && size(original.branch, 1) == 233, ...
    true, true, "Frozen source identity expected by the S13-FULL policy.");
rows = add_gate(rows, model_name, model_role, "structural_parent", ...
    "s7_dimensions", "143 buses / 246 branches / 62 generators", ...
    sprintf('%d buses / %d branches / %d generators', size(s7.bus, 1), ...
    size(s7.branch, 1), size(s7.gen, 1)), ...
    isequal([size(s7.bus, 1), size(s7.branch, 1), size(s7.gen, 1)], ...
    [143 246 62]), true, true, "S7 remains the NPCC structural provenance case.");

original_bus_rows_stable = size(candidate.bus, 1) >= 140 && ...
    isequal(candidate.bus(1:140, BUS_I), original.bus(:, BUS_I));
rows = add_gate(rows, model_name, model_role, "structural_preservation", ...
    "original_bus_row_identity", "all 140 original rows unchanged in position and ID", ...
    sprintf('%d of 140 row IDs match', count_matching_bus_rows(candidate, original)), ...
    original_bus_rows_stable, true, true, ...
    "Row identity is stronger than unordered bus membership.");

parent_bus_names_stable = has_stable_parent_bus_names(candidate, phase0_parent);
rows = add_gate(rows, model_name, model_role, "structural_preservation", ...
    "parent_bus_names_stable", ...
    "all 143 S7/Phase-0 normalized bus names unchanged", ...
    string(parent_bus_names_stable), parent_bus_names_stable, true, true, ...
    "Name identity is part of the attachment and provenance policy.");

original_branch_rows_stable = size(candidate.branch, 1) >= 233 && ...
    isequal(candidate.branch(1:233, [F_BUS T_BUS]), ...
    original.branch(:, [F_BUS T_BUS]));
rows = add_gate(rows, model_name, model_role, "structural_preservation", ...
    "original_branch_row_identity", ...
    "all 233 original rows retain ordered endpoints", ...
    sprintf('%d of 233 row endpoint identities match', ...
    count_matching_branch_rows(candidate, original, 233)), ...
    original_branch_rows_stable, true, true, ...
    "Parallel circuits are traced by stable row identity, not endpoint set alone.");

s7_bus_rows_stable = size(candidate.bus, 1) >= 143 && ...
    isequal(candidate.bus(1:143, BUS_I), s7.bus(:, BUS_I));
s7_branch_rows_stable = size(candidate.branch, 1) >= 246 && ...
    isequal(candidate.branch(1:246, [F_BUS T_BUS]), ...
    s7.branch(:, [F_BUS T_BUS]));
rows = add_gate(rows, model_name, model_role, "append_only", ...
    "s7_bus_rows_preserved", "first 143 S7 bus IDs unchanged", ...
    string(s7_bus_rows_stable), s7_bus_rows_stable, true, true, ...
    "All new physical terminals must be appended.");
rows = add_gate(rows, model_name, model_role, "append_only", ...
    "s7_branch_rows_preserved", "first 246 S7 branch endpoints unchanged", ...
    string(s7_branch_rows_stable), s7_branch_rows_stable, true, true, ...
    "Residualization may change registered R/X/B but never endpoints or row identity.");

fixed_bus_columns = [BUS_I BUS_TYPE BUS_AREA BASE_KV ZONE VMAX VMIN];
parent_bus_controls_stable = size(candidate.bus, 1) >= 143 && ...
    max(abs(candidate.bus(1:143, fixed_bus_columns) - ...
    phase0_parent.bus(:, fixed_bus_columns)), [], 'all') <= 1e-12;
fixed_branch_columns = [F_BUS T_BUS RATE_A RATE_B RATE_C TAP SHIFT ...
    BR_STATUS ANGMIN ANGMAX];
parent_branch_controls_stable = size(candidate.branch, 1) >= 246 && ...
    max(abs(candidate.branch(1:246, fixed_branch_columns) - ...
    phase0_parent.branch(:, fixed_branch_columns)), [], 'all') <= 1e-12;
original_online_rows = find(phase0_parent.branch(1:233, BR_STATUS) > 0);
original_online_still_active = size(candidate.branch, 1) >= 233 && ...
    all(candidate.branch(original_online_rows, BR_STATUS) > 0);
fixed_generator_columns = [GEN_BUS QMAX QMIN VG MBASE GEN_STATUS PMAX PMIN ...
    PC1 PC2 QC1MIN QC1MAX QC2MIN QC2MAX RAMP_AGC RAMP_10 RAMP_30 ...
    RAMP_Q APF];
generator_identity_stable = size(candidate.gen, 1) == size(phase0_parent.gen, 1) && ...
    max(abs(candidate.gen(:, fixed_generator_columns) - ...
    phase0_parent.gen(:, fixed_generator_columns)), [], 'all') <= 1e-12 && ...
    required_field_equal(candidate, phase0_parent, 'gencost') && ...
    optional_field_equal(candidate, phase0_parent, 'gentype') && ...
    optional_field_equal(candidate, phase0_parent, 'genfuel');
rows = add_gate(rows, model_name, model_role, "structural_preservation", ...
    "parent_bus_structural_controls", ...
    "S7/Phase-0 bus type area zone base-kV and limits unchanged", ...
    string(parent_bus_controls_stable), parent_bus_controls_stable, true, true, ...
    "Operating PD/QD/VM/VA are excluded from this identity comparison.");
rows = add_gate(rows, model_name, model_role, "structural_preservation", ...
    "parent_branch_status_and_controls", ...
    "S7/Phase-0 status tap shift and angle bounds unchanged", ...
    string(parent_branch_controls_stable), parent_branch_controls_stable, ...
    true, true, "Residualization may alter only registered R/X/B rows.");
rows = add_gate(rows, model_name, model_role, "structural_preservation", ...
    "original_online_branches_active", "all originally online rows remain active", ...
    string(original_online_still_active), original_online_still_active, ...
    true, true, "Outages belong in validation scenarios, not the base candidate.");
rows = add_gate(rows, model_name, model_role, "device_identity", ...
    "generator_capability_and_identity", ...
    "all 62 S7 generator identities limits capabilities costs and type/fuel retained", ...
    string(generator_identity_stable), generator_identity_stable, true, true, ...
    "PG/QG may change by operating point; fixed device fields remain traceable.");

transit_ok = all(ismember([9001; 9002; 9003], candidate.bus(:, BUS_I)));
rows = add_gate(rows, model_name, model_role, "structural_preservation", ...
    "s7_transit_buses_present", "9001|9002|9003", ...
    join(string(intersect([9001; 9002; 9003], candidate.bus(:, BUS_I))), "|"), ...
    transit_ok, true, true, "All three S7 transit buses must remain.");

[overlay, has_overlay] = overlay_metadata(candidate);
rows = add_gate(rows, model_name, model_role, "provenance", ...
    "overlay_metadata_present", "row-aligned S13 overlay metadata", ...
    string(has_overlay), has_overlay, true, true, ...
    "Free-text provenance alone is insufficient.");

added_bus_count = max(size(candidate.bus, 1) - 143, 0);
added_branch_count = max(size(candidate.branch, 1) - 246, 0);
registered_bus_count = 0; registered_branch_count = 0;
if has_overlay
    registered_bus_count = numel(overlay.added_bus_ids);
    registered_branch_count = numel(overlay.physical_branch_rows);
end
bus_registration_ok = has_overlay && added_bus_count == registered_bus_count && ...
    numel(unique(overlay.added_bus_ids)) == registered_bus_count && ...
    isequal(sort(overlay.added_bus_ids(:)), ...
    sort(candidate.bus(144:end, BUS_I))) && ...
    isequal(overlay.added_bus_rows(:), (144:size(candidate.bus, 1))');
branch_registration_ok = has_overlay && ...
    added_branch_count == registered_branch_count && ...
    isequal(overlay.physical_branch_rows(:), (247:size(candidate.branch, 1))');
rows = add_gate(rows, model_name, model_role, "provenance", ...
    "added_bus_registration", sprintf('%d appended buses with one map row each', ...
    added_bus_count), sprintf('%d appended / %d registered', ...
    added_bus_count, registered_bus_count), bus_registration_ok, true, true, ...
    "Every appended bus must be uniquely registered.");
rows = add_gate(rows, model_name, model_role, "provenance", ...
    "added_branch_registration", sprintf('%d appended branches with one map row each', ...
    added_branch_count), sprintf('%d appended / %d registered', ...
    added_branch_count, registered_branch_count), branch_registration_ok, ...
    true, true, "Every appended branch must be uniquely registered.");

overlay_identity_ok = has_overlay && ...
    string(overlay.target_model) == "npcc_ny_lite_s13_npcc_augmented_2019" && ...
    string(overlay.model_role) == "unpromoted_s13_candidate" && ...
    ismember(string(overlay.current_phase), ...
    ["phase1a","phase1b","phase1c","phase1d"]) && ...
    string(overlay.structural_parent) == ...
    "npcc_ny_lite_s7_seven_interface_perform_direct_candidate" && ...
    string(overlay.source_model) == "full_PERFORM_2019_case" && ...
    string(overlay.source_case) == ...
    "PERFORM/On Peak 2019 v23_Perform_NY/On Peak 2019 v23/" + ...
    "nyiso_On_Peak_v23_shunts_as_z_load.m";
rows = add_gate(rows, model_name, model_role, "provenance", ...
    "overlay_model_and_source_identity", ...
    "S13-FULL over S7 sourced only from full PERFORM 2019", ...
    string(overlay_identity_ok), overlay_identity_ok, true, true, ...
    "Candidate-supplied promoted/S12/Ward labels fail this gate.");

[branch_map, has_branch_map] = branch_map_from_candidate(candidate);
[bus_map, has_bus_map] = bus_map_from_candidate(candidate);
[path_register, has_path_register] = path_register_from_candidate(candidate);
perform_source = load_perform_source(helper_dir);
base_mva_ok = original.baseMVA == 100 && s7.baseMVA == 100 && ...
    phase0_parent.baseMVA == 100 && candidate.baseMVA == 100 && ...
    perform_source.baseMVA == 100;
rows = add_gate(rows, model_name, model_role, "base_identity", ...
    "common_base_mva", "NPCC parent candidate and PERFORM source all use 100 MVA", ...
    sprintf('original=%g s7=%g candidate=%g source=%g', original.baseMVA, ...
    s7.baseMVA, candidate.baseMVA, perform_source.baseMVA), ...
    base_mva_ok, true, true, ...
    "Copied per-unit impedances are meaningful only on the common base.");
source_exact = has_branch_map && has_bus_map && has_overlay && has_path_register && ...
    validate_source_exactness(candidate, branch_map, overlay, ...
    bus_map, path_register, perform_source);
rows = add_gate(rows, model_name, model_role, "source_exactness", ...
    "added_physical_r_x_b_and_ratings", ...
    "all registered rows match direct PERFORM R/X/B and RATE_A/B/C", ...
    string(source_exact), source_exact, true, true, ...
    "Physical rows may not be empirically retuned.");
bus_source_and_area_ok = has_bus_map && has_path_register && ...
    validate_bus_source_and_area(candidate, bus_map, path_register, perform_source);
rows = add_gate(rows, model_name, model_role, "source_exactness", ...
    "added_bus_source_and_npcc_area_mapping", ...
    "source IDs/names/base-kV retained and NPCC areas inherited from attachments", ...
    string(bus_source_and_area_ok), bus_source_and_area_ok, true, true, ...
    "PERFORM areas 69/71 remain provenance metadata, not NPCC control areas.");
attachment_name_match = has_bus_map && ...
    validate_attachment_name_match(candidate, bus_map, perform_source);
rows = add_gate(rows, model_name, model_role, "source_exactness", ...
    "attachment_name_match", ...
    "EDIC and RAMAPO attachment names match PERFORM after normalization", ...
    string(attachment_name_match), attachment_name_match, true, true, ...
    "Voltage and zone agreement do not replace exact-name attachment evidence.");
source_zero_injection_ok = has_bus_map && ...
    validate_source_zero_injection(bus_map, perform_source);
rows = add_gate(rows, model_name, model_role, "source_exactness", ...
    "source_added_terminals_zero_injection", ...
    "all appended terminals have zero source PD/QD/GS/BS", ...
    string(source_zero_injection_ok), source_zero_injection_ok, true, true, ...
    "Candidate zero injection must be supported by the PERFORM source rows.");

phase1a_minimum_ok = has_branch_map && has_bus_map && ...
    all(ismember([1228; 1222; 1567; 772], bus_map.model_bus)) && ...
    all(ismember([2137; 2131; 2154; 2133; 1567; 1568; 1571], ...
    branch_map.source_branch_row));
rows = add_gate(rows, model_name, model_role, "phase1a_minimum", ...
    "source_backed_e_g_overlay_present", ...
    "four Phase-1A terminals and seven direct source rows remain present", ...
    string(phase1a_minimum_ok), phase1a_minimum_ok, true, true, ...
    "Later Phase 1B/1C paths may append additional registered rows.");

phase1a_checkpoint_ok = s13_metadata_ok && ...
    isfield(s13_metadata.phase_reports, 'phase1a') && ...
    validate_phase1a_checkpoint(s13_metadata.phase_reports.phase1a, ...
    phase0_parent, helper_dir);
rows = add_gate(rows, model_name, model_role, "phase1a_immutability", ...
    "phase1a_report_rebuild_identity", ...
    "stored Phase-1A report exactly matches an independent S7 plus Phase-0 rebuild", ...
    string(phase1a_checkpoint_ok), phase1a_checkpoint_ok, true, true, ...
    "Later topology phases may append cumulative evidence but may not rewrite Phase 1A.");

[physical_register, has_physical_register] = physical_from_candidate(candidate);
physical_required = {'model_branch_row','model_from_bus','model_to_bus', ...
    'overlay_path_id','npcc_attachment_from_bus','npcc_attachment_to_bus', ...
    'source_model','source_case','source_branch_row','source_from_bus', ...
    'source_to_bus','source_circuit_id','source_r_pu','source_x_pu', ...
    'source_b_pu','source_rate_a_mva','source_rate_b_mva', ...
    'source_rate_c_mva','branch_classification','construction_method', ...
    'residual_overlap_status','dlr_eligible','dlr_data_status', ...
    'mapping_confidence','implementation_status'};
projection_ok = has_branch_map && has_physical_register && ...
    isequal(physical_register.Properties.VariableNames, physical_required) && ...
    height(physical_register) == height(branch_map) && ...
    isequal(physical_register.model_branch_row, branch_map.model_branch_row) && ...
    isequaln(physical_register, branch_map(:, ...
    physical_required));
dlr_mapping_ok = has_branch_map && ...
    all(~branch_map.dlr_eligible | ...
    branch_map.dlr_data_status == "complete_conductor_weather_mapping");
classification_ok = has_branch_map && projection_ok && dlr_mapping_ok && ...
    all(branch_map.branch_classification == "physical_circuit") && ...
    ~any(branch_map.dlr_eligible & ...
    branch_map.branch_classification ~= "physical_circuit");
rows = add_gate(rows, model_name, model_role, "dlr_scope", ...
    "only_physical_rows_can_be_dlr_eligible", "true", ...
    string(classification_ok), classification_ok, true, true, ...
    "Eligibility requires one-to-one registration and completed conductor/weather mapping.");

s12_marker = has_s12_marker(candidate);
s12_source_leak = has_branch_map && any(contains(lower(branch_map.source_model), "s12"));
kron_method_leak = has_branch_map && any(contains( ...
    lower(branch_map.construction_method), ["ward", "kron"]), 'all');
no_s12_leak = source_exact && branch_registration_ok && ...
    ~s12_marker && ~s12_source_leak && ~kron_method_leak;
rows = add_gate(rows, model_name, model_role, "model_hierarchy", ...
    "no_s12_kron_admittance", "no S12 markers sources or Ward/Kron construction", ...
    string(no_s12_leak), no_s12_leak, true, true, ...
    "S12 may supply reference evidence but never S13-FULL or S14 network admittance rows.");

changed_rxb = find(any(abs(candidate.branch(1:246, [BR_R BR_X BR_B]) - ...
    s7.branch(:, [BR_R BR_X BR_B])) > 1e-12, 2));
[residual_register, has_residual_register] = residual_from_candidate(candidate);
[residual_coverage_ok, registered_residual_rows] = ...
    validate_residual_register(candidate, phase0_parent, residual_register, ...
    has_residual_register, changed_rxb);
residual_class_policy_ok = has_residual_register && ...
    validate_residual_class_policy(residual_register, changed_rxb);
rows = add_gate(rows, model_name, model_role, "admittance_policy", ...
    "residual_candidate_class_policy", ...
    "direct overlaps separated from frozen adjacent calibration candidates", ...
    string(residual_class_policy_ok), residual_class_policy_ok, true, true, ...
    "Rows 40/42 need paired response evidence and strong regularization before adjustment.");
rows = add_gate(rows, model_name, model_role, "admittance_policy", ...
    "changed_parent_r_x_b_registered", ...
    "every changed S7 R/X/B row appears in the residual register", ...
    sprintf('%d changed / %d registered', numel(changed_rxb), ...
    numel(intersect(changed_rxb, registered_residual_rows))), ...
    residual_coverage_ok, true, true, ...
    "Phase 0 ratings-only changes do not alter R/X/B.");

changed_shunt_rows = find(any(abs(candidate.bus(1:143, [GS BS]) - ...
    phase0_parent.bus(:, [GS BS])) > 1e-12, 2));
[shunt_register, has_shunt_register] = residual_shunt_from_candidate(candidate);
[shunt_coverage_ok, registered_shunt_rows] = ...
    validate_residual_shunt_register(candidate, phase0_parent, ...
    shunt_register, has_shunt_register, changed_shunt_rows);
rows = add_gate(rows, model_name, model_role, "admittance_policy", ...
    "changed_parent_shunts_registered", ...
    "every changed S7 GS/BS row appears in the residual-shunt register", ...
    sprintf('%d changed / %d registered', numel(changed_shunt_rows), ...
    numel(intersect(changed_shunt_rows, registered_shunt_rows))), ...
    shunt_coverage_ok, true, true, ...
    "Phase 1A freezes shunts; later passive residual shunts require evidence.");

full_npcc = all(ismember(original.bus(:, BUS_I), candidate.bus(:, BUS_I))) && ...
    original_branch_rows_stable;
rows = add_gate(rows, model_name, model_role, "network_form", ...
    "full_npcc_not_boundary_equivalent", "all original NPCC buses and branch rows", ...
    string(full_npcc), full_npcc, true, true, ...
    "An NY-only equivalent cannot pass this gate.");

% Construction qualification is fail-closed until Phase 1B/1C, passive
% internal residualization, and a frozen solved reduction-source state are
% artifact-backed. Independent S12 response and public-hour operating gates
% belong to S14 promotion, not S13-FULL construction qualification.
phase1b_complete = s13_metadata_ok && ...
    validate_phase1b_minimum(candidate, s13_metadata);
phase1c_complete = s13_metadata_ok && ...
    isfield(s13_metadata.phase_reports, 'phase1c');
construction_validator_available = false;
rows = add_gate(rows, model_name, model_role, "construction_readiness", ...
    "dedicated_construction_validator_available", "implemented and artifact-backed", ...
    "not_implemented_fail_closed", construction_validator_available, ...
    false, true, "A separate S13-FULL construction validator must be implemented first.");
rows = add_gate(rows, model_name, model_role, "construction_readiness", ...
    "phase1b_physical_overlay_complete", "complete and artifact-backed", ...
    pending_or_complete(phase1b_complete, "pending_phase1b"), ...
    phase1b_complete, false, true, ...
    "UPNY-ConEd physical detail must be present before S14 retention freezes.");
rows = add_gate(rows, model_name, model_role, "construction_readiness", ...
    "phase1c_physical_overlay_complete", "complete and artifact-backed", ...
    pending_or_complete(phase1c_complete, "pending_phase1c"), ...
    phase1c_complete, false, true, ...
    "Downstate H-J/K-J physical detail must be present before S14 retention freezes.");
rows = add_gate(rows, model_name, model_role, "construction_readiness", ...
    "passive_residualization_complete", "complete and passive", ...
    overlay_status_value(overlay, has_overlay, 'residualization_status'), ...
    false, false, true, "Pending dedicated artifact-backed validation.");
rows = add_gate(rows, model_name, model_role, "construction_readiness", ...
    "s14_reduction_source_state_complete", ...
    "frozen solved source state with bounded controls", ...
    overlay_status_value(overlay, has_overlay, 's14_reduction_source_status'), ...
    false, false, true, ...
    "The external multi-port must be derived from a reproducible solved S13-FULL state.");

all_structural = all(rows.pass(rows.mandatory_for_structure));
all_construction = all(rows.pass(rows.mandatory_for_construction_qualification));
if options.write_outputs
    ny_lite_writetable_lf(rows, options.output_file);
end

out = struct('model_name', model_name, 'model_role', model_role, ...
    'gates', rows, 'all_structural_gates_pass', all_structural, ...
    'all_construction_gates_pass', all_construction, ...
    'construction_source_qualified', all_structural && all_construction, ...
    'all_promotion_gates_pass', false, ... % compatibility: S13 never promotes
    'promotion_eligible', false, ...
    'candidate_size', [size(candidate.bus, 1), size(candidate.branch, 1), ...
    size(candidate.gen, 1)], 'output_file', string(options.output_file));

if options.fail_on_structural && ~all_structural
    failed = rows.metric(rows.mandatory_for_structure & ~rows.pass);
    error('validate_s13_structural_preservation:StructuralGateFailed', ...
        'S13 structural gates failed: %s', strjoin(cellstr(failed), ', '));
end
end

function rows = empty_gate_table()
rows = table(strings(0,1), strings(0,1), strings(0,1), strings(0,1), ...
    strings(0,1), strings(0,1), false(0,1), false(0,1), false(0,1), ...
    false(0,1), ...
    strings(0,1), 'VariableNames', {'model_name','model_role','category', ...
    'metric','expected','measured','pass','mandatory_for_structure', ...
    'mandatory_for_construction_qualification','mandatory_for_promotion','note'});
end

function rows = add_gate(rows, model_name, model_role, category, metric, ...
        expected, measured, passed, structural, construction, note)
row = table(string(model_name), string(model_role), string(category), ...
    string(metric), string(expected), string(measured), logical(passed), ...
    logical(structural), logical(construction), false, string(note), ...
    'VariableNames', rows.Properties.VariableNames);
rows = [rows; row];
end

function n = count_matching_bus_rows(candidate, original)
nmax = min(size(candidate.bus, 1), size(original.bus, 1));
n = nnz(candidate.bus(1:nmax, 1) == original.bus(1:nmax, 1));
end

