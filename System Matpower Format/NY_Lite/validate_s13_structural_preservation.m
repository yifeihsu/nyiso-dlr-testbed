function tf = optional_field_equal(a, b, field)
tf = isfield(a, field) == isfield(b, field);
if tf && isfield(a, field)
    tf = isequaln(a.(field), b.(field));
end
end

function tf = required_field_equal(a, b, field)
tf = isfield(a, field) && isfield(b, field) && ...
    isequaln(a.(field), b.(field));
end

function tf = is_false_scalar(value)
tf = isscalar(value) && ...
    ((islogical(value) && ~value) || ...
    (isnumeric(value) && isfinite(value) && value == 0));
end

function [value, ok] = scalar_text_value(raw)
value = "<invalid>";
ok = false;
if isstring(raw)
    if isscalar(raw) && ~ismissing(raw) && strlength(raw) > 0
        value = raw;
        ok = true;
    end
elseif ischar(raw) && isrow(raw) && ~isempty(raw)
    value = string(raw);
    ok = true;
end
end

function value = metadata_detail_value(raw)
[value, ok] = scalar_text_value(raw);
if ok
    return;
end
if (islogical(raw) || isnumeric(raw)) && isscalar(raw)
    value = string(raw);
    return;
end
value = "<invalid:" + string(class(raw)) + ":" + ...
    strjoin(string(size(raw)), "x") + ">";
end

