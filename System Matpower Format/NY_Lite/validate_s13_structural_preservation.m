function ok = validate_phase_report(report, phase, cumulative)
tables = {'bus_map','branch_map','residual_register', ...
    'residual_shunt_register','path_register','physical_register','operator_map'};
keys = {{'model_bus'},{'model_branch_row'},{'model_branch_row'},{'model_bus'}, ...
    {'overlay_path_id'},{'model_branch_row'}, ...
    {'interface_name','component_name','model_branch_row', ...
    'source_branch_row','source_circuit_id'}};
ok = isstruct(report) && isscalar(report) && isfield(report, 'phase_id') && ...
    isfield(report, 'construction_source_qualified') && ...
    isfield(report, 'promotion_eligible');
if ~ok, return; end
[report_phase, report_phase_scalar] = scalar_text_value(report.phase_id);
[expected_phase, expected_phase_scalar] = scalar_text_value(phase);
ok = ok && report_phase_scalar && expected_phase_scalar && ...
    report_phase == expected_phase && ...
    is_false_scalar(report.construction_source_qualified) && ...
    is_false_scalar(report.promotion_eligible) && isstruct(cumulative) && ...
    isscalar(cumulative);
if ~ok, return; end
for k = 1:numel(tables)
    name = tables{k}; key = keys{k};
    if ~isfield(report, name) || ~istable(report.(name)) || ...
            ~isfield(cumulative, name) || ~istable(cumulative.(name)) || ...
            ~isequal(report.(name).Properties.VariableNames, ...
            cumulative.(name).Properties.VariableNames) || ...
            ~all(ismember(key, report.(name).Properties.VariableNames)) || ...
            ~all(ismember(key, cumulative.(name).Properties.VariableNames))
        ok = false;
        return;
    end
    report_key = phase_table_key(report.(name), key);
    cumulative_key = phase_table_key(cumulative.(name), key);
    [found, location] = ismember(report_key, cumulative_key);
    if numel(unique(report_key)) ~= numel(report_key) || ...
            numel(unique(cumulative_key)) ~= numel(cumulative_key) || ...
            ~all(found) || ...
            ~isequaln(report.(name), cumulative.(name)(location, :))
        ok = false;
        return;
    end
end
ok = ~isempty(report.branch_map) && ~isempty(report.path_register);
end

function key = phase_table_key(value, columns)
key = strings(height(value), 1);
for k = 1:numel(columns)
    part = string(value.(columns{k}));
    part = replace(part, "|", "||");
    key = key + "|" + part;
end
end

function ok = validate_cumulative_phase_union(phase_reports, phases, cumulative)
tables = {'bus_map','branch_map','residual_register', ...
    'residual_shunt_register','path_register','physical_register','operator_map'};
keys = {{'model_bus'},{'model_branch_row'},{'model_branch_row'},{'model_bus'}, ...
    {'overlay_path_id'},{'model_branch_row'}, ...
    {'interface_name','component_name','model_branch_row', ...
    'source_branch_row','source_circuit_id'}};
ok = isstruct(cumulative) && isscalar(cumulative) && ~isempty(phases);
if ~ok, return; end
for k = 1:numel(tables)
    name = tables{k};
    if ~isfield(cumulative, name) || ~istable(cumulative.(name))
        ok = false;
        return;
    end
    combined = cumulative.(name)([], :);
    owned_keys = strings(0, 1);
    for p = 1:numel(phases)
        field = char(phases(p));
        if ~isfield(phase_reports, field) || ...
                ~isfield(phase_reports.(field), name) || ...
                ~istable(phase_reports.(field).(name)) || ...
                ~isequal(phase_reports.(field).(name).Properties.VariableNames, ...
                cumulative.(name).Properties.VariableNames)
            ok = false;
            return;
        end
        part = phase_reports.(field).(name);
        part_keys = phase_table_key(part, keys{k});
        if numel(unique(part_keys)) ~= numel(part_keys) || ...
                any(ismember(part_keys, owned_keys))
            ok = false;
            return;
        end
        owned_keys = [owned_keys; part_keys]; %#ok<AGROW>
        combined = [combined; part]; %#ok<AGROW>
    end
    if ~isequaln(combined, cumulative.(name))
        ok = false;
        return;
    end
end
end

