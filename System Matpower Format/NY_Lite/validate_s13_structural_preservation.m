            abs(map.source_va_deg(k) - src.bus(si, VA)) > 1e-12 || ...
            abs(map.source_pd_mw(k) - src.bus(si, PD)) > 1e-12 || ...
            abs(map.source_qd_mvar(k) - src.bus(si, QD)) > 1e-12 || ...
            abs(map.source_gs_mw(k) - src.bus(si, GS)) > 1e-12 || ...
            abs(map.source_bs_mvar(k) - src.bus(si, BS)) > 1e-12 || ...
            map.source_bus_name(k) ~= string(strtrim(src.bus_name{si})) || ...
            map.model_bus_name(k) ~= string(strtrim(candidate.bus_name{mi}))
        ok = false;
        return;
    end
    if map.model_action(k) == "appended_physical_terminal"
        if map.terminal_electrical_policy(k) ~= ...
                "pq_zero_injection_source_limits" || ...
                candidate.bus(mi, BUS_TYPE) ~= PQ || ...
                any(abs(candidate.bus(mi, [PD QD GS BS])) > 1e-12) || ...
                any(abs(src.bus(si, [PD QD GS BS])) > 1e-12) || ...
                abs(candidate.bus(mi, VMAX) - src.bus(si, VMAX)) > 1e-12 || ...
                abs(candidate.bus(mi, VMIN) - src.bus(si, VMIN)) > 1e-12
            ok = false;
            return;
        end
    elseif map.model_action(k) == "retained_existing_npcc_attachment"
        if map.terminal_electrical_policy(k) ~= "retained_npcc_unchanged"
            ok = false;
            return;
        end
    elseif map.model_action(k) == "retained_existing_npcc_attachment_proxy"
        if map.terminal_electrical_policy(k) ~= ...
                "retained_npcc_control_and_injection_not_source_copied"
            ok = false;
            return;
        end
    else
        ok = false;
        return;
    end
end

for k = 1:height(paths)
    mf = find(candidate.bus(:, BUS_I) == paths.npcc_attachment_from_bus(k), 1);
    mt = find(candidate.bus(:, BUS_I) == paths.npcc_attachment_to_bus(k), 1);
    sf = find(src.bus(:, BUS_I) == paths.source_attachment_from_bus(k), 1);
    st = find(src.bus(:, BUS_I) == paths.source_attachment_to_bus(k), 1);
    if isempty(mf) || isempty(mt) || isempty(sf) || isempty(st) || ...
            abs(candidate.bus(mf, BASE_KV) - src.bus(sf, BASE_KV)) > 1e-12 || ...
            abs(candidate.bus(mt, BASE_KV) - src.bus(st, BASE_KV)) > 1e-12
        ok = false;
        return;
    end
end
end

function [ok, registered_rows] = validate_residual_register( ...
        candidate, parent, reg, exists, changed_rows)
define_constants;
registered_rows = [];
required = {'model_branch_row','from_bus','to_bus','original_r_pu', ...
    'original_x_pu','original_b_pu','classification','overlap_scope', ...
    'adjustment_evidence_requirement','adjustment_evidence_status', ...
    'regularization_policy', ...
    'fitted_r_pu','fitted_x_pu','fitted_b_pu','fit_objective', ...
    'residual_resistance_nonnegative','passivity_min_eigenvalue', ...
    'passivity_gate_pass','fit_status','passivity_status','dlr_eligible','freeze'};
ok = exists && istable(reg) && ~isempty(reg) && ...
    isequal(reg.Properties.VariableNames, required) && ...
    numel(unique(reg.model_branch_row)) == height(reg) && ...
    all(reg.model_branch_row >= 1 & reg.model_branch_row <= 246);
if ~ok, return; end
registered_rows = reg.model_branch_row(:);
ok = all(ismember(changed_rows, registered_rows)) && ...
    isequal(parent.branch(registered_rows, [F_BUS T_BUS]), ...
    [reg.from_bus reg.to_bus]) && ...
    max(abs(parent.branch(registered_rows, [BR_R BR_X BR_B]) - ...
    [reg.original_r_pu reg.original_x_pu reg.original_b_pu]), [], 'all') <= 1e-12 && ...
    all(ismember(reg.classification, ["physical_overlap_residual_candidate", ...
    "adjacent_equivalent_calibration_candidate"])) && ...
    all(~reg.dlr_eligible);
if ~ok, return; end
for k = 1:height(reg)
    row = reg.model_branch_row(k);
    changed = ismember(row, changed_rows);
    if changed
        ok = isfinite(reg.fitted_r_pu(k)) && isfinite(reg.fitted_x_pu(k)) && ...
            isfinite(reg.fitted_b_pu(k)) && isfinite(reg.fit_objective(k)) && ...
            reg.fit_objective(k) >= 0 && reg.fitted_r_pu(k) >= 0 && ...
            islogical(reg.residual_resistance_nonnegative) && ...
            reg.residual_resistance_nonnegative(k) && ...
            isfinite(reg.passivity_min_eigenvalue(k)) && ...
            reg.passivity_min_eigenvalue(k) >= -1e-9 && ...
            islogical(reg.passivity_gate_pass) && reg.passivity_gate_pass(k) && ...
            reg.fit_status(k) == "complete" && reg.passivity_status(k) == "pass" && ...
            max(abs(candidate.branch(row, [BR_R BR_X BR_B]) - ...
            [reg.fitted_r_pu(k) reg.fitted_x_pu(k) reg.fitted_b_pu(k)])) <= 1e-12;
    else
        ok = max(abs(candidate.branch(row, [BR_R BR_X BR_B]) - ...
            parent.branch(row, [BR_R BR_X BR_B]))) <= 1e-12;
    end
    if ~ok, return; end
end
end

function ok = validate_residual_class_policy(reg, changed_rows)
required = {'model_branch_row','classification','adjustment_evidence_requirement', ...
    'adjustment_evidence_status','regularization_policy','freeze'};
ok = istable(reg) && all(ismember(required, reg.Properties.VariableNames)) && ...
    islogical(reg.freeze);
if ~ok, return; end
physical = reg.classification == "physical_overlap_residual_candidate";
adjacent = reg.classification == "adjacent_equivalent_calibration_candidate";
ok = all(ismember([34; 36], reg.model_branch_row(physical))) && ...
    all(ismember([40; 42], reg.model_branch_row(adjacent))) && ...
    all(reg.adjustment_evidence_requirement(physical) == ...
    "source_topology_overlap_and_passivity") && ...
    all(ismember(reg.adjustment_evidence_status(physical), ...
    ["source_topology_overlap_registered", "pass"])) && ...
    all(reg.regularization_policy(physical) == "passive_residual_fit") && ...
    all(~reg.freeze(physical)) && ...
    all(reg.adjustment_evidence_requirement(adjacent) == ...
    "paired_multi_snapshot_response_and_passivity");
if ~ok, return; end
for k = find(adjacent)'
    changed = ismember(reg.model_branch_row(k), changed_rows);
    if changed
        ok = reg.adjustment_evidence_status(k) == ...
            "paired_multi_snapshot_response_pass" && ...
            reg.regularization_policy(k) == ...
            "strong_deviation_penalty_applied" && ~reg.freeze(k);
    else
        ok = (reg.adjustment_evidence_status(k) == ...
            "pending_paired_response_evidence" && ...
            reg.regularization_policy(k) == ...
            "strong_deviation_penalty_required" && reg.freeze(k)) || ...
            (reg.adjustment_evidence_status(k) == ...
            "paired_multi_snapshot_response_pass" && ...
            reg.regularization_policy(k) == ...
            "strong_deviation_penalty_applied" && ~reg.freeze(k));
    end
    if ~ok, return; end
end
end

function [ok, registered_rows] = validate_residual_shunt_register( ...
        candidate, parent, reg, exists, changed_rows)
define_constants;
registered_rows = [];
required = {'model_bus','original_gs_mw_at_v1','original_bs_mvar_at_v1', ...
    'fitted_gs_mw_at_v1','fitted_bs_mvar_at_v1','fit_status', ...
    'passivity_status','provenance','passivity_gate_pass'};
ok = exists && istable(reg) && ...
    isequal(reg.Properties.VariableNames, required);
if ~ok, return; end
if isempty(reg)
    ok = isempty(changed_rows);
    return;
end
[found, registered_rows] = ismember(reg.model_bus, parent.bus(:, BUS_I));
ok = all(found) && numel(unique(reg.model_bus)) == height(reg) && ...
    all(ismember(changed_rows, registered_rows)) && ...
    max(abs(parent.bus(registered_rows, [GS BS]) - ...
    [reg.original_gs_mw_at_v1 reg.original_bs_mvar_at_v1]), [], 'all') <= 1e-12;
if ~ok, return; end
for k = 1:height(reg)
    row = registered_rows(k);
    changed = ismember(row, changed_rows);
    if changed
        ok = isfinite(reg.fitted_gs_mw_at_v1(k)) && ...
            isfinite(reg.fitted_bs_mvar_at_v1(k)) && ...
            islogical(reg.passivity_gate_pass) && reg.passivity_gate_pass(k) && ...
            reg.fit_status(k) == "complete" && reg.passivity_status(k) == "pass" && ...
            strlength(reg.provenance(k)) > 0 && ...
            max(abs(candidate.bus(row, [GS BS]) - ...
            [reg.fitted_gs_mw_at_v1(k) reg.fitted_bs_mvar_at_v1(k)])) <= 1e-12;
    else
        ok = max(abs(candidate.bus(row, [GS BS]) - ...
            parent.bus(row, [GS BS]))) <= 1e-12;
    end
    if ~ok, return; end
end
end

