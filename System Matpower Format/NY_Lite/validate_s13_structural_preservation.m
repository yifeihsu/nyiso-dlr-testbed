function ok = validate_attachment_name_match(candidate, map, src)
ok = isfield(candidate, 'bus_name') && isfield(src, 'bus_name') && ...
    all(ismember({'model_bus','source_bus','model_action','model_bus_name', ...
    'source_bus_name'}, map.Properties.VariableNames));
if ~ok, return; end
attachment = find(startsWith(map.model_action, ...
    "retained_existing_npcc_attachment"));
phase1a_pairs = [43 1233; 76 1519];
actual_pairs = [map.model_bus(attachment) map.source_bus(attachment)];
ok = ~isempty(attachment) && ...
    all(ismember(phase1a_pairs, actual_pairs, 'rows'));
if ~ok, return; end
for k = attachment'
    mi = find(candidate.bus(:, 1) == map.model_bus(k), 1);
    si = find(src.bus(:, 1) == map.source_bus(k), 1);
    if isempty(mi) || isempty(si)
        ok = false;
        return;
    end
    model_name = normalize_bus_names(candidate.bus_name(mi));
    source_name = normalize_bus_names(src.bus_name(si));
    ok = attachment_names_equivalent(model_name, source_name, ...
        map.model_bus(k), map.source_bus(k)) && ...
        normalize_bus_names(map.model_bus_name(k)) == model_name && ...
        normalize_bus_names(map.source_bus_name(k)) == source_name;
    if ~ok, return; end
end
end

function ok = attachment_names_equivalent(model_name, source_name, ...
        model_bus, source_bus)
ok = model_name == source_name;
if ok, return; end
% The original NPCC case abbreviates Pleasant Valley as PLEASANT VLY.
ok = model_bus == 73 && source_bus == 651 && ...
    model_name == "PLEASANT VLY" && source_name == "PLEASANT VALLEY";
end

function ok = validate_source_zero_injection(map, src)
define_constants;
required = {'source_bus','model_action','source_pd_mw','source_qd_mvar', ...
    'source_gs_mw','source_bs_mvar'};
ok = all(ismember(required, map.Properties.VariableNames));
if ~ok, return; end
added = find(map.model_action == "appended_physical_terminal");
ok = ~isempty(added);
if ~ok, return; end
for k = added'
    si = find(src.bus(:, BUS_I) == map.source_bus(k), 1);
    if isempty(si)
        ok = false;
        return;
    end
    source_values = src.bus(si, [PD QD GS BS]);
    mapped_values = [map.source_pd_mw(k) map.source_qd_mvar(k) ...
        map.source_gs_mw(k) map.source_bs_mvar(k)];
    ok = max(abs(source_values), [], 'all') <= 1e-12 && ...
        max(abs(mapped_values - source_values), [], 'all') <= 1e-12;
    if ~ok, return; end
end
end

