function outputs = build_s11_dlr_pf_case(scenario_id, options)
%BUILD_S11_DLR_PF_CASE Build one hard-feasible 49-bus S11 operating case.

if nargin < 1 || isempty(scenario_id)
    scenario_id = "S1_2025_SUMMER_PEAK_PUBLIC";
end
if nargin < 2, options = struct(); end
helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
options = defaults(options, helper_dir, case_dir);
addpath(case_dir); addpath(helper_dir);
define_constants;
scenario_id = string(scenario_id);

source = loadcase(options.structural_case);
[mpc, reduction_report] = build_ny_only_equivalent_case(source);
[mpc, physical_map] = split_perform_parallel_corridors(mpc, ...
    struct('map_file', options.physical_map_file, ...
    'write_map', options.write_intermediate_maps));
if isempty(options.non_dlr_correction)
    correction_report = struct('status', 'not_applied', ...
        'dlr_frozen_exact', true, 'changed_branch_count', 0, ...
        'changed_bus_shunt_count', 0);
else
    [mpc, correction_report] = apply_s11_non_dlr_equivalent_correction( ...
        mpc, physical_map, options.non_dlr_correction);
end
[mpc, load_report] = apply_s11_public_loads(mpc, scenario_id, ...
    struct('target_file', options.load_target_file, ...
    'q_multiplier', options.q_multiplier, ...
    'use_raw_public_scale', options.use_raw_public_scale));
[mpc, external_report] = apply_s11_external_schedules(mpc, scenario_id, ...
    struct('target_file', options.external_target_file, ...
    'use_raw_public_scale', options.use_raw_public_scale, ...
    'q_mode', options.external_q_mode, ...
    'q_band_mvar', options.external_q_band_mvar));
[mpc, control_report] = apply_perform_controls_to_operating_case(mpc, ...
    struct('control_map_file', options.control_map_file));
[mapped_reference_gen, mapped_reference_zone] = ...
    mapped_operational_reference(control_report);

mpc.userdata.s11.status = 'candidate_pending_hard_validation';
mpc.userdata.s11.scenario_id = char(scenario_id);
mpc.userdata.s11.structural_source = char(options.structural_case);
mpc.userdata.s11.nominal_snapshot = char(scenario_id);
mpc.userdata.s11.q_multiplier = options.q_multiplier;
mpc.userdata.s11.public_scale = ternary(options.use_raw_public_scale, ...
    'raw_NYISO_MW', 'S7_similarity_scaled');
mpc.userdata.s11.dlr_scope = ['AC electrical operating point only; no ' ...
    'conductor, weather, thermal, sag, or dynamic-ampacity model.'];

interface_map = build_s11_interface_branch_map(mpc, options.interface_map_file, ...
    options.write_intermediate_maps);
closure_options = options.closure_options;
closure_options.interface_target_file = options.interface_target_file;
closure_options.interface_map_file = options.interface_map_file;
closure_options.interface_definitions = interface_map;
closure_options.reference_pickup_tolerance_mw = ...
    options.reference_pickup_tolerance_mw;
if ~isfield(closure_options, 'flow_tolerance_mw')
    closure_options.flow_tolerance_mw = options.interface_max_residual_mw;
end
if ~isfield(closure_options, 'interface_mae_tolerance_mw')
    closure_options.interface_mae_tolerance_mw = options.interface_mae_mw;
end
if ~isfield(closure_options, 'interface_bias_tolerance_mw')
    closure_options.interface_bias_tolerance_mw = options.interface_signed_bias_mw;
end
closure_options.active_gen_idx = control_report.active_dispatch_gen_idx;
closure_options.exclude_gen_idx = control_report.external_gen_idx;
closure_options.reference_gen_idx = mapped_reference_gen;
closure_options.reference_zone = mapped_reference_zone;
[dispatch_targets, closure] = ...
    derive_nyiso_zonal_net_injections_ac_iterative_s11( ...
    mpc, scenario_id, closure_options);
input_case = closure.final_case;
trusted_branch_mask = trusted_static_branch_mask(physical_map, input_case);
input_case.userdata.s11.trusted_static_branch_indices = ...
    find(trusted_branch_mask);

[standard_pf, q_pf, pf_diagnostics] = run_hard_pf_pair(input_case);
projection = struct('attempted', false, 'success', false, ...
    'reason', "not_required", 'result', struct());
if needs_projection(q_pf, pf_diagnostics, options, trusted_branch_mask)
    projection = project_s11_hard_ac_feasibility(input_case, options, ...
        trusted_branch_mask);
    if projection.success
        input_case = projection.input_case;
        [standard_pf, q_pf, pf_diagnostics] = run_hard_pf_pair(input_case);
    end
end

if ~isfield(q_pf, 'success') || ~logical(q_pf.success)
    error('build_s11_dlr_pf_case:HardFeasibility', ...
        'Q-limit-enforced AC power flow failed for %s.', scenario_id);
end
[dispatch_targets, final_dispatch] = refresh_final_dispatch_targets( ...
    dispatch_targets, input_case, q_pf, control_report, closure);
closure.post_projection_interface_table = ...
    recompute_final_interface_table(q_pf, closure);
metrics = validation_metrics(input_case, standard_pf, q_pf, ...
    closure, control_report, dispatch_targets, trusted_branch_mask, options);
if options.require_hard_limits && ...
        (metrics.voltage_violation_count > 0 || ...
        metrics.generator_p_violation_count > 0 || ...
        metrics.generator_q_violation_count > 0 || ...
        metrics.branch_overload_count > 0)
    error('build_s11_dlr_pf_case:HardLimits', ...
        ['Scenario %s has hard-limit violations after feasibility projection ' ...
        '(V=%d, P=%d, Q=%d, branch=%d).'], scenario_id, ...
        metrics.voltage_violation_count, metrics.generator_p_violation_count, ...
        metrics.generator_q_violation_count, ...
        metrics.branch_overload_count);
end
if options.require_operating_gates && ~metrics.all_operating_gates_pass
    error('build_s11_dlr_pf_case:OperatingGates', ...
        ['Scenario %s is hard-PF feasible but cannot be promoted: ' ...
         'closure=%d, interface MAE/max/bias=%.3f/%.3f/%.3f MW, ' ...
         'reference pickup=%.3f MW, source-balanced-prior redispatch=%.3f MW (%.3f%%).'], ...
        scenario_id, metrics.closure_converged, ...
        metrics.closure_interface_mae_mw, ...
        metrics.closure_max_calibrated_residual_mw, ...
        metrics.closure_signed_bias_mw, metrics.reference_pickup_mw, ...
        metrics.source_balanced_prior_to_final_redispatch_mw, ...
        metrics.redispatch_percent_of_load);
end

input_case.userdata.s11.status = 'hard_pf_feasible_candidate';
input_case.userdata.s11.validation_metrics = metrics;
input_case.userdata.s11.physical_circuit_map = physical_map;
input_case.userdata.s11.interface_branch_map = interface_map;
input_case.userdata.s11.dispatch_targets = dispatch_targets;
case_files = struct('input_file', "", 'solution_file', "");
if options.write_cases
    case_files = write_case_files(input_case, q_pf, scenario_id, options);
end

outputs = struct('scenario_id', scenario_id, 'input_case', input_case, ...
    'solution', q_pf, 'standard_pf', standard_pf, ...
    'reduction_report', reduction_report, 'physical_circuit_map', physical_map, ...
    'interface_branch_map', interface_map, 'load_report', load_report, ...
    'external_report', external_report, 'control_report', control_report, ...
    'correction_report', correction_report, ...
    'dispatch_targets', dispatch_targets, 'closure', closure, ...
    'final_dispatch', final_dispatch, ...
    'pf_diagnostics', pf_diagnostics, 'projection', projection, ...
    'metrics', metrics, 'case_files', case_files);
end

