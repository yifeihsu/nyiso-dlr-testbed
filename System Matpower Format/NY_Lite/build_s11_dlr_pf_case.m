end
end

function [standard_pf, q_pf, diagnostics] = run_hard_pf_pair(mpc)
standard_pf = struct('success', false);
q_pf = struct('success', false);
standard_error = ""; q_error = "";
try
    standard_pf = runpf(mpc, mpoption('verbose',0,'out.all',0, ...
        'pf.enforce_q_lims',0));
catch ex
    standard_error = string(ex.message);
end
try
    q_pf = runpf(mpc, mpoption('verbose',0,'out.all',0, ...
        'pf.enforce_q_lims',1));
catch ex
    q_error = string(ex.message);
end
diagnostics = struct('standard_error', standard_error, 'q_error', q_error);
end

function tf = needs_projection(q_pf, diagnostics, options, trusted_branch_mask)
tf = ~isfield(q_pf,'success') || ~logical(q_pf.success);
if tf, return; end
if ~options.project_on_limit_violation, return; end
define_constants;
online = q_pf.gen(:,GEN_STATUS)>0;
v = q_pf.bus(:,VM) < q_pf.bus(:,VMIN)-1e-6 | ...
    q_pf.bus(:,VM) > q_pf.bus(:,VMAX)+1e-6;
    p = online & (q_pf.gen(:,PG) < q_pf.gen(:,PMIN)-options.hard_limit_tolerance_mva | ...
        q_pf.gen(:,PG) > q_pf.gen(:,PMAX)+options.hard_limit_tolerance_mva);
    q = online & (q_pf.gen(:,QG) < q_pf.gen(:,QMIN)-options.hard_limit_tolerance_mva | ...
        q_pf.gen(:,QG) > q_pf.gen(:,QMAX)+options.hard_limit_tolerance_mva);
s = max(hypot(q_pf.branch(:,PF),q_pf.branch(:,QF)), ...
    hypot(q_pf.branch(:,PT),q_pf.branch(:,QT)));
  rated = trusted_branch_mask & q_pf.branch(:,RATE_A)>0 & ...
      q_pf.branch(:,BR_STATUS)>0;
tf = any(v) || any(p) || any(q) || ...
    any(rated & s > q_pf.branch(:,RATE_A)+options.hard_limit_tolerance_mva);
if strlength(diagnostics.q_error) > 0, tf = true; end
end

function metrics = validation_metrics(input_case, standard_pf, q_pf, ...
        closure, control_report, dispatch_targets, trusted_branch_mask, options)
define_constants;
online = q_pf.gen(:,GEN_STATUS)>0;
vviol = q_pf.bus(:,VM)<q_pf.bus(:,VMIN)-1e-6 | ...
    q_pf.bus(:,VM)>q_pf.bus(:,VMAX)+1e-6;
pviol = online & (q_pf.gen(:,PG)<q_pf.gen(:,PMIN)-options.hard_limit_tolerance_mva | ...
    q_pf.gen(:,PG)>q_pf.gen(:,PMAX)+options.hard_limit_tolerance_mva);
qviol = online & (q_pf.gen(:,QG)<q_pf.gen(:,QMIN)-options.hard_limit_tolerance_mva | ...
    q_pf.gen(:,QG)>q_pf.gen(:,QMAX)+options.hard_limit_tolerance_mva);
s = max(hypot(q_pf.branch(:,PF),q_pf.branch(:,QF)), ...
    hypot(q_pf.branch(:,PT),q_pf.branch(:,QT)));
all_rated = q_pf.branch(:,RATE_A)>0 & q_pf.branch(:,BR_STATUS)>0;
rated = trusted_branch_mask & all_rated;
bover = rated & s>q_pf.branch(:,RATE_A)+options.hard_limit_tolerance_mva;
diagnostic_bover = all_rated & ...
    s>q_pf.branch(:,RATE_A)+options.hard_limit_tolerance_mva;
variable_q = online & q_pf.gen(:,QMAX)-q_pf.gen(:,QMIN)>1e-6;
qsat = variable_q & (abs(q_pf.gen(:,QG)-q_pf.gen(:,QMIN))<=1e-4 | ...
    abs(q_pf.gen(:,QG)-q_pf.gen(:,QMAX))<=1e-4);
initial_reg = ismember(input_case.bus(:,BUS_TYPE),[PV REF]);
pv_to_pq = initial_reg & q_pf.bus(:,BUS_TYPE)==PQ;
ref_bus = input_case.bus(input_case.bus(:,BUS_TYPE)==REF,BUS_I);
ref_gen = ismember(input_case.gen(:,GEN_BUS),ref_bus) & online;
ref_pickup = sum(q_pf.gen(ref_gen,PG)-input_case.gen(ref_gen,PG));
external = control_report.external_gen_idx;
external = external(external>=1 & external<=size(q_pf.gen,1));
internal = online; internal(external)=false;
total_load = sum(q_pf.bus(:,PD));
losses = sum(q_pf.gen(online,PG))-total_load;
if isfield(closure, 'post_projection_interface_table')
    interface_rows = closure.post_projection_interface_table;
else
    interface_rows = recompute_final_interface_table(q_pf, closure);
end
calibrated = logical(interface_rows.calibration_eligible);
final_interface_residual = interface_rows.final_ac_residual_mw(calibrated);
seed_redispatch = sum(abs(dispatch_targets.seed_to_final_redispatch_mw));
source_balanced_redispatch = sum(abs( ...
    dispatch_targets.source_balanced_prior_to_final_redispatch_mw));
source_redispatch = sum(abs( ...
    dispatch_targets.source_prior_to_final_redispatch_mw));
original_redispatch = sum(abs( ...
    dispatch_targets.original_to_final_redispatch_mw));
redispatch_percent = 100 * source_balanced_redispatch / max(total_load, eps);
redispatch_justified = strlength(strtrim(string( ...
    options.redispatch_justification))) > 0;
redispatch_pass = source_balanced_redispatch <= ...
    options.redispatch_hard_limit_mw && ...
    (redispatch_percent <= options.redispatch_percent_of_load || ...
    redispatch_justified);
interface_mae = mean(abs(final_interface_residual));
interface_max = max(abs(final_interface_residual));
interface_bias = mean(final_interface_residual);
interface_pass = interface_mae <= options.interface_mae_mw && ...
    interface_max <= options.interface_max_residual_mw && ...
    abs(interface_bias) <= options.interface_signed_bias_mw;
reference_pass = abs(ref_pickup)<options.reference_pickup_tolerance_mw;
hard_limit_pass = ~any(vviol) && ~any(pviol) && ~any(qviol) && ~any(bover);
closure_pass = logical(closure.converged) && interface_pass && reference_pass;
metrics = struct('standard_pf_success', success_flag(standard_pf), ...
    'q_limit_pf_success', success_flag(q_pf), ...
    'restoration_slack_mw', 0, 'restoration_slack_mvar', 0, ...
    'voltage_violation_count', sum(vviol), ...
    'generator_p_violation_count', sum(pviol), ...
    'generator_q_violation_count', sum(qviol), ...
    'branch_overload_count', sum(bover), ...
    'diagnostic_all_rated_branch_overload_count', sum(diagnostic_bover), ...
    'q_saturation_count', sum(qsat), ...
    'regulating_generator_count', sum(variable_q), ...
    'pv_to_pq_conversion_count', sum(pv_to_pq), ...
    'reference_pickup_mw', ref_pickup, ...
    'reference_pickup_pass', reference_pass, ...
    'total_load_mw', total_load, 'active_loss_mw', losses, ...
    'internal_generation_mw', sum(q_pf.gen(internal,PG)), ...
    'external_schedule_mw', sum(q_pf.gen(external,PG)), ...
    'min_voltage_pu', min(q_pf.bus(:,VM)), ...
    'max_voltage_pu', max(q_pf.bus(:,VM)), ...
    'max_branch_overload_mva', max([0;s(bover)-q_pf.branch(bover,RATE_A)]), ...
    'closure_converged', logical(closure.converged), ...
    'closure_max_calibrated_residual_mw', interface_max, ...
    'closure_interface_mae_mw', interface_mae, ...
    'closure_signed_bias_mw', interface_bias, ...
    'interface_gate_pass', interface_pass, ...
    'seed_to_final_redispatch_mw', seed_redispatch, ...
    'source_balanced_prior_to_final_redispatch_mw', ...
        source_balanced_redispatch, ...
    'source_prior_to_final_redispatch_mw', source_redispatch, ...
    'original_to_final_redispatch_mw', original_redispatch, ...
    'redispatch_percent_of_load', redispatch_percent, ...
    'redispatch_justified', redispatch_justified, ...
    'redispatch_gate_pass', redispatch_pass, ...
    'trusted_static_branch_count', sum(rated), ...
    'hard_limit_gate_pass', hard_limit_pass, ...
    'all_operating_gates_pass', success_flag(standard_pf) && ...
        success_flag(q_pf) && closure_pass && hard_limit_pass && ...
        redispatch_pass);
end

function rows = recompute_final_interface_table(result, closure)
if ~isfield(closure, 'interface_table') || isempty(closure.interface_table) || ...
        ~isfield(closure, 'interface_definitions') || ...
        isempty(closure.interface_definitions)
    error('build_s11_dlr_pf_case:InterfaceProvenance', ...
        'Final interface validation requires the closure table and definitions.');
end
rows = closure.interface_table;
flows = ny_lite_interface_flows(result, closure.interface_definitions);
flow_names = string({flows.interface_name})';
flow_types = string({flows.result_type})';
final_flow = nan(height(rows), 1);
for k = 1:height(rows)
    idx = find(flow_names == string(rows.interface_name(k)) & ...
        flow_types == "subpath");
    if numel(idx) ~= 1
        error('build_s11_dlr_pf_case:InterfaceResolution', ...
            'Final interface %s resolved to %d subpath records.', ...
            string(rows.interface_name(k)), numel(idx));
    end
    final_flow(k) = flows(idx).flow_mw;
end
rows.final_ac_flow_mw = final_flow;
rows.final_ac_residual_mw = final_flow-rows.target_flow_mw;
end

function [targets, diagnostics] = refresh_final_dispatch_targets( ...
        targets, scheduled_case, result, control_report, closure)
required = {'zone','original_scenario_generation_mw', ...
    'seeded_initial_generation_mw','target_generation_mw', ...
    'final_actual_generation_mw','original_to_final_redispatch_mw', ...
    'seed_to_final_redispatch_mw','final_generation_error_mw'};
if ~istable(targets) || ~all(ismember(required, ...
        targets.Properties.VariableNames)) || ...
        ~isfield(control_report, 'active_dispatch_gen_idx') || ...
        ~isstruct(closure) || ...
        ~isfield(closure, 'source_pg_prior_zonal_generation_mw') || ...
        ~isfield(closure, 'source_balance_prior_zonal_generation_mw') || ...
        ~isfield(closure, 'scenario_balance_prior_zonal_generation_mw')
    error('build_s11_dlr_pf_case:DispatchProvenance', ...
        'Final dispatch validation requires zonal seed and active-control provenance.');
end
zones = string(targets.zone(:));
active_idx = double(control_report.active_dispatch_gen_idx(:));
scheduled = active_zonal_generation(scheduled_case, active_idx, zones);
actual = active_zonal_generation(result, active_idx, zones);
seed = double(targets.seeded_initial_generation_mw(:));
original = double(targets.original_scenario_generation_mw(:));
source_prior = double(closure.source_pg_prior_zonal_generation_mw(:));
source_balance_prior = double( ...
    closure.source_balance_prior_zonal_generation_mw(:));
scenario_balance_prior = double( ...
    closure.scenario_balance_prior_zonal_generation_mw(:));
if numel(source_prior) ~= numel(zones) || ...
        numel(source_balance_prior) ~= numel(zones) || ...
        numel(scenario_balance_prior) ~= numel(zones) || ...
        any(~isfinite(source_prior)) || ...
        any(~isfinite(source_balance_prior)) || ...
        any(~isfinite(scenario_balance_prior))
    error('build_s11_dlr_pf_case:DispatchProvenance', ...
        'Closure dispatch priors are missing, nonfinite, or zone-misaligned.');
end
targets.target_generation_mw = scheduled;
targets.final_actual_generation_mw = actual;
targets.source_pg_prior_generation_mw = source_prior;
targets.source_balance_prior_generation_mw = source_balance_prior;
targets.scenario_balance_prior_generation_mw = scenario_balance_prior;
targets.original_to_final_redispatch_mw = actual-original;
targets.seed_to_final_redispatch_mw = actual-seed;
targets.source_prior_to_final_redispatch_mw = actual-source_prior;
targets.source_balanced_prior_to_final_redispatch_mw = ...
    actual-source_balance_prior;
targets.scenario_balanced_prior_to_final_redispatch_mw = ...
    actual-scenario_balance_prior;
targets.final_generation_error_mw = actual-scheduled;
if all(ismember({'pmin_mw','pmax_mw','at_pmin','at_pmax'}, ...
        targets.Properties.VariableNames))
    targets.at_pmin = abs(actual-targets.pmin_mw) <= 1e-6;
    targets.at_pmax = abs(actual-targets.pmax_mw) <= 1e-6;
end
diagnostics = struct('zones', zones, ...
    'active_dispatch_gen_idx', active_idx, ...
    'scheduled_zonal_generation_mw', scheduled, ...
    'actual_zonal_generation_mw', actual, ...
    'seed_to_final_redispatch_mw', actual-seed, ...
    'source_balanced_prior_to_final_redispatch_mw', ...
        actual-source_balance_prior, ...
    'scenario_balanced_prior_to_final_redispatch_mw', ...
        actual-scenario_balance_prior, ...
    'source_prior_to_final_redispatch_mw', actual-source_prior, ...
    'total_absolute_seed_to_final_redispatch_mw', sum(abs(actual-seed)), ...
    'total_absolute_source_balanced_prior_to_final_redispatch_mw', ...
        sum(abs(actual-source_balance_prior)), ...
    'total_absolute_scenario_balanced_prior_to_final_redispatch_mw', ...
        sum(abs(actual-scenario_balance_prior)), ...
    'total_absolute_source_prior_to_final_redispatch_mw', ...
        sum(abs(actual-source_prior)));
end

function generation = active_zonal_generation(mpc, active_idx, zones)
define_constants;
if any(~isfinite(active_idx) | active_idx < 1 | ...
        active_idx > size(mpc.gen, 1) | active_idx ~= fix(active_idx))
    error('build_s11_dlr_pf_case:ActiveDispatchIndex', ...
        'An active-dispatch generator index is invalid in the final case.');
end
mpc = attach_nyiso_zone_metadata(mpc);
online_idx = active_idx(mpc.gen(active_idx,GEN_STATUS)>0);
[found, bus_idx] = ismember(mpc.gen(online_idx,GEN_BUS), mpc.bus(:,BUS_I));
if any(~found)
    error('build_s11_dlr_pf_case:ActiveDispatchBus', ...
        'An active-dispatch generator bus is absent from the final case.');
end
gen_zone = upper(string(mpc.userdata.nyiso_physical_zone(bus_idx)));
generation = zeros(numel(zones), 1);
for k = 1:numel(zones)
    generation(k) = sum(mpc.gen(online_idx(gen_zone == ...
        upper(zones(k))),PG));
end
end

function trusted = trusted_static_branch_mask(branch_map, mpc)
define_constants;
if ismember('trusted_static_limit', branch_map.Properties.VariableNames)
    trusted = logical(branch_map.trusted_static_limit);
else
    trusted = branch_map.branch_classification == "physical_circuit";
end
trusted = trusted(:) & mpc.branch(:,BR_STATUS) > 0;
end

function value = success_flag(result)
value = isfield(result,'success') && logical(result.success);
end

function [gen_idx, zone] = mapped_operational_reference(control_report)
required_report = {'generator_report','active_dispatch_gen_idx'};
if ~isstruct(control_report) || ...
        ~all(isfield(control_report, required_report)) || ...
        ~istable(control_report.generator_report)
    error('build_s11_dlr_pf_case:MappedReference', ...
        'The control mapper did not return generator-level reference provenance.');
end
rows = control_report.generator_report;
required_columns = {'reduced_gen_index','zone', ...
    'is_native_active_control','is_operational_reference'};
if ~all(ismember(required_columns, rows.Properties.VariableNames))
    error('build_s11_dlr_pf_case:MappedReference', ...
        'The control report lacks operational-reference columns.');
end
mask = logical(rows.is_operational_reference) & ...
    logical(rows.is_native_active_control) & ...
    ismember(double(rows.reduced_gen_index), ...
        double(control_report.active_dispatch_gen_idx(:)));
candidates = unique(double(rows.reduced_gen_index(mask)));
if numel(candidates) ~= 1
    error('build_s11_dlr_pf_case:MappedReference', ...
        ['Exactly one source-backed native active control must be the ' ...
        'operational reference; found %d.'], numel(candidates));
end
gen_idx = candidates(1);
zones = unique(upper(string(rows.zone(mask & ...
    double(rows.reduced_gen_index) == gen_idx))));
if numel(zones) ~= 1 || strlength(zones) ~= 1
    error('build_s11_dlr_pf_case:MappedReference', ...
        'The mapped operational reference must have one NYISO zone.');
end
zone = zones(1);
end

function files = write_case_files(input_case, solution, scenario_id, options)
role = scenario_role(scenario_id);
files = struct('input_file', "", 'solution_file', "");
is_central = abs(options.q_multiplier-1)<1e-12;
if is_central && role == "summer_peak"
    files.input_file = string(fullfile(options.case_dir, ...
        'npcc_ny_lite_s11_dlr_pf_base_candidate_unvalidated.m'));
    files.solution_file = string(fullfile(options.case_dir, ...
        'npcc_ny_lite_s11_dlr_pf_solution_candidate_unvalidated.m'));
    write_s11_case_set_atomic([files.input_file; files.solution_file], ...
        {input_case; solution}, [false; true]);
elseif is_central && role == "winter_peak"
    files.solution_file = string(fullfile(options.case_dir, ...
        'npcc_ny_lite_s11_dlr_winter_candidate_unvalidated.m'));
    write_s11_case_set_atomic(files.solution_file, {solution}, true);
elseif is_central && role == "high_total_east"
    files.solution_file = string(fullfile(options.case_dir, ...
        'npcc_ny_lite_s11_dlr_high_total_east_candidate_unvalidated.m'));
    write_s11_case_set_atomic(files.solution_file, {solution}, true);
else
    qtag = sprintf('q%03d',round(100*options.q_multiplier));
    files.solution_file = string(fullfile(options.case_dir, sprintf( ...
        'npcc_ny_lite_s11_dlr_%s_%s_candidate_unvalidated.m',role,qtag)));
    write_s11_case_set_atomic(files.solution_file, {solution}, true);
end
end

function role = scenario_role(scenario_id)
switch string(scenario_id)
    case "S1_2025_SUMMER_PEAK_PUBLIC", role = "summer_peak";
    case "S2_2025_WINTER_PEAK_PUBLIC", role = "winter_peak";
    case "S5_2025_HIGH_TOTAL_EAST_PUBLIC", role = "high_total_east";
    otherwise
        role = lower(regexprep(string(scenario_id),'[^A-Za-z0-9]+','_'));
end
end

function value = ternary(condition, yes, no)
if condition, value = yes; else, value = no; end
end
