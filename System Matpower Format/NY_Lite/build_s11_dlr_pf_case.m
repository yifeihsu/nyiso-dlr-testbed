    'use_raw_public_scale', true; ...
    'external_q_mode', "fixed_zero"; ...
    'external_q_band_mvar', 0; ...
    'reference_pickup_tolerance_mw', 0.5; ...
    'hard_limit_tolerance_mva', 1e-3; ...
    'interface_mae_mw', 100; ...
