function diagnostic = local_west_central_diagnostics(K, residual, accuracy, ...
        generation, pmin, pmax, interface_names)
wc = find(interface_names == "West_Central", 1);
other = setdiff((1:numel(interface_names))', wc);
nz = numel(generation);
lb = pmin - generation;
ub = pmax - generation;
opts = optimoptions('linprog', 'Display', 'none');

% Maximize correction in the required positive direction, ignoring all
% other interface residuals.
f = -K(wc, :)';
[d1, ~, exit1] = linprog(f, [], [], ones(1, nz), 0, lb, ub, opts);
correction_unconstrained = K(wc, :) * d1;

% Repeat while retaining the other six interfaces inside their bands.
A = [K(other, :); -K(other, :)];
b = [accuracy(other) - residual(other); accuracy(other) + residual(other)];
[d2, ~, exit2] = linprog(f, A, b, ones(1, nz), 0, lb, ub, opts);
correction_banded = NaN;
if exit2 > 0, correction_banded = K(wc, :) * d2; end
diagnostic = table("ABC_CAP_0p8", residual(wc), exit1, ...
    correction_unconstrained, residual(wc) + correction_unconstrained, ...
    exit2, correction_banded, residual(wc) + correction_banded, ...
    'VariableNames', {'envelope_name','base_west_central_residual_mw', ...
    'west_only_exitflag','maximum_west_central_correction_mw', ...
    'west_only_remaining_residual_mw','other_six_banded_exitflag', ...
    'banded_west_central_correction_mw','banded_remaining_residual_mw'});
end

function status = scenario_availability_status(scenario_id, zones, file)
available = false;
complete = false;
if exist(file, 'file') == 2
    tbl = readtable(file, 'TextType', 'string', 'VariableNamingRule', 'preserve');
    required = {'scenario_id','zone','available_pmax_mw'};
    available = all(ismember(required, tbl.Properties.VariableNames));
    if available
        rows = tbl(string(tbl.scenario_id) == scenario_id, :);
        complete = height(rows) == numel(zones) && ...
            all(ismember(zones, string(rows.zone))) && ...
            all(isfinite(rows.available_pmax_mw));
    end
end
if complete
    state = "available_not_yet_promoted";
    note = "Input exists and can be added as a separate envelope.";
else
    state = "not_run_missing_independent_input";
    note = "No complete 2025 hour-specific unit availability/commitment " + ...
        "table is present. Static Gold Book capability is not treated as " + ...
        "scenario availability.";
end
[~, input_name, input_ext] = fileparts(file);
input_id = "System Matpower Format/NY_Lite/" + string(input_name) + ...
    string(input_ext);
status = table(scenario_id, input_id, available, complete, state, note, ...
    'VariableNames', {'scenario_id','expected_input_file','schema_detected', ...
    'complete_scenario_rows','status','note'});
end

function [metrics, detail] = nonlinear_recheck(scenario_id, zones, ...
        proposed_generation, zonal_pmax, options)
define_constants;
base = loadcase(options.structural_case);
[gsk, ~] = build_perform_npcc_generation_shift_keys(base);
[core, ~] = build_ny_only_equivalent_case(base);
[core, ~] = align_npcc_generation_capacity_to_perform_gsk(core, gsk);
core = set_zonal_pmax(core, zones, zonal_pmax);
[core, ~] = apply_nyiso_zonal_loads(core, scenario_id, 1.0, ...
    struct('preserve_total_ny_load', true));
pfopt = mpoption('verbose', 0, 'out.all', 0, 'pf.enforce_q_lims', 0);
schedule = proposed_generation;
pmin = zonal_pmin(core, zones);
loss_iterations = 0;
for k = 1:5
    [scheduled_core, ~] = apply_perform_generation_allocation(core, ...
        table(zones, schedule, ...
        'VariableNames', {'zone','target_generation_mw'}), gsk);
    [mpc, ext] = apply_nyiso_external_interface_injections( ...
        scheduled_core, scenario_id, ...
        struct('target_file', options.external_target_file));
    mpc = set_zone_reference(mpc, ext.added_gen_index, "J");
    result = runpf(mpc, pfopt);
    if ~result.success
        metrics = failed_recheck(scenario_id);
        detail = empty_detail();
        return;
    end
    physical = physical_metrics(result, ext.added_gen_index, sum(schedule));
    loss_iterations = k;
    adjustment = physical.reference_adjustment_mw;
    if abs(adjustment) <= 0.1, break; end
    alpha = loss_participation(schedule, pmin, zonal_pmax, adjustment);
    required_total = sum(schedule) + adjustment;
    schedule = project_total(schedule + alpha * adjustment, ...
        pmin, zonal_pmax, required_total);
end
targets = read_public_interface_targets(scenario_id, ...
    options.interface_target_file);
flows = ny_lite_interface_flows(result, ny_lite_interface_definitions(result));
[objective, detail] = interface_target_objective_balanced(flows, targets, ...
    struct('scale_file', options.interface_scale_file, 'min_scale_mw', 500));
physical = physical_metrics(result, ext.added_gen_index, sum(schedule));
try
    qresult = runpf(mpc, mpoption('verbose', 0, 'out.all', 0, ...
        'pf.enforce_q_lims', 1));
    q_success = logical(qresult.success);
catch
    q_success = false;
end
metrics = table(scenario_id, true, objective, ...
    max(abs(detail.residual_mw)), physical.reference_adjustment_mw, ...
    physical.min_voltage_pu, physical.max_voltage_pu, ...
    physical.voltage_violation_count, physical.branch_overload_count, ...
    physical.max_branch_overload_mva, physical.generator_p_violation_count, ...
    physical.max_generator_p_violation_mw, physical.generator_q_violation_count, ...
    physical.max_generator_q_violation_mvar, q_success, loss_iterations, ...
    'VariableNames', recheck_names());
end

function pmin = zonal_pmin(mpc, zones)
define_constants;
mpc = attach_nyiso_zone_metadata(mpc);
[mapped, bi] = ismember(mpc.gen(:, GEN_BUS), mpc.bus(:, BUS_I));
gen_zone = strings(size(mpc.gen, 1), 1);
gen_zone(mapped) = string(mpc.userdata.nyiso_physical_zone(bi(mapped)));
online = mpc.gen(:, GEN_STATUS) > 0;
pmin = zeros(numel(zones), 1);
for z = 1:numel(zones)
    pmin(z) = sum(mpc.gen(online & gen_zone == zones(z), PMIN));
end
end

function alpha = loss_participation(generation, pmin, pmax, adjustment)
if adjustment >= 0
    reserve = max(0, pmax - generation);
else
    reserve = max(0, generation - pmin);
end
if sum(reserve) <= 1e-9, reserve = max(0, pmax - pmin); end
alpha = reserve / sum(reserve);
end

function projected = project_total(seed, lower, upper, total)
scale = max(100, upper - lower);
C = diag(1 ./ scale);
d = C * seed;
opts = optimoptions('lsqlin', 'Display', 'off', 'Algorithm', 'interior-point');
[projected, ~, ~, exitflag, output] = lsqlin(C, d, [], [], ...
    ones(1, numel(seed)), total, lower, upper, ...
    min(max(seed, lower), upper), opts);
if exitflag <= 0
    error('S8.1 nonlinear loss projection failed: %s', output.message);
end
end

function mpc = set_zonal_pmax(mpc, zones, targets)
define_constants;
mpc = attach_nyiso_zone_metadata(mpc);
[mapped, bi] = ismember(mpc.gen(:, GEN_BUS), mpc.bus(:, BUS_I));
gen_zone = strings(size(mpc.gen, 1), 1);
gen_zone(mapped) = string(mpc.userdata.nyiso_physical_zone(bi(mapped)));
online = mpc.gen(:, GEN_STATUS) > 0;
for z = 1:numel(zones)
    idx = find(online & gen_zone == zones(z));
    if isempty(idx)
        if targets(z) > 1e-6
            error('Zone %s has no online generators for PMAX target %.3f.', ...
                zones(z), targets(z));
        end
        continue;
    end
    current = sum(mpc.gen(idx, PMAX));
    if current <= 0
        if targets(z) > 1e-6, error('Zone %s has zero PMAX.', zones(z)); end
        continue;
    end
    mpc.gen(idx, PMAX) = mpc.gen(idx, PMAX) * targets(z) / current;
    mpc.gen(idx, PMIN) = min(mpc.gen(idx, PMIN), mpc.gen(idx, PMAX));
end
end

function mpc = set_zone_reference(mpc, external_idx, zone_name)
define_constants;
mpc = attach_nyiso_zone_metadata(mpc);
[mapped, bi] = ismember(mpc.gen(:, GEN_BUS), mpc.bus(:, BUS_I));
zone = strings(size(mpc.gen, 1), 1);
zone(mapped) = string(mpc.userdata.nyiso_physical_zone(bi(mapped)));
mask = mpc.gen(:, GEN_STATUS) > 0 & zone == zone_name;
mask(external_idx) = false;
idx = find(mask);
qrange = mpc.gen(idx, QMAX) - mpc.gen(idx, QMIN);
if any(qrange > 1e-6), idx = idx(qrange > 1e-6); end
[~, k] = max(mpc.gen(idx, PMAX) - mpc.gen(idx, PG));
mpc = set_scenario_reference_bus(mpc, idx(k), ...
    struct('require_external', false));
end

function metrics = physical_metrics(results, external_idx, scheduled_internal)
define_constants;
results = attach_nyiso_zone_metadata(results);
[mapped, bi] = ismember(results.gen(:, GEN_BUS), results.bus(:, BUS_I));
zone = strings(size(results.gen, 1), 1);
zone(mapped) = string(results.userdata.nyiso_physical_zone(bi(mapped)));
online = results.gen(:, GEN_STATUS) > 0;
internal = online & zone ~= "";
internal(external_idx) = false;
sf = hypot(results.branch(:, PF), results.branch(:, QF));
st = hypot(results.branch(:, PT), results.branch(:, QT));
smax = max(sf, st);
rated = results.branch(:, RATE_A) > 0 & results.branch(:, BR_STATUS) > 0;
over = max(0, smax - results.branch(:, RATE_A));
vviol = results.bus(:, VM) < results.bus(:, VMIN) - 1e-6 | ...
    results.bus(:, VM) > results.bus(:, VMAX) + 1e-6;
pviol = max(max(0, results.gen(:, PMIN) - results.gen(:, PG)), ...
    max(0, results.gen(:, PG) - results.gen(:, PMAX)));
qviol = max(max(0, results.gen(:, QMIN) - results.gen(:, QG)), ...
    max(0, results.gen(:, QG) - results.gen(:, QMAX)));
metrics = struct('reference_adjustment_mw', ...
    sum(results.gen(internal, PG)) - scheduled_internal, ...
    'min_voltage_pu', min(results.bus(:, VM)), ...
    'max_voltage_pu', max(results.bus(:, VM)), ...
    'voltage_violation_count', sum(vviol), ...
    'branch_overload_count', sum(rated & over > 1e-6), ...
    'max_branch_overload_mva', max([0; over(rated)]), ...
    'generator_p_violation_count', sum(pviol > 1e-6), ...
    'max_generator_p_violation_mw', max([0; pviol]), ...
    'generator_q_violation_count', sum(qviol > 1e-6), ...
    'max_generator_q_violation_mvar', max([0; qviol]));
end

