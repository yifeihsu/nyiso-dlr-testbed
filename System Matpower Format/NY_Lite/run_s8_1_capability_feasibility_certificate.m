function value = token(x)
value = replace(string(sprintf('%.3g', x)), '.', 'p');
end

function vector = vector_by_zone(tbl, zones, variable)
vector = zeros(numel(zones), 1);
for z = 1:numel(zones)
    idx = find(string(tbl.zone) == zones(z), 1);
    if isempty(idx), error('Zone %s is missing.', zones(z)); end
    vector(z) = tbl.(variable)(idx);
end
end

function K = response_matrix(tbl, interfaces, zones)
K = zeros(numel(interfaces), numel(zones));
for m = 1:numel(interfaces)
    for z = 1:numel(zones)
        idx = find(string(tbl.interface_name) == interfaces(m) & ...
            string(tbl.perturbed_zone) == zones(z), 1);
        if ~isempty(idx), K(m, z) = tbl.sensitivity_mw_per_mw(idx); end
    end
end
end

function pmax = capability_envelope(current, zones, factor, inherited_factor)
pmax = current;
abc = ismember(zones, ["A"; "B"; "C"]);
base_target = current(abc) / inherited_factor;
pmax(abc) = base_target * factor;
end

function solution = solve_minimax(K, residual, accuracy, generation, pmin, pmax)
nz = numel(generation);
f = [zeros(nz, 1); 1];
A = [K, -accuracy; -K, -accuracy];
b = [-residual; residual];
Aeq = [ones(1, nz), 0];
beq = 0;
lb = [pmin - generation; 0];
ub = [pmax - generation; Inf];
opts = optimoptions('linprog', 'Display', 'none');
[x, fval, exitflag, output, lambda] = linprog(f, A, b, ...
    Aeq, beq, lb, ub, opts);
if exitflag <= 0
    error('S8.1 strict minimax LP failed: %s', output.message);
end
solution = struct('exitflag', exitflag, 'objective', fval, ...
    'eta', x(end), 'delta_generation_mw', x(1:nz), ...
    'capability_relaxation_mw', zeros(nz, 1), ...
    'predicted_residual_mw', residual + K * x(1:nz), ...
    'upper_bound_dual', lambda.upper(1:nz), ...
    'lower_bound_dual', lambda.lower(1:nz), ...
    'capability_constraint_lp_dual', zeros(nz, 1), ...
    'capability_constraint_secondary_qp_dual', zeros(nz, 1));
end

function solution = solve_minimum_relaxation(K, residual, accuracy, ...
        generation, pmin, pmax, zones, allowed_zones)
nz = numel(generation);
nm = numel(residual);
% First stage: minimum added capability needed to enter every accuracy band.
f = [zeros(nz, 1); ones(nz, 1)];
Aflow = [K, zeros(nm, nz); -K, zeros(nm, nz)];
bflow = [accuracy - residual; accuracy + residual];
Acap = [eye(nz), -eye(nz)];
bcap = pmax - generation;
A = [Aflow; Acap];
b = [bflow; bcap];
Aeq = [ones(1, nz), zeros(1, nz)];
beq = 0;
lb = [pmin - generation; zeros(nz, 1)];
ub = [inf(nz, 1); inf(nz, 1)];
ub(nz + find(~ismember(zones, allowed_zones))) = 0;
opts = optimoptions('linprog', 'Display', 'none');
[x1, fval, exitflag, output, lambda1] = linprog(f, A, b, ...
    Aeq, beq, lb, ub, opts);
if exitflag <= 0
    error('S8.1 minimum-relaxation LP failed: %s', output.message);
end
lp_dual = capability_dual(lambda1, nm, nz);

% Second stage: retain the minimum relaxation and choose a minimum-norm
% redispatch so the nonlinear recheck is not driven to an arbitrary LP corner.
A2 = [A; zeros(1, nz), ones(1, nz)];
b2 = [b; fval + 1e-6];
H = blkdiag(diag(1 ./ max(100, pmax).^2), 1e-8 * eye(nz));
qopts = optimoptions('quadprog', 'Display', 'none');
[x, ~, qexit, ~, lambda] = quadprog(H, zeros(2 * nz, 1), ...
    A2, b2, Aeq, beq, lb, ub, x1, qopts);
if qexit <= 0
    x = x1;
    lambda = lambda1;
end
delta = x(1:nz);
relaxation = x(nz + 1:end);
solution = struct('exitflag', exitflag, 'objective', sum(relaxation), ...
    'eta', max(abs((residual + K * delta) ./ accuracy)), ...
    'delta_generation_mw', delta, ...
    'capability_relaxation_mw', relaxation, ...
    'predicted_residual_mw', residual + K * delta, ...
    'upper_bound_dual', zeros(nz, 1), 'lower_bound_dual', zeros(nz, 1), ...
    'capability_constraint_lp_dual', lp_dual, ...
    'capability_constraint_secondary_qp_dual', ...
    capability_dual(lambda, nm, nz));
end

function values = capability_dual(lambda, nm, nz)
values = zeros(nz, 1);
if isstruct(lambda) && isfield(lambda, 'ineqlin') && ...
        numel(lambda.ineqlin) >= 2 * nm + nz
    values = lambda.ineqlin(2 * nm + (1:nz));
end
end

