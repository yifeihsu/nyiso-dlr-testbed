function outputs = run_s8_1_capability_feasibility_certificate(options)
%RUN_S8_1_CAPABILITY_FEASIBILITY_CERTIFICATE Audit shoulder P capability.
%   Uses the final S8 shoulder AC sensitivity matrix to certify the minimum
%   worst engineering-normalized interface residual under alternative A/B/C
%   capability envelopes. Each linear proposal is then applied to the full
%   nonlinear AC PF on the direct-PERFORM S7 topology.

if nargin < 1, options = struct(); end
helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
addpath(case_dir); addpath(helper_dir);
options = defaults(options, helper_dir);

scenario_id = string(options.scenario_id);
zones = string(('A':'K')');
interfaces = readtable(options.interface_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
interfaces = interfaces(string(interfaces.scenario_id) == scenario_id, :);
zonal = readtable(options.zonal_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
zonal = zonal(string(zonal.scenario_id) == scenario_id, :);
sensitivity = readtable(options.sensitivity_file, 'TextType', 'string', ...
    'VariableNamingRule', 'preserve');
sensitivity = sensitivity(string(sensitivity.scenario_id) == scenario_id, :);
if height(interfaces) ~= 7 || height(zonal) ~= 11 || isempty(sensitivity)
    error('S8.1 inputs are incomplete for scenario %s.', scenario_id);
end

last_iteration = max(sensitivity.iteration);
sensitivity = sensitivity(sensitivity.iteration == last_iteration, :);
interface_names = string(interfaces.interface_name);
generation = vector_by_zone(zonal, zones, 'target_generation_mw');
pmin = vector_by_zone(zonal, zones, 'pmin_mw');
current_pmax = vector_by_zone(zonal, zones, 'pmax_mw');
residual = interfaces.operational_ac_residual_mw;
accuracy = interfaces.accuracy_scale_mw;
K = response_matrix(sensitivity, interface_names, zones);

summary_rows = table();
residual_rows = table();
dual_rows = table();
relaxation_rows = table();
recheck_rows = table();
proposal_rows = table();

for cap_factor = options.abc_cap_factors
    envelope_name = "ABC_CAP_" + token(cap_factor);
    pmax = capability_envelope(current_pmax, zones, cap_factor, ...
        options.inherited_abc_cap_factor);
    strict = solve_minimax(K, residual, accuracy, generation, pmin, pmax);
    [strict_recheck, strict_detail] = nonlinear_recheck(scenario_id, ...
        zones, generation + strict.delta_generation_mw, pmax, options);
    strict_recheck = addvars(strict_recheck, envelope_name, cap_factor, ...
        "strict_min_eta", 'After', 'scenario_id', ...
        'NewVariableNames', {'envelope_name','abc_cap_factor','solution_type'});

    srow = summary_row(scenario_id, envelope_name, cap_factor, ...
        "strict_min_eta", strict, pmax, strict_recheck);
    summary_rows = append_table(summary_rows, srow);
    residual_rows = append_table(residual_rows, residual_table( ...
        scenario_id, envelope_name, "strict_min_eta", interface_names, ...
        residual, strict.predicted_residual_mw, accuracy, strict_detail));
    dual_rows = append_table(dual_rows, dual_table(scenario_id, ...
        envelope_name, "strict_min_eta", zones, generation, pmin, pmax, ...
        strict));
    proposal_rows = append_table(proposal_rows, proposal_table( ...
        scenario_id, envelope_name, "strict_min_eta", zones, generation, ...
        pmin, pmax, strict.delta_generation_mw, zeros(numel(zones), 1)));
    recheck_rows = append_table(recheck_rows, strict_recheck);

    relaxed = solve_minimum_relaxation(K, residual, accuracy, generation, ...
        pmin, pmax, zones, options.relaxation_zones);
    relaxed_pmax = pmax + relaxed.capability_relaxation_mw;
    [relaxed_recheck, relaxed_detail] = nonlinear_recheck(scenario_id, ...
        zones, generation + relaxed.delta_generation_mw, relaxed_pmax, options);
    relaxed_recheck = addvars(relaxed_recheck, envelope_name, cap_factor, ...
        "minimum_abc_relaxation_eta1", 'After', 'scenario_id', ...
        'NewVariableNames', {'envelope_name','abc_cap_factor','solution_type'});
    rrow = summary_row(scenario_id, envelope_name, cap_factor, ...
        "minimum_abc_relaxation_eta1", relaxed, relaxed_pmax, relaxed_recheck);
    summary_rows = append_table(summary_rows, rrow);
    residual_rows = append_table(residual_rows, residual_table( ...
        scenario_id, envelope_name, "minimum_abc_relaxation_eta1", ...
        interface_names, residual, relaxed.predicted_residual_mw, accuracy, ...
        relaxed_detail));
    relaxation_rows = append_table(relaxation_rows, relaxation_table( ...
        scenario_id, envelope_name, zones, relaxed));
    proposal_rows = append_table(proposal_rows, proposal_table( ...
        scenario_id, envelope_name, "minimum_abc_relaxation_eta1", zones, ...
        generation, pmin, relaxed_pmax, relaxed.delta_generation_mw, ...
        relaxed.capability_relaxation_mw));
    recheck_rows = append_table(recheck_rows, relaxed_recheck);
end

local_diagnostics = local_west_central_diagnostics(K, residual, accuracy, ...
    generation, pmin, current_pmax, interface_names);
availability_status = scenario_availability_status(scenario_id, zones, ...
    options.scenario_availability_file);

writetable(summary_rows, options.summary_file);
writetable(residual_rows, options.residual_file);
writetable(dual_rows, options.dual_file);
writetable(relaxation_rows, options.relaxation_file);
writetable(proposal_rows, options.proposal_file);
writetable(recheck_rows, options.recheck_file);
writetable(local_diagnostics, options.local_diagnostic_file);
writetable(availability_status, options.availability_status_file);

outputs = struct('summary_file', options.summary_file, ...
    'residual_file', options.residual_file, 'dual_file', options.dual_file, ...
    'relaxation_file', options.relaxation_file, ...
    'proposal_file', options.proposal_file, 'recheck_file', options.recheck_file, ...
    'local_diagnostic_file', options.local_diagnostic_file, ...
    'availability_status_file', options.availability_status_file, ...
    'scenario_id', scenario_id, 'sensitivity_iteration', last_iteration, ...
    'summary', summary_rows, 'local_diagnostics', local_diagnostics);
end

