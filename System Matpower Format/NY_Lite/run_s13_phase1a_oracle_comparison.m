function gates = oracle_gate_ledger(local, readiness, same_snapshot, ...
        cut_flows, physical, heldout, heldout_metrics)
gates = table();
for k = 1:height(local.gate_ledger)
    g = local.gate_ledger(k, :);
    gates = append_gate(gates, "stage_a_local_identity", g.gate_id, ...
        "executed_metric", g.metric_value, g.limit, g.comparator, ...
        g.mandatory, g.pass, g.notes, "");
end
