function pass = heldout_detail_schema_complete(rows, heldout)
expected_metric = ["delta_pf_mw"; "delta_qf_mvar"; ...
    "delta_series_current_kA"; "delta_vm_pu"; ...
    "delta_aligned_va_deg"; "delta_E_G_cut_mw"; ...
    "delta_E_F_cut_mw"; "delta_internal_NY_active_loss_mw"];
expected_count = [84; 84; 84; 72; 72; 12; 12; 12];
pass = height(rows) == 432 && ...
    isequal(unique(rows.perturbation_id, 'stable'), heldout.perturbation_id) && ...
    all(strlength(rows.balancing_policy_id) > 0) && ...
    all(~rows.refit_performed) && all(rows.execution_status == "blocked") && ...
    all(rows.gate_status == "blocked");
for k = 1:numel(expected_metric)
    pass = pass && nnz(rows.metric_id == expected_metric(k)) == ...
        expected_count(k);
end
future_fields = {'oracle_baseline_value','oracle_perturbed_value', ...
    'oracle_delta_value','s13_baseline_value','s13_perturbed_value', ...
    's13_delta_value','delta_absolute_error','delta_error_percent'};
for k = 1:numel(future_fields)
    pass = pass && all(isnan(rows.(future_fields{k})));
end
keys = rows.perturbation_id + "|" + rows.entity_type + "|" + ...
    rows.entity_id + "|" + rows.metric_id;
pass = pass && numel(unique(keys)) == height(rows);
for k = 1:height(heldout)
    scenario = rows.perturbation_id == heldout.perturbation_id(k);
    physical = scenario & rows.entity_type == "physical_circuit";
    terminal = scenario & rows.entity_type == "terminal";
    system = scenario & rows.entity_type == "system";
    pass = pass && nnz(scenario) == 36 && nnz(physical) == 21 && ...
        nnz(terminal) == 12 && nnz(system) == 3 && ...
        numel(unique(rows.entity_id(physical))) == 7 && ...
        numel(unique(rows.entity_id(terminal))) == 6 && ...
        numel(unique(rows.entity_id(system))) == 3;
end
end

function out = append_gate(out, stage, id, kind, value, limit, comparator, ...
        required, passed, evidence, blocked_reason)
if passed
    status = "pass";
elseif strlength(string(blocked_reason)) > 0
    status = "blocked_fail_closed";
else
    status = "fail";
end
row = table(string(stage), string(id), string(kind), double(value), ...
    double(limit), string(comparator), logical(required), logical(passed), ...
    status, string(evidence), string(blocked_reason), ...
    'VariableNames', {'stage','gate_id','gate_kind','metric_value','limit', ...
    'comparator','required','passed','status','evidence','blocked_reason'});
if isempty(out), out = row; else, out = [out; row]; end
end

function reason = blocked_if_false(flag, value)
if flag, reason = ""; else, reason = string(value); end
end

function value = clean_token(value)
value = upper(regexprep(strtrim(string(value)), '[^A-Z0-9]+', '_'));
value = regexprep(value, '^_|_$', '');
end

function error_percent = percent_error(reference, value)
error_percent = nan(size(reference));
finite = isfinite(reference) & isfinite(value);
nonzero = finite & abs(reference) > 1e-12;
error_percent(nonzero) = 100 * abs(value(nonzero)-reference(nonzero)) ./ ...
    abs(reference(nonzero));
both_zero = finite & abs(reference) <= 1e-12 & ...
    abs(value-reference) <= 1e-12;
error_percent(both_zero) = 0;
end
