function out = run_s13_phase1a_oracle_comparison(options)
%RUN_S13_PHASE1A_ORACLE_COMPARISON Orchestrate the no-fit S13.1 evidence.
%   Stage A is executed through RUN_S13_PHASE1A_LOCAL_IDENTITY. Stage B/C
%   remain fail-closed until ASSESS_S13_PHASE1A_COMMON_INPUT_READINESS
%   establishes a frozen common operating baseline. Unexecuted metrics are
%   persisted as NaN with explicit blocked reasons; no comparison value is
%   inferred from a different operating point.

if nargin < 1, options = struct(); end
helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
options = defaults(options, helper_dir);
addpath(case_dir); addpath(helper_dir);

local = run_s13_phase1a_local_identity(struct( ...
    'write_outputs', false, 'fail_on_gate', false, 'verbose', false));
readiness = assess_s13_phase1a_common_input_readiness(struct( ...
    'write_outputs', false, 'fail_on_not_ready', false, 'verbose', false));

blocked_reason = "Frozen common S12/S13 baseline unavailable: " + ...
    strjoin(readiness.blockers, "; ");
same_snapshot = same_snapshot_manifest(local, blocked_reason);
cut_flows = cut_flow_manifest(blocked_reason);
physical_circuits = physical_circuit_evidence(local, blocked_reason);
heldout = heldout_manifest(local, blocked_reason);
heldout_metrics = heldout_metric_manifest(local, heldout, blocked_reason);
gates = oracle_gate_ledger(local, readiness, same_snapshot, cut_flows, ...
    physical_circuits, heldout, heldout_metrics);

all_required_pass = all(gates.passed(gates.required));
stage_b_executed = any(same_snapshot.execution_status == "executed");
stage_c_executed = any(heldout.execution_status == "executed");
electrically_validated = local.pass && readiness.ready && ...
    stage_b_executed && stage_c_executed && all_required_pass;

files = struct( ...
    'same_snapshot', fullfile(options.output_dir, ...
        's13_phase1a_same_snapshot_comparison.csv'), ...
    'cut_flow', fullfile(options.output_dir, ...
        's13_phase1a_cut_flow_comparison.csv'), ...
    'physical_circuit', fullfile(options.output_dir, ...
        's13_phase1a_physical_circuit_comparison.csv'), ...
    'heldout_response', fullfile(options.output_dir, ...
        's13_phase1a_heldout_response.csv'), ...
    'heldout_metric_manifest', fullfile(options.output_dir, ...
        's13_phase1a_heldout_metric_manifest.csv'), ...
    'gate_ledger', fullfile(options.output_dir, ...
        's13_phase1a_oracle_gate_ledger.csv'));
if options.write_outputs
    if ~isfolder(options.output_dir)
        error('run_s13_phase1a_oracle_comparison:OutputDirectory', ...
            'Output directory does not exist: %s', options.output_dir);
    end
    ny_lite_writetable_lf(same_snapshot, files.same_snapshot);
    ny_lite_writetable_lf(cut_flows, files.cut_flow);
    ny_lite_writetable_lf(physical_circuits, files.physical_circuit);
    ny_lite_writetable_lf(heldout, files.heldout_response);
    ny_lite_writetable_lf(heldout_metrics, files.heldout_metric_manifest);
    ny_lite_writetable_lf(gates, files.gate_ledger);
end

if electrically_validated
    status = "electrically_validated_unpromoted_checkpoint";
else
    status = "unpromoted_fail_closed_pending_common_baseline";
end

out = struct( ...
    'model_role', "unpromoted_s13_candidate", ...
    'status', status, ...
    'promotion_eligible', false, ...
    'electrically_validated', logical(electrically_validated), ...
    'all_required_gates_pass', logical(all_required_pass), ...
    'stage_a_executed', true, ...
    'stage_a_pass', logical(local.pass), ...
    'stage_b_executed', logical(stage_b_executed), ...
    'stage_c_executed', logical(stage_c_executed), ...
    'common_input_ready', logical(readiness.ready), ...
    'blocked_reason', blocked_reason, ...
    'local_identity', local, ...
    'common_input_readiness', readiness, ...
    'same_snapshot_comparison', same_snapshot, ...
    'cut_flow_comparison', cut_flows, ...
    'physical_circuit_comparison', physical_circuits, ...
    'heldout_response', heldout, ...
    'heldout_metric_manifest', heldout_metrics, ...
    'gate_ledger', gates, ...
    'passing_gate_count', nnz(gates.passed), ...
    'gate_count', height(gates), ...
    'files', files, ...
    'outputs_written', logical(options.write_outputs));

if options.verbose
    fprintf(['S13.1 oracle orchestration: %s; gates %d/%d pass; ' ...
        'Stage A=%d, Stage B executed=%d, Stage C executed=%d.\n'], ...
        status, out.passing_gate_count, out.gate_count, local.pass, ...
        stage_b_executed, stage_c_executed);
    if ~electrically_validated
        fprintf('  fail-closed: %s\n', blocked_reason);
    end
end

if options.fail_on_incomplete && ~electrically_validated
    error('run_s13_phase1a_oracle_comparison:Incomplete', ...
        'The S13.1 oracle comparison remains fail-closed: %s', blocked_reason);
end
end

function options = defaults(options, helper_dir)
if ~isfield(options, 'write_outputs'), options.write_outputs = true; end
if ~isfield(options, 'output_dir'), options.output_dir = helper_dir; end
if ~isfield(options, 'verbose'), options.verbose = true; end
if ~isfield(options, 'fail_on_incomplete'), options.fail_on_incomplete = false; end
options.write_outputs = logical(options.write_outputs);
options.verbose = logical(options.verbose);
options.fail_on_incomplete = logical(options.fail_on_incomplete);
end

