function out = run_s13_phase1b_local_identity(options)
%RUN_S13_PHASE1B_LOCAL_IDENTITY Validate the exact Phase 1B local overlays.
%   This no-fit test solves two Phase 1B subnetworks independently. The
%   Q-limit-solved full PERFORM case supplies fixed boundary phasors and
%   fixed complex-power injections derived from each omitted network. A
%   zero-injection truncation is retained as a diagnostic only.

if nargin < 1, options = struct(); end

helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
root = fileparts(case_dir);
perform_dir = fullfile(root, 'PERFORM', ...
    'On Peak 2019 v23_Perform_NY', 'On Peak 2019 v23');
options = defaults(options, helper_dir, perform_dir);
addpath(case_dir); addpath(helper_dir); addpath(perform_dir);
define_constants;

candidate = load_candidate(options.s13_case);
[phase1a_report, phase1b_report, cumulative_report] = ...
    phase_reports(candidate);
[phase1a_report_exact, phase1a_rows_exact] = ...
    assert_phase1a_immutable(candidate, phase1a_report);
candidate_fail_closed = fail_closed_status(candidate, phase1b_report);
if ~candidate_fail_closed
    error('run_s13_phase1b_local_identity:PromotionStatus', ...
        'The cumulative S13 candidate or Phase 1B report is not fail-closed.');
end

paths = path_specifications();
[physical_by_path, physical] = select_phase1b_physical( ...
    phase1b_report.physical_register, paths);

source_case = loadcase(options.source_case);
source_results = runpf(source_case, mpoption( ...
    'verbose', 0, 'out.all', 0, 'pf.enforce_q_lims', 1));
if ~source_results.success
    error('run_s13_phase1b_local_identity:SourcePF', ...
        'The full PERFORM Q-limit source power flow did not converge.');
end
source_phasors = evaluate_network_phasors(source_results);

source_rows = double(physical.source_branch_row);
source_from = double(physical.source_from_bus);
source_to = double(physical.source_to_bus);
model_rows = double(physical.model_branch_row);
model_from = double(physical.model_from_bus);
model_to = double(physical.model_to_bus);
assert_branch_mapping(source_results, candidate, source_rows, source_from, ...
    source_to, model_rows, model_from, model_to);
[raw_branch_row, raw_circuit_id] = raw_branch_identity( ...
    options.raw_file, source_results, source_rows);

identity = table();
omitted = table();
voltages = table();
path_results = repmat(struct( ...
    'overlay_path_id', "", ...
    'injection_results', struct(), ...
    'zero_injection_results', struct()), numel(paths), 1);
row_offset = 0;
for p = 1:numel(paths)
    spec = paths(p);
    physical_part = physical_by_path{p};
    local_bus = [spec.boundary_bus; spec.interior_bus];

    [omitted_part, equivalent_injection] = omitted_injection_table( ...
        source_results, source_phasors, spec.interior_bus, local_bus, ...
        spec.source_rows, spec.overlay_path_id);
    injection_case = build_local_case(source_results, local_bus, ...
        spec.boundary_bus, spec.interior_bus, spec.source_rows, ...
        equivalent_injection);
    injection_results = runpf(injection_case, mpoption( ...
        'verbose', 0, 'out.all', 0, 'pf.enforce_q_lims', 0));

    zero_case = build_local_case(source_results, local_bus, ...
        spec.boundary_bus, spec.interior_bus, spec.source_rows, ...
        zeros(numel(spec.interior_bus), 1));
    zero_results = runpf(zero_case, mpoption( ...
        'verbose', 0, 'out.all', 0, 'pf.enforce_q_lims', 0));

    rows = row_offset + (1:numel(spec.source_rows));
    identity_part = branch_identity_table(source_results, source_phasors, ...
        injection_results, zero_results, physical_part, ...
        raw_branch_row(rows), raw_circuit_id(rows), candidate, ...
        spec.overlay_path_id);
    voltage_part = voltage_table(source_results, injection_results, ...
        zero_results, candidate, cumulative_report.bus_map, local_bus, ...
        spec.boundary_bus, spec.overlay_path_id);
    if p == 1
        identity = identity_part;
        omitted = omitted_part;
        voltages = voltage_part;
    else
        identity = [identity; identity_part]; %#ok<AGROW>
        omitted = [omitted; omitted_part]; %#ok<AGROW>
        voltages = [voltages; voltage_part]; %#ok<AGROW>
    end
    path_results(p).overlay_path_id = spec.overlay_path_id;
    path_results(p).injection_results = injection_results;
    path_results(p).zero_injection_results = zero_results;
    row_offset = row_offset + numel(spec.source_rows);
end

[operator_validation, operator_status] = ...
    optional_operator_validation(candidate);
gates = gate_ledger(source_results, path_results, identity, omitted, ...
    voltages, phase1a_report_exact, phase1a_rows_exact, ...
    candidate_fail_closed, operator_status);
all_mandatory_pass = all(gates.pass(gates.mandatory));

files = struct( ...
    'local_identity', fullfile(options.output_dir, ...
        's13_phase1b_local_identity.csv'), ...
    'omitted_injections', fullfile(options.output_dir, ...
        's13_phase1b_local_omitted_injections.csv'), ...
    'terminal_voltages', fullfile(options.output_dir, ...
        's13_phase1b_terminal_voltage_comparison.csv'), ...
    'gate_ledger', fullfile(options.output_dir, ...
        's13_phase1b_gate_ledger.csv'));
if options.write_outputs
    if ~isfolder(options.output_dir)
        error('run_s13_phase1b_local_identity:OutputDirectory', ...
            'Output directory does not exist: %s', options.output_dir);
    end
    ny_lite_writetable_lf(identity, files.local_identity);
    ny_lite_writetable_lf(omitted, files.omitted_injections);
    ny_lite_writetable_lf(voltages, files.terminal_voltages);
    ny_lite_writetable_lf(gates, files.gate_ledger);
end

out = struct( ...
    'pass', all_mandatory_pass, ...
    'source_results', source_results, ...
    'path_results', path_results, ...
    'local_identity', identity, ...
    'omitted_injections', omitted, ...
    'terminal_voltages', voltages, ...
    'gate_ledger', gates, ...
    'phase1a_report_exact_match', phase1a_report_exact, ...
    'phase1a_physical_rows_bit_identical', phase1a_rows_exact, ...
    'candidate_fail_closed', candidate_fail_closed, ...
    'operator_validator_available', operator_status.available, ...
    'operator_mandatory_proxy_pass', operator_status.proxy_pass, ...
    'operator_validation', operator_validation, ...
    'zero_injection_is_gating', false, ...
    'residual_fit_performed', false, ...
    'promotion_performed', false, ...
    'files', files);

if options.verbose
    fprintf(['S13 Phase 1B local identity: %d/%d mandatory gates pass; ' ...
        'direct max P/Q %.3g/%.3g; local max P/Q %.3g/%.3g; ' ...
        'VM/VA %.3g/%.3g.\n'], nnz(gates.pass(gates.mandatory)), ...
        nnz(gates.mandatory), max(identity.direct_max_p_error_mw), ...
        max(identity.direct_max_q_error_mvar), ...
        max(identity.injection_max_p_error_mw), ...
        max(identity.injection_max_q_error_mvar), ...
        max(voltages.injection_vm_error_pu(voltages.terminal_role == ...
            "interior_pq")), ...
        max(voltages.injection_va_error_deg(voltages.terminal_role == ...
            "interior_pq")));
    fprintf(['  Zero-injection truncations are diagnostic only: max ' ...
        'VM/VA errors %.4g pu / %.4g deg.\n'], ...
        max(voltages.zero_injection_vm_error_pu), ...
        max(voltages.zero_injection_va_error_deg));
end

if options.fail_on_gate && ~all_mandatory_pass
    failed = gates.gate_id(gates.mandatory & ~gates.pass);
    error('run_s13_phase1b_local_identity:GateFailure', ...
        'Mandatory Phase 1B local-identity gates failed: %s', ...
        strjoin(cellstr(failed), ', '));
end
end

