    "f6ba2d787a4f22fcb7ae9f597cdd3111500d79921829a245d50e516c47e209ca";
contract.generator_classes=table(["original_NPCC_generation_aggregate";"S4_P_only_equivalent"], ...
    [21;14],["inherited_S7_aggregate_P_bounds_and_wide_Q_benchmark_envelope";"inherited_S7_active_power_equivalent_zero_Q"], ...
    ["assumed_benchmark_aggregate_not_verified_machine_capability";"assumed_active_power_equivalent_not_a_physical_unit"], ...
    false(2,1),'VariableNames',{'record_class','record_count','control_and_limit_interpretation', ...
    'evidence_scope','physical_machine_capability_verified'});
