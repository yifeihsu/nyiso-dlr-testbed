    "inherited_NPCC_nonthermal_equivalent";"fixed_boundary_PQ_record"],false(4,1), ...
    ["overhead_or_cable_realization_unverified";"transformer_not_an_overhead_conductor"; ...
     "aggregate_current_is_not_an_individual_conductor_current";"injection_record_is_not_a_thermal_branch"], ...
    'VariableNames',{'asset_class','thermal_eligible','thermal_exclusion_reason'});
