    "At most 200 NY buses with all 46 original NPCC NY buses and only registered focused corridor changes"; ...
    "Matched benchmark load and boundary snapshot with each injection counted once"; ...
    "Explicit aggregate versus source-circuit roles and no unresolved double-counted active path"; ...
    "AC balance voltage ratings angle and declared benchmark P/Q envelopes audited including reference adjustment"; ...
    "Independent fixed-input replay without optimizer use or hidden load/capability changes"];
