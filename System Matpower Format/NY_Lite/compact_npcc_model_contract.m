function contract=compact_npcc_model_contract(candidate)
%COMPACT_NPCC_MODEL_CONTRACT Small NY-only benchmark with selected corridors.
% Independent of research_model_contract: no earlier historical contract or
% large regional reference changes meaning. A contract never qualifies PF.
% Optional candidate input checks the size/identity policy only.
contract=struct('schema_version',1,'model_role',"compact_NPCC_NY_electrical_testbed", ...
    'case_name',"npcc_ny_compact_dlr_testbed", ...
    'operating_network',"NY_only_with_fixed_boundary_PQ", ...
    'backbone_policy',"retain_original_NPCC_NY_backbone_with_selected_source_corridor_detail", ...
    'max_operating_bus_count',200,'planned_operating_bus_count',51, ...
    'planned_operating_branch_records',92,'planned_operating_active_branches',87, ...
    'planned_operating_generator_records',35,'original_NPCC_NY_bus_count',46, ...
    'planned_full_construction_bus_count',145,'planned_full_construction_branch_records',257, ...
    'planned_full_construction_active_branches',252, ...
    'power_base_mva',100,'power_scale',"NPCC_benchmark_MW", ...
    'gross_ny_benchmark_load_mw',10902.2198, ...
    'load_evidence_class',"assumed_inherited_NPCC_benchmark", ...
    'source_vintage',"NPCC_benchmark_with_selected_PERFORM_2019_corridors", ...
    'allow_automatic_PERFORM_regional_expansion',false, ...
    'allow_wholesale_PERFORM_operating_network_substitution',false, ...
    'allow_dense_Kron_network_as_operating_backbone',false, ...
    'preserve_original_NPCC_NY_buses',true,'preserve_historical_cases',true, ...
    'large_878_bus_candidate_role',"optional_historical_electrical_reference", ...
    'boundary_source',"matched_NPCC_benchmark_reference", ...
    'boundary_evidence_class',"reproduced_benchmark_snapshot_assumed_fixed_boundary", ...
    'boundary_control',"fixed_delivered_P_and_Q_at_NY_landings", ...
    'boundary_sign_convention',"positive_into_NY", ...
    'use_PERFORM_20_exchange_schedule_for_this_case',false, ...
    'allow_boundary_slack_or_voltage_control',false, ...
    'allow_synthetic_observations',false,'allow_assumed_research_baseline',true, ...
    'thermal_model_implemented',false,'electrical_baseline_qualified',false, ...
    'contemporary_validation_coverage',"not_claimed_benchmark",'dlr_ready',false, ...
    'physical_generator_capability_validated',false,'release_ready',false, ...
    'generator_capability_source',"inherited_S7_benchmark_including_existing_S4_changes", ...
    'structure_checked',false,'checked_operating_bus_count',NaN, ...
    'structure_check_scope',"bus_budget_and_original_bus_identity_only");
contract.original_NPCC_NY_bus_ids=(37:82)';
contract.construction_parent="S7_with_Phase0_rating_corrections";
contract.automatic_overlay_phases_excluded=["Phase1A_E_G";"Phase1C_downstate_mesh"];
contract.retained_parent_branch_rows=(1:246)';
contract.parent_branch_rows_deactivated=[88;89;94;235;236];
contract.selected_source_branch_rows=[1389;1390;1391;1392;1689;1690;1734;1735;1577;1576;1738];
contract.selected_corridor_groups=[repmat("Pleasant_Valley_EFishkill_Wood_Street_Millwood",8,1); ...
    repmat("Ramapo_Ladentown_Buchanan",3,1)];
