if nargin>0
    assert(isstruct(candidate)&&isfield(candidate,'bus')&&isnumeric(candidate.bus) && ...
        size(candidate.bus,2)>=1,'compact_npcc_model_contract:Candidate','A MATPOWER bus matrix is required.');
    ids=candidate.bus(:,1);count=numel(ids);
    assert(count<=contract.max_operating_bus_count,'compact_npcc_model_contract:BusLimit', ...
        'The compact operating case exceeds the hard 200-bus ceiling.');
    assert(all(isfinite(ids)&ids==fix(ids)&ids>0)&&numel(unique(ids))==count, ...
        'compact_npcc_model_contract:BusIdentity','Candidate bus IDs must be finite, positive, unique integers.');
    assert(all(ismember(contract.original_NPCC_NY_bus_ids,ids)), ...
        'compact_npcc_model_contract:OriginalNYBuses','All 46 original NPCC NY bus IDs must remain.');
    contract.structure_checked=true;contract.checked_operating_bus_count=count;
end
end
