function outputs = build_ny_voltage_reference_sets(options)
%BUILD_NY_VOLTAGE_REFERENCE_SETS Build auditable voltage-control references.
%   Separates original NPCC VG fields, S1 OPF-solved voltage references,
%   current S7 model values, provisional PERFORM zonal aggregates, and
%   scenario boundary-equivalent references.

if nargin < 1, options = struct(); end
helper_dir = fileparts(mfilename('fullpath'));
case_dir = fileparts(helper_dir);
workspace_dir = fileparts(case_dir);
addpath(case_dir); addpath(helper_dir);
options = defaults(options, helper_dir, workspace_dir);
define_constants;

model = attach_nyiso_zone_metadata(loadcase(options.structural_case));
original = loadcase(options.original_case);
s1 = loadcase(options.s1_case);

references = table();
references = append_table(references, case_reference_rows(model, original, ...
    "ORIGINAL_NPCC_VG_REFERENCE", "original_npcc_vg_field", ...
    "npcc_original", "Original NPCC generator matrix VG", "unknown", ...
    "medium", "same retained bus number"));
references = append_table(references, case_reference_rows(model, s1, ...
    "S1_OPF_SOLVED_REFERENCE", "numerical_continuation_reference", ...
    "npcc_ny_lite_s1_acopf_feasible_uncalibrated", ...
    "S1 ACOPF result saved with opf.use_vg = 0", "S1 build", ...
    "high numerical; low physical", "same retained bus number"));
references = append_table(references, case_reference_rows(model, model, ...
    "CURRENT_S7_MODEL_REFERENCE", "current_model_vg_field", ...
    options.structural_case, "Current S7 generator matrix VG", "current", ...
    "high numerical; mixed provenance", "current model bus aggregation"));

[perform_rows, perform_zone_summary, perform_controls, perform_control_coverage, ...
    perform_classification_summary] = ...
    perform_reference_rows(model, options);
references = append_table(references, perform_rows);
boundary_rows = boundary_reference_rows(model, options);
references = append_table(references, boundary_rows);
references = sortrows(references, {'reference_set','model_bus'});

provenance = s1_provenance_rows(original, s1);
coverage = coverage_rows(model, references);
writetable(references, options.reference_file);
writetable(coverage, options.coverage_file);
writetable(provenance, options.s1_provenance_file);
writetable(perform_zone_summary, options.perform_zone_file);
writetable(perform_controls, options.perform_control_file);
writetable(perform_control_coverage, options.perform_control_coverage_file);
writetable(perform_classification_summary, ...
    options.perform_classification_summary_file);

outputs = struct('reference_file', options.reference_file, ...
    'coverage_file', options.coverage_file, ...
    's1_provenance_file', options.s1_provenance_file, ...
    'perform_zone_file', options.perform_zone_file, ...
    'perform_control_file', options.perform_control_file, ...
    'perform_control_coverage_file', options.perform_control_coverage_file, ...
    'perform_classification_summary_file', ...
    options.perform_classification_summary_file, ...
    'references', references, 'coverage', coverage, ...
    's1_provenance', provenance, 'perform_zone_summary', perform_zone_summary, ...
    'perform_controls', perform_controls, ...
    'perform_control_coverage', perform_control_coverage, ...
    'perform_classification_summary', perform_classification_summary);
end

