function rows = case_reference_rows(model, source, set_name, control_type, ...
        source_case, source_description, effective_date, confidence, mapping)
define_constants;
model = attach_nyiso_zone_metadata(model);
model_bus_ids = ny_generator_buses(model);
rows = table();
for k = 1:numel(model_bus_ids)
    bus_id = model_bus_ids(k);
    source_idx = find(source.gen(:, GEN_STATUS) > 0 & source.gen(:, GEN_BUS) == bus_id);
    if isempty(source_idx), continue; end
    weights = max(0, source.gen(source_idx, PMAX));
    if sum(weights) <= 0, weights = ones(numel(source_idx), 1); end
    weights = weights / sum(weights);
    vg = source.gen(source_idx, VG);
    source_record = source_description + "; generator rows " + ...
        join(string(source_idx(:)'), "|");
    rows = append_table(rows, reference_row(model, set_name, bus_id, ...
        sum(weights .* vg), min(vg), max(vg), control_type, source_case, ...
        source_record, effective_date, confidence, mapping, ...
        "MATPOWER VG is a local field; remote regulated-bus assignment is not encoded."));
end
end

function [rows, zone_summary, controls, control_coverage, ...
        classification_summary] = ...
        perform_reference_rows(model, options)
define_constants;
addpath(options.perform_case_dir);
perform = nyiso_On_Peak_v23_shunts_as_z_load;
mapping = readtable(fullfile(options.perform_aux_dir, ...
    'internal_NYISO_MOD2MAP.xlsx'), 'Sheet', 'BUS SUB', ...
    'VariableNamingRule', 'preserve');
control_metadata_file = fullfile(options.perform_case_dir, ...
    'GenCostTable4MATPOWERv23_ShuntsNotShown.csv');
control_import = detectImportOptions(control_metadata_file, ...
    'VariableNamingRule', 'preserve');
control_import = setvartype(control_import, 'GenID', 'string');
control_metadata = readtable(control_metadata_file, control_import);
[controls, control_coverage] = extract_perform_voltage_controls( ...
    options.perform_raw_file, options.perform_raw_source_id, mapping, perform, ...
    control_metadata);
classification_summary = classification_summary_rows(controls);
bus_zone = perform_nyiso_zone_letters(perform, perform.bus(:, BUS_I));
[gen_mapped, gen_bus_idx] = ismember(perform.gen(:, GEN_BUS), perform.bus(:, BUS_I));
gen_zone = strings(size(perform.gen, 1), 1);
gen_zone(gen_mapped) = bus_zone(gen_bus_idx(gen_mapped));
gen_fuel = lower(strtrim(string(perform.genfuel(:))));
native = perform.gen(:, GEN_STATUS) > 0 & gen_zone ~= "" & ...
    ~ismember(gen_fuel, ["import", "reference"]);

zone_summary = table();
for zone = string(('A':'K')')'
    idx = find(native & gen_zone == zone);
    if isempty(idx), continue; end
    weights = max(0, perform.gen(idx, PMAX));
    if sum(weights) <= 0, weights = ones(numel(idx), 1); end
    weights = weights / sum(weights);
    vg = perform.gen(idx, VG);
    row = table(zone, numel(idx), sum(perform.gen(idx, PMAX)), ...
        sum(weights .* vg), min(vg), max(vg), ...
        'VariableNames', {'zone','online_native_generator_count', ...
        'online_native_pmax_mw','pmax_weighted_vg_pu','min_vg_pu','max_vg_pu'});
    zone_summary = append_table(zone_summary, row);
end

for k = 1:height(zone_summary)
    ci = find(control_coverage.zone == zone_summary.zone(k), 1);
    if isempty(ci)
        zone_summary.raw_online_control_count(k, 1) = 0;
        zone_summary.raw_remote_regulation_count(k, 1) = 0;
        zone_summary.raw_missing_regulated_bus_count(k, 1) = 0;
    else
        zone_summary.raw_online_control_count(k, 1) = ...
            control_coverage.online_generator_count(ci);
        zone_summary.raw_remote_regulation_count(k, 1) = ...
            control_coverage.remote_regulation_count(ci);
        zone_summary.raw_missing_regulated_bus_count(k, 1) = ...
            control_coverage.missing_regulated_bus_count(ci);
    end
end

model = attach_nyiso_zone_metadata(model);
model_bus_ids = ny_generator_buses(model);
rows = table();
for k = 1:numel(model_bus_ids)
    bus_id = model_bus_ids(k);
    bi = find(model.bus(:, BUS_I) == bus_id, 1);
    zone = string(model.userdata.nyiso_physical_zone{bi});
    zi = find(zone_summary.zone == zone, 1);
    if isempty(zi), continue; end
    row = reference_row(model, ...
        "PERFORM_ZONE_AGGREGATE_REFERENCE", bus_id, ...
        zone_summary.pmax_weighted_vg_pu(zi), zone_summary.min_vg_pu(zi), ...
        zone_summary.max_vg_pu(zi), "provisional_zonal_vg_envelope", ...
        "PERFORM NYISO On Peak 2019 v23", ...
        "Native online generators in zone " + zone + ...
        "; PMAX-weighted converted VG with observed zonal min/max envelope", ...
        "2019 on-peak snapshot", "low", ...
        "NYISO-zone aggregate mapped to retained model bus", ...
        "RAW VS/IREG controls are extracted separately; this zonal aggregate does not preserve individual remote regulation in the reduced mapping.");
    row.remote_regulation_flag = "source_available_not_preserved_by_zonal_aggregate";
    rows = append_table(rows, row);
end
end

function [controls, coverage] = extract_perform_voltage_controls( ...
        raw_file, raw_source_id, ~, converted, control_metadata)
% Preserve source VS/IREG controls that are omitted by MATPOWER conversion.
define_constants;
[records, sections] = psse_read(raw_file, 0);
[data, warns] = psse_parse(records, sections, 0, 33); %#ok<ASGLU>
g = data.gen.num;
gt = data.gen.txt;

source_bus = g(:, 1);
generator_id = strip(erase(string(gt(:, 2)), "'"));
pg_mw = g(:, 3);
qg_mvar = g(:, 4);
qmax_mvar = g(:, 5);
qmin_mvar = g(:, 6);
voltage_target_pu = g(:, 7);
raw_ireg = str2double(string(gt(:, 8)));
raw_ireg(isnan(raw_ireg)) = 0;
status = g(:, 15);
pmax_mw = g(:, 17);
pmin_mw = g(:, 18);

regulated_bus = source_bus;
remote_mask = raw_ireg ~= 0;
regulated_bus(remote_mask) = abs(round(raw_ireg(remote_mask)));

source_zone = perform_nyiso_zone_letters(converted, source_bus);
regulated_zone = perform_nyiso_zone_letters(converted, regulated_bus);

raw_bus_id = data.bus.num(:, 1);
raw_bus_name = strip(erase(string(data.bus.txt(:, 2)), "'"));
[source_bus_found, source_bus_idx] = ismember(source_bus, raw_bus_id);
[regulated_bus_found, regulated_bus_idx] = ismember(regulated_bus, raw_bus_id);
source_bus_name = strings(size(source_bus));
regulated_bus_name = strings(size(source_bus));
source_bus_name(source_bus_found) = raw_bus_name(source_bus_idx(source_bus_found));
regulated_bus_name(regulated_bus_found) = raw_bus_name(regulated_bus_idx(regulated_bus_found));

remote_regulation = regulated_bus ~= source_bus;
mapped_to_nyiso_zone = ismember(source_zone, string(('A':'K')'));
source_id = string(strrep(char(raw_source_id), '\', '/'));

is_qs_record = upper(strtrim(generator_id)) == "QS";
converted_gen_index = nan(size(source_bus));
converted_genfuel = strings(size(source_bus));
converted_fuel = lower(strtrim(string(converted.genfuel(:))));
if height(control_metadata) ~= size(converted.gen, 1) || ...
        any(double(control_metadata.GEN_BUS) ~= converted.gen(:, GEN_BUS))
    error('PERFORM generator metadata is not aligned with the converted case.');
end
metadata_id = upper(strtrim(string(control_metadata.GenID)));
raw_id = upper(strtrim(generator_id));
mapped_converted = false(size(converted.gen, 1), 1);
for r = find(~is_qs_record(:))'
    converted_row = find(double(control_metadata.GEN_BUS) == source_bus(r) & ...
        metadata_id == raw_id(r));
    if numel(converted_row) ~= 1
        error(['PERFORM RAW generator key (%g, %s) maps to %d converted ' ...
            'metadata rows; expected exactly one.'], source_bus(r), raw_id(r), ...
            numel(converted_row));
    end
    converted_gen_index(r) = converted_row;
    converted_genfuel(r) = converted_fuel(converted_row);
    mapped_converted(converted_row) = true;
end
if ~all(mapped_converted) || ...
        sum(isfinite(converted_gen_index)) ~= size(converted.gen, 1)
    error('PERFORM RAW-to-converted generator mapping is not one-to-one.');
end
converted_status = nan(size(status));
non_qs = isfinite(converted_gen_index);
converted_status(non_qs) = converted.gen(converted_gen_index(non_qs), GEN_STATUS);
snapshot_effective_status = status;
snapshot_effective_status(non_qs) = converted_status(non_qs);
raw_converted_status_mismatch = non_qs & status ~= converted_status;

tol = 1e-6;
online = status > 0;
positive_active_capability = online & pmax_mw > tol;
zero_active_capability = online & abs(pmax_mw) <= tol & abs(pmin_mw) <= tol;
fixed_negative_active = online & pmax_mw < -tol & ...
    abs(pmax_mw - pmin_mw) <= tol;
reactive_only_qs = online & is_qs_record & zero_active_capability & ...
    qmax_mvar - qmin_mvar > tol;
fuel_boundary = ismember(converted_genfuel, ["import", "reference"]);
% Boundary/reference classification has precedence over storage heuristics.
% In particular, the PERFORM Marcy RF record has a negative-to-positive P
% range but is a reference-balance equivalent, not a physical storage unit.
storage_or_pumping = online & ~fuel_boundary & ...
    (contains(converted_genfuel, "storage") | ...
    contains(converted_genfuel, "pump") | (pmin_mw < -tol & pmax_mw > tol));
fixed_import_or_boundary_equivalent = online & ...
    (fixed_negative_active | fuel_boundary);
synchronous_condenser = online & ~is_qs_record & zero_active_capability & ...
    qmax_mvar - qmin_mvar > tol & ~fuel_boundary;
native_generator = online & positive_active_capability & ...
    ~fixed_import_or_boundary_equivalent & ~storage_or_pumping;
offline = ~online;

device_class = repmat("unclassified_generator_section_record", size(source_bus));
device_class(offline) = "offline";
device_class(online & native_generator) = "native_generator";
device_class(online & synchronous_condenser) = "synchronous_condenser";
device_class(online & storage_or_pumping) = "storage_or_pumping";
device_class(online & fixed_import_or_boundary_equivalent) = ...
    "fixed_import_or_boundary_equivalent";
device_class(online & reactive_only_qs) = "reactive_only_QS";

classification_rule = repmat("manual_review_required", size(source_bus));
classification_confidence = repmat("low", size(source_bus));
classification_rule(offline) = "RAW STAT is offline";
classification_confidence(offline) = "high";
classification_rule(native_generator) = ...
    "positive PMAX and converted fuel is not import/reference";
classification_confidence(native_generator) = "medium";
classification_rule(synchronous_condenser) = ...
    "zero P range with nonzero Q range and ID is not QS";
classification_confidence(synchronous_condenser) = "medium";
classification_rule(storage_or_pumping) = ...
    "negative-to-positive P range or storage/pump fuel label";
classification_confidence(storage_or_pumping) = "medium";
classification_rule(fixed_import_or_boundary_equivalent) = ...
    "converted import/reference fuel or fixed negative P";
classification_confidence(fixed_import_or_boundary_equivalent) = "high";
classification_rule(reactive_only_qs) = ...
    "ID QS with zero P capability and nonzero Q range";
classification_confidence(reactive_only_qs) = "high";
control_group_id = source_zone + "_REG_BUS_" + string(regulated_bus);
control_group_id(source_zone == "") = ...
    "UNMAPPED_REG_BUS_" + string(regulated_bus(source_zone == ""));

controls = table(source_bus, source_bus_name, generator_id, source_zone, ...
    pg_mw, qg_mvar, qmin_mvar, qmax_mvar, pmin_mw, pmax_mw, ...
    voltage_target_pu, raw_ireg, regulated_bus, regulated_bus_name, ...
    regulated_zone, remote_regulation, regulated_bus_found, status, ...
    converted_status, snapshot_effective_status, raw_converted_status_mismatch, ...
    mapped_to_nyiso_zone, converted_gen_index, converted_genfuel, ...
    device_class, native_generator, reactive_only_qs, ...
    fixed_import_or_boundary_equivalent, synchronous_condenser, ...
    storage_or_pumping, offline, positive_active_capability, ...
    fixed_negative_active, is_qs_record, control_group_id, ...
    classification_rule, classification_confidence, ...
    repmat("PERFORM PSS/E RAW rev33", size(source_bus)), ...
    repmat(source_id, size(source_bus)), ...
    'VariableNames', {'source_bus','source_bus_name','generator_id','source_zone', ...
    'pg_mw','qg_mvar','qmin_mvar','qmax_mvar','pmin_mw','pmax_mw', ...
    'voltage_target_pu','raw_ireg','regulated_bus','regulated_bus_name', ...
    'regulated_zone','remote_regulation','regulated_bus_found','status', ...
    'converted_status','snapshot_effective_status','raw_converted_status_mismatch', ...
    'mapped_to_nyiso_zone','converted_gen_index','converted_genfuel', ...
    'device_class','native_generator','reactive_only_QS', ...
    'fixed_import_or_boundary_equivalent','synchronous_condenser', ...
    'storage_or_pumping','offline','positive_active_capability', ...
    'fixed_negative_active','originated_from_shunt_as_generator_conversion', ...
    'control_group_id','classification_rule','classification_confidence', ...
    'source_format','source_file'});

coverage = table();
for zone = string(('A':'K')')'
    zi = controls.source_zone == zone & controls.status > 0;
    row = table(zone, sum(zi), sum(zi & controls.remote_regulation), ...
        sum(zi & ~controls.remote_regulation), ...
        sum(zi & ~controls.regulated_bus_found), ...
        sum(controls.pmax_mw(zi)), numel(unique(controls.source_bus(zi))), ...
        sum(zi & controls.reactive_only_QS), ...
        sum(zi & controls.positive_active_capability), ...
        sum(zi & controls.fixed_import_or_boundary_equivalent), ...
        sum(zi & controls.native_generator), ...
        'VariableNames', {'zone','online_generator_count', ...
        'remote_regulation_count','local_regulation_count', ...
        'missing_regulated_bus_count','online_pmax_mw', ...
        'distinct_source_bus_count','reactive_only_qs_count', ...
        'positive_active_capability_count', ...
        'fixed_import_or_boundary_equivalent_count','native_generator_count'});
    coverage = append_table(coverage, row);
end
end

function summary = classification_summary_rows(controls)
online_ak = controls.status > 0 & controls.mapped_to_nyiso_zone;
metrics = [ ...
    "raw_generator_section_records"; ...
    "online_a_k_generator_section_control_records"; ...
    "online_a_k_distinct_source_buses"; ...
    "online_a_k_reactive_only_qs_records"; ...
    "online_a_k_positive_active_capability_records"; ...
    "online_a_k_fixed_negative_active_records"; ...
    "online_a_k_remote_regulation_records"; ...
    "online_a_k_missing_regulated_bus_records"; ...
    "raw_converted_status_mismatch_records"; ...
    "converted_snapshot_online_a_k_control_records"; ...
    "converted_non_qs_mapping_records"];
values = [ ...
    height(controls); ...
    sum(online_ak); ...
    numel(unique(controls.source_bus(online_ak))); ...
    sum(online_ak & controls.reactive_only_QS); ...
    sum(online_ak & controls.positive_active_capability); ...
    sum(online_ak & controls.fixed_negative_active); ...
    sum(online_ak & controls.remote_regulation); ...
    sum(online_ak & ~controls.regulated_bus_found); ...
    sum(controls.raw_converted_status_mismatch); ...
    sum(controls.snapshot_effective_status > 0 & controls.mapped_to_nyiso_zone); ...
    sum(isfinite(controls.converted_gen_index))];
unit = repmat("records", numel(metrics), 1);
unit(3) = "buses";
notes = [ ...
    "All PSS/E RAW generator-section rows"; ...
    "Online records whose source bus maps to NYISO A-K"; ...
    "Distinct source buses among online A-K records"; ...
    "ID QS; zero P capability; nonzero Q range"; ...
    "Positive PMAX; includes native and positive import/reference records"; ...
    "PMIN equals PMAX below zero"; ...
    "IREG points to a nonlocal bus"; ...
    "Regulated bus absent from source RAW bus table"; ...
    "RAW STAT differs from converted MATPOWER GEN_STATUS"; ...
    "Converted-case status for non-QS records; RAW status for QS records"; ...
    "RAW non-QS rows aligned to converted PERFORM gen/genfuel rows"];
summary = table(metrics, values, unit, notes, ...
    'VariableNames', {'metric','value','unit','note'});
end

function rows = boundary_reference_rows(model, options)
