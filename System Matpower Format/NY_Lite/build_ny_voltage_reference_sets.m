end

function row = reference_row(model, set_name, bus_id, reference, ref_min, ...
        ref_max, control_type, source_case, source_record, effective_date, ...
        confidence, mapping, notes)
define_constants;
bi = find(model.bus(:, BUS_I) == bus_id, 1);
if isempty(bi)
    bus_name = "BOUNDARY_BUS_" + string(bus_id);
    zone = "";
else
    bus_name = string(strtrim(model.bus_name{bi}));
    zone = string(model.userdata.nyiso_physical_zone{bi});
end
device_class = "retained_generator_or_aggregate_proxy";
if bus_id == 78
    device_class = "zone_I_interface_voltage_support_proxy";
elseif bus_id >= 9000
    device_class = "added_zero_load_transit_or_supply_proxy";
elseif set_name == "SHOULDER_BOUNDARY_EQUIVALENT_REFERENCE"
    device_class = "external_boundary_equivalent";
end
row = table(string(set_name), "BUS_" + string(bus_id), bus_id, bus_name, ...
    zone, NaN, string(control_type), reference, ref_min, ref_max, ...
    (ref_max - ref_min) / 2, "not_encoded", "available_in_source_snapshot", ...
    string(source_case), string(source_record), string(effective_date), ...
    string(confidence), device_class, string(mapping), string(notes), ...
    'VariableNames', {'reference_set','generator_or_proxy_id','model_bus', ...
    'model_bus_name','model_zone','regulated_bus','control_type', ...
    'voltage_reference_pu','voltage_reference_min_pu', ...
    'voltage_reference_max_pu','voltage_deadband_pu', ...
    'remote_regulation_flag','scenario_status','source_case','source_record', ...
    'effective_date','confidence','device_class','mapping_method','notes'});
end

function rows = s1_provenance_rows(original, s1)
define_constants;
rows = table();
for g = 1:size(s1.gen, 1)
    bus_id = s1.gen(g, GEN_BUS);
    candidates = find(original.gen(:, GEN_BUS) == bus_id);
    if isempty(candidates), continue; end
    if isscalar(candidates)
        source_g = candidates;
    else
        occurrence = sum(s1.gen(1:g, GEN_BUS) == bus_id);
        source_g = candidates(min(occurrence, numel(candidates)));
    end
    original_vg = original.gen(source_g, VG);
    s1_vg = s1.gen(g, VG);
    row = table(g, source_g, bus_id, original_vg, s1_vg, s1_vg - original_vg, ...
        abs(s1_vg - original_vg) > 1e-10, ...
        "S1 saved from ACOPF solved case with opf.use_vg = 0", ...
        'VariableNames', {'s1_gen_index','original_gen_index','bus_id', ...
        'original_npcc_vg_pu','s1_saved_vg_pu','delta_vg_pu','changed', ...
        'provenance'});
    rows = append_table(rows, row);
end
end

function coverage = coverage_rows(model, references)
define_constants;
model_buses = ny_generator_buses(attach_nyiso_zone_metadata(model));
coverage = table();
for set_name = unique(references.reference_set, 'stable')'
    rows = references(references.reference_set == set_name, :);
    covered = intersect(model_buses, rows.model_bus);
    missing = setdiff(model_buses, covered);
    ce = rows(rows.model_bus == 78, :);
    ce_reference = NaN;
    ce_class = "not_available";
    if ~isempty(ce)
        ce_reference = ce.voltage_reference_pu(1);
        ce_class = ce.device_class(1);
    end
    row = table(set_name, numel(model_buses), numel(covered), numel(missing), ...
        join(string(missing(:)'), "|"), ce_reference, ce_class, ...
        'VariableNames', {'reference_set','current_model_generator_bus_count', ...
        'covered_bus_count','missing_bus_count','missing_model_bus_ids', ...
        'ce_ug_reference_pu','ce_ug_device_class'});
    coverage = append_table(coverage, row);
end
end

function bus_ids = ny_generator_buses(model)
define_constants;
online_bus_ids = unique(model.gen(model.gen(:, GEN_STATUS) > 0, GEN_BUS), 'stable');
bus_ids = zeros(0, 1);
for k = 1:numel(online_bus_ids)
    bi = find(model.bus(:, BUS_I) == online_bus_ids(k), 1);
    if ~isempty(bi) && string(model.userdata.nyiso_physical_zone{bi}) ~= ""
        bus_ids(end + 1, 1) = online_bus_ids(k); %#ok<AGROW>
    end
end
end

function out = append_table(out, row)
if isempty(row), return; end
if isempty(out), out = row; else, out = [out; row]; end
end
