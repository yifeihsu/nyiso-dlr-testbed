function mpc = npcc_nygrid_2025_western_corrected_dc(hour_index, topology, mode)
%NPCC_NYGRID_2025_WESTERN_CORRECTED_DC Source-corrected western DC reconstruction.
% Default combined: corrected generator locations and NYIS-reported physical
% exchanges for all four neighboring regions, with the frozen bounded source-
% prior generation projection. Individual units are reconstructed, not observed.
% Ontario-only modes retain schedules elsewhere and are diagnostic scenarios.
% Original four DC-device schedules and external P34 PAR targets are retained.
if nargin<1, hour_index=1; end
if nargin<2 || isempty(topology), topology='dated'; end
if nargin<3 || isempty(mode), mode='combined'; end
assert(any(strcmp(topology,{'dated','year_end'})), ...
    'westernCorrection:Topology','Choose dated or year_end.');
modes={'mapping_only','Ontario_actual_only','Ontario_actual_and_mapping', ...
    'all_boundary_actual_only','combined'};
assert(any(strcmp(mode,modes)),'westernCorrection:Mode','Unknown western reconstruction mode.');
mpc=npcc_nygrid_2025_par_controlled_dc(hour_index,topology);
root=fileparts(fileparts(mfilename('fullpath')));
folder=fullfile(root,'output','nygrid_2025_western_audit');
file=fullfile(folder,'replay',[char(topology),'_',char(mode),'.mat']);
assert(isfile(file),'westernCorrection:MissingReplay','Build and validate the selected replay first.');
persistent cached_file cached_signature replay dispatch
info=dir(file);signature=[info.bytes,info.datenum];
if isempty(replay)||~strcmp(cached_file,file)||~isequal(cached_signature,signature)
    replay=load(file,'hour_index','timestamp_utc','qualified','corrected_generator_buses', ...
        'gamma','generation_source','boundary_basis','additional_mapping_repair_used');
    assert(isequal(replay.hour_index(:),(1:8760)'),'westernCorrection:HourAxis','Unexpected hour axis.');
    if strcmp(replay.boundary_basis,'scheduled')
        dispatch=[];
    else
        dispatch=load(fullfile(folder,'dispatch',[char(replay.generation_source),'.mat']), ...
            'hour_index','timestamp_utc','qualified','gen_pg','gamma','native_generator_rows_1based');
        assert(isequal(dispatch.hour_index(:),replay.hour_index(:)) ...
            &&isequal(string(dispatch.timestamp_utc(:)),string(replay.timestamp_utc(:))) ...
            &&isequal(logical(dispatch.qualified(:)),logical(replay.qualified(:))) ...
            &&dispatch.gamma==replay.gamma, ...
            'westernCorrection:DispatchAxis','Replay and dispatch time/quality/scale differ.');
    end
    cached_file=file;cached_signature=signature;
end
assert(logical(replay.qualified(hour_index)),'westernCorrection:UnqualifiedHour', ...
    'An external source is missing, quarantined, or the bounded reconstruction is infeasible.');
assert(replay.gamma==mpc.userdata.nygrid2025.scale_factor_gamma ...
    &&numel(replay.corrected_generator_buses)==size(mpc.gen,1), ...
    'westernCorrection:GeneratorAxis','Replay scale or generator axis changed.');
reference=mpc.bus(mpc.bus(:,2)==3,1);
mpc.gen(:,1)=replay.corrected_generator_buses(:);
if ~isempty(dispatch)
    native=dispatch.native_generator_rows_1based(:);
    assert(isequal(native,(1:1436)'),'westernCorrection:NativeAxis','Unexpected native generator identity axis.');
    external=setdiff((1:size(mpc.gen,1))',native);
    assert(numel(external)==28,'westernCorrection:ExternalAxis','Expected 28 fixed external equivalents.');
    mpc.gen(:,2)=dispatch.gen_pg(hour_index,:)';
    mpc.gen(external,9:10)=repmat(mpc.gen(external,2),1,2);
    mpc.gen(:,8)=(mpc.gen(:,9)>0)|(mpc.gen(:,10)<0);
    mpc.userdata.moses_correction.frozen_unit_PG_and_bounds_preserved=false;
    mpc.userdata.nygrid2025.fixed_external_schedule_equivalents=false;
end
mpc.bus(:,2)=1;
mpc.bus(ismember(mpc.bus(:,1),mpc.gen(mpc.gen(:,8)==1,1)),2)=2;
assert(isscalar(reference)&&any(mpc.gen(:,1)==reference&mpc.gen(:,8)==1), ...
    'westernCorrection:Reference','Corrected reference lacks an active generator.');
mpc.bus(mpc.bus(:,1)==reference,2)=3;
assert(all(isfinite(mpc.gen),'all') ...
    &&all(mpc.gen(:,2)>=mpc.gen(:,10)-1e-8) ...
    &&all(mpc.gen(:,2)<=mpc.gen(:,9)+1e-8), ...
    'westernCorrection:Capacity','Reconstructed generation is nonfinite or exceeds a source bound.');
mpc.userdata.western_correction=struct('mode',mode,'topology',topology, ...
    'boundary_basis',char(replay.boundary_basis), ...
    'source_generation_bus_correction',logical(replay.additional_mapping_repair_used), ...
    'native_generation_reconstructed',~isempty(dispatch), ...
    'native_priors_weights_and_capacity_bounds_preserved',true, ...
    'original_loads_four_DC_schedules_and_PAR_flows_preserved',true, ...
    'fixed_external_exchange_equivalents',true, ...
    'Ontario_only_is_mixed_boundary_basis_diagnostic',strcmp(replay.boundary_basis,'Ontario'), ...
    'individual_Niagara_tie_flows_observed',false, ...
    'Dysinger_East_Stolle_PAR_added',false, ...
    'internal_interface_observations_used_for_fit',false,'DC_only',true);
end
