function mpc = npcc_nygrid_2025_ac(hour_index)
%NPCC_NYGRID_2025_AC Full synthetic AC case on unchanged model power base.
% Engineering study assumptions, not an as-built or historical AC replay.
% All hourly native active-power boxes and six prescribed transfers survive.
% Native Q boxes use hourly admitted capability at assumed0.95PF; external
% boundary equivalents use fixed-P circle slices at finite declared MVA.
% Costs penalize departure from the DC prior and Q use; they are not economic.
% Default hour8508 is a tested post-Dover snapshot; qualification is per hour.
if nargin<1,hour_index=8508;end
root=fileparts(fileparts(mfilename('fullpath')));
prior=npcc_nygrid_2025_dover_dc(hour_index,'bounded','x_nominal');
mpc=prior;
if prior.userdata.dover.new_parameters_applied
    n=load(fullfile(root,'output','nygrid_2025_dover_parameters','network','x_nominal.mat'));
    c=n.full_case;c.branch(411:412,10)=prior.userdata.dover.bank_shift_model_deg;
else
    n=load(fullfile(root,'output','nygrid_2025_line_parameters','overlays','engineering_nominal','full191_network_cases.mat'));
    c=n.(prior.userdata.slim.network_state);
end
mpc.bus=c.bus;mpc.branch=c.branch;mpc.bus_name=c.bus_name(:);
overlay_file=fullfile(root,'output','nygrid_2025_ac_system','branches','engineering_overlay.mat');
assert(isfile(overlay_file),'AC:MissingOverlay','Build the full synthetic branch-equivalent overlay first.');
overlay=load(overlay_file);
if prior.userdata.dover.new_parameters_applied
    branch_reference=overlay.branch_reference;
else
    branch_reference=overlay.pre_dover_branch_reference;
end
assert(overlay.baseMVA==mpc.baseMVA&&isequal(size(branch_reference),size(mpc.branch)) ...
    &&isequal(branch_reference(:,[1 2 9 12 13]),mpc.branch(:,[1 2 9 12 13])), ...
    'AC:BranchIdentity','Engineering overlay changed branch identities, taps or angle limits.');
branch_keys=overlay.branch_keys(1:size(mpc.branch,1));branch_keys=branch_keys(:);
assert(numel(unique(string(branch_keys)))==size(mpc.branch,1),'AC:BranchKeys','Duplicate branch identity key.');
mpc.branch(:,3:8)=branch_reference(:,3:8);
[found,ix]=ismember(prior.bus(:,1),mpc.bus(:,1));assert(all(found));
mpc.bus(:,3:4)=0;mpc.bus(ix,3:4)=prior.bus(:,3:4);
mpc.branch(211,11)=0; % Existing Ontario controls remain the original2 transfers.
mpc.bus(:,2)=1;mpc.bus(ismember(mpc.bus(:,1),mpc.gen(mpc.gen(:,8)>0,1)),2)=2;
ref=prior.bus(prior.bus(:,2)==3,1);mpc.bus(ismember(mpc.bus(:,1),ref),2)=3;
addpath(fullfile(root,'scripts','nygrid_2025_ac_system','branches'));
[mpc,section_info]=nygrid_ac_apply_sections(mpc,branch_keys);
branch_keys=section_info.branch_keys(:);
mpc.bus(:,12)=min(mpc.bus(:,12),1.05);
mpc.bus(:,13)=max(mpc.bus(:,13),0.95);
assert(all(mpc.bus(:,12)>mpc.bus(:,13)));
mpc.bus(:,8)=min(max(mpc.bus(:,8),mpc.bus(:,13)),mpc.bus(:,12));
mpc.bus(:,9)=0;
mpc.genfuel=mpc.genfuel(:);ng=size(mpc.gen,1);
external=strcmp(mpc.genfuel,'Import');
assert(nnz(external)==28&&all(mpc.gen(external,9)==mpc.gen(external,10)));
p_cap=max(abs(mpc.gen(:,9:10)),[],2);cap=p_cap;online=mpc.gen(:,8)>0;
parent_file=fullfile(root,'output','nygrid_2025_inputs','model','operating_inputs.mat');
parent=load(parent_file,'base_case');
parent_rows=find(strcmp(parent.base_case.genfuel(:),'Import'));
assert(numel(parent_rows)==nnz(external)&&isequal(parent.base_case.gen(parent_rows,1),mpc.gen(external,1)));
% Fixed net dispatch is not installed aggregate capability. The finite
% historical synthetic P bounds provide an explicit static Q-capacity proxy.
cap(external)=max(abs(parent.base_case.gen(parent_rows,9:10)),[],2);
assert(all(p_cap(external)<=cap(external)/.95+1e-8), ...
    'AC:ExternalCapacity','Fixed external schedule exceeds declared apparent-capacity proxy.');
qcap=cap*tan(acos(.95));
% Regional boundary equivalents are finite MVA resources, not individual
% machine PF rectangles. Use their full fixed-P circle slice at unchanged S.
qcap(external)=sqrt(max(0,(cap(external)/.95).^2-prior.gen(external,2).^2));
qcap(~online)=0;
mpc.gen(:,3)=0;mpc.gen(:,4)=qcap;mpc.gen(:,5)=-qcap;
[found,gb]=ismember(mpc.gen(:,1),mpc.bus(:,1));assert(all(found));
mpc.gen(:,6)=mpc.bus(gb,8);
mpc.gen(:,7)=max(cap/.95,1); % Finite declared per-row machine base, not telemetry.
p_weight=1./max(p_cap,1);q_weight=.01./max(qcap,1);
mpc.gencost=[2*ones(ng,1),zeros(ng,2),3*ones(ng,1),p_weight, ...
    -2*p_weight.*prior.gen(:,2),p_weight.*prior.gen(:,2).^2; ...
    2*ones(ng,1),zeros(ng,2),3*ones(ng,1),q_weight,zeros(ng,2)];
assert(isequal(mpc.gen(:,[1 2 8 9 10]),prior.gen(:,[1 2 8 9 10])));
assert(isequal(mpc.dcline,prior.dcline)&&mpc.baseMVA==100);
mpc.userdata=struct('source_dc',prior.userdata,'ac_system',struct( ...
    'version','synthetic_ac_v1','modeltype','bounded_synthetic_AC','hour_index',hour_index, ...
    'timestamp_utc',prior.userdata.nygrid2025.timestamp_utc, ...
    'gamma',prior.userdata.nygrid2025.scale_factor_gamma, ...
    'power_and_impedance_rescaling_applied',false,'baseMVA',mpc.baseMVA, ...
    'power_scale','synthetic_existing_gamma_scaled_injections','current_gamma_lift',false, ...
    'full_network_not_Schur',true,'as_built_equivalence_claimed',false, ...
    'inherited_DC_interface_operators_valid_for_this_case',false, ...
    'branch_keys',{branch_keys},'branch_parameter_overlay_sha256',file_sha256(overlay_file), ...
    'branch_parameter_overlay_file',overlay_file, ...
    'branch_overlay_metadata',overlay.metadata, ...
    'sectioned_design_status',section_info.status,'sectioned_design_construction_checked',section_info.design_passed, ...
    'line_design_receipt_sha256',section_info.design_receipt_sha256, ...
    'sectioned_design_plan_sha256',section_info.design_plan_sha256, ...
    'branch_parent_row',section_info.branch_parent_row, ...
    'generator_q_policy','native_hourly_admitted_max_abs_P_bound_times_tan_acos_0p95', ...
    'generator_reactive_policy_version','native_PF_rectangle_external_boundary_MVA_circle_v2', ...
    'generator_capability_policy_sha256',file_sha256(fullfile(root,'output','nygrid_2025_ac_system','ac_validation','generator_capability_policy.json')), ...
    'external_reactive_policy','regional_boundary_MVA_equivalent_full_fixed_P_apparent_power_circle_slice', ...
    'external_Q_uses_complete_fixed_P_apparent_power_circle_slice',true, ...
    'external_S_proxy_enlarged_when_Q_policy_changed',false, ...
    'external_capacity_is_engineering_model_proxy_not_observed_nameplate',true, ...
    'external_parent_generator_rows',parent_rows,'external_current_generator_rows',find(external), ...
    'external_capacity_source_file',parent_file,'external_capacity_source_sha256',file_sha256(parent_file), ...
    'offline_reactive_support_allowed',false,'assumed_power_factor',.95, ...
    'GEN_STATUS_is_DC_availability_admission_not_observed_commitment',true, ...
    'physical_unit_commitment_and_generator_D_curves_validated',false, ...
    'generator_p_reference',prior.gen(:,2),'generator_capability_reference',cap, ...
    'generator_q_cap',qcap,'generator_assumed_s_cap',cap/.95, ...
    'p_objective_weight',p_weight,'q_objective_weight',q_weight, ...
    'economic_dispatch_claimed',false,'external_generator_mask',external, ...
    'voltage_limits_pu',[.95 1.05],'fixed_six_transfers_preserved',true, ...
    'fixed_external_P_is_generator_injection_not_loss_corrected_regional_interchange',true, ...
    'generator_active_bounds_preserved',true,'native_generation_supplies_losses',true, ...
    'engineering_branch_overlay_applied',true,'thermal_constraints_applied',false, ...
    'AC_feasibility_validated',false,'AC_thermal_feasibility_validated',false));
mpc.userdata.ac_sections=section_info;
if iscell(section_info.thermal_segments),section_info.thermal_segments=[section_info.thermal_segments{:}];end
mpc.userdata.ac_system.thermal_segments=struct2table(section_info.thermal_segments);
if iscell(section_info.cable_segments),section_info.cable_segments=[section_info.cable_segments{:}];end
mpc.userdata.ac_system.cable_segments=struct2table(section_info.cable_segments);
assert(size(section_info.terminal_current_limit_A,1)==size(mpc.branch,1) ...
    &&size(section_info.terminal_current_limit_A,2)==2, ...
    'AC:TerminalLimits','Missing per-terminal hardware current-limit matrix.');
amps=section_info.terminal_current_limit_A;
terminal_rows=find(mpc.branch(:,11)>0&any(isfinite(amps)&amps>0,2));
terminal_limits=table(terminal_rows,amps(terminal_rows,1),amps(terminal_rows,2), ...
    'VariableNames',{'branch_row','total_terminal_current_limit_from_a','total_terminal_current_limit_to_a'});
addpath(fullfile(root,'scripts','nygrid_2025_ac_system','thermal'));
addpath(fullfile(root,'System Matpower Format','NY_Lite'));
mpc=add_ac_terminal_current_limits(mpc,terminal_limits);
amps=section_info.static_cable_current_limit_A;
assert(isequal(size(amps),[size(mpc.branch,1) 2]),'AC:CableLimits','Cable current-limit matrix shape changed.');
cable_rows=find(mpc.branch(:,11)>0&any(isfinite(amps)&amps>0,2));
cable_limits=table(cable_rows,amps(cable_rows,1),amps(cable_rows,2), ...
    'VariableNames',{'branch_row','total_terminal_current_limit_from_a','total_terminal_current_limit_to_a'});
mpc=add_ac_terminal_current_limits(mpc,cable_limits,'cable_section_static_ampacity');
end

function digest=file_sha256(path)
engine=java.security.MessageDigest.getInstance('SHA-256');fid=fopen(path,'rb');assert(fid>=0);cleanup=onCleanup(@()fclose(fid));
while ~feof(fid),bytes=fread(fid,1048576,'*uint8');if ~isempty(bytes),engine.update(typecast(bytes,'int8'));end,end
raw=typecast(engine.digest(),'uint8');digest=lower(reshape(dec2hex(raw,2)',1,[]));
end
