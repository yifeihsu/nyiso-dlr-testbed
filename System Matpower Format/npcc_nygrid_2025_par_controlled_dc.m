function mpc = npcc_nygrid_2025_par_controlled_dc(hour_index, topology)
%NPCC_NYGRID_2025_PAR_CONTROLLED_DC Direction-verified external PAR-flow replay.
% Two ideal lossless PAR transfer equivalents use the dcline container. They
% are NOT new physical HVDC links or a simulation of measured physical taps.
% The original branch211 stays as a provenance record, inactive only because
% its transfer is represented by the two source-identified controlled ports.
% Each input passes the nominal300MVA-derived |P| screen. UnknownQ, actual tap
% states and emergency envelopes prevent complete hardware-feasibility claims.
if nargin<1, hour_index=1; end
if nargin<2 || isempty(topology), topology='dated'; end
assert(any(strcmp(topology,{'dated','year_end'})), ...
    'nygridPAR:Topology','Choose dated or year_end.');
mpc=npcc_nygrid_2025_moses_corrected_dc(hour_index,'hydro_zone_corrected',topology);
root=fileparts(fileparts(mfilename('fullpath')));
file=fullfile(root,'output','nygrid_2025_par_controls','replay', ...
    [char(topology),'_verified_PAR_flows.mat']);
assert(isfile(file),'nygridPAR:MissingArtifact','Build and validate the source-controlled replay first.');
persistent cached_file cached_signature r
info=dir(file);signature=[info.bytes,info.datenum];
if isempty(r)||~strcmp(cached_file,file)||~isequal(cached_signature,signature)
    r=load(file,'hour_index','qualified','par_transfer_model_mw', ...
        'corrected_generator_buses','gamma','ptids','necessary_p_only_limits_model_mw');
    assert(isequal(r.hour_index(:),(1:8760)')&&isequal(r.ptids(:),[25118;25119]), ...
        'nygridPAR:Axes','Unexpected physical-hour or device identity axis.');
    cached_file=file;cached_signature=signature;
end
assert(logical(r.qualified(hour_index)),'nygridPAR:UnqualifiedHour', ...
    'An original or per-device control source is missing or outside its necessary P-only envelope.');
assert(isequal(mpc.gen(:,1),r.corrected_generator_buses(:)), ...
    'nygridPAR:GeneratorAxis','The confirmed hydro repair differs from this replay.');
target=r.par_transfer_model_mw(hour_index,:)';
envelope=r.necessary_p_only_limits_model_mw(:);
assert(isfinite(r.gamma)&&r.gamma==mpc.userdata.nygrid2025.scale_factor_gamma ...
    &&all(isfinite(envelope))&&all(envelope>0)&&all(abs(envelope-300*r.gamma)<1e-9), ...
    'nygridPAR:EnvelopeMetadata','Device envelope or power scale differs from the verified source.');
assert(all(isfinite(target))&&all(abs(target)<=envelope+1e-9), ...
    'nygridPAR:Envelope','Invalid control target; source measurements are never clipped.');
assert(isequal(mpc.branch(211,1:2),[48 100])&&mpc.branch(211,11)==1, ...
    'nygridPAR:BranchIdentity','Expected the active original Moses-Ontario equivalent.');
assert(size(mpc.dcline,1)==4&&size(mpc.dcline,2)==17, ...
    'nygridPAR:DCIdentity','Expected exactly four original source DC records.');
mpc.branch(211,11)=0;
added=zeros(2,17);
added(:,1:3)=repmat([100 48 1],2,1);
added(:,4:5)=repmat(target,1,2);
added(:,8:9)=1;
added(:,10:11)=repmat(target,1,2);
mpc.dcline=[mpc.dcline;added];
mpc.userdata.par_controls=struct( ...
    'ptids',[25118;25119],'kind','ideal_PAR_controlled_transfer_equivalents', ...
    'source','NYISO P-34 observed external PAR flows', ...
    'positive_source_direction','Ontario St. Lawrence toward New York Moses', ...
    'sign_convention_effective','2024-12-03','represented_from_bus',100,'represented_to_bus',48, ...
    'original_passive_branch',211,'passive_status_change_is_representation_substitution',true, ...
    'passive_status_change_is_physical_outage',false, ...
    'logical_original_branch211_flow_model_mw',-sum(target), ...
    'nominal_device_mva',[300;300],'necessary_p_only_limit_model_mw',envelope, ...
    'hardware_no_load_phase_design_range_deg',[-60 60], ...
    'physical_tap_reconstruction_available',false,'physical_operating_envelope_complete',false, ...
    'new_physical_HVDC_count',0,'existing_source_DC_records_preserved',4, ...
    'internal_interface_observations_used',false,'external_flow_conditioned_reconstruction',true);
end
