function inputs = npcc_nygrid_2025_operating_inputs(hour_index, artifact_folder)
%NPCC_NYGRID_2025_OPERATING_INPUTS Scaled annual source inputs for full NPCC.
% Returns an input struct, not a runnable MATPOWER case. The 2025 fleet landing
% and a bounded balanced generator dispatch are subsequent build stages.
% Hours are ordered by UTC; local 2025 spring/fall DST hours remain distinct.
if nargin < 1, hour_index = 1; end
assert(isnumeric(hour_index) && isscalar(hour_index) && isfinite(hour_index) ...
    && hour_index == fix(hour_index) && hour_index >= 1 && hour_index <= 8760, ...
    'nygrid2025:HourIndex', 'Use an integer physical-hour index from 1 through 8760.');
root = fileparts(fileparts(mfilename('fullpath')));
if nargin < 2 || isempty(artifact_folder)
    artifact_folder = fullfile(root, 'output', 'nygrid_2025_inputs', 'model');
end
file = fullfile(artifact_folder, 'operating_inputs.mat');
assert(isfile(file), 'nygrid2025:MissingInputs', 'Build the 2025 operating-input package first.');
d = load(file);
assert(isequal(d.hour_index(:), (1:8760)') && size(d.bus_gross_pd, 1) == 8760, ...
    'nygrid2025:Coverage', 'Expected the complete physical 2025 hour axis.');
inputs = struct('model_year', 2025, 'hour_index', hour_index, ...
    'scale_factor_gamma', d.gamma, 'reference_ny_load_mw', d.reference_ny_load_mw, ...
    'timestamp_utc', string(d.timestamp_utc{hour_index}), 'bus_id', d.bus_id, ...
    'zone_names', {d.zone_names}, 'gross_pd_mw', d.bus_gross_pd(hour_index, :)', ...
    'gross_qd_mvar', d.bus_gross_qd(hour_index, :)', ...
    'zonal_load_public_mw', d.zonal_load_public_mw(hour_index, :)', ...
    'zonal_load_model_mw', d.zonal_load_model_mw(hour_index, :)', ...
    'boundary_channel_names', {d.boundary_channel_names}, ...
    'boundary_public_mw', d.boundary_public_mw(hour_index, :)', ...
    'boundary_model_mw', d.boundary_model_mw(hour_index, :)', ...
    'boundary_hour_qualified', logical(d.boundary_hour_qualified(hour_index)), ...
    'external_generator_input_mw', d.external_input_pg(hour_index, :)', ...
    'dc_transfer_mw', d.dcline_pf(hour_index, :)', ...
    'generation_prior_fuel_names', {d.generation_prior_fuel_names}, ...
    'zonal_generation_prior_public_mw', squeeze(d.zonal_generation_prior_public_mw(hour_index, :, :)), ...
    'zonal_generation_prior_model_mw', squeeze(d.zonal_generation_prior_model_mw(hour_index, :, :)), ...
    'zonal_generation_prior_qualified', logical(squeeze(d.zonal_generation_prior_qualified(hour_index, :, :))), ...
    'ny_balance_residual_model_mw', d.ny_balance_residual_model_mw(hour_index), ...
    'ny_generation_dispatch_available', false, 'ready_for_dc_power_flow', false, ...
    'ac_feasibility_validated', false);
end
